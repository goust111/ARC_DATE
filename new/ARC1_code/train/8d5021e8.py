import numpy as np
from arc_utils import Color, draw_line, paste, randomly_scatter_points
import random


# concepts:
# flip

# description:
# In the input you will see a monochromatic sprite.
# To make the output, 
# 1. flip the grid horizontally with y-axis on the left side of the grid, making the canvas twice larger.
# 2. flip it down with x-axis on the bottom side of the grid.
# 3. concatenate the flipped grid in step 2 to the top and bottom of the grid in step 1.
# In total the output grid is twice as wide and three times as tall as the input.

def main(input_grid):
    """
    Tile the input with horizontal and vertical reflections into a 3-by-2 mirrored canvas.

    Input structure:
    - The input is a monochromatic sprite on a black background.
    - The full input pattern is used as the source tile.
    - The output is three times taller and twice as wide as the input.

    Rule:
    - Build the middle band by concatenating a left-right reflection beside the original.
    - Flip that middle band top-to-bottom.
    - Stack the flipped band above and below the middle band.

    Key insight:
    - The output is generated by reflecting the source across the left and horizontal band edges.
    """
    # In canonical (r,c), output is 3x taller and 2x wider than input.
    # Middle band = [fliplr(input) | input], top/bottom bands = flipud(middle).
    middle = np.concatenate((np.fliplr(input_grid), input_grid), axis=1)
    top_bottom = np.flipud(middle)
    return np.concatenate((top_bottom, middle, top_bottom), axis=0)

def generate_input():
    # Generate grid of size n x m
    n, m = np.random.randint(2, 6), np.random.randint(2, 6)
    grid = np.zeros((m, n), dtype=int)

    # Randomly choose 1 color
    color = np.random.choice(list(Color.NOT_BLACK))

    # Randomly choose the density of the color
    density = np.random.randint(2, m * n) / (m * n)

    # Randomly scatter the color in the grid
    randomly_scatter_points(grid, color=color, density=density)

    return grid
