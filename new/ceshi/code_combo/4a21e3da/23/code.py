"""
Design analysis for combo D4/3 + D15/1
======================================

a) concretization_and_trace:
  original:
    - a border control on top/bottom fixes a vertical cut at its own column; a
      left/right control fixes a horizontal cut at its own row.
    - the ray on that same row/column runs inward until the farthest foreground
      pixel on the line, skipping over fg cells and only painting background.
    - cut pieces are then slid to corners using the same region-touching logic.
  combo:
    - control pixels still live on the border and still indicate only direction:
      top/bottom means "there is a vertical split", left/right means "there is a
      horizontal split".
    - the actual split line is not at the control coordinate any more. It is the
      integer centroid line of the fg sprite: the mean fg column for vertical
      splits and the mean fg row for horizontal splits.
    - the ray is drawn on that centroid line, not on the control's own row/col.
      The control pixel stays visible on the border as a symbolic length code.
    - to keep D4 learnable from 2-4 samples, the edge-position encoding is
      quantized into three visible bins by distance from the edge midpoint:
        near midpoint -> long ray -> stop at farthest split-line fg cell
        mid distance  -> medium ray -> stop at middle split-line fg cell
        far distance  -> short ray -> stop at nearest split-line fg cell
  small_trace:
    - suppose a top control is at border column 3, but the sprite centroid column
      is 9. Original logic would cut at column 3 and draw the red ray at column 3.
    - combo logic instead cuts at column 9. The output keeps fg pixels on column 9
      fixed, partitions left/right around column 9, and draws the red ray on
      column 9 from the top edge down only to a depth encoded by how close column 3
      is to the board midpoint.
    - if a left control also exists, the horizontal split is likewise forced to the
      mean fg row, so the final cross goes through the sprite's own center rather
      than through the control coordinates.

b) complexity_calibration:
  - The task still has at most one vertical split and one horizontal split, so the
    object vocabulary stays close to the source task.
  - The new length rule uses only three bins. That is enough to make the ray-depth
    change visible while avoiding a brittle fine-grained numeric code.
  - The generator deliberately creates repeated support for these bins by sampling
    controls from near/mid/far midpoint bands.
  - The centroid constraint is made exact, not approximate: the generator mirrors
    fg pieces so the relevant mean coordinate is an integer and the split line is
    unambiguous on the pixel grid.

c) implicit_assumption_review_of_original_main:
  - Original code assumed `c_split == control_col` and `r_split == control_row`.
    That fails here. The new solver derives active axes from border controls but
    derives split positions from fg centroid coordinates instead.
  - Original ray code assumed the control pixel lies on the ray. That no longer
    holds. The new solver treats the control pixel as metadata that selects a stop
    depth on the centroid split line.
  - Original farthest-stop logic assumed every example should use the maximum depth.
    That is now only one of three bins.
  - Original region classification around the split line still works once the split
    row/column is replaced, because the downstream move-to-corner rule is unchanged.

d) placement_legality:
  - Grid size stays 18-20 square with colors {1,2,7}.
  - The sprite stays at least four cells from every edge, leaving whitespace for
    disconnected symbolic control pixels and for rays drawn on centroid lines.
  - Single-axis cases are generated by exact mirror pairs; two-axis cases use
    four-way quadrant mirroring. This guarantees legal, non-overlapping placements
    and exact centroid lines.
  - Split-line fg pixels are added as short connected line segments so the sprite
    remains 4-connected and the ray has multiple candidate stop depths.

e) visual_observability:
  - A human can see that the stationary fg line in the output goes through the
    sprite's geometric center, not through the control coordinate, because the
    border control is visibly offset from that line.
  - The ray-length rule is visible because otherwise similar examples can have a
    long, medium, or short ray on the same kind of split line.
  - The generator rejects cases where the combo output equals either:
      1. `centroid + farthest-stop` (would erase D4),
      2. `control-position split + farthest-stop` (would erase D15).

f) visual_cleanliness:
  - Only three colors are used.
  - Red is reserved for controls and rays, orange for the sprite material, blue for
    background.
  - Rays are confined to the centroid row/column, while moved pieces go to corners,
    so layers remain visually separable.

g) new_solver_assumptions_and_generator_guarantees:
  - Assumption: the relevant centroid coordinate is an integer.
    Guarantee: the generator enforces mirror symmetry on the active axis/axes.
  - Assumption: each active split line contains at least three fg pixels so long /
    medium / short are distinct.
    Guarantee: split-line fg is generated as a 3- or 5-cell segment.
  - Assumption: at least one control uses a non-long ray bin, so the length code is
    visible.
    Guarantee: the generator rejects samples whose controls are all in the near bin.
"""


def _grow_piece(max_h: int, max_w: int, target_px: int) -> frozenset[tuple[int, int]]:
    cells = {(0, 0)}
    for _ in range(int(target_px) - 1):
        neighbors = set()
        for r, c in cells:
            for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                nr, nc = int(r + dr), int(c + dc)
                if (nr, nc) not in cells:
                    neighbors.add((int(nr), int(nc)))
        valid = [
            (int(nr), int(nc))
            for nr, nc in neighbors
            if max(r for r, _ in cells | {(int(nr), int(nc))}) - min(r for r, _ in cells | {(int(nr), int(nc))}) + 1 <= int(max_h)
            and max(c for _, c in cells | {(int(nr), int(nc))}) - min(c for _, c in cells | {(int(nr), int(nc))}) + 1 <= int(max_w)
        ]
        if not valid:
            break
        cells.add(random.choice(valid))
    rs = [int(r) for r, _ in cells]
    cs = [int(c) for _, c in cells]
    return frozenset((int(r - min(rs)), int(c - min(cs))) for r, c in cells)


def _make_piece(
    max_h: int,
    max_w: int,
    target_px: int,
    *,
    full_h: bool,
    full_w: bool,
    require_bottom_right: bool = False,
) -> frozenset[tuple[int, int]] | None:
    for _ in range(120):
        piece = _grow_piece(int(max_h), int(max_w), int(target_px))
        ph = int(max(r for r, _ in piece) + 1)
        pw = int(max(c for _, c in piece) + 1)
        if full_h and ph != int(max_h):
            continue
        if full_w and pw != int(max_w):
            continue
        if require_bottom_right and (int(max_h - 1), int(max_w - 1)) not in piece:
            continue
        return piece
    return None


def _grow_from_seed(max_h: int, max_w: int, target_px: int, seed: set[tuple[int, int]]) -> frozenset[tuple[int, int]] | None:
    cells = {(int(r), int(c)) for r, c in seed}
    if any(not (0 <= int(r) < int(max_h) and 0 <= int(c) < int(max_w)) for r, c in cells):
        return None
    while len(cells) < int(target_px):
        neighbors = set()
        for r, c in cells:
            for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                nr, nc = int(r + dr), int(c + dc)
                if 0 <= nr < int(max_h) and 0 <= nc < int(max_w) and (nr, nc) not in cells:
                    neighbors.add((int(nr), int(nc)))
        if not neighbors:
            break
        cells.add(random.choice(sorted(neighbors)))
    return frozenset(cells) if len(cells) == int(target_px) else None


def _touches_edges(hs: str, vs: str) -> set[str]:
    te: set[str] = set()
    if hs in ("T", "A"):
        te.add("top")
    if hs in ("B", "A"):
        te.add("bottom")
    if vs in ("L", "A"):
        te.add("left")
    if vs in ("R", "A"):
        te.add("right")
    return te


def _pick_dest(E: set[str], r_split: int | None, c_split: int | None, hs: str, vs: str) -> tuple[str, str]:
    if r_split is not None:
        dh = hs
    elif "top" in E and "bottom" not in E:
        dh = "T"
    elif "bottom" in E and "top" not in E:
        dh = "B"
    else:
        dh = "T"

    if c_split is not None:
        dv = vs
    elif "left" in E and "right" not in E:
        dv = "L"
    elif "right" in E and "left" not in E:
        dv = "R"
    else:
        dv = "L"
    return str(dh), str(dv)


def _edge_mid_distance(pos: int, size: int) -> int:
    mids = [int(size // 2)] if int(size) % 2 == 1 else [int(size // 2 - 1), int(size // 2)]
    return int(min(abs(int(pos) - m) for m in mids))


def _distance_bin(pos: int, size: int) -> int:
    d = int(_edge_mid_distance(int(pos), int(size)))
    if d <= 1:
        return 0
    if d <= 3:
        return 1
    return 2


def _border_pos_for_bin(size: int, split: int, wanted_bin: int) -> int | None:
    for min_sep in [2, 1, 0]:
        cands = [
            int(i)
            for i in range(1, int(size) - 1)
            if int(i) != int(split) and abs(int(i) - int(split)) >= int(min_sep) and _distance_bin(int(i), int(size)) == int(wanted_bin)
        ]
        if cands:
            return int(random.choice(cands))
    return None


def _ctrl_and_fg(g: np.ndarray, bg: int) -> tuple[int, int]:
    nonbg = colors_present(g, exclude={bg})
    border_cols = set(map(int, g[0, :])) | set(map(int, g[-1, :])) | set(map(int, g[:, 0])) | set(map(int, g[:, -1]))
    border_cols.discard(int(bg))
    assert len(border_cols) == 1
    ctrl = int(next(iter(border_cols)))
    fg = int(next(c for c in nonbg if int(c) != int(ctrl)))
    return int(ctrl), int(fg)


def _ctrl_info(g: np.ndarray, bg: int) -> tuple[int, int, list[tuple[int, int, str]], set[str]]:
    H, W = g.shape
    ctrl, fg = _ctrl_and_fg(g, bg)
    info: list[tuple[int, int, str]] = []
    E: set[str] = set()
    for r, c in np.argwhere(g == int(ctrl)):
        r = int(r)
        c = int(c)
        if r == 0:
            edge = "top"
        elif r == H - 1:
            edge = "bottom"
        elif c == 0:
            edge = "left"
        else:
            edge = "right"
        info.append((int(r), int(c), edge))
        E.add(edge)
    return int(ctrl), int(fg), info, E


def _split_from_control(ctrl_info: list[tuple[int, int, str]], H: int, W: int) -> tuple[int | None, int | None]:
    _ = H, W
    c_split: int | None = None
    r_split: int | None = None
    for r, c, edge in ctrl_info:
        if edge in ("top", "bottom"):
            c_split = int(c)
        else:
            r_split = int(r)
    return c_split, r_split


def _split_from_centroid(g: np.ndarray, fg: int, need_v: bool, need_h: bool) -> tuple[int | None, int | None]:
    pts = np.argwhere(g == int(fg))
    assert pts.size > 0
    n = int(len(pts))
    c_split: int | None = None
    r_split: int | None = None
    if need_v:
        c_sum = int(pts[:, 1].sum())
        assert c_sum % n == 0
        c_split = int(c_sum // n)
    if need_h:
        r_sum = int(pts[:, 0].sum())
        assert r_sum % n == 0
        r_split = int(r_sum // n)
    return c_split, r_split


def _distance_stop(hits_sorted: list[int], edge: str, ctrl_pos: int, size: int) -> int:
    if edge in ("top", "left"):
        ordered = [int(x) for x in hits_sorted]
    else:
        ordered = [int(x) for x in hits_sorted[::-1]]
    assert len(ordered) >= 3
    b = int(_distance_bin(int(ctrl_pos), int(size)))
    if b == 0:
        return int(ordered[-1])
    if b == 1:
        return int(ordered[len(ordered) // 2])
    return int(ordered[0])


def _solve(grid: np.ndarray, *, use_centroid_split: bool, use_distance_stop: bool) -> np.ndarray:
    g = np.array(grid, dtype=int)
    H, W = g.shape
    bg = int(get_bg(g))
    ctrl, fg, ctrl_info, E = _ctrl_info(g, bg)
    need_v = any(edge in ("top", "bottom") for _r, _c, edge in ctrl_info)
    need_h = any(edge in ("left", "right") for _r, _c, edge in ctrl_info)

    if use_centroid_split:
        c_split, r_split = _split_from_centroid(g, fg, need_v=need_v, need_h=need_h)
    else:
        c_split, r_split = _split_from_control(ctrl_info, H, W)

    out = np.full((H, W), int(bg), dtype=int)

    for _r, ctrl_pos, edge in ctrl_info:
        if edge in ("top", "bottom"):
            assert c_split is not None
            rows = [int(rr) for rr in np.argwhere(g[:, int(c_split)] == int(fg)).flatten()]
            rows.sort()
            if rows:
                if use_distance_stop:
                    stop = _distance_stop(rows, edge, int(ctrl_pos), W)
                else:
                    stop = int(max(rows)) if edge == "top" else int(min(rows))
                if edge == "top":
                    for rr in range(0, int(stop) + 1):
                        if int(g[int(rr), int(c_split)]) == int(bg):
                            out[int(rr), int(c_split)] = int(ctrl)
                else:
                    for rr in range(H - 1, int(stop) - 1, -1):
                        if int(g[int(rr), int(c_split)]) == int(bg):
                            out[int(rr), int(c_split)] = int(ctrl)
        else:
            assert r_split is not None
            cols = [int(cc) for cc in np.argwhere(g[int(r_split), :] == int(fg)).flatten()]
            cols.sort()
            if cols:
                if use_distance_stop:
                    stop = _distance_stop(cols, edge, int(ctrl_pos), H)
                else:
                    stop = int(max(cols)) if edge == "left" else int(min(cols))
                if edge == "left":
                    for cc in range(0, int(stop) + 1):
                        if int(g[int(r_split), int(cc)]) == int(bg):
                            out[int(r_split), int(cc)] = int(ctrl)
                else:
                    for cc in range(W - 1, int(stop) - 1, -1):
                        if int(g[int(r_split), int(cc)]) == int(bg):
                            out[int(r_split), int(cc)] = int(ctrl)

    for r, c, _edge in ctrl_info:
        out[int(r), int(c)] = int(ctrl)

    for r, c in np.argwhere(g == int(fg)):
        r = int(r)
        c = int(c)
        if (c_split is not None and c == int(c_split)) or (r_split is not None and r == int(r_split)):
            out[int(r), int(c)] = int(fg)

    regions: dict[tuple[str, str], list[tuple[int, int]]] = {}
    for r, c in np.argwhere(g == int(fg)):
        r = int(r)
        c = int(c)
        if (c_split is not None and c == int(c_split)) or (r_split is not None and r == int(r_split)):
            continue
        hs = "A"
        vs = "A"
        if r_split is not None:
            hs = "T" if r < int(r_split) else "B"
        if c_split is not None:
            vs = "L" if c < int(c_split) else "R"
        regions.setdefault((hs, vs), []).append((int(r), int(c)))

    for (hs, vs), pts in regions.items():
        if not (_touches_edges(hs, vs) & E):
            continue
        dh, dv = _pick_dest(E, r_split, c_split, hs, vs)
        rs = [int(r) for r, _ in pts]
        cs = [int(c) for _, c in pts]
        rmin, rmax = int(min(rs)), int(max(rs))
        cmin, cmax = int(min(cs)), int(max(cs))
        dr = int(-rmin) if dh == "T" else int(H - 1 - rmax)
        dc = int(-cmin) if dv == "L" else int(W - 1 - cmax)
        for r, c in pts:
            rr = int(r + dr)
            cc = int(c + dc)
            if 0 <= rr < H and 0 <= cc < W:
                out[int(rr), int(cc)] = int(fg)

    return out


def main(grid: np.ndarray) -> np.ndarray:
    """
    Combo rule:
    - border controls still indicate which split axes are active;
    - the split line(s) pass through the fg centroid, not through the controls;
    - each control's distance from the edge midpoint selects long / medium / short
      ray depth on that centroid split line;
    - piece motion after the split is unchanged from the source task.
    """
    return _solve(grid, use_centroid_split=True, use_distance_stop=True)


def _mirror_h(pts: set[tuple[int, int]], c_split: int) -> set[tuple[int, int]]:
    return {(int(r), int(2 * c_split - c)) for r, c in pts}


def _mirror_v(pts: set[tuple[int, int]], r_split: int) -> set[tuple[int, int]]:
    return {(int(2 * r_split - r), int(c)) for r, c in pts}


def _bbox_size(pts: set[tuple[int, int]]) -> tuple[int, int]:
    arr = np.array(list(pts), dtype=int)
    h = int(arr[:, 0].max() - arr[:, 0].min() + 1)
    w = int(arr[:, 1].max() - arr[:, 1].min() + 1)
    return int(h), int(w)


def _make_vertical_case(H: int, W: int, edge: str) -> np.ndarray | None:
    bg, fg, ctrl_color = 1, 7, 2
    sprite_h = random.randint(5, 8)
    c_split = random.randint(8, W - 9)
    sprite_r0 = random.randint(4, H - 5 - sprite_h + 1)
    sprite_r1 = int(sprite_r0 + sprite_h - 1)

    density = random.uniform(0.40, 0.56)
    piece_px = int(round((density * (sprite_h * 9) - 3) / 2))
    seed = {(int(r), 3) for r in range(sprite_h)} | {(0, int(c)) for c in range(4)}
    piece_px = max(len(seed), min(int(piece_px), int(sprite_h * 4)))
    piece = _grow_from_seed(sprite_h, 4, piece_px, seed)
    if piece is None:
        return None

    left = {(int(sprite_r0 + r), int(c_split - 4 + c)) for r, c in piece}
    right = _mirror_h(left, c_split)

    line_rows = [int(sprite_r0), int(sprite_r0 + sprite_h // 2), int(sprite_r1)]
    split = {(int(r), int(c_split)) for r in line_rows}

    fg_pts = set(left) | set(right) | set(split)
    if not is_contiguous(np.array([[1 if (r, c) in fg_pts else 0 for c in range(W)] for r in range(H)], dtype=int)):
        return None

    bbox_h, bbox_w = _bbox_size(fg_pts)
    if not (5 <= bbox_h <= 8 and 8 <= bbox_w <= 10):
        return None
    density_now = len(fg_pts) / float(bbox_h * bbox_w)
    if not (0.39 <= density_now <= 0.60):
        return None

    wanted_bin = random.choice([0, 1, 2])
    ctrl_col = _border_pos_for_bin(W, c_split, wanted_bin)
    if ctrl_col is None:
        return None

    grid = np.full((H, W), int(bg), dtype=int)
    for r, c in fg_pts:
        grid[int(r), int(c)] = int(fg)
    grid[0 if edge == "top" else H - 1, int(ctrl_col)] = int(ctrl_color)
    return grid


def _make_horizontal_case(H: int, W: int, edge: str) -> np.ndarray | None:
    bg, fg, ctrl_color = 1, 7, 2
    half_h = random.choice([2, 3])
    sprite_w = random.randint(8, 10)
    r_split = random.randint(4 + half_h, H - 5 - half_h)
    sprite_c0 = random.randint(4, W - 5 - sprite_w + 1)
    sprite_c1 = int(sprite_c0 + sprite_w - 1)

    density = random.uniform(0.40, 0.56)
    full_h = int(2 * half_h + 1)
    piece_px = int(round((density * (full_h * sprite_w) - 3) / 2))
    seed = {(int(half_h - 1), int(c)) for c in range(sprite_w)} | {(int(r), 0) for r in range(half_h)}
    piece_px = max(len(seed), min(int(piece_px), int(half_h * sprite_w)))
    piece = _grow_from_seed(half_h, sprite_w, piece_px, seed)
    if piece is None:
        return None

    top = {(int(r_split - half_h + r), int(sprite_c0 + c)) for r, c in piece}
    bottom = _mirror_v(top, r_split)

    line_cols = [int(sprite_c0), int(sprite_c0 + sprite_w // 2), int(sprite_c1)]
    split = {(int(r_split), int(c)) for c in line_cols}

    fg_pts = set(top) | set(bottom) | set(split)
    if not is_contiguous(np.array([[1 if (r, c) in fg_pts else 0 for c in range(W)] for r in range(H)], dtype=int)):
        return None

    bbox_h, bbox_w = _bbox_size(fg_pts)
    if not (5 <= bbox_h <= 8 and 8 <= bbox_w <= 10):
        return None
    density_now = len(fg_pts) / float(bbox_h * bbox_w)
    if not (0.39 <= density_now <= 0.60):
        return None

    wanted_bin = random.choice([0, 1, 2])
    ctrl_row = _border_pos_for_bin(H, r_split, wanted_bin)
    if ctrl_row is None:
        return None

    grid = np.full((H, W), int(bg), dtype=int)
    for r, c in fg_pts:
        grid[int(r), int(c)] = int(fg)
    grid[int(ctrl_row), 0 if edge == "left" else W - 1] = int(ctrl_color)
    return grid


def _make_cross_case(H: int, W: int, v_edge: str, h_edge: str) -> np.ndarray | None:
    bg, fg, ctrl_color = 1, 7, 2
    half_h = random.choice([2, 3])
    r_split = random.randint(4 + half_h, H - 5 - half_h)
    c_split = random.randint(8, W - 9)
    cross_px = 5

    total_h = int(2 * half_h + 1)
    total_w = 9
    density = random.uniform(0.40, 0.56)
    piece_px = int(round((density * (total_h * total_w) - cross_px) / 4))
    seed = {(int(half_h - 1), int(c)) for c in range(4)} | {(int(r), 3) for r in range(half_h)}
    piece_px = max(len(seed), min(int(piece_px), int(half_h * 4)))
    piece = _grow_from_seed(half_h, 4, piece_px, seed)
    if piece is None:
        return None

    tl = {(int(r_split - half_h + r), int(c_split - 4 + c)) for r, c in piece}
    tr = _mirror_h(tl, c_split)
    bl = _mirror_v(tl, r_split)
    br = _mirror_v(tr, r_split)

    v_rows = [int(r_split - half_h), int(r_split), int(r_split + half_h)]
    h_cols = [int(c_split - 4), int(c_split), int(c_split + 4)]
    split = {(int(r), int(c_split)) for r in v_rows} | {(int(r_split), int(c)) for c in h_cols}

    fg_pts = set(tl) | set(tr) | set(bl) | set(br) | set(split)
    if not is_contiguous(np.array([[1 if (r, c) in fg_pts else 0 for c in range(W)] for r in range(H)], dtype=int)):
        return None

    bbox_h, bbox_w = _bbox_size(fg_pts)
    if not (5 <= bbox_h <= 8 and 8 <= bbox_w <= 10):
        return None
    density_now = len(fg_pts) / float(bbox_h * bbox_w)
    if not (0.39 <= density_now <= 0.60):
        return None

    v_bin = random.choice([0, 1, 2])
    h_bin = random.choice([0, 1, 2])
    ctrl_col = _border_pos_for_bin(W, c_split, v_bin)
    ctrl_row = _border_pos_for_bin(H, r_split, h_bin)
    if ctrl_col is None or ctrl_row is None:
        return None

    grid = np.full((H, W), int(bg), dtype=int)
    for r, c in fg_pts:
        grid[int(r), int(c)] = int(fg)
    grid[0 if v_edge == "top" else H - 1, int(ctrl_col)] = int(ctrl_color)
    grid[int(ctrl_row), 0 if h_edge == "left" else W - 1] = int(ctrl_color)
    return grid


def _behavior_metrics(inp: np.ndarray) -> dict[str, int]:
    g = np.array(inp, dtype=int)
    H, W = g.shape
    bg = int(get_bg(g))
    _ctrl, fg, ctrl_info, _E = _ctrl_info(g, bg)
    need_v = any(edge in ("top", "bottom") for _r, _c, edge in ctrl_info)
    need_h = any(edge in ("left", "right") for _r, _c, edge in ctrl_info)
    c_split, r_split = _split_from_centroid(g, fg, need_v=need_v, need_h=need_h)

    split_offset = 0
    nonlong_controls = 0
    for r, c, edge in ctrl_info:
        if edge in ("top", "bottom"):
            split_offset += abs(int(c) - int(c_split))
            nonlong_controls += int(_distance_bin(int(c), W) > 0)
        else:
            split_offset += abs(int(r) - int(r_split))
            nonlong_controls += int(_distance_bin(int(r), H) > 0)

    combo = _solve(g, use_centroid_split=True, use_distance_stop=True)
    centroid_farthest = _solve(g, use_centroid_split=True, use_distance_stop=False)
    legacy = _solve(g, use_centroid_split=False, use_distance_stop=False)

    return {
        "split_offset": int(split_offset),
        "nonlong_controls": int(nonlong_controls),
        "ray_diff": int(np.count_nonzero(combo != centroid_farthest)),
        "legacy_diff": int(np.count_nonzero(combo != legacy)),
    }


def _gen_attempt() -> np.ndarray | None:
    H = W = random.randint(18, 20)
    # Single-axis samples keep the centroid-vs-control offset and the three ray-depth
    # bins visually cleaner; the solver still supports two-axis inputs.
    mode = random.choice(["vertical", "horizontal"])

    if mode == "vertical":
        edge = random.choice(["top", "bottom"])
        grid = _make_vertical_case(H, W, edge)
    else:
        edge = random.choice(["left", "right"])
        grid = _make_horizontal_case(H, W, edge)

    if grid is None:
        return None

    metrics = _behavior_metrics(grid)
    if metrics["split_offset"] < 2:
        return None
    if metrics["nonlong_controls"] < 1:
        return None
    if metrics["ray_diff"] <= 0:
        return None
    if metrics["legacy_diff"] <= 0:
        return None

    _ = main(grid)
    return grid


def generate_input() -> np.ndarray:
    for _ in range(500):
        result = _gen_attempt()
        if result is not None:
            return result
    raise RuntimeError("Failed to generate valid input after 500 attempts")
