# Combo variant of 28a6681f (index 33)
# combo_spec: D7/2+D9/1+D19/0
# Name: 带孔壁面+连通器均衡+阶梯壁高

from __future__ import annotations

import random

import numpy as np

# Design analysis
# a) Concrete layout and behavior trace
#    The fused variant fixes the puzzle to one bottom-anchored three-chamber vessel chain:
#    - chamber A occupies cols 1..3 and is the only source chamber;
#    - chamber B occupies cols 5..6;
#    - chamber C occupies col 8;
#    - divider A/B stands at col 4 and is shorter;
#    - divider B/C stands at col 7 and is taller, so wall height strictly increases left->right.
#    Both dividers contain exactly one visible one-cell hole. A representative profile is:
#    left divider top row 6 with a hole at row 7; right divider top row 4 with a hole at row 5.
#    Original local-fall logic would only move pixels downward/sideways and cannot express
#    "fill, connect, rebalance, then possibly connect again at a higher level" as one global step.
#    The fused rule instead reasons by water level:
#    - with 11 water cells, the surface reaches row 7, submerges the low left hole, and chambers
#      A+B become one connected vessel; output fills every open cell in that connected region
#      below row 7, including the hole cell itself, while chamber C stays dry;
#    - with 27 water cells, the merged A+B waterline rises to row 5; now the tall right-wall hole
#      at row 5 also submerges, and the shorter left divider is simultaneously overtopped at row 5,
#      so the final connected region spans A+B+C and all those reachable cells rebalance to one
#      common level.
#
# b) Complexity calibration
#    The geometry is intentionally narrow and repetitive rather than highly free-form:
#    two divider profiles are used, both keeping the same chamber widths, the same left-to-right
#    height ordering, and the same two activation stages. This keeps the key signals repeated:
#    a lower hole that activates first, a higher hole that activates later, and a shorter divider
#    that can eventually be overtopped. The generator only samples exact complete-level water
#    counts, so the output always shows crisp shared waterlines instead of ambiguous partial rows.
#
# c) Implicit-assumption audit for main()
#    - The original `settle()` loop assumes water motion is monotone downward or sideways. That
#      breaks under communicating-vessel equalization because water must effectively "rise" inside
#      neighboring chambers after passing through a lower hole. The fused solver replaces pixelwise
#      motion with level-set analysis on the open vessel geometry.
#    - The original output check required each final water cell to be wedged left/right/below.
#      That no longer holds once a shared waterline can span open connector cells or the space just
#      above a shorter divider crest. Output validation therefore changes to "water exactly fills one
#      connected open region below a single level".
#    - Hole cells and overtopped crest cells contribute real volume. Any solver that counts only
#      chamber rectangles would undercount the water and silently break the fusion. The new solver
#      measures the connected open component at each candidate waterline, so both mechanisms are
#      included automatically.
#    - The solver assumes one serial vessel network rooted at chamber A. The generator guarantees
#      that by fixing the outer walls, floor, and divider columns.
#
# d) Placement legality
#    Outer walls are fixed at cols 0 and 9, the floor is row 9, divider columns are 4 and 7, and
#    all chambers remain within the 10x10 grid. Each divider hole is placed strictly inside the wall
#    span, so no hole removes the entire wall. Input water is generated by keeping zero or one full
#    stable bottom row in place and moving the rest into left-packed supported source slots inside
#    chamber A; this avoids overlap and preserves the support assertions.
#
# e) Visual observability
#    Across a small set of examples, a human can see two distinct stages:
#    - stage 2 examples: chambers A and B end with one shared level, the lower left hole is visibly
#      filled, and chamber C remains empty because the higher right hole is still above the waterline;
#    - stage 3 examples: water also appears in chamber C and at the higher right-hole row, while the
#      shorter left divider is now low enough that the top surface also passes across it.
#    Because the holes are visible and the divider heights form a staircase, the connection order is
#    inferable from geometry rather than from hidden numeric color values.
#
# f) Visual cleanliness
#    The grid uses only background, water, and three solid colors. No guides, labels, or overlays are
#    added. Walls, floors, holes, and chamber interiors occupy disjoint cells, so the leaky-vessel
#    structure reads cleanly even in 10x10.
#
# g) Color inference
#    Colors do not encode ordering, thresholds, or stage labels. They only separate the three bottom
#    structures visually. All behavior comes from visible spatial cues: chamber widths, divider height,
#    hole height, and whether a waterline reaches those openings.
#
# New solver assumptions audited against the generator
#    - The only valid water totals are exact connected-component volumes for one complete level-set
#      fill; current profiles yield the visibly useful counts 11, 16, and 27. `generate_input()`
#      samples only those counts.
#    - Chamber A always contains enough source slots for the moved water after at most one retained
#      stable bottom row. The fixed 3-column source chamber provides 27 slots total.
#    - The shorter left divider always satisfies `left_top - 1 == right_hole`, so stage 3 examples
#      simultaneously show the higher right-hole activation and the shorter-wall overtop event.
#    - Water-bearing cells always belong to the single vessel rooted at (8, 1); the generator never
#      introduces unrelated blue components elsewhere in the grid.

H = 10
W = 10
BG = 0
WATER = 1
FLOOR_ROW = 9
OPEN_BOTTOM = 8
OUTER_WALLS = (0, 9)
DIVIDER_COLS = (4, 7)
CHAMBERS = ((1, 3), (5, 6), (8, 8))
SOURCE_CELL = (OPEN_BOTTOM, CHAMBERS[0][0])
OBSTACLE_COLORS = tuple(range(2, 10))
PROFILES = (
    {"left_top": 6, "left_hole": 7, "right_top": 4, "right_hole": 5},
    {"left_top": 6, "left_hole": 7, "right_top": 3, "right_hole": 5},
)


def _collect_component(mask: np.ndarray, start: tuple[int, int]) -> list[tuple[int, int]]:
    if not mask[start]:
        return []
    stack = [start]
    seen = {start}
    comp: list[tuple[int, int]] = []
    while stack:
        r, c = stack.pop()
        comp.append((r, c))
        for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            rr = r + dr
            cc = c + dc
            nxt = (rr, cc)
            if 0 <= rr < H and 0 <= cc < W and mask[rr, cc] and nxt not in seen:
                seen.add(nxt)
                stack.append(nxt)
    return comp


def _structure_only(grid: np.ndarray) -> np.ndarray:
    base = np.array(grid, dtype=int).copy()
    base[base == int(WATER)] = int(BG)
    return base


def _divider_profile(base: np.ndarray, col: int) -> tuple[int, int]:
    solid_rows = [int(r) for r in range(OPEN_BOTTOM + 1) if int(base[r, col]) != int(BG)]
    assert solid_rows, f"divider at col {col} is missing"
    top = min(solid_rows)
    holes = [int(r) for r in range(top, OPEN_BOTTOM + 1) if int(base[r, col]) == int(BG)]
    assert len(holes) == 1, f"divider at col {col} must contain exactly one hole"
    hole = holes[0]
    assert top < hole <= OPEN_BOTTOM, "hole must lie below the divider crest"
    return int(top), int(hole)


def _analyze_layout(base: np.ndarray) -> dict[str, int]:
    assert base.shape == (H, W), "grid must be 10x10"
    assert SOURCE_CELL[0] < H and SOURCE_CELL[1] < W
    assert all(int(base[FLOOR_ROW, c]) != int(BG) for c in range(W)), "bottom floor must be solid"
    assert all(int(base[r, OUTER_WALLS[0]]) != int(BG) for r in range(H)), "left outer wall must be solid"
    assert all(int(base[r, OUTER_WALLS[1]]) != int(BG) for r in range(H)), "right outer wall must be solid"
    assert int(base[SOURCE_CELL]) == int(BG), "left source chamber bottom must be open"
    for start, end in CHAMBERS:
        assert np.all(base[: FLOOR_ROW, start : end + 1] == int(BG)), "chamber interiors must be open"
    left_top, left_hole = _divider_profile(base, DIVIDER_COLS[0])
    right_top, right_hole = _divider_profile(base, DIVIDER_COLS[1])
    assert left_top > right_top, "divider heights must increase from left to right"
    assert left_hole > right_hole, "hole heights must also increase from left to right"
    assert left_top - 1 == right_hole, "stage-3 samples require the shorter wall crest and higher hole to align"
    return {
        "left_top": int(left_top),
        "left_hole": int(left_hole),
        "right_top": int(right_top),
        "right_hole": int(right_hole),
    }


def _component_at_level(base: np.ndarray, level: int) -> list[tuple[int, int]]:
    open_mask = base == int(BG)
    level_mask = np.zeros_like(open_mask, dtype=bool)
    level_mask[level : OPEN_BOTTOM + 1] = True
    return _collect_component(np.logical_and(open_mask, level_mask), SOURCE_CELL)


def _solve_level(base: np.ndarray, water_count: int) -> tuple[int, list[tuple[int, int]]]:
    if water_count == 0:
        return OPEN_BOTTOM + 1, []
    for level in range(OPEN_BOTTOM, -1, -1):
        component = _component_at_level(base, level)
        volume = len(component)
        if volume == int(water_count):
            return int(level), component
        if volume > int(water_count):
            break
    raise AssertionError("water count does not match any complete communicating-vessel level")


def _behavior_signature(grid: np.ndarray) -> dict[str, int | bool]:
    base = _structure_only(grid)
    layout = _analyze_layout(base)
    water_positions = [(int(r), int(c)) for r, c in np.argwhere(grid == int(WATER))]
    if not water_positions:
        return {
            "top_row": OPEN_BOTTOM + 1,
            "hole1_active": False,
            "hole2_active": False,
            "low_wall_overtopped": False,
            "connected_chambers": 0,
        }
    top_row = min(r for r, _c in water_positions)
    chambers_with_water = 0
    for start, end in CHAMBERS:
        if np.any(grid[:, start : end + 1] == int(WATER)):
            chambers_with_water += 1
    return {
        "top_row": int(top_row),
        "hole1_active": bool(top_row <= int(layout["left_hole"])),
        "hole2_active": bool(top_row <= int(layout["right_hole"])),
        "low_wall_overtopped": bool(top_row <= int(layout["left_top"]) - 1),
        "connected_chambers": int(chambers_with_water),
    }


def main(grid: np.ndarray, check_input: bool = True, check_output: bool = True) -> np.ndarray:
    """
    Rebalance water inside stepped leaky chambers by filling the connected vessel region level by level.

    Input structure:
    - bg = 0 and water = 1.
    - Other colors form a bottom-anchored three-chamber vessel with full outer walls, a shorter
      left divider, a taller right divider, and one visible hole in each divider.
    - Water starts as a supported pile in the left source chamber, optionally with a small retained
      stable row already sitting in the lower chambers.

    Rule:
    - Ignore the lopsided source arrangement and keep only the total number of water pixels.
    - For each candidate waterline, look at all open cells on or below that row that are 4-connected
      to the left source chamber through chamber interiors, submerged holes, and any now-submerged
      space above a shorter divider crest.
    - The final output is the unique complete level whose connected open-region volume exactly matches
      the total water count.

    Key insight: The answer is determined by staged connectivity thresholds. A lower hole can merge
    the first two chambers at one level, while a higher hole and a shorter wall crest only matter
    once the common waterline rises further, at which point the whole connected region equalizes.
    """
    g = np.array(grid, dtype=int).copy()
    base = _structure_only(g)
    layout = _analyze_layout(base)
    initial_water = int(np.count_nonzero(g == int(WATER)))

    if check_input:
        for r, c in np.argwhere(g == int(WATER)):
            rr = int(r)
            cc = int(c)
            assert rr == FLOOR_ROW or int(g[rr + 1, cc]) != int(BG), "input water must be supported"
            left_bg = cc > 0 and int(g[rr, cc - 1]) == int(BG)
            right_bg = cc + 1 < W and int(g[rr, cc + 1]) == int(BG)
            assert not (left_bg and right_bg), "input water cannot have bg on both horizontal sides"
        assert layout["left_top"] > layout["right_top"]
        assert layout["left_hole"] > layout["right_hole"]

    _level, component = _solve_level(base, initial_water)
    out = base.copy()
    for r, c in component:
        out[r, c] = int(WATER)

    if check_output:
        assert int(np.count_nonzero(out == int(WATER))) == initial_water, "water count must be conserved"
        solved_again = main(out, check_input=True, check_output=False)
        assert np.array_equal(solved_again, out), "output must already be at equilibrium"
        sig = _behavior_signature(out)
        if sig["connected_chambers"] >= 2:
            assert sig["hole1_active"], "middle chamber water requires the lower hole to be submerged"
        if sig["connected_chambers"] == 3:
            assert sig["hole2_active"], "right chamber water requires the higher hole to be submerged"
            assert sig["low_wall_overtopped"], "stage-3 outputs must also overtop the shorter divider"

    return out


def _build_terrain(profile: dict[str, int], colors: tuple[int, int, int]) -> np.ndarray:
    g = np.zeros((H, W), dtype=int)
    left_color, mid_color, right_color = colors

    g[:, OUTER_WALLS[0]] = left_color
    g[:, OUTER_WALLS[1]] = right_color
    g[FLOOR_ROW, 0:5] = left_color
    g[FLOOR_ROW, 5:8] = mid_color
    g[FLOOR_ROW, 8:10] = right_color

    for r in range(int(profile["left_top"]), FLOOR_ROW):
        if r != int(profile["left_hole"]):
            g[r, DIVIDER_COLS[0]] = left_color
    for r in range(int(profile["right_top"]), FLOOR_ROW):
        if r != int(profile["right_hole"]):
            g[r, DIVIDER_COLS[1]] = mid_color

    return g


def _level_options(base: np.ndarray) -> list[tuple[int, int, list[tuple[int, int]]]]:
    layout = _analyze_layout(base)
    options: list[tuple[int, int, list[tuple[int, int]]]] = []
    source_capacity = (OPEN_BOTTOM + 1) * (CHAMBERS[0][1] - CHAMBERS[0][0] + 1)
    for level in range(OPEN_BOTTOM, -1, -1):
        component = _component_at_level(base, level)
        if not component:
            continue
        volume = len(component)
        if volume > source_capacity:
            continue
        if level <= int(layout["right_hole"]):
            stage = 3
        elif level <= int(layout["left_hole"]):
            stage = 2
        else:
            stage = 1
        options.append((stage, volume, component))
    return options


def _make_input(output: np.ndarray, retain_rows: int) -> np.ndarray:
    inp = np.array(output, dtype=int).copy()
    retain: set[tuple[int, int]] = set()
    if retain_rows > 0:
        min_row = OPEN_BOTTOM - int(retain_rows) + 1
        retain = {(int(r), int(c)) for r, c in np.argwhere(output == int(WATER)) if int(r) >= min_row}

    moved = []
    for r, c in np.argwhere(output == int(WATER)):
        cell = (int(r), int(c))
        if cell in retain:
            continue
        moved.append(cell)
        inp[cell] = int(BG)

    source_slots = []
    for r in range(OPEN_BOTTOM, -1, -1):
        for c in range(CHAMBERS[0][0], CHAMBERS[0][1] + 1):
            cell = (int(r), int(c))
            if cell not in retain:
                source_slots.append(cell)

    assert len(moved) <= len(source_slots), "source chamber is too small for the moved water"
    for idx, cell in enumerate(source_slots[: len(moved)]):
        inp[cell] = int(WATER)
        assert idx < len(moved) + 1

    return inp


def _variant_visible(output: np.ndarray) -> bool:
    sig = _behavior_signature(output)
    if sig["connected_chambers"] == 2:
        return bool(sig["hole1_active"] and not sig["hole2_active"] and not np.any(output[:, CHAMBERS[2][0] : CHAMBERS[2][1] + 1] == int(WATER)))
    if sig["connected_chambers"] == 3:
        return bool(sig["hole2_active"] and sig["low_wall_overtopped"] and np.any(output[:, CHAMBERS[2][0] : CHAMBERS[2][1] + 1] == int(WATER)))
    return False


def generate_input() -> np.ndarray:
    for _ in range(100):
        profile = dict(random.choice(PROFILES))
        colors = tuple(random.sample(OBSTACLE_COLORS, 3))
        base = _build_terrain(profile, colors)
        options = [(stage, volume) for stage, volume, _component in _level_options(base) if stage in (2, 3)]
        if not options:
            continue

        stage = random.choice([2, 2, 3])
        stage_options = [volume for stage_id, volume in options if stage_id == stage]
        if not stage_options:
            stage_options = [volume for stage_id, volume in options if stage_id in (2, 3)]
        water_count = int(random.choice(stage_options))

        seed = base.copy()
        source_slots = [
            (r, c)
            for r in range(OPEN_BOTTOM, -1, -1)
            for c in range(CHAMBERS[0][0], CHAMBERS[0][1] + 1)
        ]
        assert water_count <= len(source_slots)
        for r, c in source_slots[:water_count]:
            seed[r, c] = int(WATER)

        output = main(seed)
        if not _variant_visible(output):
            continue

        retain_rows = random.choice((0, 1))
        input_grid = _make_input(output, retain_rows=retain_rows)

        try:
            solved = main(input_grid)
        except AssertionError:
            continue
        if not np.array_equal(solved, output):
            continue
        if np.array_equal(input_grid, output):
            continue

        sig = _behavior_signature(output)
        if sig["connected_chambers"] == 2:
            assert sig["hole1_active"] and not sig["hole2_active"]
        if sig["connected_chambers"] == 3:
            assert sig["hole2_active"] and sig["low_wall_overtopped"]
        return input_grid

    raise AssertionError("failed to generate a valid stepped-hole communicating-vessel example")
