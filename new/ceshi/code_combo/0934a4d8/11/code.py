# Combo variant of 0934a4d8 (index 11)
# combo_spec: D1/1+D15/2
# Name: C4旋转对称+同心矩形环纹理

from __future__ import annotations

import numpy as np

from arc_utils import bbox


# Design analysis for the combo variant
#
# a) Concrete behavior:
# - The original task recovers the hidden rectangle from LR+UD reflection orbits,
#   with a transpose fallback when the marker overlaps the top/left free border.
# - This combo replaces the mirrored core with a C4-symmetric square block and also
#   changes the texture from a random mirrored tile to nested concentric square rings.
# - A hidden interior cell now recovers from its quarter-turn orbit
#   {(r,c), (c, lo+hi-r), (lo+hi-r, lo+hi-c), (lo+hi-c, r)}.
#   A hidden top-border cell (0/1, c) recovers from the left border partner
#   (lo+hi-c, r), and symmetrically for hidden left-border cells.
# - Example with lo=2, hi=9: an interior cell (4,7) shares its value with
#   (7,7), (7,4), (4,4) under 90-degree turns. A top-border cell (1,8) instead
#   uses the border partner (3,1). The visible texture is not generic random C4:
#   it is arranged as nested square ring bands, each mostly keeping its own layer
#   color while carrying a rotated accent motif around the ring.
#
# b) Complexity calibration:
# - Purely uniform rings would be too weak: they remain LR/UD symmetric and often
#   let a solver guess by ring radius alone, which would erase the D1 change.
# - Purely random C4 orbits would lose the D15 visual cue. The generator therefore
#   uses ring bands with dominant per-layer colors plus asymmetric C4 accent marks.
# - Marker placement is forced to overlap both the outer top/left border and the
#   inner ring block, and it must cover at least two ring layers inside the block.
#   That makes both the C4 recovery rule and the ring structure visibly relevant.
#
# c) Hidden assumptions in the original main():
# - `_find_reflected_strip_start` assumed separate horizontal and vertical mirrors;
#   this is invalid after switching to quarter-turn symmetry, so it must become a
#   full-block 90-degree consistency check.
# - `_reflection_orbit_values` assumed the value source comes from two reflections;
#   the combo instead needs a 4-cycle generated by repeated 90-degree rotation.
# - The original transpose fallback is no longer justified. It is replaced by the
#   explicit top-border <-> left-border 90-degree partner used by the generator.
# - The original random mirrored texture had little shape structure. With rings we
#   must also ensure the texture does not accidentally create another unique solid
#   rectangle candidate; generator self-checks the marker detection on final inputs.
#
# d) Placement legality:
# - The marker may overlap the top border or left border, but it may not touch the
#   top-left lo x lo corner because that corner has no guaranteed rotational partner.
# - Every hidden interior cell must keep at least one visible orbit mate outside the
#   marker; otherwise the rotation orbit would be fully occluded and unrecoverable.
# - The rectangle must stay within bounds and remain the only fully solid rectangle.
#
# e) Visual observability:
# - Across examples a human can see a large lower-right square made of nested ring
#   bands, not a mirrored quilt. The same accent motif rotates side-to-side instead
#   of reflecting, which makes the C4 rule visible from samples.
# - The output remains the marker-sized hidden patch, so the relationship between
#   the masked region and the rotated ring fragments is directly inspectable.
#
# f) Visual cleanliness:
# - There is only one explicit object: the solid marker rectangle.
# - Everything else belongs either to the ring-textured C4 square or to the thin
#   helper border that acts as a 90-degree auxiliary copy, so the image stays tidy.
#
# g) Change inferability:
# - Colors are never remapped by id. They only propagate through rotational orbits.
# - Ring layers use a small fixed palette, repeated across samples, with position-
#   based accents. The structure, not raw color ids, explains why hidden pixels take
#   their recovered values.
#
# Post-change audit of new main() assumptions:
# - `main()` assumes the marker is still the unique full solid rectangle; generator
#   validates `_solid_rectangle_marker(inp)` on every accepted sample.
# - `main()` assumes the smallest rotated-consistent strip start is the real lo=2;
#   generator rejects any sample where `_find_rotated_strip_start(inp, marker) != 2`.
# - `main()` assumes border-hidden cells always have an exposed 90-degree partner and
#   interior-hidden cells never hide an entire orbit; placement filtering enforces it.
# - Generator sampling explicitly balances top-border and left-border marker cases so
#   both border-recovery branches appear regularly across examples.


def _solid_rectangle_marker(g: np.ndarray) -> tuple[int, tuple[int, int, int, int]]:
    candidates: list[tuple[int, int, tuple[int, int, int, int]]] = []
    for color in np.unique(g):
        mask = g == int(color)
        b = bbox(mask)
        assert b is not None
        r0, c0, r1, c1 = b
        area = int((r1 - r0 + 1) * (c1 - c0 + 1))
        if area > 1 and int(mask.sum()) == area and bool(np.all(mask[r0 : r1 + 1, c0 : c1 + 1])):
            candidates.append((area, int(color), b))

    assert len(candidates) == 1
    _area, color, b = candidates[0]
    return color, b


def _find_rotated_strip_start(g: np.ndarray, marker: int) -> int:
    n, m = map(int, g.shape)
    assert n == m

    for lo in range(n // 2 + 1):
        block = g[lo:n, lo:n]
        rotated = np.rot90(block, -1)
        known = (block != marker) & (rotated != marker)
        if bool(np.any((block != rotated) & known)):
            continue
        return lo

    raise AssertionError("no rotated strip found")


def _rotate90(r: int, c: int, lo: int, hi: int) -> tuple[int, int]:
    return int(c), int(lo + hi - r)


def _rotation_orbit(r: int, c: int, lo: int, hi: int) -> list[tuple[int, int]]:
    coords: list[tuple[int, int]] = []
    rr, cc = int(r), int(c)
    for _ in range(4):
        coords.append((rr, cc))
        rr, cc = _rotate90(rr, cc, lo, hi)
    return coords


def _rotation_orbit_values(g: np.ndarray, r: int, c: int, lo: int, marker: int) -> set[int]:
    hi = int(g.shape[0] - 1)
    values: set[int] = set()
    for rr, cc in _rotation_orbit(r, c, lo, hi):
        value = int(g[rr, cc])
        if value != marker:
            values.add(value)
    return values


def main(grid: np.ndarray) -> np.ndarray:
    """
    Recover the marker-covered rectangle from a quarter-turn symmetric ring texture.

    Input structure:
    - A square grid contains exactly one solid rectangular marker color that covers
      a patch of the real pattern.
    - The main visible pattern lives in the square block [lo..N-1] x [lo..N-1],
      where nested concentric square ring bands follow 90-degree rotational symmetry.
    - The thin top border and left border outside that block provide auxiliary
      90-degree border copies of each other, while the top-left lo x lo corner is free.

    Rule:
    - Locate the unique color whose entire support is a filled rectangle; its bbox is
      the output window.
    - Infer the smallest lo whose lower-right square block is consistent with a
      quarter-turn rotation when marker pixels are ignored.
    - For each hidden cell inside that block, collect the visible values from its
      0/90/180/270-degree rotation orbit and copy the unique non-marker value.
    - For each hidden cell on the top border or left border, use the paired cell on
      the other helper border given by the same 90-degree rotation.

    Key insight:
    The solid rectangle is only an occluder. The real content belongs to a larger
    C4-symmetric system of concentric ring bands, so every hidden pixel is fixed by
    either its quarter-turn orbit inside the ring square or its auxiliary border mate.
    """
    g = np.asarray(grid, dtype=int)
    marker, (r0, c0, r1, c1) = _solid_rectangle_marker(g)
    lo = _find_rotated_strip_start(g, marker)

    h = int(r1 - r0 + 1)
    w = int(c1 - c0 + 1)
    out = np.empty((h, w), dtype=int)

    for rr in range(h):
        for cc in range(w):
            r = int(r0 + rr)
            c = int(c0 + cc)
            if lo <= r < g.shape[0] and lo <= c < g.shape[1]:
                values = _rotation_orbit_values(g, r, c, lo, marker)
                assert values
                assert len(values) == 1
                out[rr, cc] = values.pop()
            elif r < lo <= c:
                value = int(g[lo + g.shape[0] - 1 - c, r])
                assert value != marker
                out[rr, cc] = value
            elif c < lo <= r:
                value = int(g[c, lo + g.shape[0] - 1 - r])
                assert value != marker
                out[rr, cc] = value
            else:
                raise AssertionError("marker overlaps unsupported top-left corner")

    return out


# --------------- generator (o5x) ---------------

# --- CFG: canvas & structure ---
_N = 30
_LO = 2
_HI = _N - 1
_INNER = _N - _LO
_HALF_SPAN = _INNER // 2

# --- CFG: colors ---
_PALETTE = np.array([1, 2, 3, 4, 5, 6, 7, 9], dtype=int)
_MARKER = 8

# --- CFG: marker rectangle size ---
_MARKER_DIM_LO = 3
_MARKER_DIM_HI = 9
_MARKER_AREA_LO = 16
_MARKER_AREA_HI = 36

# --- CFG: generation retries ---
_MAX_RETRIES = 400

_RNG = np.random.default_rng()
_SIZE_PAIRS = [
    (h, w)
    for h in range(_MARKER_DIM_LO, _MARKER_DIM_HI + 1)
    for w in range(_MARKER_DIM_LO, _MARKER_DIM_HI + 1)
    if _MARKER_AREA_LO <= h * w <= _MARKER_AREA_HI
]


def _compositions(total: int, lo: int, hi: int) -> list[tuple[int, ...]]:
    out: list[tuple[int, ...]] = []

    def rec(remaining: int, cur: list[int]) -> None:
        if remaining == 0:
            out.append(tuple(cur))
            return
        for value in range(lo, min(hi, remaining) + 1):
            cur.append(value)
            rec(remaining - value, cur)
            cur.pop()

    rec(total, [])
    return out


_THICKNESS_CHOICES = [
    parts
    for parts in _compositions(_HALF_SPAN, 1, 3)
    if 5 <= len(parts) <= 8
]
_PLACEMENT_CACHE: dict[tuple[tuple[int, ...], int, int], list[tuple[int, int, int]]] = {}


def _build_ring_layout(thicknesses: tuple[int, ...]) -> tuple[np.ndarray, list[tuple[int, int]]]:
    band_of_distance = np.empty(_HALF_SPAN, dtype=int)
    bounds: list[tuple[int, int]] = []
    d = 0
    for band, thickness in enumerate(thicknesses):
        start = d
        end = d + thickness - 1
        band_of_distance[start : end + 1] = band
        bounds.append((start, end))
        d += thickness
    assert d == _HALF_SPAN
    return band_of_distance, bounds


def _pick_distinct_color(*forbidden: int) -> int:
    banned = set(int(x) for x in forbidden)
    choices = [int(color) for color in _PALETTE if int(color) not in banned]
    return int(choices[int(_RNG.integers(len(choices)))])


def _build_inner_block(thicknesses: tuple[int, ...]) -> tuple[np.ndarray, np.ndarray]:
    band_of_distance, bounds = _build_ring_layout(thicknesses)
    block = np.empty((_INNER, _INNER), dtype=int)

    params: list[tuple[int, int, int, int, int]] = []
    prev_base = -1
    for band, (start, end) in enumerate(bounds):
        base = _pick_distinct_color(prev_base)
        accent = _pick_distinct_color(base)
        period = int(_RNG.integers(3, 6))
        phase = int(_RNG.integers(0, period))
        step = int(_RNG.integers(1, 4))
        params.append((base, accent, period, phase, step))
        prev_base = base

    seen: set[tuple[int, int]] = set()
    for r in range(_INNER):
        for c in range(_INNER):
            if (r, c) in seen:
                continue
            orbit = _rotation_orbit(r, c, 0, _INNER - 1)
            for coord in orbit:
                seen.add(coord)

            d = min(r, c, _INNER - 1 - r, _INNER - 1 - c)
            band = int(band_of_distance[d])
            start, _end = bounds[band]
            base, accent, period, phase, step = params[band]
            rep_r, rep_c = min(orbit)
            local_r = int(rep_r - start)
            local_c = int(rep_c - start)
            token = int(local_c + step * local_r + 2 * band + phase)
            color = accent if token % period == 0 else base
            for rr, cc in orbit:
                block[rr, cc] = int(color)

    return block, band_of_distance


def _build_clean(
    thicknesses: tuple[int, ...],
) -> tuple[np.ndarray, np.ndarray]:
    clean = _RNG.choice(_PALETTE, size=(_N, _N))
    block, band_of_distance = _build_inner_block(thicknesses)
    clean[_LO:_N, _LO:_N] = block

    clean[:_LO, _LO:_N] = _RNG.choice(_PALETTE, size=(_LO, _N - _LO))
    for r in range(_LO, _N):
        for c in range(_LO):
            clean[r, c] = clean[c, _LO + _HI - r]
    clean[:_LO, :_LO] = _RNG.choice(_PALETTE, size=(_LO, _LO))
    return clean, band_of_distance


def _reflection_mismatches(clean: np.ndarray) -> int:
    block = clean[_LO:_N, _LO:_N]
    lr = int(np.count_nonzero(block != block[:, ::-1]))
    ud = int(np.count_nonzero(block != block[::-1, :]))
    return lr + ud


def _ring_distance(r: int, c: int) -> int:
    rr = int(r - _LO)
    cc = int(c - _LO)
    return int(min(rr, cc, _INNER - 1 - rr, _INNER - 1 - cc))


def _placement_stats(
    r0: int,
    c0: int,
    h: int,
    w: int,
    band_of_distance: np.ndarray,
) -> tuple[bool, int, int, int]:
    border_cells = 0
    inner_cells = 0
    ring_bands: set[int] = set()
    r1, c1 = r0 + h, c0 + w

    for r in range(r0, r1):
        for c in range(c0, c1):
            if r < _LO and c < _LO:
                return False, 0, 0, 0
            if r < _LO or c < _LO:
                border_cells += 1
                continue
            inner_cells += 1
            ring_bands.add(int(band_of_distance[_ring_distance(r, c)]))
            orbit = _rotation_orbit(r, c, _LO, _HI)
            inside = [r0 <= rr < r1 and c0 <= cc < c1 for rr, cc in orbit]
            if all(inside):
                return False, 0, 0, 0

    if border_cells == 0 or inner_cells == 0:
        return False, 0, 0, 0
    if len(ring_bands) < 2:
        return False, 0, 0, 0
    return True, border_cells, inner_cells, len(ring_bands)


def _valid_placements(
    thicknesses: tuple[int, ...],
    h: int,
    w: int,
    band_of_distance: np.ndarray,
) -> list[tuple[int, int, int]]:
    key = (thicknesses, h, w)
    if key not in _PLACEMENT_CACHE:
        placements: list[tuple[int, int, int]] = []
        for r0 in range(_N - h + 1):
            for c0 in range(_N - w + 1):
                ok, border_cells, inner_cells, band_count = _placement_stats(r0, c0, h, w, band_of_distance)
                if ok:
                    score = int(10 * band_count + 2 * border_cells + inner_cells)
                    placements.append((r0, c0, score))
        _PLACEMENT_CACHE[key] = placements
    return _PLACEMENT_CACHE[key]


def _pick_branch_balanced_placement(placements: list[tuple[int, int, int]]) -> tuple[int, int, int]:
    top_only = [placement for placement in placements if placement[0] < _LO]
    left_only = [placement for placement in placements if placement[1] < _LO]
    assert top_only or left_only

    if top_only and left_only:
        pool = top_only if int(_RNG.integers(2)) == 0 else left_only
    else:
        pool = top_only if top_only else left_only

    weights = np.array([score for _r0, _c0, score in pool], dtype=float)
    weights /= weights.sum()
    idx = int(_RNG.choice(len(pool), p=weights))
    return pool[idx]


def _behavior_metrics(inp: np.ndarray) -> tuple[int, int, int]:
    marker, (r0, c0, r1, c1) = _solid_rectangle_marker(inp)
    lo = _find_rotated_strip_start(inp, marker)
    border_cells = 0
    inner_cells = 0
    border_recovery_cells = 0
    for r in range(r0, r1 + 1):
        for c in range(c0, c1 + 1):
            if r < lo or c < lo:
                border_cells += 1
                border_recovery_cells += 1
            else:
                inner_cells += 1
    return border_cells, inner_cells, border_recovery_cells


def _gen_attempt() -> np.ndarray | None:
    thicknesses = _THICKNESS_CHOICES[int(_RNG.integers(len(_THICKNESS_CHOICES)))]
    clean, band_of_distance = _build_clean(thicknesses)
    if _reflection_mismatches(clean) < 80:
        return None

    h, w = _SIZE_PAIRS[int(_RNG.integers(len(_SIZE_PAIRS)))]
    placements = _valid_placements(thicknesses, h, w, band_of_distance)
    if not placements:
        return None

    r0, c0, _score = _pick_branch_balanced_placement(placements)

    expected = clean[r0 : r0 + h, c0 : c0 + w].copy()
    inp = clean.copy()
    inp[r0 : r0 + h, c0 : c0 + w] = _MARKER

    try:
        marker, _bbox = _solid_rectangle_marker(inp)
        if marker != _MARKER:
            return None
        if _find_rotated_strip_start(inp, _MARKER) != _LO:
            return None
        border_cells, inner_cells, border_recovery_cells = _behavior_metrics(inp)
        if border_cells == 0 or inner_cells == 0 or border_recovery_cells == 0:
            return None
        if np.array_equal(main(inp), expected):
            return inp
    except Exception:
        return None
    return None


def generate_input() -> np.ndarray:
    for _ in range(_MAX_RETRIES):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a valid 0934a4d8 combo input")
