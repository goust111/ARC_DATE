# Combo variant of e3721c99 (index 18)
# combo_spec: D4/2+D7/2
# Name: 并排对比输出+颜色交换
#
# Design analysis
# fusion_variant:
#   concrete_behavior:
#     - 输入面板仍是原题的 30x30 单面布局：边缘图例、分隔线、工作区灰色精灵。
#     - 小例子：若面板里有一个红色 2 洞图例，以及一个灰色 2 洞精灵和一个 4 洞干扰物：
#       原题单面输出会把 2 洞精灵变红，图例保持红色，4 洞干扰物擦除。
#       本融合版先做颜色交换单面变换：2 洞精灵变红、对应红图例整块变灰、4 洞干扰物擦除；
#       再把输出改成并排双面：左半保留原输入，右半放这张交换后的单面结果。
#     - 因此差异发生在两个层面：图例不再保持原色，且结果不覆盖原图而是与原图并排对照。
#   complexity_calibration:
#     - 保留原题 2-4 个图例、8-11 个精灵、1-7 个干扰物，避免退化成只看单个交换对。
#     - 每个图例至少仍有 1 个匹配精灵，保证右半面板中每种图例色都能在工作区出现支撑样例。
#     - 图例洞数保持互异，右半只存在一种 hole_count -> color 的解释，避免多义匹配。
#   implicit_assumptions_review:
#     - 原 solver 假设输出尺寸等于输入尺寸；融合后失效，`main()` 必须返回宽度翻倍的网格。
#     - 原 solver 只需改写灰色连通块；融合后还必须记录并改写“被识别为图例”的具体坐标，
#       因为颜色 1 同时可能属于分隔线，不能按颜色值整体替换。
#     - 图例读取必须基于原输入完成，然后才能生成右半交换结果；如果先改色，图例会混入灰色集合。
#     - generator 不能再把 expected 当作与输入同尺寸的单面网格逐步涂写，而要先造出合法输入，
#       再用同一套 solver 逻辑得到右半单面结果，并拼成双面输出做校验。
#   placement_legality:
#     - 输入的几何布局完全沿用原题约束，所以图例、分隔线、精灵的合法放置条件不变。
#     - 双面输出只是对输入和右半结果做水平拼接，不新增对象，也不会引入重叠、越界或遮挡。
#   observability_and_tidiness:
#     - 左半是原图，右半是同布局的变换图，解题者可以直接逐位置对照哪些精灵得色、哪些图例失色。
#     - 变化集中在已有对象上，没有额外符号层；双面板比在原图上直接覆盖更容易肉眼归纳。
#   color_inference:
#     - 颜色种类仍限制在 2-4 个图例色，且每种颜色都由“左半图例原色”和“右半匹配精灵得色”共同提示。
#     - 右半图例统一变灰提供稳定线索，使人类能从少量样例推断出是双向交换而非单向重涂。
#   new_solver_assumptions:
#     - `main()` 假设输入仍是原题的单面网格，双面板仅存在于输出；generator 用原题布局保证这一点。
#     - `main()` 假设至少存在一个合法图例连通块；generator 继续强制生成 2-4 个图例。

