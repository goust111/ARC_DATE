def _hole_count(mask: np.ndarray) -> int:
    """
    Count holes in a binary mask using 4-connectivity.
    A hole is a background component that does not touch the mask's bounding box border.
    """
    h, w = mask.shape
    bg = ~mask
    vis = np.zeros((h, w), dtype=bool)
    holes = 0
    for r0 in range(h):
        for c0 in range(w):
            if not bg[r0, c0] or vis[r0, c0]:
                continue
            st = [(r0, c0)]
            vis[r0, c0] = True
            touches = False
            while st:
                r, c = st.pop()
                if r == 0 or c == 0 or r == h - 1 or c == w - 1:
                    touches = True
                for rr, cc in neighbors4(r, c):
                    if 0 <= rr < h and 0 <= cc < w and bg[rr, cc] and not vis[rr, cc]:
                        vis[rr, cc] = True
                        st.append((rr, cc))
            if not touches:
                holes += 1
    return holes


def _legend_entries(g: np.ndarray, bg: int, grey: int) -> dict[int, dict[str, object]]:
    """
    Pick one legend component per non-(bg, grey) color.
    Each entry stores the legend color and the exact component coordinates.
    """
    h, w = g.shape
    entries: dict[int, dict[str, object]] = {}
    colors = [c for c in sorted(set(map(int, np.unique(g)))) if c not in (bg, grey)]
    for c in colors:
        comps = components_mask(g == c, connectivity=4)
        candidates: list[tuple[np.ndarray, tuple[int, int, int, int]]] = []
        for pts in comps:
            r0, c0, r1, c1 = bbox_coords(pts)
            if r0 == 0 or c0 == 0 or r1 == h - 1 or c1 == w - 1:
                continue
            if (r1 - r0 + 1) < 2 or (c1 - c0 + 1) < 2:
                continue
            candidates.append((pts, (r0, c0, r1, c1)))
        if not candidates:
            continue
        assert len(candidates) == 1, f"color {c} must have exactly one legend component"
        pts, (r0, c0, r1, c1) = candidates[0]
        sub = g[r0 : r1 + 1, c0 : c1 + 1] == c
        hc = _hole_count(sub)
        assert hc not in entries, f"legend hole count {hc} must map to exactly one color"
        entries[hc] = {"color": int(c), "coords": pts}
    return entries


def _swap_panel(grid: np.ndarray) -> np.ndarray:
    """Apply the color-swap single-panel transform used on the right comparison panel."""
    g = np.asarray(grid, dtype=int)
    bg = get_bg(g)
    grey = 5

    legend = _legend_entries(g, bg, grey)
    assert legend, "legend mapping must be non-empty: grid must contain colored legend shapes"

    out = g.copy()
    for pts in components_mask(g == grey, connectivity=4):
        r0, c0, r1, c1 = bbox_coords(pts)
        sub = np.zeros((r1 - r0 + 1, c1 - c0 + 1), dtype=bool)
        for r, c in pts:
            sub[r - r0, c - c0] = True
        hc = _hole_count(sub)
        newc = int(legend[hc]["color"]) if hc in legend else bg
        for r, c in pts:
            out[r, c] = newc

    for entry in legend.values():
        for r, c in entry["coords"]:
            out[r, c] = grey

    return out


def _compose_output(inp: np.ndarray, right_panel: np.ndarray) -> np.ndarray:
    """Build the side-by-side comparison output."""
    return np.hstack([np.asarray(inp, dtype=int), np.asarray(right_panel, dtype=int)])


def main(grid: np.ndarray) -> np.ndarray:
    """
    Show the original panel beside its color-swapped resolution by hole-count matching.

    Input structure:
    - The input is still a single 30x30 scene with bg as the dominant color, grey (5) sprites in the workspace,
      and colored legend glyphs parked near an edge behind a divider.
    - Each legend glyph is a non-grey connected component away from the outer border, and each one encodes a
      distinct enclosed-hole count.

    Rule:
    - Read the legend as hole_count -> legend_color from the input panel.
    - Build a transformed copy of that same panel: matching grey sprites take the legend color, unmatched grey
      sprites are erased to bg, and every legend glyph that donated a color turns grey.
    - Output a width-doubled grid whose left half is the untouched input panel and whose right half is the
      transformed copy.

    Key insight: The solver must combine two ideas at once: hole count still determines correspondence, but the
    answer is now an explicit before/after comparison where color moves from legend to sprite only on the right.
    """
    g = np.asarray(grid, dtype=int)
    return _compose_output(g, _swap_panel(g))


