# Design analysis for the combo D3/1 + D5/0 variant
# a) Concretization and behavior trace:
#    - The left side still uses the original 2-column tiling of 3x3 monochrome glyphs.
#      Shape keeps the old motion code:
#        area 4 -> down 2, area 5 -> right 3, area 6 -> left 4, area 7 -> left 2.
#    - D3/1 breaks the old color-shape binding: a plus may be orange, teal, maroon, etc.,
#      and a cross may reuse the same color. Individual glyph color is no longer a segment-level
#      instruction.
#    - D5/0 then collapses all segment paint into one shared color. In this combo we make that
#      color the unique most frequent glyph color on the left panel. Example with four glyphs:
#        glyphs in reading order = cross(teal), plus(maroon), diamond(teal), plus(orange)
#        path geometry = left4, down2, right3, down2 from the shapes alone
#        output color = teal everywhere because teal appears twice and the others once each.
#      Compared with the base task, color no longer follows shape; compared with D3/1 alone,
#      color no longer changes from segment to segment.
# b) Complexity calibration:
#    - Keep the original four masks, board size, divider, and reading order so only the intended
#      dimensions change.
#    - Restrict glyph colors to {1,2,3,6,7,8,9}; this avoids bg/divider/start confusion while
#      still breaking the original canonical palette.
#    - Generator enforces a unique majority color, at least two distinct shapes, and at least one
#      repeated shape painted with different colors. This makes the decoupling visible without
#      adding too many degrees of freedom.
# c) Hidden-assumption review of the original main():
#    - Original code assumed glyph color could be copied directly onto the matching segment.
#      That is false now: the solver must first collect all glyphs, compute the majority color,
#      and then use that single color for every segment.
#    - Original code filtered left-side components by color {bg, 5, divider}. D3/1 means color
#      is sampled independently, so filtering by color would be unsafe in principle. We therefore
#      accept every 3x3 monochrome component on the left panel as a glyph.
#    - Motion decoding by area is still valid because the shape templates are unchanged.
# d) Placement legality:
#    - Glyphs still occupy fixed non-overlapping 3x3 slots at c0 in {0,4} and r0 spaced by 4.
#    - The path sampler works in output space and only accepts area sequences whose shifted start,
#      intermediate horizontal runs, and final row all stay within the 7-column left canvas.
#    - Majority-color assignment never changes geometry, so legality depends only on the sampled path.
# e) Visual observability:
#    - Across examples, users will see differently colored copies of the same shape producing the
#      same movement, which exposes color as a distractor for geometry.
#    - Outputs are uniformly colored, and that shared color matches the most common glyph color in
#      the input. A unique majority makes this visually recoverable from 2-4 examples.
# f) Visual cleanliness:
#    - The polyline still descends one row between instructions, so later segments do not scribble
#      over earlier rows chaotically.
#    - Avoiding glyph colors 4 and 5 keeps divider/start markers visually distinct from the glyph set.
# g) Change inferability:
#    - Color inference uses only a small repeated palette and a strict majority rule.
#    - Geometry inference uses repeated shapes under different colors, so the human can separate
#      "shape -> motion" from "global color choice -> final paint".
# Solver/generator contract after the change:
#    - main() assumes each left-side foreground object of bbox 3x3 is one glyph, and that there is
#      exactly one unique majority glyph color when examples are generated by generate_input().
#    - generate_input() guarantees the majority is unique, the output differs from both the base
#      task and the D3-only variant, and the sampled colors visibly break shape-color binding.


def find_full_height_constant_col(grid: np.ndarray, *, bg: int | None = None) -> tuple[int | None, int | None]:
    """Find a full-height constant non-background column."""
    _H, W = grid.shape
    if bg is None:
        bg = get_bg(grid)
    bg = int(bg)

    for c in range(int(W)):
        col = grid[:, int(c)]
        if (col == col[0]).all() and int(col[0]) != bg:
            return int(c), int(col[0])
    return None, None


def _sorted_glyphs(left: np.ndarray, *, bg: int) -> list[dict[str, int]]:
    glyphs: list[dict[str, int]] = []
    for comp in find_components(left, bg=bg, connectivity=8, monochromatic=True, return_format="dict"):
        b = comp["bbox"]
        if bbox_h(b) != 3 or bbox_w(b) != 3:
            continue
        r0, c0, _r1, _c1 = map(int, b)
        glyphs.append({"color": int(comp["color"]), "r0": int(r0), "c0": int(c0), "area": int(comp["area"])})
    glyphs.sort(key=lambda d: (int(d["c0"]), int(d["r0"])))
    return glyphs


def _majority_color_in_reading_order(glyphs: list[dict[str, int]]) -> int:
    counts = Counter(int(glyph["color"]) for glyph in glyphs)
    best_color = int(glyphs[0]["color"])
    best_count = -1
    for glyph in glyphs:
        color = int(glyph["color"])
        count = int(counts[color])
        if count > best_count:
            best_color = color
            best_count = count
    return int(best_color)


def main(grid: np.ndarray) -> np.ndarray:
    """
    Decode a tiled glyph panel into a single-color polyline on the left canvas.

    Input structure:
    - A full-height divider splits the board into a left glyph field and a right start-marker field.
    - The left field contains monochromatic 3x3 glyphs on background; the right field contains one gray (5) start cell.

    Rule:
    - Remove the divider, shift the gray start onto the left canvas, and read the glyphs in column-major order.
    - Each glyph's shape still determines the segment geometry: area 4 -> down 2, area 5 -> right 3, area 6 -> left 4, area 7 -> left 2.
    - Ignore per-glyph paint when drawing the path itself: every segment uses one shared color, namely the most frequent glyph color in the input.

    Key insight:
    - Color no longer identifies the motion of an individual glyph. Shape alone gives the walk, while the glyph colors matter only globally through their majority color.
    """
    g = np.array(grid, dtype=int)
    H, _W = g.shape
    bg = int(get_bg(g))

    div_c, _div_color = find_full_height_constant_col(g, bg=bg)
    assert div_c is not None

    out = np.zeros((H, int(div_c)), dtype=int)

    gray = np.argwhere(g == 5)
    if gray.size == 0:
        return out
    r_cur, c_cur = map(int, gray[0])
    c_cur = int(c_cur - (int(div_c) + 1))
    if not (0 <= c_cur < int(div_c)):
        return out
    out[int(r_cur), int(c_cur)] = 5

    left = g[:, : int(div_c)]
    glyphs = _sorted_glyphs(left, bg=bg)
    if not glyphs:
        return out

    color = _majority_color_in_reading_order(glyphs)
    area_to_len = {4: 2, 5: 3, 6: 4, 7: 2}
    area_to_dir = {5: 1, 6: -1, 7: -1}

    for glyph in glyphs:
        area = int(glyph["area"])
        assert area in area_to_len, f"unexpected glyph area: {area}"
        seg_len = int(area_to_len[area])

        r_cur = int(r_cur + 1)
        assert r_cur < H, f"segment exits bottom: r_cur={r_cur}, H={H}"
        out[r_cur, int(c_cur)] = color

        if area == 4:
            end_r = r_cur + (seg_len - 1)
            assert end_r < H, f"vertical segment exits bottom: end_r={end_r}, H={H}"
            for _ in range(seg_len - 1):
                r_cur = int(r_cur + 1)
                out[r_cur, int(c_cur)] = color
        else:
            dir_h = int(area_to_dir[area])
            end_c = int(c_cur) + dir_h * (seg_len - 1)
            assert 0 <= end_c < int(div_c), (
                f"horizontal segment exits canvas: c_cur={c_cur}, dir={dir_h}, seg_len={seg_len}, div_c={div_c}"
            )
            for _ in range(seg_len - 1):
                c_cur = int(c_cur + dir_h)
                out[r_cur, c_cur] = color

    return out


N_MIN, N_MAX = 2, 5
GRID_W = 15
DIVIDER_COL = 7
DIVIDER_COLOR = 4
LEFT_W = 7
TILE_COLS = (0, 4)
TILE_ROW_STRIDE = 4
GRAY = 5
GRAY_START_ROW = 0
MAX_ATTEMPTS = 600
PATH_ATTEMPTS = 100
COLOR_ATTEMPTS = 200
MIN_DIRECTION_CHANGES = 2

_TEMPLATES = {
    4: np.array([[1, 0, 1], [0, 1, 0], [0, 1, 0]], dtype=int),
    5: np.array([[1, 1, 0], [1, 0, 1], [0, 1, 0]], dtype=int),
    6: np.array([[1, 1, 1], [0, 1, 0], [1, 0, 1]], dtype=int),
    7: np.array([[1, 0, 1], [1, 0, 1], [1, 1, 1]], dtype=int),
}
_AREA_TO_LEN = {4: 2, 5: 3, 6: 4, 7: 2}
_AREA_TO_DIR = {5: 1, 6: -1, 7: -1}
_AREA_DELTA = {4: (2, 0), 5: (1, 2), 6: (1, -3), 7: (1, -1)}
_AREAS = (4, 5, 6, 7)
_OLD_AREA_TO_COLOR = {4: 6, 5: 1, 6: 3, 7: 2}
_GLYPH_COLORS = (1, 2, 3, 6, 7, 8, 9)
_NOVEL_COLORS = (7, 8, 9)


def _direction_change_count(areas: list[int]) -> int:
    kinds = [a == 4 for a in areas]
    return sum(1 for i in range(1, len(kinds)) if kinds[i] != kinds[i - 1])


def _sample_path(N: int, start_col: int) -> list[int] | None:
    """Sample a valid area sequence that stays inside the left canvas."""
    H = 4 * N - 1
    for _ in range(PATH_ATTEMPTS):
        r, c = GRAY_START_ROW, start_col
        areas: list[int] = []
        for _step in range(2 * N):
            opts = [a for a in _AREAS if r + _AREA_DELTA[a][0] < H and 0 <= c + _AREA_DELTA[a][1] < LEFT_W]
            if not opts:
                break
            # Favor still-unused shapes so larger examples expose more of the motion grammar.
            weights = [4 if a not in areas else 1 for a in opts]
            area = random.choices(opts, weights=weights, k=1)[0]
            areas.append(area)
            dr, dc = _AREA_DELTA[area]
            r += dr
            c += dc

        if len(areas) != 2 * N:
            continue
        if _direction_change_count(areas) < MIN_DIRECTION_CHANGES:
            continue
        min_shapes = 3 if len(areas) >= 6 else 2
        if len(set(areas)) < min_shapes:
            continue
        if not any(areas.count(area) >= 2 for area in set(areas)):
            continue
        return areas
    return None


def _majority_target_count(num_glyphs: int, num_shapes: int) -> int:
    lower = num_glyphs // 2 + 1
    upper = num_glyphs - (num_shapes - 1)
    return max(lower, min(upper, lower + 1))


def _color_assignment_is_informative(areas: list[int], colors: list[int]) -> bool:
    color_counts = Counter(colors)
    if len(color_counts) < 3:
        return False
    dominant_color, dominant_count = color_counts.most_common(1)[0]
    if dominant_color not in _NOVEL_COLORS:
        return False
    if dominant_count <= max(count for color, count in color_counts.items() if color != dominant_color):
        return False
    if sum(color != _OLD_AREA_TO_COLOR[area] for area, color in zip(areas, colors)) < 3:
        return False

    same_shape_diff_color = any(len({colors[i] for i, area2 in enumerate(areas) if area2 == area}) >= 2 for area in set(areas))
    if not same_shape_diff_color:
        return False

    dominant_shapes = {areas[i] for i, color in enumerate(colors) if color == dominant_color}
    if len(dominant_shapes) < 2:
        return False

    return True


def _sample_colors(areas: list[int]) -> list[int] | None:
    groups: dict[int, list[int]] = {}
    for idx, area in enumerate(areas):
        groups.setdefault(area, []).append(idx)

    repeated_areas = [area for area, idxs in groups.items() if len(idxs) >= 2]
    if not repeated_areas or len(groups) < 2:
        return None

    num_glyphs = len(areas)
    num_shapes = len(groups)
    dominant_target = _majority_target_count(num_glyphs, num_shapes)

    for _ in range(COLOR_ATTEMPTS):
        dominant_color = random.choice(_NOVEL_COLORS)
        other_colors = random.sample([c for c in _GLYPH_COLORS if c != dominant_color], k=2)
        palette = [dominant_color, *other_colors]

        repeat_area = random.choice(repeated_areas)
        repeat_idxs = random.sample(groups[repeat_area], 2)
        other_area = random.choice([area for area in groups if area != repeat_area])
        other_idx = random.choice(groups[other_area])

        dominant_idxs = {repeat_idxs[0], other_idx}
        remaining = [idx for idx in range(num_glyphs) if idx not in dominant_idxs]
        need_more = dominant_target - len(dominant_idxs)
        if need_more < 0 or need_more > len(remaining):
            continue
        if need_more:
            dominant_idxs.update(random.sample(remaining, need_more))

        colors: list[int] = [other_colors[0]] * num_glyphs
        for idx in dominant_idxs:
            colors[idx] = dominant_color

        colors[repeat_idxs[1]] = other_colors[1]
        for idx in range(num_glyphs):
            if idx in dominant_idxs or idx == repeat_idxs[1]:
                continue
            colors[idx] = random.choice(other_colors)

        final_colors = [int(c) for c in colors]
        if _color_assignment_is_informative(areas, final_colors):
            return final_colors
    return None


def _simulate_output(H: int, start_col: int, areas: list[int], colors: list[int], *, mode: str) -> np.ndarray:
    out = np.zeros((H, LEFT_W), dtype=int)
    out[GRAY_START_ROW, start_col] = GRAY

    if mode == "uniform-majority":
        counts = Counter(colors)
        paint_color = max(counts.items(), key=lambda kv: kv[1])[0]
    r_cur, c_cur = GRAY_START_ROW, start_col
    for area, glyph_color in zip(areas, colors):
        if mode == "uniform-majority":
            paint = paint_color
        elif mode == "per-glyph":
            paint = glyph_color
        elif mode == "canonical-shape":
            paint = _OLD_AREA_TO_COLOR[area]
        else:
            raise ValueError(f"unknown simulation mode: {mode}")

        seg_len = _AREA_TO_LEN[area]
        r_cur += 1
        out[r_cur, c_cur] = paint
        if area == 4:
            for _ in range(seg_len - 1):
                r_cur += 1
                out[r_cur, c_cur] = paint
        else:
            dir_h = _AREA_TO_DIR[area]
            for _ in range(seg_len - 1):
                c_cur += dir_h
                out[r_cur, c_cur] = paint
    return out


def _render_grid(N: int, start_col: int, areas: list[int], colors: list[int]) -> np.ndarray:
    H = 4 * N - 1
    grid = np.zeros((H, GRID_W), dtype=int)
    grid[:, DIVIDER_COL] = DIVIDER_COLOR
    grid[GRAY_START_ROW, DIVIDER_COL + 1 + start_col] = GRAY

    for i, (area, color) in enumerate(zip(areas, colors)):
        tile_col = TILE_COLS[i // N]
        r0 = TILE_ROW_STRIDE * (i % N)
        grid[r0 : r0 + 3, tile_col : tile_col + 3] = _TEMPLATES[area] * color
    return grid


def _fusion_metrics(areas: list[int], colors: list[int], expected: np.ndarray, per_glyph: np.ndarray, canonical: np.ndarray) -> dict[str, int]:
    counts = Counter(colors)
    dominant_color, dominant_count = counts.most_common(1)[0]
    second_count = counts.most_common(2)[1][1] if len(counts) >= 2 else 0
    return {
        "dominant_color": int(dominant_color),
        "dominant_margin": int(dominant_count - second_count),
        "num_colors": int(len(counts)),
        "num_shapes": int(len(set(areas))),
        "same_shape_diff_color": int(
            any(len({colors[i] for i, area2 in enumerate(areas) if area2 == area}) >= 2 for area in set(areas))
        ),
        "uniform_vs_per_glyph_diff": int(np.count_nonzero(expected != per_glyph)),
        "uniform_vs_canonical_diff": int(np.count_nonzero(expected != canonical)),
    }


def _gen_attempt() -> tuple[np.ndarray, np.ndarray, dict[str, int]] | None:
    N = random.randint(N_MIN, N_MAX)
    H = 4 * N - 1
    start_col = random.randint(0, LEFT_W - 1)

    areas = _sample_path(N, start_col)
    if areas is None:
        return None

    colors = _sample_colors(areas)
    if colors is None:
        return None

    expected = _simulate_output(H, start_col, areas, colors, mode="uniform-majority")
    per_glyph = _simulate_output(H, start_col, areas, colors, mode="per-glyph")
    canonical = _simulate_output(H, start_col, areas, colors, mode="canonical-shape")
    metrics = _fusion_metrics(areas, colors, expected, per_glyph, canonical)

    if metrics["uniform_vs_per_glyph_diff"] <= 0:
        return None
    if metrics["uniform_vs_canonical_diff"] <= 0:
        return None
    if metrics["dominant_margin"] <= 0:
        return None
    if metrics["same_shape_diff_color"] <= 0:
        return None

    return _render_grid(N, start_col, areas, colors), expected, metrics


def generate_input() -> np.ndarray:
    for _ in range(MAX_ATTEMPTS):
        try:
            attempt = _gen_attempt()
            if attempt is None:
                continue
            inp, expected, _metrics = attempt
            out = main(inp)
            if out.shape != expected.shape:
                continue
            if not np.array_equal(out, expected):
                continue
            return inp
        except Exception:
            continue
    raise RuntimeError(f"generate_input: failed after {MAX_ATTEMPTS} attempts")
