# Variant of 3dc255db
# Dimension: D1 — 路径类型 (path)
# Change: straight_ray — 内容像素从尖刺沿尾部方向发射为一条直线... → 反弹弹射
#
# Design analysis for this variant
# spec_variant:
#   core_change:
#     original: Content pixels were erased from the cup mouth and re-drawn on the tail side as
#       a one-way straight ray that stopped at the first grid exit.
#     variant: The ejection path is simulated step-by-step. Whenever the next step would leave
#       the grid, the direction reflects off that boundary and the ray continues until every
#       content pixel has been placed.
#   observability_adjustment:
#     issue: With a monochrome orthogonal ray, "bounce at boundary then retrace" is invisible
#       if the path is forced to stop at the spike, because the reflected segment overlaps the
#       original segment exactly.
#     chosen_fix: The reflected ray is allowed to pass back through the spike and the cup's
#       central corridor. This keeps the change localized to path simulation, but makes the
#       reflected continuation visible as content-colored cells on the spike / mouth side.
#   concrete_trace:
#     setup: Tail points upward, spike at row 3, content count = 7.
#     original_steps: rows 2,1,0 then stop/drop overflow.
#     variant_steps: rows 2,1,0,1,2,3,4 after reflecting at row 0.
#     visible_difference: the spike row 3 and mouth-side row 4 become content-colored only in
#       the variant, so the transformation is human-visible.
#   complexity_calibration:
#     kept: same cup detector, same color semantics, same scattered mouth contents, same stray
#       pixels, same 10..13 grid bounds, same 1..3 cups.
#     changed: only the path generator and path executor.
#     support_for_examples: generator forces each cup to have enough content to cross the launch
#       boundary and return at least to the spike, so 2-4 examples visibly demonstrate the new
#       rule instead of silently collapsing to the original one-way ray.
#   implicit_assumption_audit_main:
#     - Candidate spike detection still relies on "exactly one border cell on one bbox edge";
#       the variant does not change cup geometry, so this remains valid.
#     - Mouth detection still floods from the edge opposite a candidate spike; the reflected
#       output path may later overwrite the spike or mouth in the output, but input detection
#       happens before that, so the flood logic remains valid.
#     - The original straight-ray loop assumed overflow is dropped at the first boundary exit.
#       This is no longer valid; it is replaced by a bounded "place exactly N pixels" loop with
#       boundary reflection before each move.
#     - The original code implicitly assumed the path never revisits old cells. In the variant
#       revisits are normal, so generator and solver both treat the path as a sequence of steps,
#       not as a simple set-to-edge run.
#   placement_legality:
#     - Cups still keep a 1-cell gap between bboxes.
#     - Each chosen reflected prefix must avoid other cups and prior paths outside its own bbox.
#     - The path may traverse the cup's own bbox after reflecting; this is intentional and is
#       the visual signature of the variant.
#   visual_cleanliness:
#     - Paths are still axis-aligned single-pixel traces, so the image stays readable.
#     - Generator rejects placements whose reflected prefix touches another cup/path outside the
#       source cup bbox, preventing dense clutter.
#   behavior_metric:
#     - A sample is considered "variant-visible" when some cup has content_count >= 2*d + 1,
#       where d is the straight run from spike to the launch-side boundary. Then the reflected
#       prefix reaches at least the spike cell, making the output differ from the original task.

