# Variant of a47bf94d
# Dimension: D4 — token形状分解方式 (transform)
# Change: 分解（decomposition）——实心3x3块被分解为十字形（中心+4个正交邻居，留在原位）和四角星形（4个对角角，... → 反向分解（对角留、正交走）

import random

import numpy as np

from arc_utils import components_mask, get_bg, neighbors4

# Design analysis for the D4 variant
# a) 具体化与行为追踪
#    - 原代码里可观察的两种“分解后部件”并不是抽象描述里的“4个对角角”和“十字+中心”字面像素，
#      而是现成的两个 token 词汇：`_X_OFF`（对角+中心）与 `_DIAMOND_OFF`（4 个正交格）。
#      因此本变体不引入新的 4-角-only / plus-only 图元，而是把“实心块拆解后哪一个词汇留在原位、
#      哪一个词汇沿导线到远端”这件事反过来。
#    - 小例子：若某色实心 3x3 放在上侧端点附近，原题输出是在上侧留下 diamond、下侧补一个 X；
#      现在改成上侧留下 X、下侧补一个 diamond。若输入本来就是 X，则它仍然表示“本地已经是留下的那一半”，
#      远端仍补 diamond。
#    - 影响环节：`main()` 里只有“solid 原地改写”和“solid 经导线发射什么形状”两处需要反转；导线追踪、
#      9-矩形穿越、X-token 路由逻辑都保持不变。generator 端则必须把期望输出与输入源端绑定：
#      源端输出 X，另一端输出 diamond。
# b) 复杂度校准
#    - 保留原题的 4-5 条通道、非恒等置换、0-3 个 9-矩形、0-2 个 X 输入，避免变体退化成简单的
#      单边复制题。多数通道仍使用 solid 输入，因此“solid -> 原地 X / 远端 diamond”会在每个样本里重复出现。
# c) 隐式假设审查
#    - `_find_solid_3x3` / `_find_x_3x3` 只负责识别输入图元，和 D4 变体无关，保留。
#    - `track_mask` 依旧需要去掉 solid 的整块 3x3 与 X 的 5 个格，避免 token 被当成导线。
#    - 原代码“Solid tokens become diamonds in place”这个循环依赖旧分解规则，必须改成原地写 X。
#    - 原代码在路由阶段对 solid 目的地写 `_X_OFF`，这同样依赖旧规则，必须改成写 `_DIAMOND_OFF`。
#    - `elif cen in xs` 分支原本就表示“X 留在原位、远端补 diamond”，该前提在本变体下仍成立，所以不动。
# d) 放置合法性
#    - token 仍放在距离 degree-1 端点 2 格的位置，沿用原始高度/宽度/间距约束，因此不会越界。
#    - 输出侧的 X / diamond 仍只占原来就允许的 3x3 token 区域，不与导线或 9-矩形重叠。
#    - generator 里 source side 一旦决定，solid 与 X 输入都只能放在“最终应留下 X”的那一侧；另一侧只允许为空，
#      或在 X 输入通道里预放一个 diamond（与原题同类的“远端已补全”情况）。
# e) 视觉可观察性
#    - 关键可见差异是：实心块在输出里不再变成 diamond，而是变成 X。因为每题至少有 2 条 solid 通道，
#      解题者在少量样例里就能看出“实心块本地剩下的部件变了”。
#    - 不使用颜色 id 做任何排序或变换；颜色只沿原通道对应传递。
# f) 可视化整洁度
#    - 沿用原题的纵向通道和 sparse token 摆放；变体只交换 token 形状角色，不增加新叠层。
# g) 颜色变化可推断性
#    - 颜色完全保持原色传输，不引入颜色映射。可推断线索仍然是“同色 token + 导线路由”。
# 9) 新 `main()` 的输入假设与 generator 保证
#    - 假设每个会发射 diamond 的源 token（solid 或 X）紧邻某条导线分量的端点两格之外；
#      generator 继续按这个几何关系构造。
#    - 假设 solid 通道的远端默认没有与待发射 diamond 冲突的同色残片；generator 对 solid 通道不预放远端图元。
#    - 假设 X 通道若预放远端 diamond，也只是“已经完成的目标形状”，不会需要再次识别成源 token；
#      generator 仅以原题相同方式少量加入这种情况。

_N4 = [(-1, 0), (1, 0), (0, -1), (0, 1)]

_DIAMOND_OFF = [(-1, 0), (1, 0), (0, -1), (0, 1)]
_X_OFF = [(-1, -1), (-1, 1), (0, 0), (1, -1), (1, 1)]


def _find_solid_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for maximal 3x3 solid blocks."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            col = int(sub[0, 0])
            if col == bg or np.any(sub != col):
                continue
            maximal = True
            for rr in range(r0, r0 + 3):
                for cc in range(c0, c0 + 3):
                    for nr, nc in neighbors4(rr, cc):
                        if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                            if int(g[nr, nc]) == col:
                                maximal = False
                                break
                    if not maximal:
                        break
                if not maximal:
                    break
            if not maximal:
                continue
            found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _find_x_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for isolated 3x3 X-patterns."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}

    mask = np.zeros((3, 3), dtype=bool)
    for rr, cc in [(0, 0), (0, 2), (1, 1), (2, 0), (2, 2)]:
        mask[rr, cc] = True

    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            col = int(sub[0, 0])
            if col == bg:
                continue
            if np.any(sub[mask] != col) or np.any(sub[~mask] != bg):
                continue
            isolated = True
            for dr0, dc0 in _X_OFF:
                rr, cc = r0 + 1 + dr0, c0 + 1 + dc0
                for nr, nc in neighbors4(rr, cc):
                    if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                        if int(g[nr, nc]) == col:
                            isolated = False
                            break
                if not isolated:
                    break
            if not isolated:
                continue
            found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _components(mask: np.ndarray) -> list[list[tuple[int, int]]]:
    return [[(int(r), int(c)) for r, c in comp] for comp in components_mask(mask, connectivity=4)]


def _find_9rects(g: np.ndarray) -> list[tuple[set, dict]]:
    """Find color-9 rectangular blocks and their wire connections per face."""
    mask9 = g == 9
    if not mask9.any():
        return []
    h, w = g.shape
    rects = []
    for comp9 in components_mask(mask9, connectivity=4):
        cells = set((int(r), int(c)) for r, c in comp9)
        rs = [r for r, _ in cells]
        cs = [c for _, c in cells]
        r0, r1, c0, c1 = min(rs), max(rs), min(cs), max(cs)
        faces: dict[str, list] = {}
        for r, c in cells:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) not in cells and 0 <= nr < h and 0 <= nc < w and int(g[nr, nc]) in (5, 8):
                    face = "N" if nr < r0 else "S" if nr > r1 else "W" if nc < c0 else "E"
                    faces.setdefault(face, []).append((nr, nc))
        rects.append((cells, faces))
    return rects


_OPP = {"N": "S", "S": "N", "E": "W", "W": "E"}
_DIR2FACE = {(1, 0): "N", (-1, 0): "S", (0, 1): "W", (0, -1): "E"}
_FACE2DIR = {"S": (1, 0), "N": (-1, 0), "E": (0, 1), "W": (0, -1)}


def _trace_wire(
    comp: set[tuple[int, int]],
    start: tuple[int, int],
    dir0: tuple[int, int],
    h: int,
    w: int,
    rects_9: list[tuple[set, dict]],
) -> tuple[tuple[int, int], tuple[int, int]]:
    """
    Greedy wire following with 9-rect pass-through.

    At a color-9 rectangle: exit from the opposite face when possible;
    otherwise, use the unique other available face.
    """
    cur, d, prev = start, dir0, None
    visited: set[tuple[tuple[int, int], tuple[int, int]]] = set()
    for _ in range(h * w * 4):
        if (cur, d) in visited:
            assert False, "wire trace looped — should not happen with 9-rect pass-through"
        visited.add((cur, d))

        jumped = False
        for cells9, faces9 in rects_9:
            if cur in cells9:
                entry_face = _DIR2FACE[d]
                opp = _OPP[entry_face]
                if opp in faces9:
                    exit_face = opp
                else:
                    others = [f for f in faces9 if f != entry_face]
                    assert len(others) == 1
                    exit_face = others[0]
                pts = faces9[exit_face]
                er, ec = cur
                if entry_face in ("N", "S"):
                    exit_cell = min(pts, key=lambda p: abs(p[1] - ec))
                else:
                    exit_cell = min(pts, key=lambda p: abs(p[0] - er))
                cur, d, prev = exit_cell, _FACE2DIR[exit_face], None
                jumped = True
                break
        if jumped:
            continue

        r, c = cur
        opts = [((nr, nc), nr - r, nc - c) for nr, nc in neighbors4(r, c) if (nr, nc) in comp]
        if not opts:
            return cur, d

        rev = (-d[0], -d[1])
        nonrev = [o for o in opts if (o[1], o[2]) != rev]
        opts2 = nonrev if nonrev else opts

        straight = [o for o in opts2 if (o[1], o[2]) == d]
        if straight:
            p, dr, dc = straight[0]
        else:
            perp = [o for o in opts2 if o[1] * d[0] + o[2] * d[1] == 0]
            if perp:
                p, dr, dc = sorted(perp, key=lambda x: (x[1], x[2]))[0]
            else:
                p, dr, dc = opts2[0]

        if p == prev:
            return cur, d

        prev = cur
        cur = p
        d = (dr, dc)

    assert False, "wire trace exceeded step limit"


def main(grid: np.ndarray) -> np.ndarray:
    """
    Route colored endpoint tokens through the wire network, but reverse which half of a solid block stays local.

    Input structure:
    - Background cells are the dominant color. Non-background cells form orthogonal wire components plus 3x3 tokens near wire endpoints.
    - Tokens are either solid 3x3 blocks or X-patterns (diagonals + center); some far endpoints may already show a diamond.

    Rule:
    - Every solid 3x3 token is rewritten in place as an X-pattern.
    - Any solid or X token attached to a wire endpoint sends a diamond (the 4 cardinal cells around a 3x3 center) to the opposite endpoint.

    Key insight:
    - The wire-routing logic is unchanged; only the solid-token split is inverted, so the local residue is now the diagonal-heavy X while the transported completion is the cardinal diamond.
    """
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    bg = get_bg(g)

    solids = _find_solid_3x3(g, bg)
    xs = _find_x_3x3(g, bg)

    track_mask = g != bg
    for (_, _), (_, (r0, c0)) in solids.items():
        track_mask[r0 : r0 + 3, c0 : c0 + 3] = False
    for cr, cc in xs.keys():
        for dr, dc in _X_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w:
                track_mask[rr, cc2] = False

    comps = _components(track_mask)
    rects_9 = _find_9rects(g)

    out = g.copy()

    for (cr, cc), (col, (r0, c0)) in solids.items():
        out[r0 : r0 + 3, c0 : c0 + 3] = bg
        for dr, dc in _X_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w:
                out[rr, cc2] = col

    for pts in comps:
        comp = set(pts)
        if len(comp) < 4:
            continue

        comp_colors = {int(g[r, c]) for r, c in comp}

        deg = {p: 0 for p in comp}
        for r, c in comp:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) in comp:
                    deg[(r, c)] += 1
        endpoints = [p for p in comp if deg[p] <= 1]
        if not endpoints:
            continue

        for ep in endpoints:
            er, ec = ep
            for odr, odc in _N4:
                cen = (er + 2 * odr, ec + 2 * odc)
                if not (0 <= cen[0] < h and 0 <= cen[1] < w):
                    continue

                if cen in solids:
                    col, _ = solids[cen]
                    if col in comp_colors:
                        continue
                    dir_in = (-odr, -odc)
                    end, dd = _trace_wire(comp, ep, dir_in, h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    for dr, dc in _DIAMOND_OFF:
                        rr, cc2 = dest[0] + dr, dest[1] + dc
                        if 0 <= rr < h and 0 <= cc2 < w:
                            out[rr, cc2] = col

                elif cen in xs:
                    col, _ = xs[cen]
                    if col in comp_colors:
                        continue
                    dir_in = (-odr, -odc)
                    end, dd = _trace_wire(comp, ep, dir_in, h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    for dr, dc in _DIAMOND_OFF:
                        rr, cc2 = dest[0] + dr, dest[1] + dc
                        if 0 <= rr < h and 0 <= cc2 < w:
                            out[rr, cc2] = col

    return out


