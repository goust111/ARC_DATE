# Variant of a47bf94d
# Dimension: D4 — token形状分解方式 (transform)
# Change: 分解（decomposition）——实心3x3块被分解为十字形（中心+4个正交邻居，留在原位）和四角星形（4个对角角，... → L形分解
#
# Design analysis
# - Source task: None. The wire-routing / 9-rectangle mechanism comes directly from the original task.
# - Specificized token vocabulary:
#   - solid: full 3x3 monochrome block.
#   - stay-L (5 cells): a fixed upper-left heavy L inside the 3x3 footprint.
#       ###      relative offsets = {(-1,-1), (-1,0), (-1,1), (0,-1), (0,0)}
#       ##.
#       ...
#   - travel-L (4 cells): the complementary lower-right L inside the same 3x3 footprint.
#       ...
#       ..#
#       ###
# - Concrete behavior trace:
#   - Old D4 at one endpoint: a solid 3x3 became a local diamond and sent an X to the far end.
#   - New D4 at one endpoint: a solid 3x3 is cleared and restamped as the 5-cell stay-L at the same center,
#     then the far endpoint receives the complementary 4-cell travel-L.
#   - If the input already contains a travel-L near an endpoint, it stays as-is and only the far endpoint is
#     completed with the 5-cell stay-L. This preserves the original "partial token can trigger completion"
#     role, but replaces X/diamond with the new asymmetric pair.
# - Complexity calibration:
#   - The split is fixed to one orientation pair. That keeps inference tractable from 2-4 examples while still
#     making the transform visibly different from the original symmetric cross/X decomposition.
#   - The generator still mixes two active input types: solid blocks and pre-split travel-L tokens. This avoids
#     degenerating into a one-case dataset while keeping the branch count small.
# - Hidden assumptions from the original main() that had to change:
#   - `_find_x_3x3` and the diamond/X offsets were hard-wired to the old token family; both detection and output
#     stamping now use the stay-L / travel-L masks instead.
#   - The original `track_mask` intentionally left diamonds inside the wire component so a pre-placed far token
#     could suppress routing via `comp_colors`. That becomes fragile with the denser L shapes, so this variant
#     explicitly detects passive stay-L tokens and removes every token cell from the track mask. Routing is then
#     driven only by the active token found two cells from an endpoint.
#   - Unconditional stamping remains safe because every channel has a unique color and generator placement keeps
#     token footprints disjoint from one another except for legitimate rewrites of the same target cells.
# - Placement legality:
#   - The 3x3 token footprint is unchanged, so all original row/column spacing constraints remain valid.
#   - Both L shapes stay inside the same 3x3 box around the endpoint offset used by the original task, so no
#     extra margins are needed and the existing output-first permutation builder still applies.
# - Visual observability / cleanliness:
#   - The local half is a 5-cell top-left-heavy corner; the remote half is a 4-cell bottom-right corner.
#     That asymmetry is obvious by eye and does not depend on color ids or hidden ordering.
#   - Wire colors and token colors remain disjoint, and there are no new overlays on top of 9-rect junctions.
# - New main() assumptions reviewed against generator:
#   - Every active token center is exactly two cells from a degree-1 wire endpoint in a cardinal direction.
#   - Passive stay-L tokens may already exist at far ends, but generator never places stray same-colored shapes
#     elsewhere; therefore pattern detection remains unambiguous.
#   - Token colors are still drawn from {1,2,3,4,6,7}, excluding wire colors 5/8/9, so token masks and wire
#     components stay separable after explicit token removal.

import random

import numpy as np

from arc_utils import components_mask, get_bg, neighbors4

_N4 = [(-1, 0), (1, 0), (0, -1), (0, 1)]

_STAY_L_OFF = [(-1, -1), (-1, 0), (-1, 1), (0, -1), (0, 0)]
_TRAVEL_L_OFF = [(0, 1), (1, -1), (1, 0), (1, 1)]
_SOLID_OFF = [
    (-1, -1), (-1, 0), (-1, 1),
    (0, -1), (0, 0), (0, 1),
    (1, -1), (1, 0), (1, 1),
]

_STAY_L_MASK = np.array(
    [
        [1, 1, 1],
        [1, 1, 0],
        [0, 0, 0],
    ],
    dtype=bool,
)
_TRAVEL_L_MASK = np.array(
    [
        [0, 0, 0],
        [0, 0, 1],
        [1, 1, 1],
    ],
    dtype=bool,
)


def _find_solid_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for maximal 3x3 solid blocks."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            col = int(sub[0, 0])
            if col == bg or np.any(sub != col):
                continue
            maximal = True
            for rr in range(r0, r0 + 3):
                for cc in range(c0, c0 + 3):
                    for nr, nc in neighbors4(rr, cc):
                        if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                            if int(g[nr, nc]) == col:
                                maximal = False
                                break
                    if not maximal:
                        break
                if not maximal:
                    break
            if maximal:
                found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _find_pattern_3x3(
    g: np.ndarray,
    bg: int,
    mask: np.ndarray,
) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for isolated 3x3 monochrome patterns defined by `mask`."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    first_rr, first_cc = map(int, np.argwhere(mask)[0])
    offsets = [(rr - 1, cc - 1) for rr, cc in np.argwhere(mask)]

    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            col = int(sub[first_rr, first_cc])
            if col == bg:
                continue
            if np.any(sub[mask] != col) or np.any(sub[~mask] != bg):
                continue
            isolated = True
            cr, cc = r0 + 1, c0 + 1
            for dr0, dc0 in offsets:
                rr, cc2 = cr + dr0, cc + dc0
                for nr, nc in neighbors4(rr, cc2):
                    if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                        if int(g[nr, nc]) == col:
                            isolated = False
                            break
                if not isolated:
                    break
            if isolated:
                found[(cr, cc)] = (col, (r0, c0))
    return found


def _components(mask: np.ndarray) -> list[list[tuple[int, int]]]:
    return [[(int(r), int(c)) for r, c in comp] for comp in components_mask(mask, connectivity=4)]


def _find_9rects(g: np.ndarray) -> list[tuple[set, dict]]:
    """Find color-9 rectangular blocks and their wire connections per face."""
    mask9 = g == 9
    if not mask9.any():
        return []
    h, w = g.shape
    rects = []
    for comp9 in components_mask(mask9, connectivity=4):
        cells = set((int(r), int(c)) for r, c in comp9)
        rs = [r for r, _ in cells]
        cs = [c for _, c in cells]
        r0, r1, c0, c1 = min(rs), max(rs), min(cs), max(cs)
        faces: dict[str, list[tuple[int, int]]] = {}
        for r, c in cells:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) not in cells and 0 <= nr < h and 0 <= nc < w and int(g[nr, nc]) in (5, 8):
                    face = "N" if nr < r0 else "S" if nr > r1 else "W" if nc < c0 else "E"
                    faces.setdefault(face, []).append((nr, nc))
        rects.append((cells, faces))
    return rects


_OPP = {"N": "S", "S": "N", "E": "W", "W": "E"}
_DIR2FACE = {(1, 0): "N", (-1, 0): "S", (0, 1): "W", (0, -1): "E"}
_FACE2DIR = {"S": (1, 0), "N": (-1, 0), "E": (0, 1), "W": (0, -1)}


def _trace_wire(
    comp: set[tuple[int, int]],
    start: tuple[int, int],
    dir0: tuple[int, int],
    h: int,
    w: int,
    rects_9: list[tuple[set, dict]],
) -> tuple[tuple[int, int], tuple[int, int]]:
    """
    Greedy wire following with 9-rect pass-through.

    At a color-9 rectangle: exit from opposite face (aligned with entry column/row).
    If no opposite exit, assert exactly one other exit face and use that.
    """
    cur, d, prev = start, dir0, None
    visited: set[tuple[tuple[int, int], tuple[int, int]]] = set()
    for _ in range(h * w * 4):
        if (cur, d) in visited:
            assert False, "wire trace looped — should not happen with 9-rect pass-through"
        visited.add((cur, d))

        jumped = False
        for cells9, faces9 in rects_9:
            if cur in cells9:
                entry_face = _DIR2FACE[d]
                opp = _OPP[entry_face]
                if opp in faces9:
                    exit_face = opp
                else:
                    others = [f for f in faces9 if f != entry_face]
                    assert len(others) == 1
                    exit_face = others[0]
                pts = faces9[exit_face]
                er, ec = cur
                if entry_face in ("N", "S"):
                    exit_cell = min(pts, key=lambda p: abs(p[1] - ec))
                else:
                    exit_cell = min(pts, key=lambda p: abs(p[0] - er))
                cur, d, prev = exit_cell, _FACE2DIR[exit_face], None
                jumped = True
                break
        if jumped:
            continue

        r, c = cur
        opts = [((nr, nc), nr - r, nc - c) for nr, nc in neighbors4(r, c) if (nr, nc) in comp]
        if not opts:
            return cur, d

        rev = (-d[0], -d[1])
        nonrev = [o for o in opts if (o[1], o[2]) != rev]
        opts2 = nonrev if nonrev else opts

        straight = [o for o in opts2 if (o[1], o[2]) == d]
        if straight:
            p, dr, dc = straight[0]
        else:
            perp = [o for o in opts2 if o[1] * d[0] + o[2] * d[1] == 0]
            if perp:
                p, dr, dc = sorted(perp, key=lambda x: (x[1], x[2]))[0]
            else:
                p, dr, dc = opts2[0]

        if p == prev:
            return cur, d

        prev = cur
        cur = p
        d = (dr, dc)

    assert False, "wire trace exceeded step limit"


def _stamp_token(grid: np.ndarray, center_r: int, center_c: int, color: int, offsets: list[tuple[int, int]]) -> None:
    """Write a token pattern onto the grid at the given center."""
    for dr, dc in offsets:
        grid[center_r + dr, center_c + dc] = color


def main(grid: np.ndarray) -> np.ndarray:
    """
    Send split 3x3 tokens through the wire permutation, using an asymmetric pair of complementary L-shapes.

    Input structure:
    - Background cells are 0. Non-background cells form one wire network with optional 9-rect junctions, plus
      3x3 monochrome tokens positioned exactly two cells away from wire endpoints.
    - Active tokens are either full 3x3 solids or the 4-cell travel-L half; the passive 5-cell stay-L half may
      already be present at a far endpoint.

    Rule:
    - A solid 3x3 token is decomposed into two fixed complementary parts inside the same 3x3 footprint:
      the 5-cell upper-left stay-L remains at the source, and the 4-cell lower-right travel-L is emitted to the
      endpoint reached by following that wire component.
    - A travel-L token already represents the transmitted half, so it stays unchanged and causes the far endpoint
      to receive the complementary 5-cell stay-L instead.

    Key insight:
    - The wire logic is unchanged; only the token alphabet changes. Solids split into a fixed 5+4 L-pair, and a
      pre-split travel-L is completed by routing its missing complement to the opposite endpoint.
    """
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    bg = get_bg(g)

    solids = _find_solid_3x3(g, bg)
    travel_ls = _find_pattern_3x3(g, bg, _TRAVEL_L_MASK)
    stay_ls = _find_pattern_3x3(g, bg, _STAY_L_MASK)

    track_mask = g != bg
    for _, (_, (r0, c0)) in solids.items():
        track_mask[r0 : r0 + 3, c0 : c0 + 3] = False
    for pats, offsets in ((travel_ls, _TRAVEL_L_OFF), (stay_ls, _STAY_L_OFF)):
        for (cr, cc) in pats.keys():
            for dr, dc in offsets:
                rr, cc2 = cr + dr, cc + dc
                if 0 <= rr < h and 0 <= cc2 < w:
                    track_mask[rr, cc2] = False

    comps = _components(track_mask)
    rects_9 = _find_9rects(g)

    out = g.copy()

    for (cr, cc), (col, (r0, c0)) in solids.items():
        out[r0 : r0 + 3, c0 : c0 + 3] = bg
        _stamp_token(out, cr, cc, col, _STAY_L_OFF)

    for pts in comps:
        comp = set(pts)
        if len(comp) < 4:
            continue

        deg = {p: 0 for p in comp}
        for r, c in comp:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) in comp:
                    deg[(r, c)] += 1
        endpoints = [p for p in comp if deg[p] <= 1]
        if not endpoints:
            continue

        for ep in endpoints:
            er, ec = ep
            for odr, odc in _N4:
                cen = (er + 2 * odr, ec + 2 * odc)
                if not (0 <= cen[0] < h and 0 <= cen[1] < w):
                    continue

                if cen in solids:
                    col, _ = solids[cen]
                    dir_in = (-odr, -odc)
                    end, dd = _trace_wire(comp, ep, dir_in, h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    _stamp_token(out, dest[0], dest[1], col, _TRAVEL_L_OFF)
                elif cen in travel_ls:
                    col, _ = travel_ls[cen]
                    dir_in = (-odr, -odc)
                    end, dd = _trace_wire(comp, ep, dir_in, h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    _stamp_token(out, dest[0], dest[1], col, _STAY_L_OFF)

    return out


