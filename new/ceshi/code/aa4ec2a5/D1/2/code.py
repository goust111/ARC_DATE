# Variant of aa4ec2a5
# Dimension: D1 — 轮廓绘制方式 (transform)
# Change: 在每个蓝色对象周围绘制1像素宽的8邻域（Chebyshev距离=1）红色轮廓... → 内轮廓而非外轮廓

from __future__ import annotations

import random

import numpy as np

from arc_utils import bbox_coords, components_mask, find_components, get_bg, is_contiguous


# Design analysis
# source_task: none
# a) concretization_and_trace:
#    - Input stays the same: a yellow background with 3-4 blue 4-connected components; 1-2 of them
#      are hollow and enclose rectangular background holes.
#    - The original solver paints red on background cells at Chebyshev distance 1 from each component.
#      The variant inverts only that contour direction: red now lands on the component-side cells that
#      touch the exterior under the same 8-neighborhood notion.
#    - Concrete trace on a 3x3 solid block:
#      original: the 3x3 blue block remains blue and gains a red halo outside it;
#      variant: the outer 8 cells of that 3x3 block become red and only the center stays blue.
#      This is a true shrink effect rather than background overwrite.
#    - Concrete trace on a hollow object:
#      original logic first recolors the shell to teal and the hole to magenta, then computes the
#      contour from "shell + hole" so the hole does not receive a red ring.
#      Variant keeps that same solidification step, but colors the internal boundary cells of that
#      solid mask; therefore only the outer shell edge turns red, while hole-adjacent shell pixels
#      stay teal and the hole stays magenta.
# b) complexity_calibration:
#    - Only the contour side flips; object count, hole mechanics, colors, and spacing stay stable.
#    - To keep the new rule visually inferable, the generator rejects grids where too few components
#      have any surviving non-red core after the shrink. Otherwise many thin shapes would collapse to
#      all-red blobs and the inversion would be harder to see from a few examples.
# c) implicit_assumption_audit_for_main:
#    - _interior_holes still assumes holes are detected inside each component bbox; that remains valid.
#    - The old _outline_mask depended on writing only onto background cells. That assumption breaks for
#      this variant because red must overwrite object cells instead; the new helper returns mask cells.
#    - The old "solid = mask + holes" step must remain, otherwise hollow objects would gain a second
#      red contour around the magenta hole, which is not the inverted analogue of the original task.
#    - The assignment must target only original object cells, not the filled-in hole cells used during
#      contour computation, so the final write intersects the inner contour with mask.
# d) placement_legality:
#    - Input placement constraints remain safe: components are still separated by Chebyshev >= 3 and
#      at least 1 cell from the border, so the new red shrink never merges components or leaves the grid.
#    - Because red is written inside each object, border clearance is less critical than before, but the
#      original spacing still guarantees clean isolated examples.
# e) visual_observability:
#    - Human-solvable evidence comes from blue/teal regions shrinking inward instead of yellow regions
#      being overwritten outside. At least two components with surviving cores make that contrast obvious.
#    - Small components are still allowed, but they appear alongside thicker ones so the rule is not
#      misread as "paint every object red".
# f) visual_cleanliness:
#    - No new overlaps are introduced because red replaces existing object pixels only.
#    - Hollow objects still use only three output colors locally: red boundary, teal shell interior,
#      magenta hole; this keeps the output structured rather than noisy.
# g) color_change_inference:
#    - Color usage remains sparse and role-based: blue/teal are object interiors, magenta marks holes,
#      and red marks the contour. The only changed mapping is spatial: contour pixels moved from outside
#      the object onto its boundary cells.


def _coords_mask(shape: tuple[int, int], coords: np.ndarray) -> np.ndarray:
    mask = np.zeros(shape, dtype=bool)
    mask[coords[:, 0], coords[:, 1]] = True
    return mask


def _interior_holes(mask: np.ndarray, coords: np.ndarray) -> list[np.ndarray]:
    r0, c0, r1, c1 = bbox_coords(coords)
    sub = mask[r0 : r1 + 1, c0 : c1 + 1]

    holes: list[np.ndarray] = []
    for hole in components_mask(~sub, connectivity=4):
        touches_edge = np.any(
            (hole[:, 0] == 0)
            | (hole[:, 1] == 0)
            | (hole[:, 0] == sub.shape[0] - 1)
            | (hole[:, 1] == sub.shape[1] - 1)
        )
        if not bool(touches_edge):
            shifted = hole.copy()
            shifted[:, 0] += int(r0)
            shifted[:, 1] += int(c0)
            holes.append(shifted)
    return holes


def _inner_outline_mask(mask: np.ndarray) -> np.ndarray:
    padded = np.pad(mask, 1, constant_values=False)
    outline = np.zeros_like(mask, dtype=bool)
    rows, cols = np.where(mask)
    for r, c in zip(rows, cols):
        if not padded[r : r + 3, c : c + 3].all():
            outline[r, c] = True
    return outline


def _component_core_count(grid: np.ndarray, bg: int) -> int:
    core_components = 0
    for comp in find_components(grid, bg=bg, connectivity=4, monochromatic=True):
        coords = comp["coords"]
        mask = _coords_mask(grid.shape, coords)
        holes = _interior_holes(mask, coords)

        solid = mask.copy()
        for hole in holes:
            solid[hole[:, 0], hole[:, 1]] = True

        inner = _inner_outline_mask(solid) & mask
        if np.any(mask & ~inner):
            core_components += 1
    return core_components


def main(grid: np.ndarray) -> np.ndarray:
    """
    Recolor hollow objects, then paint red on the inside edge of each object.

    Input structure:
    - A uniform background holds several blue 4-connected foreground components.
    - Some components surround enclosed 4-connected background holes inside their bbox.

    Rule:
    - For every foreground component, recolor its boundary cells red (2) on the object side.
    - The boundary is the one-cell 8-neighborhood inner contour: object cells touching the exterior
      of the component's solid shape become red.
    - If a component encloses holes, recolor the component to teal (8) and those holes to magenta (6)
      before applying the inner contour.

    Key insight: Hollow components are first treated as solid by temporarily filling their holes for
    contour detection, so the red shrink follows only the outer perimeter rather than the hole rim.
    """
    g = np.asarray(grid, dtype=int)
    bg = get_bg(g)
    out = g.copy()

    for comp in find_components(g, bg=bg, connectivity=4, monochromatic=True):
        coords = comp["coords"]
        mask = _coords_mask(g.shape, coords)
        holes = _interior_holes(mask, coords)

        solid = mask.copy()
        if holes:
            out[mask] = 8
            for hole in holes:
                out[hole[:, 0], hole[:, 1]] = 6
                solid[hole[:, 0], hole[:, 1]] = True

        inner = _inner_outline_mask(solid) & mask
        out[inner] = 2

    return out


