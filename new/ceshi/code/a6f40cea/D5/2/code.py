# Variant of a6f40cea
# Dimension: D5 — 输出裁剪方式 (grid_shape)
# Change: 裁剪为封闭矩形框架的内部区域尺寸（去掉边框本身）... → 包含边框的裁剪

# Design analysis for the D5 variant
# ----------------------------------
# variant_spec:
#   core_change:
#     original_output: crop only the closed frame interior, shape = (r1-r0-1, c1-c0-1)
#     new_output: crop the whole closed frame including its 1px border,
#       shape = (r1-r0+1, c1-c0+1)
#   preserved_structure:
#     input still contains one uniform-filled closed rectangle, 2-3 outside ring-touching
#       components, and optional distractor blobs.
#     path semantics stay the same: monochrome traces become solid Manhattan segments,
#       two-color traces become alternating Manhattan paths, and U-pairs still become
#       full-span stripes.
#   visible_effect:
#     the output now shows the border color as a decorative boundary, while the paths
#       remain strictly inside that frame. This makes the D5 change directly observable.
#
# a) Concrete behavior trace:
#    Example: suppose the frame bbox is rows 5..11 and cols 8..17, so the old output
#    was 5x8 and the new output is 7x10. A top-side ring touch at input (4, 12) used
#    to map to output (0, 3), which was the top row of the old output. In the variant
#    it must map to (1, 4), because row 0 / col 0 are now reserved for the preserved
#    frame border. The path geometry is unchanged; only the crop coordinate system shifts.
# b) Complexity calibration:
#    Keeping the border is visually obvious and does not add new matching ambiguity. The
#    border color is already present in the input, so the solver still needs to identify
#    the same frame and project the same outside components; it simply retains one more
#    visible layer in the crop.
# c) Implicit assumptions that break if left unchanged:
#    - `outH/outW` based on interior size would silently drop the border again.
#    - `map_to_out()` previously clamped ring touches onto row/col 0 or outH-1/outW-1.
#      In the variant those locations are border cells and must stay reserved for `bc`.
#    - `inside_corner()` and deferred stripe logic previously treated 0 / outH-1 /
#      outW-1 as interior edges. Those thresholds must move inward by one cell.
#    - `expected` in the generator previously started as the fill-only interior, so it
#      would wrongly validate a solver that ignored the new border requirement.
# d) Placement legality:
#    The input generator can keep the same margins and external open-rectangle placement,
#    because only the output crop changed. Paths are still painted only on interior cells,
#    now offset by +1 inside the expected crop so they never overwrite the border.
# e) Visual observability:
#    Across 2-4 examples a human can see that the output is not a bare interior crop
#    anymore: every output retains the same rectangular border color found in the input.
#    No hidden color-id ordering is introduced.
# f) Visual cleanliness:
#    The border is a single clean ring around the result. External traces are still
#    discarded, so the output remains uncluttered: border outside, paths inside.
# g) Color inference:
#    No new color mapping is introduced. The preserved border keeps its original border
#    color, and path colors still come directly from the outside traces.
#
# Post-change solver assumptions and generator guarantees:
# - Solver assumption: all projected path coordinates must stay off the preserved border.
#   Generator guarantee: ring touches are never placed at frame corners, and solver-side
#   clamping forces all projected coordinates into the interior band [1:-1, 1:-1].
# - Solver assumption: deferred monochrome stripes should span between opposite interior
#   sides, not on the border itself. Generator guarantee: U-pair touches still land on
#   opposite interior edges after the +1 offset.

from __future__ import annotations

from collections import Counter, defaultdict
import random

import numpy as np
from scipy.ndimage import label

from arc_utils import STRUCT4, get_bg, neighbors4


def _find_framed_rect_uniform_fill(
    g: np.ndarray,
    *,
    bg: int | None = None,
    structure=STRUCT4,
) -> tuple[int, int, int, int, int, int] | None:
    """
    Detect the main 1px-thick rectangular frame with uniform interior fill.

    Returns (r0, c0, r1, c1, border_color, fill_color) for the largest such rectangle, else None.
    """
    if bg is None:
        bg = int(get_bg(g))
    else:
        bg = int(bg)

    best = None  # (area, r0,c0,r1,c1, bc, fill)
    for bc in sorted(set(map(int, g.flatten())) - {int(bg)}):
        lab, n = label(g == int(bc), structure=structure)
        for cid in range(1, int(n) + 1):
            pts = np.argwhere(lab == int(cid))
            if int(len(pts)) < 8:
                continue

            r0, c0 = pts.min(axis=0)
            r1, c1 = pts.max(axis=0)
            r0, c0, r1, c1 = map(int, (r0, c0, r1, c1))
            h = int(r1 - r0 + 1)
            w = int(c1 - c0 + 1)
            if h < 3 or w < 3:
                continue

            per = int(2 * (h + w) - 4)
            if int(len(pts)) != per:
                continue
            if not (g[r0, c0 : c1 + 1] == int(bc)).all():
                continue
            if not (g[r1, c0 : c1 + 1] == int(bc)).all():
                continue
            if not (g[r0 : r1 + 1, c0] == int(bc)).all():
                continue
            if not (g[r0 : r1 + 1, c1] == int(bc)).all():
                continue

            inner = g[r0 + 1 : r1, c0 + 1 : c1]
            if inner.size == 0:
                continue
            fill = int(Counter(inner.flatten()).most_common(1)[0][0])
            if fill == int(bc):
                continue
            if not (inner == int(fill)).all():
                continue

            area = int(h * w)
            cand = (area, r0, c0, r1, c1, int(bc), int(fill))
            if best is None or cand[0] > best[0]:
                best = cand

    if best is None:
        return None
    _area, r0, c0, r1, c1, bc, fill = best
    return int(r0), int(c0), int(r1), int(c1), int(bc), int(fill)


def _make_framed_output(height: int, width: int, border_color: int, fill_color: int) -> np.ndarray:
    """Create a uniform-filled rectangle crop whose outer ring is the frame border."""
    out = np.full((int(height), int(width)), int(fill_color), dtype=int)
    out[0, :] = int(border_color)
    out[-1, :] = int(border_color)
    out[:, 0] = int(border_color)
    out[:, -1] = int(border_color)
    return out


def main(grid: np.ndarray) -> np.ndarray:
    """
    Reconstruct the paths inside the main frame, then crop the full frame including its border.

    Input structure:
    - A uniform background, one 1px closed rectangular frame, and a uniformly filled interior.
    - Colored components lie outside the frame and touch the ring adjacent to the frame edges.

    Rule:
    - Output the closed frame crop itself, preserving the border color on all four sides.
    - Project each ring-touch position inward onto the frame interior, one cell inside the border.
    - Monochrome components paint solid Manhattan segments; two-color components paint alternating ones.

    Key insight: The outside traces still determine the same interior geometry; the variant only changes
    the crop coordinate system, so the preserved border must stay untouched while all projected paths
    are shifted one cell inward.
    """
    g = np.array(grid, dtype=int)
    H, W = g.shape
    bg = int(get_bg(g))

    found = _find_framed_rect_uniform_fill(g, bg=int(bg))
    assert not (found is None)
    r0, c0, r1, c1, bc, fill = found
    outH = int(r1 - r0 + 1)
    outW = int(c1 - c0 + 1)
    out = _make_framed_output(outH, outW, int(bc), int(fill))

    def map_to_out(rr: int, cc: int) -> tuple[int, int]:
        # Project ring-touch cells onto the interior band; border cells 0/-1 stay reserved for `bc`.
        r = max(1, min(outH - 2, int(rr - r0)))
        c = max(1, min(outW - 2, int(cc - c0)))
        return int(r), int(c)

    def build_manhattan(p1: tuple[int, int], p2: tuple[int, int], cornerA: bool) -> list[tuple[int, int]]:
        (ra, ca), (rb, cb) = p1, p2
        if ra == rb:
            step = 1 if cb >= ca else -1
            return [(int(ra), int(c)) for c in range(int(ca), int(cb) + step, step)]
        if ca == cb:
            step = 1 if rb >= ra else -1
            return [(int(r), int(ca)) for r in range(int(ra), int(rb) + step, step)]
        if cornerA:
            step = 1 if rb >= ra else -1
            path = [(int(r), int(ca)) for r in range(int(ra), int(rb) + step, step)]
            step = 1 if cb >= ca else -1
            path += [(int(rb), int(c)) for c in range(int(ca) + step, int(cb) + step, step)]
            return path
        step = 1 if cb >= ca else -1
        path = [(int(ra), int(c)) for c in range(int(ca), int(cb) + step, step)]
        step = 1 if rb >= ra else -1
        path += [(int(r), int(cb)) for r in range(int(ra) + step, int(rb) + step, step)]
        return path

    def inside_corner(p1: tuple[int, int], p2: tuple[int, int], cornerA: bool) -> bool:
        (ra, ca), (rb, cb) = p1, p2
        if ra == rb or ca == cb:
            return True
        corner = (rb, ca) if cornerA else (ra, cb)
        rr, cc = corner
        return (1 < rr < outH - 2) and (1 < cc < outW - 2)

    comp_mask = (g != int(bg)) & (g != int(fill)) & (g != int(bc))
    clab, cn = label(comp_mask, structure=STRUCT4)

    ring = set()
    for cc in range(c0, c1 + 1):
        for rr in (r0 - 1, r1 + 1):
            if 0 <= rr < H:
                ring.add((int(rr), int(cc)))
    for rr in range(r0, r1 + 1):
        for cc in (c0 - 1, c1 + 1):
            if 0 <= cc < W:
                ring.add((int(rr), int(cc)))

    comp_pts: dict[int, list[tuple[int, int, int]]] = defaultdict(list)
    for rr, cc in ring:
        cid = int(clab[rr, cc])
        if cid == 0:
            continue
        col = int(g[rr, cc])
        mr, mc = map_to_out(rr, cc)
        comp_pts[cid].append((mr, mc, col))

    comp_cols: dict[int, list[int]] = {}
    for cid in range(1, int(cn) + 1):
        comp_cols[cid] = sorted(set(map(int, g[clab == int(cid)].flatten())))

    deferred: dict[int, set[tuple[int, int]]] = defaultdict(set)

    for cid, pts in comp_pts.items():
        if len(pts) < 2:
            continue
        cols = comp_cols.get(cid, [])
        if not cols:
            continue

        hist: dict[tuple[int, int], Counter] = defaultdict(Counter)
        for r, c, col in pts:
            hist[(int(r), int(c))][int(col)] += 1

        coords = list(hist.keys())

        if len(cols) == 1:
            colv = int(cols[0])
            uniq = coords
            rows = {r for r, _c in uniq}
            cols2 = {c for _r, c in uniq}
            if len(rows) == 1 or len(cols2) == 1:
                for p in uniq:
                    deferred[colv].add((int(p[0]), int(p[1])))
                continue

            best = None
            for i in range(len(uniq)):
                for j in range(i + 1, len(uniq)):
                    d = abs(uniq[i][0] - uniq[j][0]) + abs(uniq[i][1] - uniq[j][1])
                    if best is None or d > best[0]:
                        best = (d, uniq[i], uniq[j])
            if best is None:
                continue
            _d, p1, p2 = best
            pathA = build_manhattan(p1, p2, True)
            pathB = build_manhattan(p1, p2, False)
            chosen = pathB if (inside_corner(p1, p2, False) and not inside_corner(p1, p2, True)) else pathA
            for rr, cc in chosen:
                out[int(rr), int(cc)] = int(colv)
            continue

        if len(cols) == 2:
            best = None
            for i in range(len(coords)):
                for j in range(i + 1, len(coords)):
                    d = abs(coords[i][0] - coords[j][0]) + abs(coords[i][1] - coords[j][1])
                    if best is None or d > best[0]:
                        best = (d, coords[i], coords[j])
            if best is None:
                continue
            _d, a, b = best
            ca, cb = map(int, cols)
            ha = int(hist[a].most_common(1)[0][0])
            hb = int(hist[b].most_common(1)[0][0])

            pathA = build_manhattan(a, b, True)
            pathB = build_manhattan(a, b, False)
            path = pathB if (inside_corner(a, b, False) and not inside_corner(a, b, True)) else pathA

            def paint_alt(path_pts: list[tuple[int, int]], start_color: int):
                cur = int(start_color)
                for rr, cc in path_pts:
                    out[int(rr), int(cc)] = int(cur)
                    cur = int(cb) if cur == int(ca) else int(ca)

            chosen = None
            for path_pts in (path, list(reversed(path))):
                for start_color in (ca, cb):
                    end_color = start_color if ((len(path_pts) - 1) % 2 == 0) else (cb if start_color == ca else ca)
                    if int(start_color) != int(ha):
                        continue
                    if int(end_color) != int(hb):
                        continue
                    chosen = (path_pts, int(start_color))
                    break
                if chosen is not None:
                    break

            assert chosen is not None

            path_pts, start_color = chosen
            paint_alt(path_pts, start_color)
            continue

    for col, pts in deferred.items():
        pts = list(pts)
        if not pts:
            continue
        tops = [p for p in pts if p[0] == 1]
        bots = [p for p in pts if p[0] == outH - 2]
        if tops and bots:
            for cc in sorted({c for _r, c in pts}):
                rs = [r for r, c in pts if c == cc]
                for rr in range(min(rs), max(rs) + 1):
                    out[int(rr), int(cc)] = int(col)
            continue
        lefts = [p for p in pts if p[1] == 1]
        rights = [p for p in pts if p[1] == outW - 2]
        if lefts and rights:
            for rr in sorted({r for r, _c in pts}):
                cs = [c for r, c in pts if r == rr]
                for cc in range(min(cs), max(cs) + 1):
                    out[int(rr), int(cc)] = int(col)
            continue
        if len(pts) == 1:
            rr, cc = pts[0]
            out[int(rr), int(cc)] = int(col)
            continue
        best = None
        for i in range(len(pts)):
            for j in range(i + 1, len(pts)):
                d = abs(pts[i][0] - pts[j][0]) + abs(pts[i][1] - pts[j][1])
                if best is None or d > best[0]:
                    best = (d, pts[i], pts[j])
        if best is None:
            continue
        _d, p1, p2 = best
        pathA = build_manhattan(p1, p2, True)
        pathB = build_manhattan(p1, p2, False)
        chosen = pathB if (inside_corner(p1, p2, False) and not inside_corner(p1, p2, True)) else pathA
        for rr, cc in chosen:
            out[int(rr), int(cc)] = int(col)

    return out


