import random

import numpy as np


BG = 0


def _marker_pairs(g: np.ndarray):
    pairs = []
    marker_cells = set()
    for color in sorted(set(map(int, g.ravel())) - {BG}):
        pts = [(int(r), int(c)) for r, c in zip(*np.where(g == color))]
        if len(pts) == 2:
            a, b = pts
            pairs.append((a, b))
            marker_cells.update(pts)
    assert pairs, "expected same-color point pairs"
    return pairs, marker_cells


def _transform(pair, cell):
    (r0, c0), (r1, c1) = pair
    r, c = cell
    if r0 == r1:
        return r, c0 + c1 - c
    if c0 == c1:
        return r0 + r1 - r, c
    return r0 + r1 - r, c0 + c1 - c


def main(grid: np.ndarray) -> np.ndarray:
    """
    Repeatedly complete missing pattern cells through the mirror/rotation
    transforms generated by same-color point pairs. Marker points stay fixed and
    do not themselves propagate color.
    """
    g = np.asarray(grid, dtype=int)
    out = g.copy()
    pairs, marker_cells = _marker_pairs(g)
    h, w = out.shape

    changed = True
    while changed:
        changed = False
        additions = {}
        for r in range(h):
            for c in range(w):
                if out[r, c] != BG or (r, c) in marker_cells:
                    continue
                colors = set()
                for pair in pairs:
                    tr, tc = _transform(pair, (r, c))
                    if 0 <= tr < h and 0 <= tc < w and (tr, tc) not in marker_cells:
                        color = int(out[tr, tc])
                        if color != BG:
                            colors.add(color)
                if colors:
                    assert len(colors) == 1, "ambiguous transform completion"
                    additions[(r, c)] = colors.pop()
        for (r, c), color in additions.items():
            out[r, c] = color
            changed = True
    for r, c in marker_cells:
        out[r, c] = g[r, c]
    return out


def _apply_all(pairs, cell):
    return [_transform(pair, cell) for pair in pairs]


def _closure(seed_map, pairs, h, w, marker_cells):
    full = dict(seed_map)
    changed = True
    while changed:
        changed = False
        for cell, color in list(full.items()):
            for nxt in _apply_all(pairs, cell):
                r, c = nxt
                if not (0 <= r < h and 0 <= c < w) or nxt in marker_cells:
                    continue
                if nxt in full and full[nxt] != color:
                    return None
                if nxt not in full:
                    full[nxt] = color
                    changed = True
    return full


def _orbit(cell, pairs, h, w, marker_cells):
    seen = {cell}
    changed = True
    while changed:
        changed = False
        for cur in list(seen):
            for nxt in _apply_all(pairs, cur):
                r, c = nxt
                if 0 <= r < h and 0 <= c < w and nxt not in marker_cells and nxt not in seen:
                    seen.add(nxt)
                    changed = True
    return seen


def _gen_attempt():
    n = random.choice([15, 17, 19])
    center = n // 2
    grid = np.zeros((n, n), dtype=int)
    pair_specs = [
        (7, (1, center - 4), (1, center + 4)),
        (8, (center - 4, 1), (center + 4, 1)),
        (9, (center - 3, center - 3), (center + 3, center + 3)),
    ]
    pairs = []
    marker_cells = set()
    for color, a, b in pair_specs:
        grid[a] = color
        grid[b] = color
        pairs.append((a, b))
        marker_cells.update([a, b])

    seeds = {}
    palette = [1, 2, 3, 4]
    for _ in range(random.randint(6, 9)):
        for _try in range(100):
            r = random.randint(center - 3, center)
            c = random.randint(center + 1, center + 4)
            if (r, c) not in seeds and (r, c) not in marker_cells:
                seeds[(r, c)] = random.choice(palette)
                break
    full = _closure(seeds, pairs, n, n, marker_cells)
    if full is None or len(full) < 16:
        return None

    kept = {}
    seen = set()
    for cell in list(full):
        if cell in seen:
            continue
        orb = _orbit(cell, pairs, n, n, marker_cells) & set(full)
        seen |= orb
        same_color = {p for p in orb if full[p] == full[cell]}
        if same_color != orb:
            return None
        cells = list(orb)
        random.shuffle(cells)
        keep_n = random.randint(1, max(1, len(cells) - 1))
        for p in cells[:keep_n]:
            kept[p] = full[p]
    counts = {color: list(kept.values()).count(color) for color in palette}
    if any(v == 2 for v in counts.values()):
        return None
    if len(kept) >= len(full):
        return None
    for (r, c), color in kept.items():
        grid[r, c] = color
    try:
        out = main(grid)
    except Exception:
        return None
    for (r, c), color in full.items():
        if out[r, c] != color:
            return None
    return grid


def generate_input() -> np.ndarray:
    for _ in range(500):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate valid input")
