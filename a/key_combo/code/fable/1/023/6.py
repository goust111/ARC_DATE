from __future__ import annotations

from collections import Counter, deque
import random

import numpy as np


BG = 0
PATH_COLOR = 5
MOTIF_COLORS = (1, 2, 3, 4, 6, 7, 8, 9)
DIR4 = [(-1, 0), (1, 0), (0, -1), (0, 1)]


def _get_bg(grid: np.ndarray) -> int:
    return int(Counter(map(int, grid.flat)).most_common(1)[0][0])


def _in_bounds(shape: tuple[int, int], r: int, c: int) -> bool:
    h, w = shape
    return 0 <= int(r) < int(h) and 0 <= int(c) < int(w)


def _bbox_from_coords(coords: list[tuple[int, int]]) -> tuple[int, int, int, int]:
    rows = [r for r, _c in coords]
    cols = [c for _r, c in coords]
    return min(rows), min(cols), max(rows), max(cols)


def _find_components_of_color(grid: np.ndarray, color: int) -> list[dict]:
    h, w = grid.shape
    seen = np.zeros((h, w), dtype=bool)
    out: list[dict] = []
    for r in range(h):
        for c in range(w):
            if seen[r, c] or int(grid[r, c]) != int(color):
                continue
            queue = deque([(r, c)])
            seen[r, c] = True
            coords: list[tuple[int, int]] = []
            while queue:
                rr, cc = queue.popleft()
                coords.append((rr, cc))
                for dr, dc in DIR4:
                    nr = rr + dr
                    nc = cc + dc
                    if _in_bounds((h, w), nr, nc) and not seen[nr, nc] and int(grid[nr, nc]) == int(color):
                        seen[nr, nc] = True
                        queue.append((nr, nc))
            out.append(
                {
                    "color": int(color),
                    "coords": coords,
                    "bbox": _bbox_from_coords(coords),
                    "area": len(coords),
                }
            )
    return out


def _component_endpoints(coords: list[tuple[int, int]]) -> list[tuple[int, int]]:
    coord_set = set(coords)
    endpoints = []
    for r, c in coords:
        degree = 0
        for dr, dc in DIR4:
            if (r + dr, c + dc) in coord_set:
                degree += 1
        if degree == 1:
            endpoints.append((r, c))
    assert len(endpoints) == 2, "each gray path must have exactly two endpoints"
    return sorted(endpoints)


def _extract_motif_cells(grid: np.ndarray, bg: int) -> tuple[list[tuple[int, int, int]], tuple[int, int, int, int]]:
    coords = np.argwhere((grid != int(bg)) & (grid != PATH_COLOR))
    assert len(coords) > 0, "expected a colored motif stamp"
    motif_cells = [(int(r), int(c), int(grid[r, c])) for r, c in coords]
    bbox = (
        int(coords[:, 0].min()),
        int(coords[:, 1].min()),
        int(coords[:, 0].max()),
        int(coords[:, 1].max()),
    )
    return motif_cells, bbox


def _visible_lattice_shifts(
    shape: tuple[int, int],
    bbox: tuple[int, int, int, int],
    v1: tuple[int, int],
    v2: tuple[int, int],
    coeff_limit: int,
) -> dict[tuple[int, int], tuple[int, int]]:
    h, w = shape
    r0, c0, r1, c1 = bbox
    shifts: dict[tuple[int, int], tuple[int, int]] = {}
    for i in range(-int(coeff_limit), int(coeff_limit) + 1):
        for j in range(-int(coeff_limit), int(coeff_limit) + 1):
            dr = i * int(v1[0]) + j * int(v2[0])
            dc = i * int(v1[1]) + j * int(v2[1])
            if r1 + dr < 0 or r0 + dr >= h or c1 + dc < 0 or c0 + dc >= w:
                continue
            shifts.setdefault((dr, dc), (i, j))
    return shifts


def _stamp_lattice(
    shape: tuple[int, int],
    motif_cells: list[tuple[int, int, int]],
    motif_bbox: tuple[int, int, int, int],
    v1: tuple[int, int],
    v2: tuple[int, int],
    bg: int,
    coeff_limit: int,
) -> tuple[np.ndarray, dict[tuple[int, int], tuple[int, int]], bool]:
    h, w = shape
    out = np.full((h, w), int(bg), dtype=int)
    covered = np.zeros((h, w), dtype=bool)
    shifts = _visible_lattice_shifts(shape, motif_bbox, v1, v2, coeff_limit=coeff_limit)
    overlap = False
    for (dr, dc), _coeffs in shifts.items():
        for r, c, color in motif_cells:
            rr = r + dr
            cc = c + dc
            if not _in_bounds(shape, rr, cc):
                continue
            if covered[rr, cc]:
                overlap = True
                if int(out[rr, cc]) != int(color):
                    continue
            covered[rr, cc] = True
            out[rr, cc] = int(color)
    return out, shifts, overlap


def main(grid: np.ndarray) -> np.ndarray:
    """
    Stamp the colored motif across the full lattice generated by the endpoint deltas of two gray zigzag paths.

    Input structure:
    - A black-dominant background contains one small multicolor motif stamp.
    - Two disconnected gray 4-connected polylines also appear on the canvas.
    - Each gray polyline has exactly two endpoints and does not belong to the motif.

    Rule:
    - For each gray polyline, take the difference between its two endpoint coordinates to obtain a generator vector.
    - Keep the motif at its original position and stamp identical translated copies at every integer combination
      `i*v1 + j*v2`, allowing positive, negative, and zero coefficients.
    - Clip any out-of-bounds part of a stamped copy and erase the two gray polylines from the output.

    Key insight:
    - The turns of each polyline are irrelevant; only the net endpoint displacement matters.
    - The two endpoint vectors span a 2D lattice, so mixed offsets such as `v1 + v2` must also be stamped.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2 and g.size > 0, "expected a non-empty 2D grid"

    bg = _get_bg(g)
    gray_components = _find_components_of_color(g, PATH_COLOR)
    assert len(gray_components) == 2, "expected exactly two gray zigzag paths"

    vectors = []
    for component in gray_components:
        a, b = _component_endpoints(component["coords"])
        vectors.append((int(b[0] - a[0]), int(b[1] - a[1])))

    v1, v2 = vectors
    det = v1[0] * v2[1] - v1[1] * v2[0]
    assert det != 0, "the two endpoint deltas must span a 2D lattice"

    motif_cells, motif_bbox = _extract_motif_cells(g, bg)
    out, _shifts, _overlap = _stamp_lattice(
        g.shape,
        motif_cells,
        motif_bbox,
        v1,
        v2,
        bg=bg,
        coeff_limit=2 * max(g.shape),
    )
    return out


GRID_RANGE = (18, 28)
MOTIF_SIZE_RANGE = (2, 4)
MOTIF_CELL_RANGE = (4, 8)
VISIBLE_STAMPS_RANGE = (5, 11)
CLIPPED_STAMPS_RANGE = (1, 4)
MAX_GENERATION_ATTEMPTS = 400
VECTOR_CHOICES = [
    (dr, dc)
    for dr in range(-8, 9)
    for dc in range(-8, 9)
    if abs(dr) >= 2 and abs(dc) >= 2 and 6 <= abs(dr) + abs(dc) <= 12
]


def _random_partition(total: int, parts: int) -> list[int]:
    if parts == 1:
        return [int(total)]
    cuts = sorted(random.sample(range(1, int(total)), int(parts) - 1))
    prev = 0
    out = []
    for cut in cuts + [int(total)]:
        out.append(cut - prev)
        prev = cut
    return out


def _grow_connected_shape(height: int, width: int, n_cells: int) -> list[tuple[int, int]]:
    coords = {(random.randrange(height), random.randrange(width))}
    while len(coords) < n_cells:
        frontier = []
        for r, c in coords:
            for dr, dc in DIR4:
                nr = r + dr
                nc = c + dc
                if 0 <= nr < height and 0 <= nc < width and (nr, nc) not in coords:
                    frontier.append((nr, nc))
        coords.add(random.choice(frontier))
    arr = np.array(sorted(coords), dtype=int)
    arr[:, 0] -= int(arr[:, 0].min())
    arr[:, 1] -= int(arr[:, 1].min())
    return [(int(r), int(c)) for r, c in arr]


def _make_motif_patch() -> np.ndarray:
    while True:
        raw_h = random.randint(*MOTIF_SIZE_RANGE)
        raw_w = random.randint(*MOTIF_SIZE_RANGE)
        max_cells = min(raw_h * raw_w, MOTIF_CELL_RANGE[1])
        n_cells = random.randint(MOTIF_CELL_RANGE[0], max_cells)
        coords = _grow_connected_shape(raw_h, raw_w, n_cells)
        h = max(r for r, _c in coords) + 1
        w = max(c for _r, c in coords) + 1
        if h < 2 or w < 2:
            continue
        patch = np.full((h, w), BG, dtype=int)
        n_colors = random.randint(2, min(4, len(coords)))
        palette = random.sample(MOTIF_COLORS, n_colors)
        shuffled = coords[:]
        random.shuffle(shuffled)
        for color, (r, c) in zip(palette, shuffled):
            patch[r, c] = int(color)
        for r, c in shuffled[n_colors:]:
            patch[r, c] = int(random.choice(palette))
        if len(set(int(v) for v in patch[patch != BG])) >= 2:
            return patch


def _motif_cells_from_patch(patch: np.ndarray, anchor: tuple[int, int]) -> list[tuple[int, int, int]]:
    ar, ac = anchor
    coords = np.argwhere(patch != BG)
    return [(int(ar + r), int(ac + c), int(patch[r, c])) for r, c in coords]


def _classify_shifts(
    shifts: dict[tuple[int, int], tuple[int, int]],
    motif_bbox: tuple[int, int, int, int],
    shape: tuple[int, int],
) -> tuple[int, int, bool, bool, bool, bool]:
    h, w = shape
    r0, c0, r1, c1 = motif_bbox
    clipped = 0
    has_axis_1 = False
    has_axis_2 = False
    has_combo = False
    has_full_combo = False
    for (dr, dc), (i, j) in shifts.items():
        full = 0 <= r0 + dr and r1 + dr < h and 0 <= c0 + dc and c1 + dc < w
        if not full:
            clipped += 1
        if i != 0 and j == 0:
            has_axis_1 = True
        if i == 0 and j != 0:
            has_axis_2 = True
        if i != 0 and j != 0:
            has_combo = True
            if full:
                has_full_combo = True
    return len(shifts), clipped, has_axis_1, has_axis_2, has_combo, has_full_combo


def _choose_layout(
    shape: tuple[int, int],
    patch: np.ndarray,
) -> dict | None:
    h, w = shape
    ph, pw = patch.shape
    anchors = [(r, c) for r in range(1, h - ph) for c in range(1, w - pw)]
    if not anchors:
        return None
    random.shuffle(anchors)

    for _ in range(220):
        v1 = random.choice(VECTOR_CHOICES)
        v2 = random.choice(VECTOR_CHOICES)
        det = v1[0] * v2[1] - v1[1] * v2[0]
        if abs(det) < max(18, ph * pw * 3) or abs(det) > 72:
            continue
        for anchor in anchors[:160]:
            motif_bbox = (anchor[0], anchor[1], anchor[0] + ph - 1, anchor[1] + pw - 1)
            motif_cells = _motif_cells_from_patch(patch, anchor)
            out, shifts, overlap = _stamp_lattice(
                shape,
                motif_cells,
                motif_bbox,
                v1,
                v2,
                bg=BG,
                coeff_limit=max(shape),
            )
            if overlap:
                continue
            count, clipped, has_axis_1, has_axis_2, has_combo, has_full_combo = _classify_shifts(
                shifts, motif_bbox, shape
            )
            if not (VISIBLE_STAMPS_RANGE[0] <= count <= VISIBLE_STAMPS_RANGE[1]):
                continue
            if not (CLIPPED_STAMPS_RANGE[0] <= clipped <= CLIPPED_STAMPS_RANGE[1]):
                continue
            if not (has_axis_1 and has_axis_2 and has_combo and has_full_combo):
                continue
            if np.count_nonzero(out) > (h * w) // 3:
                continue
            return {
                "anchor": anchor,
                "v1": v1,
                "v2": v2,
                "output": out,
                "motif_bbox": motif_bbox,
                "motif_cells": motif_cells,
            }
    return None


def _pad_mask(mask: np.ndarray) -> np.ndarray:
    padded = mask.copy()
    h, w = mask.shape
    coords = np.argwhere(mask)
    for r, c in coords:
        for dr in (-1, 0, 1):
            for dc in (-1, 0, 1):
                nr = int(r) + dr
                nc = int(c) + dc
                if 0 <= nr < h and 0 <= nc < w:
                    padded[nr, nc] = True
    return padded


def _zigzag_path(vector: tuple[int, int]) -> list[tuple[int, int]]:
    dr, dc = vector
    sr = 1 if dr > 0 else -1
    sc = 1 if dc > 0 else -1
    adr = abs(dr)
    adc = abs(dc)

    r_parts = random.randint(1, min(3, adr))
    c_parts = random.randint(1, min(3, adc))
    if r_parts + c_parts < 3:
        if adr > r_parts:
            r_parts += 1
        else:
            c_parts += 1

    r_lengths = _random_partition(adr, r_parts)
    c_lengths = _random_partition(adc, c_parts)

    segments: list[tuple[int, int, int]] = []
    next_axis = random.choice(["r", "c"])
    while r_lengths or c_lengths:
        if next_axis == "r" and r_lengths:
            segments.append((sr, 0, r_lengths.pop(0)))
            next_axis = "c"
        elif next_axis == "c" and c_lengths:
            segments.append((0, sc, c_lengths.pop(0)))
            next_axis = "r"
        else:
            next_axis = "c" if next_axis == "r" else "r"

    coords = [(0, 0)]
    r = 0
    c = 0
    for step_r, step_c, length in segments:
        for _ in range(length):
            r += step_r
            c += step_c
            coords.append((r, c))

    assert coords[-1] == (dr, dc)
    assert len(coords) == len(set(coords)), "monotone zigzag should remain self-avoiding"
    return coords


def _place_path(
    shape: tuple[int, int],
    vector: tuple[int, int],
    blocked: np.ndarray,
) -> list[tuple[int, int]] | None:
    h, w = shape
    for _ in range(60):
        rel = _zigzag_path(vector)
        min_r = min(r for r, _c in rel)
        max_r = max(r for r, _c in rel)
        min_c = min(c for _r, c in rel)
        max_c = max(c for _r, c in rel)
        starts = []
        for sr in range(-min_r, h - max_r):
            for sc in range(-min_c, w - max_c):
                abs_coords = [(sr + r, sc + c) for r, c in rel]
                if all(not blocked[r, c] for r, c in abs_coords):
                    starts.append((sr, sc))
        if not starts:
            continue
        sr, sc = random.choice(starts)
        return [(sr + r, sc + c) for r, c in rel]
    return None


def _build_input_from_layout(layout: dict, patch: np.ndarray) -> np.ndarray | None:
    grid = np.full(layout["output"].shape, BG, dtype=int)
    grid[layout["anchor"][0] : layout["anchor"][0] + patch.shape[0], layout["anchor"][1] : layout["anchor"][1] + patch.shape[1]] = patch

    blocked = _pad_mask(layout["output"] != BG)
    paths = []
    for vector in (layout["v1"], layout["v2"]):
        path = _place_path(grid.shape, vector, blocked)
        if path is None:
            return None
        for r, c in path:
            blocked[r, c] = True
        blocked = _pad_mask(blocked)
        paths.append(path)

    for path in paths:
        for r, c in path:
            grid[r, c] = PATH_COLOR
    return grid


def _validate_semantics(inp: np.ndarray, patch: np.ndarray, layout: dict) -> bool:
    expected = layout["output"]
    if np.array_equal(inp, expected):
        return False
    if not np.array_equal(main(inp), expected):
        return False

    gray_components = _find_components_of_color(inp, PATH_COLOR)
    if len(gray_components) != 2:
        return False
    for comp in gray_components:
        try:
            _component_endpoints(comp["coords"])
        except AssertionError:
            return False

    motif_colors = set(int(v) for v in inp[(inp != BG) & (inp != PATH_COLOR)])
    if len(motif_colors) < 2:
        return False
    if np.any((inp == PATH_COLOR) & (expected != BG)):
        return False

    recovered_patch = inp[
        layout["anchor"][0] : layout["anchor"][0] + patch.shape[0],
        layout["anchor"][1] : layout["anchor"][1] + patch.shape[1],
    ]
    if not np.array_equal(recovered_patch, patch):
        return False
    return True


def _gen_attempt() -> np.ndarray | None:
    shape = (random.randint(*GRID_RANGE), random.randint(*GRID_RANGE))
    patch = _make_motif_patch()
    layout = _choose_layout(shape, patch)
    if layout is None:
        return None
    inp = _build_input_from_layout(layout, patch)
    if inp is None:
        return None
    if not _validate_semantics(inp, patch, layout):
        return None
    return inp


def generate_input() -> np.ndarray:
    for _ in range(MAX_GENERATION_ATTEMPTS):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a valid zigzag-lattice stamp input")
