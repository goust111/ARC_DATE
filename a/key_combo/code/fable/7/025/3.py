_ARC = _load_arc_utils()
Color = _ARC.Color
components_mask = _ARC.components_mask
crop_bbox = _ARC.crop_bbox
find_components = _ARC.find_components
get_bg = _ARC.get_bg
paste = _ARC.paste
random_free_location = _ARC.random_free_location


BG = Color.BLACK
PALETTE = [color for color in Color.NOT_BLACK]
CLOSED_CAVITIES = [(2, 2), (2, 3), (2, 4), (3, 3), (2, 5), (3, 4), (3, 5), (4, 4)]
OPEN_CAVITIES = CLOSED_CAVITIES + [(4, 5)]
GEN_RETRIES = 400
PATCH_MARGIN = 2
TAB_LENGTH_RANGE = (1, 2)
TAB_COUNT_RANGE = (0, 4)
GRID_SIDE_RANGE = (22, 30)


@dataclass
class ObjectInfo:
    color: int
    coords: np.ndarray
    area: int
    closed: bool
    capacity: int


@dataclass
class PlannedObject:
    color: int
    patch: np.ndarray
    closed: bool
    capacity: int
    nominal_capacity: int
    area: int
    coords: np.ndarray | None = None


def _touches_border(coords: np.ndarray, shape: tuple[int, int]) -> bool:
    rows = coords[:, 0]
    cols = coords[:, 1]
    return bool(
        (rows == 0).any()
        or (cols == 0).any()
        or (rows == shape[0] - 1).any()
        or (cols == shape[1] - 1).any()
    )


def _analyze_objects(grid: np.ndarray) -> list[ObjectInfo]:
    g = np.asarray(grid, dtype=int)
    bg = int(get_bg(g))
    components = find_components(
        g,
        bg=bg,
        connectivity=4,
        monochromatic=True,
        return_format="dict",
    )
    analyses: list[ObjectInfo] = []
    for component in components:
        color = int(component["color"])
        coords = component["coords"]
        local = crop_bbox(g, component["bbox"])
        obj_mask = local == color
        padded = np.zeros((obj_mask.shape[0] + 2, obj_mask.shape[1] + 2), dtype=bool)
        padded[1:-1, 1:-1] = obj_mask

        enclosed = [
            hole
            for hole in components_mask(~padded, connectivity=4)
            if not _touches_border(hole, padded.shape)
        ]
        closed = len(enclosed) == 1
        capacity = int(enclosed[0].shape[0]) if closed else 0
        analyses.append(
            ObjectInfo(
                color=color,
                coords=coords,
                area=int(component["area"]),
                closed=closed,
                capacity=capacity,
            )
        )
    return analyses


def _cycle_output(
    grid: np.ndarray,
    records: list[ObjectInfo] | list[PlannedObject],
    order: list[int],
) -> np.ndarray:
    out = np.asarray(grid, dtype=int).copy()
    if len(order) < 2:
        return out
    for src_idx, dst_idx in zip(order, order[1:] + order[:1]):
        coords = records[src_idx].coords
        assert coords is not None
        out[coords[:, 0], coords[:, 1]] = int(records[dst_idx].color)
    return out


def main(input_grid: np.ndarray) -> np.ndarray:
    """
    Recolor only the fully enclosed hollow objects by cycling colors along the ranking of cavity sizes.

    Input structure:
    - The grid has a black background and several pairwise color-distinct hollow objects.
    - Most objects are closed 1-cell-thick shells around black cavities, while a few have a subtle 1-cell gap.
    - Closed objects have distinct cavity capacities, and object-pixel counts are not a reliable ranking key.

    Rule:
    - Detect each monochrome object and flood-style test whether its black interior is fully enclosed.
    - Ignore every gapped object completely; it keeps its original color and does not affect the ranking.
    - Sort only the closed objects by enclosed black-cell count, then recolor each whole shell to the next larger
      closed object's color, with the largest capacity wrapping to the smallest.
    - Leave all black cells, including enclosed cavities and exterior background, unchanged.

    Key insight:
    - Eligibility is determined by closure first, and the color permutation is generated by cavity-capacity ranking
      rather than by object size, location, or a fixed color table.
    """
    g = np.asarray(input_grid, dtype=int)
    assert g.ndim == 2 and g.size > 0, "expected a non-empty 2D grid"

    objects = _analyze_objects(g)
    closed_order = sorted(
        [idx for idx, obj in enumerate(objects) if obj.closed],
        key=lambda idx: (objects[idx].capacity, objects[idx].color),
    )
    return _cycle_output(g, objects, closed_order)


def _draw_base_ring(patch: np.ndarray, color: int, cavity_h: int, cavity_w: int) -> tuple[int, int, int, int]:
    outer_h = cavity_h + 2
    outer_w = cavity_w + 2
    r0 = PATCH_MARGIN
    c0 = PATCH_MARGIN
    r1 = r0 + outer_h - 1
    c1 = c0 + outer_w - 1
    patch[r0, c0 : c1 + 1] = color
    patch[r1, c0 : c1 + 1] = color
    patch[r0 : r1 + 1, c0] = color
    patch[r0 : r1 + 1, c1] = color
    return r0, c0, r1, c1


def _interior_positions(length: int, width: int) -> list[int]:
    return list(range(1, length - 1)) if width > 0 else []


def _add_tabs(
    patch: np.ndarray,
    color: int,
    ring_box: tuple[int, int, int, int],
) -> dict[str, set[int]]:
    r0, c0, r1, c1 = ring_box
    outer_h = r1 - r0 + 1
    outer_w = c1 - c0 + 1
    covered = {"top": set(), "bottom": set(), "left": set(), "right": set()}
    tab_count = random.randint(*TAB_COUNT_RANGE)

    for _ in range(tab_count):
        side = random.choice(("top", "bottom", "left", "right"))
        tab_len = random.randint(*TAB_LENGTH_RANGE)
        if side in {"top", "bottom"}:
            positions = _interior_positions(outer_w, tab_len)
            if not positions:
                continue
            span = random.randint(1, len(positions))
            start_idx = random.randint(0, len(positions) - span)
            cols = positions[start_idx : start_idx + span]
            rr = slice(r0 - tab_len, r0) if side == "top" else slice(r1 + 1, r1 + tab_len + 1)
            patch[rr, c0 + cols[0] : c0 + cols[-1] + 1] = color
            covered[side].update(cols)
        else:
            positions = _interior_positions(outer_h, tab_len)
            if not positions:
                continue
            span = random.randint(1, len(positions))
            start_idx = random.randint(0, len(positions) - span)
            rows = positions[start_idx : start_idx + span]
            cc = slice(c0 - tab_len, c0) if side == "left" else slice(c1 + 1, c1 + tab_len + 1)
            patch[r0 + rows[0] : r0 + rows[-1] + 1, cc] = color
            covered[side].update(rows)
    return covered


def _open_gap(
    patch: np.ndarray,
    color: int,
    ring_box: tuple[int, int, int, int],
    covered: dict[str, set[int]],
) -> None:
    r0, c0, r1, c1 = ring_box
    candidates: list[tuple[str, int]] = []

    for side, limit in (("top", c1 - c0), ("bottom", c1 - c0)):
        for offset in range(1, limit):
            if offset not in covered[side]:
                candidates.append((side, offset))
    for side, limit in (("left", r1 - r0), ("right", r1 - r0)):
        for offset in range(1, limit):
            if offset not in covered[side]:
                candidates.append((side, offset))

    if not candidates:
        raise ValueError("no valid gap location")

    side, offset = random.choice(candidates)
    if side == "top":
        patch[r0, c0 + offset] = BG
    elif side == "bottom":
        patch[r1, c0 + offset] = BG
    elif side == "left":
        patch[r0 + offset, c0] = BG
    else:
        patch[r0 + offset, c1] = BG

    assert int(np.count_nonzero(patch == color)) > 0


def _build_object_patch(color: int, cavity_h: int, cavity_w: int, closed: bool) -> np.ndarray:
    for _ in range(20):
        patch = np.zeros((cavity_h + 2 * PATCH_MARGIN + 2, cavity_w + 2 * PATCH_MARGIN + 2), dtype=int)
        ring_box = _draw_base_ring(patch, color, cavity_h, cavity_w)
        covered = _add_tabs(patch, color, ring_box)
        if not closed:
            try:
                _open_gap(patch, color, ring_box, covered)
            except ValueError:
                continue
        if random.random() < 0.75:
            patch = np.rot90(patch, k=random.randint(0, 3))
        return patch
    raise ValueError("failed to build object patch")


def _plan_objects() -> list[PlannedObject] | None:
    closed_count = random.choice((3, 4, 5))
    open_count = random.choice((1, 1, 2))
    total = closed_count + open_count
    colors = random.sample(PALETTE, total)

    closed_specs = random.sample(CLOSED_CAVITIES, closed_count)
    open_specs = random.sample(OPEN_CAVITIES, open_count)

    planned: list[PlannedObject] = []
    for color, (h, w) in zip(colors[:closed_count], closed_specs):
        patch = _build_object_patch(color, h, w, closed=True)
        planned.append(
            PlannedObject(
                color=color,
                patch=patch,
                closed=True,
                capacity=h * w,
                nominal_capacity=h * w,
                area=int(np.count_nonzero(patch == color)),
            )
        )
    for color, (h, w) in zip(colors[closed_count:], open_specs):
        patch = _build_object_patch(color, h, w, closed=False)
        planned.append(
            PlannedObject(
                color=color,
                patch=patch,
                closed=False,
                capacity=0,
                nominal_capacity=h * w,
                area=int(np.count_nonzero(patch == color)),
            )
        )

    closed_planned = [obj for obj in planned if obj.closed]
    capacity_order = [obj.color for obj in sorted(closed_planned, key=lambda obj: obj.capacity)]
    area_order = [obj.color for obj in sorted(closed_planned, key=lambda obj: obj.area)]
    if len({obj.area for obj in closed_planned}) != len(closed_planned):
        return None
    if capacity_order == area_order:
        return None
    return planned


def _place_objects(planned: list[PlannedObject]) -> np.ndarray | None:
    height = random.randint(*GRID_SIDE_RANGE)
    width = random.randint(*GRID_SIDE_RANGE)
    grid = np.zeros((height, width), dtype=int)
    reserve = np.zeros((height, width), dtype=int)

    order = list(range(len(planned)))
    random.shuffle(order)
    for idx in order:
        obj = planned[idx]
        reserve_patch = np.ones(obj.patch.shape, dtype=int)
        try:
            r0, c0 = random_free_location(
                reserve,
                reserve_patch,
                transparent=0,
                border=0,
                padding=1,
                padding_connectivity=8,
            )
        except ValueError:
            return None
        paste(reserve, reserve_patch, r0, c0, transparent=0)
        paste(grid, obj.patch, r0, c0, transparent=0)
        coords = np.argwhere(obj.patch == obj.color)
        obj.coords = coords + np.array([[r0, c0]])
    return grid


def _expected_from_plan(grid: np.ndarray, planned: list[PlannedObject]) -> np.ndarray:
    closed_order = sorted(
        [idx for idx, obj in enumerate(planned) if obj.closed],
        key=lambda idx: planned[idx].capacity,
    )
    return _cycle_output(grid, planned, closed_order)


def _alternative_all_objects_output(grid: np.ndarray, planned: list[PlannedObject]) -> np.ndarray:
    order = sorted(range(len(planned)), key=lambda idx: (planned[idx].nominal_capacity, planned[idx].color))
    return _cycle_output(grid, planned, order)


def _alternative_area_output(grid: np.ndarray, planned: list[PlannedObject]) -> np.ndarray:
    order = sorted(
        [idx for idx, obj in enumerate(planned) if obj.closed],
        key=lambda idx: (planned[idx].area, planned[idx].color),
    )
    return _cycle_output(grid, planned, order)


def _validate_generated_case(grid: np.ndarray, planned: list[PlannedObject]) -> bool:
    analyses = _analyze_objects(grid)
    if len(analyses) != len(planned):
        return False

    planned_by_color = {obj.color: obj for obj in planned}
    analysis_by_color = {obj.color: obj for obj in analyses}
    if set(planned_by_color) != set(analysis_by_color):
        return False

    for color, planned_obj in planned_by_color.items():
        seen = analysis_by_color[color]
        if seen.closed != planned_obj.closed:
            return False
        if seen.area != planned_obj.area:
            return False
        if seen.capacity != planned_obj.capacity:
            return False

    expected = _expected_from_plan(grid, planned)
    actual = main(grid)
    if not np.array_equal(actual, expected):
        return False

    if np.array_equal(expected, _alternative_all_objects_output(grid, planned)):
        return False
    if np.array_equal(expected, _alternative_area_output(grid, planned)):
        return False

    closed_capacities = [obj.capacity for obj in planned if obj.closed]
    if len(closed_capacities) < 3 or len(set(closed_capacities)) != len(closed_capacities):
        return False
    if not any(not obj.closed for obj in planned):
        return False
    return True


def _generate_attempt() -> np.ndarray | None:
    for _ in range(80):
        planned = _plan_objects()
        if planned is None:
            continue
        grid = _place_objects(planned)
        if grid is None:
            continue
        if _validate_generated_case(grid, planned):
            return grid
    return None


def generate_input() -> np.ndarray:
    for _ in range(GEN_RETRIES):
        grid = _generate_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a valid input")
