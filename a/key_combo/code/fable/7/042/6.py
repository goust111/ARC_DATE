from __future__ import annotations

import random

import numpy as np


def _mirror_row(row: int, height: int) -> int:
    return height - 1 - row


def _orbit_key(row: int, col: int, height: int, period: int) -> tuple[int, int]:
    return min(row, _mirror_row(row, height)), col % period


def _tile_for_period(grid: np.ndarray, erase_color: int, period: int) -> dict[tuple[int, int], int] | None:
    height, width = grid.shape
    tile: dict[tuple[int, int], int] = {}
    for row in range(height):
        for col in range(width):
            color = int(grid[row, col])
            if color == erase_color:
                continue
            key = _orbit_key(row, col, height, period)
            prev = tile.get(key)
            if prev is None:
                tile[key] = color
            elif prev != color:
                return None
    if len(tile) != ((height + 1) // 2) * period:
        return None
    return tile


def _reconstruct(height: int, width: int, period: int, tile: dict[tuple[int, int], int]) -> np.ndarray:
    out = np.empty((height, width), dtype=int)
    for row in range(height):
        base_row = min(row, _mirror_row(row, height))
        for col in range(width):
            out[row, col] = tile[(base_row, col % period)]
    return out


def _solve(grid: np.ndarray) -> tuple[int, int, np.ndarray]:
    colors = [int(color) for color in np.unique(grid)]
    height, width = grid.shape
    solutions: list[tuple[int, int, np.ndarray]] = []
    for erase_color in colors:
        best_period = None
        best_out = None
        for period in range(1, width + 1):
            tile = _tile_for_period(grid, erase_color, period)
            if tile is None:
                continue
            out = _reconstruct(height, width, period, tile)
            if np.any(out == erase_color):
                continue
            if not np.any(grid == erase_color):
                continue
            best_period = period
            best_out = out
            break
        if best_out is not None and best_period is not None:
            solutions.append((erase_color, best_period, best_out))
    assert len(solutions) == 1, "expected a unique erase color and period"
    return solutions[0]


def main(grid: np.ndarray) -> np.ndarray:
    """Repair the erased cells by combining horizontal repetition with top-bottom mirror symmetry.

    Input structure:
    - The grid is a fully colored rectangle except for one dedicated erase color.
    - Every row repeats with one shared smallest horizontal period.
    - The whole pattern is symmetric under reflection across the horizontal midline.

    Rule:
    - Identify the unique erase color and the smallest horizontal period consistent with all visible cells.
    - Group cells by the closure of two relations: same row-period residue and same-column mirror partner.
    - Each such orbit has one visible color; copy that color into every erased cell of the orbit.

    Key insight:
    - Some holes lose all same-row periodic twins and some also lose their direct mirror twin, so reconstruction must use the combined orbit generated by both redundancies rather than either one alone.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2, "expected a 2D grid"
    _erase_color, _period, out = _solve(g)
    return out


def _full_has_period(grid: np.ndarray, period: int) -> bool:
    return bool(np.all(grid[:, period:] == grid[:, :-period]))


def _minimal_period(grid: np.ndarray) -> int:
    width = int(grid.shape[1])
    for period in range(1, width + 1):
        if _full_has_period(grid, period):
            return period
    raise AssertionError("grid must have some period")

def _assemble_pattern(canonical_rows: np.ndarray, height: int, period: int, repeats: int) -> np.ndarray:
    width = period * repeats
    full = np.empty((height, width), dtype=int)
    for row in range(height):
        base_row = min(row, _mirror_row(row, height))
        pattern = canonical_rows[base_row]
        full[row] = pattern[np.arange(width) % period]
    return full


def _orbit_positions(height: int, width: int, base_row: int, residue: int, period: int) -> list[tuple[int, int]]:
    cols = list(range(residue, width, period))
    other_row = _mirror_row(base_row, height)
    rows = [base_row] if other_row == base_row else [base_row, other_row]
    positions: list[tuple[int, int]] = []
    for row in rows:
        for col in cols:
            positions.append((row, col))
    return positions


def _random_orbit_subset(positions: list[tuple[int, int]], height: int) -> list[tuple[int, int]]:
    top = [pos for pos in positions if pos[0] <= _mirror_row(pos[0], height)]
    bottom = [pos for pos in positions if pos[0] > _mirror_row(pos[0], height)]
    mode = random.choice(("none", "single", "pair", "row", "scatter"))
    if mode == "none":
        return []
    if mode == "single":
        return [random.choice(positions)]
    if mode == "pair" and bottom:
        col = random.choice(sorted({col for _row, col in positions}))
        pair = [(row, cc) for row, cc in positions if cc == col]
        if len(pair) < len(positions):
            return pair
    if mode == "row" and top and bottom:
        chosen = top if random.random() < 0.5 else bottom
        if len(chosen) < len(positions):
            return chosen
    count = random.randint(1, max(1, len(positions) - 1))
    return random.sample(positions, count)


def _has_joint_only_cell(grid: np.ndarray, erase_color: int, period: int) -> bool:
    height, width = grid.shape
    for row, col in np.argwhere(grid == erase_color):
        row = int(row)
        col = int(col)
        same_row = [
            (row, cc)
            for cc in range(col % period, width, period)
            if cc != col
        ]
        mirror_row = _mirror_row(row, height)
        mirror_peer = []
        if mirror_row != row:
            mirror_peer = [(mirror_row, col)]
        orbit = _orbit_positions(height, width, min(row, mirror_row), col % period, period)
        others = [pos for pos in orbit if pos != (row, col)]
        if not any(int(grid[r, c]) != erase_color for r, c in same_row) and not any(
            int(grid[r, c]) != erase_color for r, c in mirror_peer
        ) and any(int(grid[r, c]) != erase_color for r, c in others):
            return True
    return False


def _gen_attempt() -> np.ndarray | None:
    height = random.randint(6, 10)
    period = random.randint(3, 6)
    repeats = random.randint(3, min(5, 30 // period))
    width = period * repeats
    if width > 30:
        return None

    row_count = (height + 1) // 2
    all_colors = list(range(10))
    palette_size = random.randint(3, 5)
    palette = random.sample(all_colors, palette_size)
    erase_choices = [color for color in all_colors if color not in palette]
    erase_color = random.choice(erase_choices)

    for _ in range(200):
        canonical = np.random.choice(palette, size=(row_count, period), replace=True).astype(int)
        full = _assemble_pattern(canonical, height, period, repeats)
        if _minimal_period(full) != period:
            continue
        if len(set(map(int, full.ravel()))) < palette_size - 1:
            continue
        break
    else:
        return None

    corrupted = full.copy()

    eligible_rows = [row for row in range(height) if _mirror_row(row, height) != row]
    chosen_row = random.choice(eligible_rows)
    hard_row = min(chosen_row, _mirror_row(chosen_row, height))
    hard_residue = random.randrange(period)
    hard_cols = list(range(hard_residue, width, period))
    visible_col = random.choice(hard_cols)
    for col in hard_cols:
        corrupted[hard_row, col] = erase_color
        corrupted[_mirror_row(hard_row, height), col] = erase_color
    corrupted[_mirror_row(hard_row, height), visible_col] = full[_mirror_row(hard_row, height), visible_col]

    for base_row in range(row_count):
        for residue in range(period):
            if base_row == hard_row and residue == hard_residue:
                continue
            positions = _orbit_positions(height, width, base_row, residue, period)
            erase_positions = _random_orbit_subset(positions, height)
            if len(erase_positions) >= len(positions):
                erase_positions = erase_positions[:-1]
            for row, col in erase_positions:
                corrupted[row, col] = erase_color

    if not np.any(corrupted == erase_color):
        return None
    if np.array_equal(corrupted, full):
        return None
    if not _has_joint_only_cell(corrupted, erase_color, period):
        return None
    solved = main(corrupted)
    if not np.array_equal(solved, full):
        return None
    return corrupted


def generate_input() -> np.ndarray:
    for _ in range(300):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a valid input")
