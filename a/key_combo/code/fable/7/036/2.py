from __future__ import annotations

import random

import numpy as np


BLACK = 0
ARC_COLORS = tuple(range(10))


def _strict_phase_tile(grid: np.ndarray, tile_h: int, tile_w: int) -> np.ndarray | None:
    """Return phase modes when every phase has repeated, strict-majority support."""
    tile = np.empty((tile_h, tile_w), dtype=int)
    for tr in range(tile_h):
        for tc in range(tile_w):
            values = grid[tr::tile_h, tc::tile_w].ravel()
            # "Appears multiple times" is made operational as at least three votes:
            # a single corruption then cannot create or tie a majority.
            if values.size < 3:
                return None
            colors, counts = np.unique(values, return_counts=True)
            winner = int(np.argmax(counts))
            if int(counts[winner]) * 2 <= int(values.size):
                return None
            tile[tr, tc] = int(colors[winner])
    return tile


def _infer_minimal_tile(grid: np.ndarray) -> np.ndarray:
    """Infer the unique smallest-area period supported by strict phase majorities."""
    height, width = map(int, grid.shape)
    by_area = sorted(
        ((h * w, h, w) for h in range(1, height + 1) for w in range(1, width + 1)),
        key=lambda item: item[0],
    )

    first_area: int | None = None
    best: list[np.ndarray] = []
    for area, tile_h, tile_w in by_area:
        if first_area is not None and area > first_area:
            break
        tile = _strict_phase_tile(grid, tile_h, tile_w)
        if tile is not None:
            first_area = area
            best.append(tile)

    assert best, "expected at least one majority-supported repeating tile"
    assert len(best) == 1, "expected a unique minimum-area repeating tile"
    return best[0]


def _crop_to_mask(grid: np.ndarray, mask: np.ndarray) -> np.ndarray:
    """Crop using the inclusive (row, column) bbox convention from arc_utils."""
    coords = np.argwhere(mask)
    assert coords.size, "expected at least one defect"
    r0, c0 = coords.min(axis=0)
    r1, c1 = coords.max(axis=0)
    return grid[int(r0) : int(r1) + 1, int(c0) : int(c1) + 1].copy()


def main(grid: np.ndarray) -> np.ndarray:
    """
    Extract the latent original colors of periodic-wallpaper defects as a cropped constellation.

    Input structure:
    - The entire grid is a wallpaper generated by one unique minimum repeating tile, with no
      separate background; black is an ordinary tile color.
    - A few pixels disagree with their tile phases, while every phase occurs repeatedly and its
      original color has strict majority support.

    Rule:
    - Treat every color, including black, as data and infer the unique minimum-area tile whose
      phase classes each have a strict majority color.
    - Mark every pixel that differs from its phase majority as a defect. In the defects' bounding
      box, place each defect's predicted majority color and fill all other cells with black.

    Key insight:
    - The output is neither the observed bad pixels nor the repaired wallpaper: it is a tight crop
      of the missing original colors that exist only in the latent periodic prediction.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2 and g.size, "expected a non-empty 2D grid"

    tile = _infer_minimal_tile(g)
    tile_h, tile_w = map(int, tile.shape)
    predicted = tile[
        np.arange(g.shape[0])[:, None] % tile_h,
        np.arange(g.shape[1])[None, :] % tile_w,
    ]
    defects = g != predicted
    assert np.any(defects), "expected at least one periodic defect"

    constellation = np.full(g.shape, BLACK, dtype=int)
    constellation[defects] = predicted[defects]
    return _crop_to_mask(constellation, defects)


def _period_is_exact(tile: np.ndarray) -> bool:
    """Independent exact check that a pristine tile has one unique minimum period."""
    tiled = np.tile(tile, (4, 4))
    inferred = _infer_minimal_tile(tiled)
    return inferred.shape == tile.shape and np.array_equal(inferred, tile)


def _make_tile(tile_h: int, tile_w: int, palette: list[int]) -> np.ndarray:
    """Make a balanced random tile, including black, then reject accidental subperiods."""
    area = tile_h * tile_w
    values = [palette[i % len(palette)] for i in range(area)]
    random.shuffle(values)
    return np.asarray(values, dtype=int).reshape(tile_h, tile_w)


def _expected_constellation(
    tile: np.ndarray, defect_records: list[tuple[int, int, int]], shape: tuple[int, int]
) -> np.ndarray:
    """Construct the semantic oracle directly from recorded latent originals."""
    rows = [r for r, _c, _old in defect_records]
    cols = [c for _r, c, _old in defect_records]
    r0, r1 = min(rows), max(rows)
    c0, c1 = min(cols), max(cols)
    out = np.full((r1 - r0 + 1, c1 - c0 + 1), BLACK, dtype=int)
    for r, c, original in defect_records:
        assert original == int(tile[r % tile.shape[0], c % tile.shape[1]])
        out[r - r0, c - c0] = original
    assert max(out.shape) <= max(shape)
    return out


def _generation_attempt() -> np.ndarray | None:
    tile_h, tile_w = random.choice(
        [(h, w) for h in range(2, 6) for w in range(2, 6) if h * w >= 10]
    )
    palette = [BLACK, *random.sample(range(1, 10), random.randint(3, 4))]
    tile = _make_tile(tile_h, tile_w, palette)
    if not _period_is_exact(tile):
        return None

    repeat_r = random.randint(3, min(6, 30 // tile_h))
    repeat_c = random.randint(3, min(6, 30 // tile_w))
    pristine = np.tile(tile, (repeat_r, repeat_c))
    height, width = map(int, pristine.shape)

    black_phases = [tuple(map(int, p)) for p in np.argwhere(tile == BLACK)]
    nonblack_phases = [tuple(map(int, p)) for p in np.argwhere(tile != BLACK)]
    defect_count = min(random.randint(5, 8), len(nonblack_phases) + 1)
    if not black_phases or defect_count < 5 or len(nonblack_phases) < defect_count - 1:
        return None

    phases = [random.choice(black_phases), *random.sample(nonblack_phases, defect_count - 1)]
    records: list[tuple[int, int, int]] = []
    used_cells: set[tuple[int, int]] = set()
    for phase_r, phase_c in phases:
        choices = [
            (phase_r + kr * tile_h, phase_c + kc * tile_w)
            for kr in range(repeat_r)
            for kc in range(repeat_c)
            if (phase_r + kr * tile_h, phase_c + kc * tile_w) not in used_cells
        ]
        r, c = random.choice(choices)
        used_cells.add((r, c))
        records.append((r, c, int(tile[phase_r, phase_c])))

    rows = [r for r, _c, _v in records]
    cols = [c for _r, c, _v in records]
    r0, r1, c0, c1 = min(rows), max(rows), min(cols), max(cols)
    if r1 - r0 < 2 or c1 - c0 < 2:
        return None

    # The one black-original defect is interior, so every crop boundary is visibly justified.
    br, bc, _ = records[0]
    if br in (r0, r1) or bc in (c0, c1):
        return None
    edge_records = [rec for rec in records if rec[0] in (r0, r1) or rec[1] in (c0, c1)]
    if any(original == BLACK for _r, _c, original in edge_records):
        return None
    if len({original for _r, _c, original in records if original != BLACK}) < 2:
        return None

    inp = pristine.copy()
    # Force one non-black wallpaper pixel to become black; black cannot be treated as a hole.
    forced_black_index = random.randrange(1, len(records))
    for index, (r, c, original) in enumerate(records):
        if index == forced_black_index:
            replacement = BLACK
        else:
            replacement = random.choice([color for color in ARC_COLORS if color != original])
        inp[r, c] = replacement

    # Validate the actual semantic premises, not merely main(generate_input()).
    for tr in range(tile_h):
        for tc in range(tile_w):
            phase = inp[tr::tile_h, tc::tile_w].ravel()
            expected = int(tile[tr, tc])
            assert int(np.count_nonzero(phase == expected)) * 2 > int(phase.size)
    try:
        inferred = _infer_minimal_tile(inp)
    except AssertionError:
        return None
    if inferred.shape != tile.shape or not np.array_equal(inferred, tile):
        return None

    expected = _expected_constellation(tile, records, inp.shape)
    actual = main(inp)
    if not np.array_equal(actual, expected):
        return None
    if np.array_equal(actual, inp) or actual.shape == inp.shape:
        return None
    return inp


def generate_input() -> np.ndarray:
    """Generate diverse, independently validated defective periodic wallpapers."""
    for _ in range(600):
        grid = _generation_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a non-degenerate defect constellation")
