from __future__ import annotations

import random

import numpy as np


BG = 0
COLORS = tuple(range(1, 10))
Coord = tuple[int, int]
Plan = tuple[str, Coord, int, int, Coord]  # (owner, center, radius, color, scatter)

SQUARE_OFFSETS = tuple((dr, dc) for dr in (-1, 0, 1) for dc in (-1, 0, 1))
CROSS_OFFSETS = ((0, 0), (-1, 0), (1, 0), (0, -1), (0, 1))


def _bbox(coords: np.ndarray) -> tuple[int, int, int, int]:
    r0, c0 = coords.min(axis=0)
    r1, c1 = coords.max(axis=0)
    return int(r0), int(c0), int(r1), int(c1)


def _center_from_bbox(box: tuple[int, int, int, int]) -> Coord:
    r0, c0, r1, c1 = box
    return (r0 + r1) // 2, (c0 + c1) // 2


def _shape_cells(center: Coord, kind: str) -> set[Coord]:
    cr, cc = center
    offsets = SQUARE_OFFSETS if kind == "square" else CROSS_OFFSETS
    return {(cr + dr, cc + dc) for dr, dc in offsets}


def _is_square_anchor(coords: np.ndarray) -> bool:
    if coords.shape[0] != 9:
        return False
    r0, c0, r1, c1 = _bbox(coords)
    if r1 - r0 + 1 != 3 or c1 - c0 + 1 != 3:
        return False
    return {(int(r), int(c)) for r, c in coords} == {
        (r, c) for r in range(r0, r1 + 1) for c in range(c0, c1 + 1)
    }


def _is_cross_anchor(coords: np.ndarray) -> bool:
    if coords.shape[0] != 5:
        return False
    r0, c0, r1, c1 = _bbox(coords)
    if r1 - r0 + 1 != 3 or c1 - c0 + 1 != 3:
        return False
    cr, cc = _center_from_bbox((r0, c0, r1, c1))
    return {(int(r), int(c)) for r, c in coords} == _shape_cells((cr, cc), "cross")


def _cheb(a: Coord, b: Coord) -> int:
    return max(abs(int(a[0]) - int(b[0])), abs(int(a[1]) - int(b[1])))


def _manh(a: Coord, b: Coord) -> int:
    return abs(int(a[0]) - int(b[0])) + abs(int(a[1]) - int(b[1]))


def _nearest_owner(point: Coord, square_center: Coord, cross_center: Coord) -> str:
    sq_cheb = _cheb(point, square_center)
    cr_cheb = _cheb(point, cross_center)
    sq_manh = _manh(point, square_center)
    cr_manh = _manh(point, cross_center)
    assert sq_cheb != cr_cheb and sq_manh != cr_manh, "scatter must have a unique nearest anchor"

    square_by_cheb = sq_cheb < cr_cheb
    square_by_manh = sq_manh < cr_manh
    assert square_by_cheb == square_by_manh, "nearest-anchor decision must agree in both metrics"
    return "square" if square_by_cheb else "cross"


def _full_ring_coords(center: Coord, radius: int, metric: str) -> list[Coord]:
    cr, cc = center
    radius = int(radius)
    coords: list[Coord] = []
    if metric == "square":
        for dr in range(-radius, radius + 1):
            for dc in range(-radius, radius + 1):
                if max(abs(dr), abs(dc)) == radius:
                    coords.append((cr + dr, cc + dc))
    else:
        for dr in range(-radius, radius + 1):
            rem = radius - abs(dr)
            if rem == 0:
                coords.append((cr + dr, cc))
            else:
                coords.append((cr + dr, cc - rem))
                coords.append((cr + dr, cc + rem))
    return coords


def _ring_coords(shape: tuple[int, int], center: Coord, radius: int, metric: str) -> set[Coord]:
    h, w = shape
    return {
        (r, c)
        for r, c in _full_ring_coords(center, radius, metric)
        if 0 <= r < h and 0 <= c < w
    }


def _ring_is_clipped(shape: tuple[int, int], center: Coord, radius: int, metric: str) -> bool:
    return len(_ring_coords(shape, center, radius, metric)) < len(_full_ring_coords(center, radius, metric))


def _detect_parts(g: np.ndarray) -> tuple[tuple[int, Coord, set[Coord]], tuple[int, Coord, set[Coord]], list[tuple[int, Coord]]]:
    square: tuple[int, Coord, set[Coord]] | None = None
    cross: tuple[int, Coord, set[Coord]] | None = None
    scatters: list[tuple[int, Coord]] = []

    for color in sorted(int(c) for c in np.unique(g) if int(c) != BG):
        coords = np.argwhere(g == color)
        if _is_square_anchor(coords):
            assert square is None, "expected one square anchor"
            center = _center_from_bbox(_bbox(coords))
            square = (color, center, {(int(r), int(c)) for r, c in coords})
        elif _is_cross_anchor(coords):
            assert cross is None, "expected one cross anchor"
            center = _center_from_bbox(_bbox(coords))
            cross = (color, center, {(int(r), int(c)) for r, c in coords})
        elif coords.shape[0] == 1:
            r, c = coords[0]
            scatters.append((color, (int(r), int(c))))
        else:
            raise AssertionError("non-anchor foreground colors must be single-pixel generators")

    assert square is not None and cross is not None, "expected one square and one cross anchor"
    assert scatters, "expected at least one generator pixel"
    return square, cross, scatters


def main(grid: np.ndarray) -> np.ndarray:
    """
    Draw the metric ring generated by each colored singleton around its nearest shape anchor.

    Input structure:
    - The background is black.
    - There are exactly two monochrome anchors in distinct colors: one solid 3x3
      square and one five-cell cross centered in a 3x3 box.
    - Every other foreground color appears as one isolated generator pixel.

    Rule:
    - Assign each generator pixel to the anchor whose center is closer; the
      Chebyshev and Manhattan nearest-anchor tests must agree and have no tie.
    - A generator assigned to the square anchor draws the Chebyshev-distance ring
      around that square center at the generator's Chebyshev distance.
    - A generator assigned to the cross anchor draws the Manhattan-distance ring
      around that cross center at the generator's Manhattan distance.
    - Rings use the generator color and are clipped by the grid boundary; anchor
      cells keep their original colors.

    Key insight:
    - The anchor shape names the metric: the filled square is the Chebyshev unit
      ball and the cross is the Manhattan unit ball, while each singleton supplies
      one ring color and radius.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2

    square, cross, scatters = _detect_parts(g)
    _square_color, square_center, square_cells = square
    _cross_color, cross_center, cross_cells = cross
    anchor_cells = square_cells | cross_cells
    scatter_by_cell = {pt: color for color, pt in scatters}
    assert len(scatter_by_cell) == len(scatters), "generator pixels must occupy distinct cells"

    plans: list[Plan] = []
    for color, point in sorted(scatters, key=lambda item: item[1]):
        owner = _nearest_owner(point, square_center, cross_center)
        if owner == "square":
            radius = _cheb(point, square_center)
            center = square_center
        else:
            radius = _manh(point, cross_center)
            center = cross_center
        assert radius >= 2, "generator pixel must lie outside its anchor"
        plans.append((owner, center, radius, color, point))

    painted: dict[Coord, int] = {}
    for owner, center, radius, color, _point in plans:
        metric = "square" if owner == "square" else "cross"
        for cell in _ring_coords(g.shape, center, radius, metric):
            if cell in anchor_cells:
                continue
            other_scatter = scatter_by_cell.get(cell)
            assert other_scatter is None or other_scatter == color, "rings must not pass through another generator"
            previous = painted.get(cell)
            assert previous is None or previous == color, "rings must not overlap with different colors"
            painted[cell] = color

    out = g.copy()
    for (r, c), color in painted.items():
        out[r, c] = int(color)
    for r, c in anchor_cells:
        out[r, c] = g[r, c]
    return out


# --------------- generator ---------------


def _corner_center(kind: int, h: int, w: int) -> Coord:
    top = kind in (0, 1)
    left = kind in (0, 2)
    r_jitter = random.choice((0, 0, 1, 2, 3))
    c_jitter = random.choice((0, 0, 1, 2, 3))
    r = 1 + r_jitter if top else h - 2 - r_jitter
    c = 1 + c_jitter if left else w - 2 - c_jitter
    return int(r), int(c)


def _metric_distance(point: Coord, center: Coord, metric: str) -> int:
    return _cheb(point, center) if metric == "square" else _manh(point, center)


def _offsets_for_radius(radius: int, metric: str, require_off_axis: bool) -> list[Coord]:
    offsets: list[Coord] = []
    for r, c in _full_ring_coords((0, 0), radius, metric):
        if require_off_axis and (r == 0 or c == 0):
            continue
        offsets.append((r, c))
    random.shuffle(offsets)
    return offsets


def _draw_plan_output(grid: np.ndarray, plans: list[Plan], anchor_cells: set[Coord]) -> np.ndarray:
    out = grid.copy()
    for owner, center, radius, color, _point in plans:
        metric = "square" if owner == "square" else "cross"
        for r, c in _ring_coords(grid.shape, center, radius, metric):
            if (r, c) not in anchor_cells:
                out[r, c] = int(color)
    for r, c in anchor_cells:
        out[r, c] = grid[r, c]
    return out


def _wrong_metric_output(grid: np.ndarray, plans: list[Plan], anchor_cells: set[Coord], wrong_owner: str) -> np.ndarray:
    out = grid.copy()
    for owner, center, radius, color, point in plans:
        if owner == wrong_owner:
            metric = "cross" if owner == "square" else "square"
            radius = _metric_distance(point, center, metric)
        else:
            metric = "square" if owner == "square" else "cross"
        for r, c in _ring_coords(grid.shape, center, radius, metric):
            if (r, c) not in anchor_cells:
                out[r, c] = int(color)
    for r, c in anchor_cells:
        out[r, c] = grid[r, c]
    return out


def _place_generator(
    *,
    owner: str,
    grid_shape: tuple[int, int],
    square_center: Coord,
    cross_center: Coord,
    color: int,
    used_radii: set[int],
    anchor_cells: set[Coord],
    occupied_rings: set[Coord],
    occupied_generators: set[Coord],
    require_off_axis: bool,
    require_clipped: bool,
) -> Plan | None:
    center = square_center if owner == "square" else cross_center
    metric = "square" if owner == "square" else "cross"
    radii = [r for r in range(3, 8) if r not in used_radii]
    random.shuffle(radii)

    for radius in radii:
        if require_clipped and not _ring_is_clipped(grid_shape, center, radius, metric):
            continue
        ring = _ring_coords(grid_shape, center, radius, metric)
        if ring & anchor_cells:
            continue
        if ring & occupied_rings:
            continue

        for dr, dc in _offsets_for_radius(radius, metric, require_off_axis):
            point = (center[0] + dr, center[1] + dc)
            pr, pc = point
            if not (0 <= pr < grid_shape[0] and 0 <= pc < grid_shape[1]):
                continue
            if point in anchor_cells or point in occupied_generators or point in occupied_rings:
                continue
            try:
                actual_owner = _nearest_owner(point, square_center, cross_center)
            except AssertionError:
                continue
            if actual_owner != owner:
                continue
            if point not in ring:
                continue
            used_radii.add(radius)
            occupied_rings.update(ring)
            occupied_generators.add(point)
            return (owner, center, radius, int(color), point)
    return None


def _paint_anchor(grid: np.ndarray, center: Coord, kind: str, color: int) -> None:
    for r, c in _shape_cells(center, kind):
        grid[r, c] = int(color)


def _gen_attempt() -> np.ndarray | None:
    h = random.randint(18, 30)
    w = random.randint(18, 30)
    square_corner = random.randrange(4)
    cross_corner = {0: 3, 1: 2, 2: 1, 3: 0}[square_corner]
    square_center = _corner_center(square_corner, h, w)
    cross_center = _corner_center(cross_corner, h, w)

    square_cells = _shape_cells(square_center, "square")
    cross_cells = _shape_cells(cross_center, "cross")
    if square_cells & cross_cells:
        return None

    square_count = random.randint(1, 3)
    cross_count = random.randint(1, 3)
    if square_count + cross_count < 3:
        if random.random() < 0.5:
            square_count += 1
        else:
            cross_count += 1
    total_generators = square_count + cross_count

    palette = random.sample(COLORS, 2 + total_generators)
    square_color, cross_color = palette[0], palette[1]
    gen_colors = palette[2:]

    grid = np.full((h, w), BG, dtype=int)
    _paint_anchor(grid, square_center, "square", square_color)
    _paint_anchor(grid, cross_center, "cross", cross_color)

    anchor_cells = square_cells | cross_cells
    occupied_rings: set[Coord] = set()
    occupied_generators: set[Coord] = set()
    used_radii = {"square": set(), "cross": set()}
    plans: list[Plan] = []
    clipped_owner = random.choice(("square", "cross"))

    owners = ["square"] * square_count + ["cross"] * cross_count
    ordered_owners: list[str] = []
    for owner in ("square", "cross"):
        ordered_owners.append(owner)
    rest = owners.copy()
    rest.remove("square")
    rest.remove("cross")
    random.shuffle(rest)
    ordered_owners.extend(rest)

    first_for_owner = {"square": True, "cross": True}
    for color, owner in zip(gen_colors, ordered_owners):
        plan = _place_generator(
            owner=owner,
            grid_shape=grid.shape,
            square_center=square_center,
            cross_center=cross_center,
            color=color,
            used_radii=used_radii[owner],
            anchor_cells=anchor_cells,
            occupied_rings=occupied_rings,
            occupied_generators=occupied_generators,
            require_off_axis=first_for_owner[owner],
            require_clipped=first_for_owner[owner] and owner == clipped_owner,
        )
        if plan is None:
            return None
        first_for_owner[owner] = False
        plans.append(plan)
        _owner, _center, _radius, plan_color, point = plan
        grid[point] = int(plan_color)

    if not any(owner == "square" for owner, *_ in plans):
        return None
    if not any(owner == "cross" for owner, *_ in plans):
        return None
    if not any(_ring_is_clipped(grid.shape, center, radius, "square" if owner == "square" else "cross")
               for owner, center, radius, _color, _point in plans):
        return None

    expected = _draw_plan_output(grid, plans, anchor_cells)
    try:
        actual = main(grid)
    except AssertionError:
        return None
    if not np.array_equal(actual, expected):
        return None
    if np.array_equal(expected, grid):
        return None

    wrong_square = _wrong_metric_output(grid, plans, anchor_cells, "square")
    wrong_cross = _wrong_metric_output(grid, plans, anchor_cells, "cross")
    if np.array_equal(wrong_square, expected) or np.array_equal(wrong_cross, expected):
        return None
    return grid


def generate_input() -> np.ndarray:
    for _ in range(600):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a valid metric-anchor input")
