from __future__ import annotations

from collections import Counter, deque
import random

import numpy as np


Coord = tuple[int, int]


def _bbox_coords(coords: list[Coord] | np.ndarray) -> tuple[int, int, int, int]:
    arr = np.asarray(coords, dtype=int)
    r0, c0 = arr.min(axis=0)
    r1, c1 = arr.max(axis=0)
    return int(r0), int(c0), int(r1), int(c1)


def _cropped_mask(coords: list[Coord]) -> tuple[np.ndarray, tuple[int, int, int, int]]:
    r0, c0, r1, c1 = _bbox_coords(coords)
    mask = np.zeros((r1 - r0 + 1, c1 - c0 + 1), dtype=bool)
    for r, c in coords:
        mask[r - r0, c - c0] = True
    return mask, (r0, c0, r1, c1)


def _components(mask: np.ndarray) -> list[list[Coord]]:
    h, w = mask.shape
    seen = np.zeros((h, w), dtype=bool)
    out: list[list[Coord]] = []
    for r in range(h):
        for c in range(w):
            if not bool(mask[r, c]) or bool(seen[r, c]):
                continue
            seen[r, c] = True
            queue: deque[Coord] = deque([(r, c)])
            comp: list[Coord] = []
            while queue:
                rr, cc = queue.popleft()
                comp.append((rr, cc))
                for nr, nc in ((rr - 1, cc), (rr + 1, cc), (rr, cc - 1), (rr, cc + 1)):
                    if 0 <= nr < h and 0 <= nc < w and bool(mask[nr, nc]) and not bool(seen[nr, nc]):
                        seen[nr, nc] = True
                        queue.append((nr, nc))
            out.append(comp)
    return out


def _is_connected(coords: list[Coord]) -> bool:
    if not coords:
        return False
    mask, _ = _cropped_mask(coords)
    comps = _components(mask)
    return len(comps) == 1 and len(comps[0]) == len(coords)


def _orbit(start: Coord, size: int) -> tuple[Coord, ...]:
    seen = {start}
    queue = [start]
    last = size - 1
    while queue:
        r, c = queue.pop()
        for rr, cc in ((c, r), (r, last - c), (last - r, c)):
            if 0 <= rr < size and 0 <= cc < size and (rr, cc) not in seen:
                seen.add((rr, cc))
                queue.append((rr, cc))
    return tuple(sorted(seen))


def _all_orbits(size: int) -> list[tuple[Coord, ...]]:
    seen: set[Coord] = set()
    out: list[tuple[Coord, ...]] = []
    for r in range(size):
        for c in range(size):
            if (r, c) in seen:
                continue
            orb = _orbit((r, c), size)
            seen.update(orb)
            out.append(orb)
    return out


def _find_divider(grid: np.ndarray) -> int:
    h, w = grid.shape
    candidates = [
        c
        for c in range(1, w - 1)
        if c == h and np.all(grid[:, c] == grid[0, c])
    ]
    assert len(candidates) == 1, "expected one full-height divider whose left side is square"
    return int(candidates[0])


def _detect_intruders(panel: np.ndarray) -> list[Coord]:
    n = int(panel.shape[0])
    intruders: list[Coord] = []
    for orb in _all_orbits(n):
        counts = Counter(int(panel[r, c]) for r, c in orb)
        ranked = counts.most_common()
        true_color, true_count = ranked[0]
        if len(ranked) > 1:
            assert true_count > ranked[1][1], "each corrupted orbit must have a unique majority color"
        bad = [(r, c) for r, c in orb if int(panel[r, c]) != int(true_color)]
        assert len(bad) <= 1, "each symmetry orbit may contain at most one intruder cell"
        intruders.extend(bad)
    assert intruders, "expected at least one intruder cell"
    return intruders


def _template_components(panel: np.ndarray) -> list[tuple[np.ndarray, int]]:
    bg = int(Counter(map(int, panel.flatten())).most_common(1)[0][0])
    comps = _components(panel != bg)
    out: list[tuple[np.ndarray, int]] = []
    for comp in comps:
        colors = {int(panel[r, c]) for r, c in comp}
        assert len(colors) == 1, "each right-panel template must be monochromatic"
        mask, _ = _cropped_mask(comp)
        out.append((mask, colors.pop()))
    assert out, "expected at least one candidate template"
    return out


def main(grid: np.ndarray) -> np.ndarray:
    """
    Find the symmetry-breaking intruder shape and recolor its cropped mask using the matching right-panel template.

    Input structure:
    - A full-height vertical divider splits the grid into a left square panel and a right template panel.
    - The left panel is invariant under main-diagonal transpose and under horizontal and vertical flips, except for one small connected intruder region recolored with already-used palette colors.
    - The right panel contains several separated monochrome candidate templates with pairwise different normalized masks.

    Rule:
    - Partition the left panel into symmetry orbits generated by transpose, horizontal flip, and vertical flip.
    - In each orbit, take the majority color as the true color; any cell that disagrees with that majority is an intruder cell.
    - Crop the full intruder mask to its bounding box, then find the unique right-panel template whose normalized mask exactly matches that crop.
    - Output the cropped intruder bbox, painting intruder cells with the matched template color and every other cell black.

    Key insight:
    - Color alone does not expose the intrusion: symmetry orbits localize the wrong cells, and only shape matching against the template panel determines the output color.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2, "expected a 2D grid"

    divider = _find_divider(g)
    left = g[:, :divider]
    right = g[:, divider + 1 :]
    assert left.shape[0] == left.shape[1], "left panel must be square"
    assert right.size > 0, "right template panel must be nonempty"

    intruders = _detect_intruders(left)
    intruder_mask, _ = _cropped_mask(intruders)

    matches = [
        color
        for mask, color in _template_components(right)
        if mask.shape == intruder_mask.shape and np.array_equal(mask, intruder_mask)
    ]
    assert len(matches) == 1, "expected exactly one template with the intruder shape"

    out = np.zeros(intruder_mask.shape, dtype=int)
    out[intruder_mask] = int(matches[0])
    return out


BG = 0
GEN_TRIES = 400
LEFT_SIZE_RANGE = (9, 13)
PALETTE = tuple(range(1, 10))
TEMPLATE_COUNT_RANGE = (3, 6)
SHAPE_AREA_RANGE = (2, 6)


def _mask_key(mask: np.ndarray) -> tuple[tuple[int, int], tuple[int, ...]]:
    return tuple(map(int, mask.shape)), tuple(int(x) for x in mask.astype(np.uint8).flatten())


def _orbit_representatives(size: int) -> dict[Coord, tuple[Coord, ...]]:
    reps: dict[Coord, tuple[Coord, ...]] = {}
    for orb in _all_orbits(size):
        reps[min(orb)] = orb
    return reps


def _grow_connected_shape(candidates: set[Coord], area: int) -> list[Coord] | None:
    if len(candidates) < area:
        return None
    start = random.choice(sorted(candidates))
    shape = {start}
    frontier = {
        nbr
        for nbr in ((start[0] - 1, start[1]), (start[0] + 1, start[1]), (start[0], start[1] - 1), (start[0], start[1] + 1))
        if nbr in candidates
    }
    while len(shape) < area and frontier:
        cell = random.choice(sorted(frontier))
        frontier.remove(cell)
        shape.add(cell)
        for nbr in ((cell[0] - 1, cell[1]), (cell[0] + 1, cell[1]), (cell[0], cell[1] - 1), (cell[0], cell[1] + 1)):
            if nbr in candidates and nbr not in shape:
                frontier.add(nbr)
    if len(shape) != area:
        return None
    coords = sorted(shape)
    if not _is_connected(coords):
        return None
    return coords


def _choose_intruder_shape(size: int) -> tuple[list[Coord], dict[Coord, tuple[Coord, ...]]] | None:
    reps = _orbit_representatives(size)
    mode = random.choice(("strict8", "mixed4or8"))
    if mode == "strict8":
        allowed = {rep for rep, orb in reps.items() if len(orb) == 8}
    else:
        allowed = {rep for rep, orb in reps.items() if len(orb) >= 4}
    if len(allowed) < SHAPE_AREA_RANGE[0]:
        return None

    max_area = min(SHAPE_AREA_RANGE[1], len(allowed))
    for _ in range(60):
        area = random.randint(SHAPE_AREA_RANGE[0], max_area)
        coords = _grow_connected_shape(allowed, area)
        if coords is None:
            continue
        if len({len(reps[c]) for c in coords}) == 1 and random.random() < 0.35:
            continue
        return coords, reps
    return None


def _build_clean_panel(size: int, divider_color: int, palette: list[int]) -> np.ndarray:
    panel = np.zeros((size, size), dtype=int)
    reps = _orbit_representatives(size)
    band_r = random.randint(1, 3)
    band_c = random.randint(1, 3)
    phase = random.randint(0, len(palette) - 1)
    stride = random.randint(1, len(palette))
    color_by_rep: dict[Coord, int] = {}
    for i, rep in enumerate(sorted(reps)):
        ridx = rep[0] // band_r
        cidx = rep[1] // band_c
        idx = (ridx + stride * cidx + phase + (i % len(palette))) % len(palette)
        color_by_rep[rep] = int(palette[idx])

    missing = [color for color in palette if color not in color_by_rep.values()]
    for color, rep in zip(missing, sorted(reps), strict=False):
        color_by_rep[rep] = int(color)

    assert divider_color not in color_by_rep.values()
    for rep, orb in reps.items():
        color = color_by_rep[rep]
        for r, c in orb:
            panel[r, c] = color
    return panel


def _corrupt_panel(clean: np.ndarray, shape: list[Coord], palette: list[int]) -> tuple[np.ndarray, dict[Coord, int]]:
    panel = clean.copy()
    true_colors = {int(clean[r, c]) for r, c in shape}
    shared_wrong = [color for color in palette if color not in true_colors]
    forced_uniform = bool(shared_wrong) and random.random() < 0.55
    wrong_map: dict[Coord, int] = {}
    uniform_color = random.choice(shared_wrong) if forced_uniform else None
    for r, c in shape:
        true_color = int(clean[r, c])
        if uniform_color is not None:
            wrong = int(uniform_color)
        else:
            choices = [color for color in palette if color != true_color]
            wrong = int(random.choice(choices))
        panel[r, c] = wrong
        wrong_map[(r, c)] = wrong
    return panel, wrong_map


def _random_connected_mask(
    *,
    exact_area: int | None = None,
    exact_shape: tuple[int, int] | None = None,
    max_side: int = 5,
) -> np.ndarray | None:
    if exact_shape is not None:
        h, w = exact_shape
    else:
        h = random.randint(1, max_side)
        w = random.randint(1, max_side)
    max_area = h * w
    if exact_area is None:
        low = 1 if max_area == 1 else 2
        area = random.randint(low, min(max_area, 7))
    else:
        area = exact_area
    if not (1 <= area <= max_area):
        return None

    cells = {(random.randrange(h), random.randrange(w))}
    frontier: set[Coord] = set()
    start = next(iter(cells))
    for nbr in ((start[0] - 1, start[1]), (start[0] + 1, start[1]), (start[0], start[1] - 1), (start[0], start[1] + 1)):
        if 0 <= nbr[0] < h and 0 <= nbr[1] < w:
            frontier.add(nbr)
    while len(cells) < area and frontier:
        cell = random.choice(sorted(frontier))
        frontier.remove(cell)
        cells.add(cell)
        for nbr in ((cell[0] - 1, cell[1]), (cell[0] + 1, cell[1]), (cell[0], cell[1] - 1), (cell[0], cell[1] + 1)):
            if 0 <= nbr[0] < h and 0 <= nbr[1] < w and nbr not in cells:
                frontier.add(nbr)
    if len(cells) != area:
        return None

    mask = np.zeros((h, w), dtype=bool)
    for r, c in cells:
        mask[r, c] = True
    coords = [tuple(map(int, rc)) for rc in np.argwhere(mask)]
    cropped, _ = _cropped_mask(coords)
    if exact_shape is not None and cropped.shape != exact_shape:
        return None
    return cropped


def _distinct_transforms(mask: np.ndarray) -> list[np.ndarray]:
    variants = []
    seen = {_mask_key(mask)}
    for transformed in (
        np.rot90(mask, 1),
        np.rot90(mask, 2),
        np.rot90(mask, 3),
        np.fliplr(mask),
        np.flipud(mask),
    ):
        key = _mask_key(transformed)
        if key not in seen:
            seen.add(key)
            variants.append(np.array(transformed, dtype=bool))
    return variants


def _make_template_masks(target_mask: np.ndarray, total_count: int) -> list[np.ndarray] | None:
    masks = [target_mask.copy()]
    seen = {_mask_key(target_mask)}
    target_area = int(target_mask.sum())
    target_shape = tuple(map(int, target_mask.shape))

    transforms = _distinct_transforms(target_mask)
    if transforms and len(masks) < total_count and random.random() < 0.75:
        hard = random.choice(transforms)
        masks.append(hard)
        seen.add(_mask_key(hard))

    for _ in range(80):
        if len(masks) >= total_count:
            break
        mode = random.choice(("same_bbox", "same_area", "free"))
        if mode == "same_bbox":
            cand = _random_connected_mask(exact_shape=target_shape)
        elif mode == "same_area":
            cand = _random_connected_mask(exact_area=target_area)
        else:
            cand = _random_connected_mask()
        if cand is None:
            continue
        key = _mask_key(cand)
        if key in seen:
            continue
        masks.append(cand)
        seen.add(key)

    if len(masks) != total_count:
        return None
    return masks


def _place_templates(height: int, width: int, masks: list[np.ndarray], colors: list[int]) -> np.ndarray | None:
    panel = np.full((height, width), BG, dtype=int)
    occupied = np.zeros((height, width), dtype=bool)
    order = list(range(len(masks)))
    order.sort(key=lambda i: masks[i].shape[0] * masks[i].shape[1], reverse=True)

    for idx in order:
        mask = masks[idx]
        color = int(colors[idx])
        h, w = map(int, mask.shape)
        placed = False
        for _ in range(120):
            r0 = random.randint(0, height - h)
            c0 = random.randint(0, width - w)
            rr0 = max(0, r0 - 1)
            cc0 = max(0, c0 - 1)
            rr1 = min(height, r0 + h + 1)
            cc1 = min(width, c0 + w + 1)
            if bool(occupied[rr0:rr1, cc0:cc1].any()):
                continue
            block = panel[r0 : r0 + h, c0 : c0 + w]
            block[mask] = color
            occupied[r0 : r0 + h, c0 : c0 + w] |= mask
            placed = True
            break
        if not placed:
            return None
    return panel


def _expected_output(shape: list[Coord], color: int) -> np.ndarray:
    mask, _ = _cropped_mask(shape)
    out = np.zeros(mask.shape, dtype=int)
    out[mask] = int(color)
    return out


def _validate_generated(
    grid: np.ndarray,
    clean_left: np.ndarray,
    intruder_shape: list[Coord],
    matched_color: int,
) -> np.ndarray | None:
    divider = _find_divider(grid)
    left = grid[:, :divider]
    right = grid[:, divider + 1 :]
    assert left.shape == clean_left.shape
    assert _is_connected(intruder_shape)

    for orb in _all_orbits(left.shape[0]):
        clean_colors = {int(clean_left[r, c]) for r, c in orb}
        assert len(clean_colors) == 1, "clean left panel must already satisfy the symmetry"

    detected = sorted(_detect_intruders(left))
    expected_coords = sorted(intruder_shape)
    if detected != expected_coords:
        return None

    masks = _template_components(right)
    target_mask, _ = _cropped_mask(intruder_shape)
    matches = [color for mask, color in masks if mask.shape == target_mask.shape and np.array_equal(mask, target_mask)]
    if matches != [matched_color]:
        return None

    expected = _expected_output(intruder_shape, matched_color)
    try:
        actual = main(grid)
    except AssertionError:
        return None
    if not np.array_equal(actual, expected):
        return None
    return expected


def _generate_case() -> tuple[np.ndarray, np.ndarray] | None:
    size = random.randint(*LEFT_SIZE_RANGE)
    divider_color = random.choice(list(PALETTE))
    left_palette_size = random.randint(3, 5)
    left_palette = random.sample([c for c in PALETTE if c != divider_color], left_palette_size)

    chosen = _choose_intruder_shape(size)
    if chosen is None:
        return None
    intruder_shape, reps = chosen
    if any(len(reps[cell]) == 1 for cell in intruder_shape):
        return None

    clean_left = _build_clean_panel(size, divider_color, left_palette)
    dirty_left, _ = _corrupt_panel(clean_left, intruder_shape, left_palette)

    target_mask, _ = _cropped_mask(intruder_shape)
    template_count = random.randint(*TEMPLATE_COUNT_RANGE)
    masks = _make_template_masks(target_mask, template_count)
    if masks is None:
        return None

    right_w_min = max(8, max(mask.shape[1] for mask in masks) + 2)
    right_w_max = 30 - size - 1
    if right_w_min > right_w_max:
        return None
    right_w = random.randint(right_w_min, right_w_max)

    template_colors = random.sample([c for c in PALETTE if c != divider_color], template_count)
    random.shuffle(masks)
    matched_color = template_colors[0]
    try:
        original_idx = next(i for i, mask in enumerate(masks) if np.array_equal(mask, target_mask))
    except StopIteration:
        return None
    masks[0], masks[original_idx] = masks[original_idx], masks[0]

    right = _place_templates(size, right_w, masks, template_colors)
    if right is None:
        return None

    divider = np.full((size, 1), divider_color, dtype=int)
    grid = np.hstack([dirty_left, divider, right])
    expected = _validate_generated(grid, clean_left, intruder_shape, matched_color)
    if expected is None:
        return None
    return grid, expected


def generate_input() -> np.ndarray:
    for _ in range(GEN_TRIES):
        built = _generate_case()
        if built is None:
            continue
        grid, _expected = built
        return grid
    raise RuntimeError("failed to generate a valid symmetric-lie ARC input")
