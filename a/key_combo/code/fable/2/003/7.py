from arc_utils import Color, crop_bbox, find_components  # noqa: E402


MAX_TILE_AREA = 10
INPUT_COLORS = [
    Color.BLACK,
    Color.BLUE,
    Color.RED,
    Color.GREEN,
    Color.YELLOW,
    Color.PINK,
    Color.ORANGE,
    Color.TEAL,
    Color.MAROON,
]

TILE_SHAPES = [(2, 2), (2, 3), (3, 2), (2, 4), (4, 2), (3, 3)]
SHIFT_MODES = ("row", "col", "diag")
REGION_MODES = ("rect", "el", "blob", "frame")

GRID_REPEAT_MIN = 3
GRID_REPEAT_MAX = 7
GEN_RETRIES = 500


def _majority_value(values: np.ndarray) -> tuple[int, int, int] | None:
    counts = Counter(map(int, values.ravel()))
    ranked = counts.most_common(2)
    if len(ranked) > 1 and int(ranked[0][1]) == int(ranked[1][1]):
        return None
    winner, top_count = ranked[0]
    runner_up = int(ranked[1][1]) if len(ranked) > 1 else 0
    return int(winner), int(top_count), int(top_count - runner_up)


def _render_periodic(tile: np.ndarray, phase: tuple[int, int], shape: tuple[int, int]) -> np.ndarray:
    h, w = map(int, shape)
    th, tw = map(int, tile.shape)
    row_ids = (np.arange(h) + int(phase[0])) % th
    col_ids = (np.arange(w) + int(phase[1])) % tw
    return tile[row_ids[:, None], col_ids[None, :]]


def _mask_components(mask: np.ndarray) -> list[dict]:
    return find_components(
        mask.astype(int),
        bg=0,
        colors=[1],
        connectivity=4,
        monochromatic=True,
    )


def _render_output(mask: np.ndarray, bbox: tuple[int, int, int, int]) -> np.ndarray:
    local = crop_bbox(mask.astype(int), bbox).astype(bool)
    out = np.full(local.shape, Color.BLACK, dtype=int)
    out[local] = Color.GREY
    return out


def _evaluate_candidate(grid: np.ndarray, tile_h: int, tile_w: int) -> dict | None:
    h, w = map(int, grid.shape)
    tile = np.empty((tile_h, tile_w), dtype=int)
    support = 0
    min_margin = None

    for rr in range(tile_h):
        for cc in range(tile_w):
            majority = _majority_value(grid[rr::tile_h, cc::tile_w])
            if majority is None:
                return None
            color, top_count, margin = majority
            tile[rr, cc] = color
            support += int(top_count)
            min_margin = margin if min_margin is None else min(min_margin, margin)

    if len({int(v) for v in tile.ravel()}) != tile_h * tile_w:
        return None

    predicted = _render_periodic(tile, (0, 0), (h, w))
    mismatch = predicted != grid
    mismatch_count = int(mismatch.sum())
    if mismatch_count == 0:
        return None

    components = _mask_components(mismatch)
    if len(components) != 1 or int(components[0]["area"]) != mismatch_count:
        return None

    return {
        "tile": tile,
        "mask": mismatch,
        "bbox": components[0]["bbox"],
        "key": (mismatch_count, tile_h * tile_w, -support, -(min_margin or 0), tile_h, tile_w),
        "primary_key": (mismatch_count, tile_h * tile_w),
    }


def _candidate_solutions(grid: np.ndarray) -> list[dict]:
    h, w = map(int, grid.shape)
    candidates: list[dict] = []

    max_h = min(h // 2, MAX_TILE_AREA)
    max_w = min(w // 2, MAX_TILE_AREA)
    for tile_h in range(1, max_h + 1):
        for tile_w in range(1, max_w + 1):
            if tile_h * tile_w > MAX_TILE_AREA:
                continue
            candidate = _evaluate_candidate(grid, tile_h, tile_w)
            if candidate is not None:
                candidates.append(candidate)

    candidates.sort(key=lambda item: item["key"])
    return candidates


def _solve_grid(grid: np.ndarray) -> tuple[np.ndarray, list[dict]]:
    candidates = _candidate_solutions(grid)
    assert candidates, "failed to infer a unique periodic wallpaper baseline"
    best = candidates[0]
    return _render_output(best["mask"], best["bbox"]), candidates


def main(grid: np.ndarray) -> np.ndarray:
    """
    Extract the unseen silhouette exposed by a local phase slip in a periodic wallpaper.

    Input structure:
    - The whole grid is generated by repeating a small tile whose cells all have distinct colors.
    - One 4-connected region is redrawn with the same tile but under a different non-zero row/column phase.
    - Locally every cell still looks legal; only the global phase baseline is broken inside that region.

    Rule:
    - Recover the smallest globally repeated tile and its majority phase baseline from the unshifted cells.
    - Mark every cell that disagrees with that global extension; this mismatch set is exactly the hidden silhouette.
    - Crop to the silhouette's bounding box and output grey on silhouette cells, black elsewhere.

    Key insight:
    - The anomaly is not a new color but a coherent phase offset, so the shape only appears after reconstructing the dominant periodic field and subtracting it.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2, "expected a 2D grid"
    assert max(g.shape) <= 30, "ARC grids must stay within 30x30"

    out, _candidates = _solve_grid(g)
    return out


def _choose_grid_side(period: int) -> int:
    repeats = random.randint(GRID_REPEAT_MIN, min(GRID_REPEAT_MAX, 30 // period))
    extra = random.randint(0, min(period - 1, 30 - repeats * period))
    return int(repeats * period + extra)


def _place_local(local: np.ndarray, shape: tuple[int, int], touch_edge: bool) -> np.ndarray:
    h, w = map(int, shape)
    lh, lw = map(int, local.shape)
    mask = np.zeros((h, w), dtype=bool)

    if touch_edge and (lh == h or lw == w):
        touch_edge = False

    if touch_edge:
        edge_mode = random.choice(("row", "col", "corner"))
        if edge_mode == "row":
            r0 = random.choice((0, h - lh))
            c0 = random.randint(0, w - lw)
        elif edge_mode == "col":
            r0 = random.randint(0, h - lh)
            c0 = random.choice((0, w - lw))
        else:
            r0 = random.choice((0, h - lh))
            c0 = random.choice((0, w - lw))
    else:
        r0 = random.randint(0, h - lh)
        c0 = random.randint(0, w - lw)

    mask[r0 : r0 + lh, c0 : c0 + lw] = local
    return mask


def _rect_mask(shape: tuple[int, int], touch_edge: bool) -> np.ndarray:
    h, w = map(int, shape)
    rh = random.randint(2, max(2, min(h - 1, int(round(h * 0.75)))))
    rw = random.randint(2, max(2, min(w - 1, int(round(w * 0.75)))))
    return _place_local(np.ones((rh, rw), dtype=bool), shape, touch_edge)


def _el_mask(shape: tuple[int, int], touch_edge: bool) -> np.ndarray:
    h, w = map(int, shape)
    lh = random.randint(4, max(4, min(h, int(round(h * 0.8)))))
    lw = random.randint(4, max(4, min(w, int(round(w * 0.8)))))
    arm_w = random.randint(1, max(1, lw // 2))
    arm_h = random.randint(1, max(1, lh // 2))

    local = np.zeros((lh, lw), dtype=bool)
    local[:, :arm_w] = True
    local[lh - arm_h :, :] = True
    if random.random() < 0.5:
        local = np.flipud(local)
    if random.random() < 0.5:
        local = np.fliplr(local)
    return _place_local(local, shape, touch_edge)


def _grow_blob(height: int, width: int, target: int) -> np.ndarray:
    local = np.zeros((height, width), dtype=bool)
    start = (random.randrange(height), random.randrange(width))
    filled = {start}
    frontier = set()
    for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
        nr, nc = start[0] + dr, start[1] + dc
        if 0 <= nr < height and 0 <= nc < width:
            frontier.add((nr, nc))

    while frontier and len(filled) < target:
        cell = random.choice(tuple(frontier))
        frontier.remove(cell)
        filled.add(cell)
        for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            nr, nc = cell[0] + dr, cell[1] + dc
            if 0 <= nr < height and 0 <= nc < width and (nr, nc) not in filled:
                frontier.add((nr, nc))

    for r, c in filled:
        local[r, c] = True
    return local


def _blob_mask(shape: tuple[int, int], touch_edge: bool) -> np.ndarray:
    h, w = map(int, shape)
    bh = random.randint(3, max(3, min(h, int(round(h * 0.75)))))
    bw = random.randint(3, max(3, min(w, int(round(w * 0.75)))))
    target = random.randint(max(5, (bh * bw) // 3), max(5, (2 * bh * bw) // 3))
    return _place_local(_grow_blob(bh, bw, target), shape, touch_edge)


def _frame_mask(shape: tuple[int, int], touch_edge: bool) -> np.ndarray:
    h, w = map(int, shape)
    fh = random.randint(5, max(5, min(h, int(round(h * 0.8)))))
    fw = random.randint(5, max(5, min(w, int(round(w * 0.8)))))
    max_thick = max(1, min(2, (min(fh, fw) - 1) // 2))
    thick = random.randint(1, max_thick)

    local = np.ones((fh, fw), dtype=bool)
    local[thick : fh - thick, thick : fw - thick] = False
    return _place_local(local, shape, touch_edge)


def _residue_majority_ok(mask: np.ndarray, tile_shape: tuple[int, int]) -> bool:
    tile_h, tile_w = map(int, tile_shape)
    for rr in range(tile_h):
        for cc in range(tile_w):
            residue = mask[rr::tile_h, cc::tile_w]
            if int(residue.sum()) * 2 >= residue.size:
                return False
    return True


def _region_mask(shape: tuple[int, int], tile_shape: tuple[int, int]) -> np.ndarray | None:
    mode = random.choice(REGION_MODES)
    touch_edge = random.random() < 0.35
    builders = {
        "rect": _rect_mask,
        "el": _el_mask,
        "blob": _blob_mask,
        "frame": _frame_mask,
    }
    mask = builders[mode](shape, touch_edge)
    area = int(mask.sum())
    h, w = map(int, shape)
    if area < max(4, (h * w) // 14) or area > max(8, (h * w) // 3):
        return None
    if not _residue_majority_ok(mask, tile_shape):
        return None

    components = _mask_components(mask)
    if len(components) != 1:
        return None
    r0, c0, r1, c1 = components[0]["bbox"]
    if r1 == r0 or c1 == c0:
        return None
    if (r1 - r0 + 1) == h and (c1 - c0 + 1) == w:
        return None
    return mask


def _phase_shift(tile_shape: tuple[int, int]) -> tuple[int, int]:
    tile_h, tile_w = map(int, tile_shape)
    mode = random.choice(SHIFT_MODES)
    if mode == "row":
        return random.randint(1, tile_h - 1), 0
    if mode == "col":
        return 0, random.randint(1, tile_w - 1)
    return random.randint(1, tile_h - 1), random.randint(1, tile_w - 1)


def _best_is_unique(candidates: list[dict], truth_mask: np.ndarray) -> bool:
    best = candidates[0]
    if not np.array_equal(best["mask"], truth_mask):
        return False
    for candidate in candidates[1:]:
        if candidate["primary_key"] != best["primary_key"]:
            break
        if not np.array_equal(candidate["mask"], truth_mask):
            return False
    return True


def _generate_case() -> tuple[np.ndarray, np.ndarray, np.ndarray] | None:
    tile_h, tile_w = random.choice(TILE_SHAPES)
    tile_colors = random.sample(INPUT_COLORS, tile_h * tile_w)
    tile = np.array(tile_colors, dtype=int).reshape(tile_h, tile_w)

    grid_h = _choose_grid_side(tile_h)
    grid_w = _choose_grid_side(tile_w)
    base_phase = (random.randrange(tile_h), random.randrange(tile_w))

    clean = _render_periodic(tile, base_phase, (grid_h, grid_w))
    mask = _region_mask(clean.shape, tile.shape)
    if mask is None:
        return None

    slip = _phase_shift(tile.shape)
    shifted = _render_periodic(tile, (base_phase[0] + slip[0], base_phase[1] + slip[1]), clean.shape)
    inp = clean.copy()
    inp[mask] = shifted[mask]

    expected = _render_output(mask, _mask_components(mask)[0]["bbox"])
    try:
        solved, candidates = _solve_grid(inp)
    except AssertionError:
        return None

    if not np.array_equal(solved, expected):
        return None
    if not _best_is_unique(candidates, mask):
        return None
    return inp, expected, mask


def generate_input() -> np.ndarray:
    for _ in range(GEN_RETRIES):
        case = _generate_case()
        if case is not None:
            return case[0]
    raise RuntimeError("failed to generate a valid phase-slip wallpaper input")
