from __future__ import annotations

import random

import numpy as np


UNKNOWN = 0
NON_BLACK_COLORS = tuple(range(1, 10))
# Under the exact 28e73c20 spiral rule, 8x8 and 9x9 exceed the requested
# 60% occlusion cap, so 10x10 is the only valid size in the stated range.
GRID_SIZES = (10,)
TILE_SIZES = (2, 3)
MAX_GENERATION_ATTEMPTS = 500


def _turn_clockwise(dr: int, dc: int) -> tuple[int, int]:
    return dc, -dr


def _spiral_mask(size: int) -> np.ndarray:
    mask = np.zeros((size, size), dtype=bool)
    r = c = 0
    dr, dc = 0, 1
    mask[r, c] = True

    while True:
        nr, nc = r + dr, c + dc
        if nr < 0 or nr >= size or nc < 0 or nc >= size:
            dr, dc = _turn_clockwise(dr, dc)
            continue
        if mask[nr, nc]:
            break
        fr, fc = r + 2 * dr, c + 2 * dc
        if 0 <= fr < size and 0 <= fc < size and mask[fr, fc]:
            dr, dc = _turn_clockwise(dr, dc)
            continue
        r, c = nr, nc
        mask[r, c] = True

    return mask


def _candidate_templates(grid: np.ndarray) -> list[tuple[int, int, int, np.ndarray]]:
    h, w = grid.shape
    observed = np.argwhere(grid != UNKNOWN)
    assert observed.size > 0

    candidates: list[tuple[int, int, int, np.ndarray]] = []
    for ph in range(1, h + 1):
        for pw in range(1, w + 1):
            template = np.full((ph, pw), -1, dtype=int)
            ok = True
            for r, c in observed:
                tr = int(r % ph)
                tc = int(c % pw)
                value = int(grid[r, c])
                if template[tr, tc] == -1:
                    template[tr, tc] = value
                elif template[tr, tc] != value:
                    ok = False
                    break
            if ok and np.all(template != -1):
                candidates.append((ph * pw, ph, pw, template))

    candidates.sort(key=lambda item: (item[0], item[1], item[2]))
    return candidates


def _infer_unique_smallest_template(grid: np.ndarray) -> np.ndarray:
    candidates = _candidate_templates(grid)
    assert candidates, "expected at least one valid periodic template"
    best_area = candidates[0][0]
    best = [item for item in candidates if item[0] == best_area]
    assert len(best) == 1, "expected a unique smallest template"
    return best[0][3]


def _render_tiling(template: np.ndarray, shape: tuple[int, int]) -> np.ndarray:
    h, w = shape
    rr = np.arange(h) % template.shape[0]
    cc = np.arange(w) % template.shape[1]
    return template[np.ix_(rr, cc)]


def _primitive_period(grid: np.ndarray) -> tuple[int, int]:
    template = _infer_unique_smallest_template(np.asarray(grid, dtype=int))
    return int(template.shape[0]), int(template.shape[1])


def main(grid: np.ndarray) -> np.ndarray:
    """
    Recover the periodic tiled image after treating the black spiral as an occlusion mask.

    Input structure:
    - The grid is square and contains a full-image periodic tiling built from a 2x2 or 3x3 non-black tile.
    - Black pixels occur only on one clockwise spiral path that starts at the top-left corner.
    - All non-black pixels are visible tile samples; black does not belong to the tile palette.

    Rule:
    - Recognize the black cells as the exact clockwise spiral generated by the standard turn-on-boundary / turn-on-two-step-collision rule.
    - Treat those spiral cells as unknown and ignore them when inferring the repeating tile.
    - Infer the unique smallest rectangular template consistent with every visible pixel under modular repetition.
    - Re-tile that template across the whole canvas and use it to fill the spiral cells.

    Key insight:
    - The black structure is not part of the pattern: it is a precisely defined spiral occlusion, and only after separating that geometry can the remaining pixels reveal the tile period needed to restore the hidden cells.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2
    h, w = g.shape
    assert h == w, "expected a square grid"

    spiral = _spiral_mask(h)
    assert np.array_equal(g == UNKNOWN, spiral), "black cells must be exactly the spiral mask"

    template = _infer_unique_smallest_template(g)
    out = _render_tiling(template, g.shape)
    assert np.array_equal(out[~spiral], g[~spiral])
    return out


def _sample_primitive_tile() -> np.ndarray:
    while True:
        size = random.choice(TILE_SIZES)
        color_count = random.choice((2, 3))
        palette = random.sample(NON_BLACK_COLORS, color_count)
        values = [random.choice(palette) for _ in range(size * size)]
        tile = np.array(values, dtype=int).reshape(size, size)
        if len(set(map(int, tile.flat))) != color_count:
            continue
        if _primitive_period(tile) != (size, size):
            continue
        return tile


def _residue_has_visible_and_hidden(
    spiral: np.ndarray,
    ph: int,
    pw: int,
) -> bool:
    for tr in range(ph):
        for tc in range(pw):
            residue = spiral[tr::ph, tc::pw]
            if not np.any(residue):
                return False
            if np.all(residue):
                return False
    return True


def _validate_instance(inp: np.ndarray, out: np.ndarray, tile: np.ndarray) -> bool:
    h, w = inp.shape
    if h != w or h not in GRID_SIZES:
        return False

    spiral = _spiral_mask(h)
    if not np.array_equal(inp == UNKNOWN, spiral):
        return False
    if spiral.mean() > 0.60:
        return False

    ph, pw = tile.shape
    if (ph, pw) not in ((2, 2), (3, 3)):
        return False
    if _primitive_period(tile) != (ph, pw):
        return False
    if not _residue_has_visible_and_hidden(spiral, ph, pw):
        return False

    masked_colors = set(map(int, out[spiral]))
    visible_colors = set(map(int, inp[~spiral]))
    if len(masked_colors) < 2 or len(visible_colors) < 2:
        return False

    try:
        inferred = _infer_unique_smallest_template(inp)
    except AssertionError:
        return False
    if not np.array_equal(inferred, tile):
        return False

    solved = main(inp)
    if not np.array_equal(solved, out):
        return False

    candidates = _candidate_templates(inp)
    min_area = candidates[0][0]
    if sum(area == min_area for area, _ph, _pw, _template in candidates) != 1:
        return False

    return True


def _generate_attempt() -> tuple[np.ndarray, np.ndarray, np.ndarray] | None:
    size = random.choice(GRID_SIZES)
    spiral = _spiral_mask(size)
    if spiral.mean() > 0.60:
        return None

    tile = _sample_primitive_tile()
    out = _render_tiling(tile, (size, size))
    inp = out.copy()
    inp[spiral] = UNKNOWN

    if not _validate_instance(inp, out, tile):
        return None
    return inp, out, tile


def generate_input() -> np.ndarray:
    for _ in range(MAX_GENERATION_ATTEMPTS):
        sample = _generate_attempt()
        if sample is not None:
            return sample[0]
    raise RuntimeError(f"generate_input: failed after {MAX_GENERATION_ATTEMPTS} attempts")
