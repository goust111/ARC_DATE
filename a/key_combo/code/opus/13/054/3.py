from __future__ import annotations

import random
from collections import Counter

import numpy as np


BACKGROUND = 0
CENTER_COLOR = 4
SOURCE_COLORS = (1, 2, 3, 6)
GRID_SIZES = (13, 15)
MAX_GENERATION_ATTEMPTS = 400


def _sign(value: int) -> int:
    return (value > 0) - (value < 0)


def _diagonal_cells(a: tuple[int, int], b: tuple[int, int]) -> list[tuple[int, int]]:
    r0, c0 = map(int, a)
    r1, c1 = map(int, b)
    dr = r1 - r0
    dc = c1 - c0
    assert dr != 0 and abs(dr) == abs(dc), "endpoints must define a strict diagonal"
    step_r = _sign(dr)
    step_c = _sign(dc)
    return [(r0 + k * step_r, c0 + k * step_c) for k in range(abs(dr) + 1)]


def _get_center(grid: np.ndarray) -> tuple[int, int]:
    h, w = map(int, grid.shape)
    assert h == w and h % 2 == 1, "expected an odd square grid"
    cr = h // 2
    cc = w // 2
    center_coords = np.argwhere(grid == CENTER_COLOR)
    assert len(center_coords) == 1, "expected exactly one center marker"
    assert tuple(map(int, center_coords[0])) == (cr, cc), "center marker must be at the grid center"
    return cr, cc


def main(grid: np.ndarray) -> np.ndarray:
    """
    Reflect each singleton color through the yellow center, then connect each created endpoint pair by a strict diagonal.

    Input structure:
    - The grid is an odd square with black background and a single yellow center marker.
    - Every other foreground color is a singleton endpoint candidate.
    - Each singleton is positioned so that its 180-degree point reflection through the center lies on a strict 45-degree diagonal with it.

    Rule:
    - Keep the yellow center marker fixed.
    - For every non-black, non-yellow singleton, create its 180-degree point-reflected partner through the center.
    - Fill every cell on the strict diagonal segment joining the original singleton and its reflected partner.
    - If a segment passes through the center cell, that cell stays yellow instead of taking the segment color.

    Key insight:
    - The input does not contain endpoint pairs yet; the missing second endpoint must be generated by point symmetry before diagonal completion can happen.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2, "grid must be 2D"
    cr, cc = _get_center(g)

    colors = [int(color) for color in np.unique(g) if int(color) not in (BACKGROUND, CENTER_COLOR)]
    out = g.copy()
    planned: dict[tuple[int, int], int] = {}

    for color in colors:
        coords = np.argwhere(g == color)
        assert len(coords) == 1, "each non-center color must appear exactly once in the input"
        r, c = map(int, coords[0])
        rr = 2 * cr - r
        rc = 2 * cc - c
        assert 0 <= rr < g.shape[0] and 0 <= rc < g.shape[1], "reflected endpoint must stay in bounds"

        for cell in _diagonal_cells((r, c), (rr, rc)):
            if cell == (cr, cc):
                continue
            prev = planned.get(cell)
            assert prev is None or prev == color, "different diagonal segments may only meet at the center"
            planned[cell] = color

    out.fill(BACKGROUND)
    for (r, c), color in planned.items():
        out[r, c] = int(color)
    out[cr, cc] = CENTER_COLOR
    return out


def _render_expected(size: int, specs: list[tuple[int, int, int]]) -> np.ndarray:
    grid = np.full((size, size), BACKGROUND, dtype=int)
    cr = cc = size // 2
    occupied: dict[tuple[int, int], int] = {}

    for color, dr, dc in specs:
        src = (cr + dr, cc + dc)
        dst = (cr - dr, cc - dc)
        for cell in _diagonal_cells(src, dst):
            if cell == (cr, cc):
                continue
            prev = occupied.get(cell)
            if prev is not None and prev != color:
                raise ValueError("non-center intersection")
            occupied[cell] = color

    for (r, c), color in occupied.items():
        grid[r, c] = int(color)
    grid[cr, cc] = CENTER_COLOR
    return grid


def _render_input(size: int, specs: list[tuple[int, int, int]]) -> np.ndarray:
    grid = np.full((size, size), BACKGROUND, dtype=int)
    cr = cc = size // 2
    grid[cr, cc] = CENTER_COLOR
    for color, dr, dc in specs:
        grid[cr + dr, cc + dc] = int(color)
    return grid


def _validate_instance(inp: np.ndarray, out: np.ndarray, specs: list[tuple[int, int, int]]) -> None:
    size = int(inp.shape[0])
    assert inp.shape == (size, size)
    assert out.shape == (size, size)
    cr = cc = size // 2

    assert int(inp[cr, cc]) == CENTER_COLOR and int(out[cr, cc]) == CENTER_COLOR
    assert np.count_nonzero(inp == CENTER_COLOR) == 1
    assert np.count_nonzero(out == CENTER_COLOR) == 1

    expected_input = _render_input(size, specs)
    expected_output = _render_expected(size, specs)
    assert np.array_equal(inp, expected_input), "generator input does not match its sampled parameters"
    assert np.array_equal(out, expected_output), "solver output disagrees with the geometric specification"

    input_colors = Counter(map(int, inp.flatten()))
    output_colors = Counter(map(int, out.flatten()))
    for color, dr, dc in specs:
        assert input_colors[color] == 1, "each sampled color must be a singleton in the input"
        distance = abs(int(dr))
        assert distance == abs(int(dc)) and distance >= 1
        assert output_colors[color] == 2 * distance, "output must be the full diagonal segment minus the center cell"

    source_cells = {
        (cr + dr, cc + dc)
        for _color, dr, dc in specs
    }
    assert len(source_cells) == len(specs), "source singletons must be distinct"

    non_bg_non_center = {
        tuple(map(int, cell))
        for cell in np.argwhere(inp != BACKGROUND)
        if tuple(map(int, cell)) != (cr, cc)
    }
    assert non_bg_non_center == source_cells, "input must contain only the center and the source singletons"


def _sample_specs(size: int) -> list[tuple[int, int, int]]:
    center = size // 2
    colors = random.sample(SOURCE_COLORS, 2)
    top_dist = random.randint(1, center - 1)
    bottom_dist = random.randint(1, center - 1)

    # Minimal consistent family: one source on each left-side diagonal so the two completed
    # segments intersect only at the center.
    return [
        (colors[0], -top_dist, -top_dist),
        (colors[1], bottom_dist, -bottom_dist),
    ]


def _gen_attempt() -> np.ndarray | None:
    size = random.choice(GRID_SIZES)
    specs = _sample_specs(size)
    inp = _render_input(size, specs)
    try:
        out = main(inp)
        _validate_instance(inp, out, specs)
    except Exception:
        return None

    # Reject accidental low-diversity cases where both colors and distances repeat a previous
    # geometry too often inside a single run by requiring the two segment lengths to be visible.
    segment_lengths = sorted(abs(dr) for _color, dr, _dc in specs)
    if segment_lengths[1] < 2:
        return None
    return inp


def generate_input() -> np.ndarray:
    for _ in range(MAX_GENERATION_ATTEMPTS):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a valid input for puzzle 3")
