from __future__ import annotations

import random
import numpy as np

BG = 0


def _compress_adjacent_rows(grid: np.ndarray) -> np.ndarray:
    rows = [grid[0]]
    for r in range(1, grid.shape[0]):
        if not np.array_equal(grid[r], rows[-1]):
            rows.append(grid[r])
    return np.stack(rows, axis=0)


def _compress_adjacent_cols(grid: np.ndarray) -> np.ndarray:
    rows = grid
    cols = [rows[:, 0]]
    for c in range(1, rows.shape[1]):
        if not np.array_equal(rows[:, c], cols[-1]):
            cols.append(rows[:, c])
    return np.stack(cols, axis=1)


def _deduplicate(grid: np.ndarray) -> np.ndarray:
    return _compress_adjacent_cols(_compress_adjacent_rows(grid))


def main(grid: np.ndarray) -> np.ndarray:
    """
    Decompress rows/columns by merging adjacent duplicates, then tile the sprite according to color statistics.

    Input structure:
    - A rectangular grid generated by expanding a small square sprite.
    - Expansion repeats each sprite row and column by one or more times.
    - Sprite itself is square and uses black as background with one foreground color.

    Rule:
    - Deduplicate adjacent identical rows and columns to recover the hidden square sprite.
    - Count F = number of non-black foreground pixels and B = number of black pixels in the recovered sprite.
    - Build a B×B canvas of sprite-sized slots (black background), each slot size = sprite size.
    - Place recovered sprite in the first F slots in row-major order; other slots remain black.

    Key insight:
    - The information needed to tile the output is hidden in run-length patterns of rows and columns, not in the visible expanded grid itself.
    """
    hidden = _deduplicate(np.asarray(grid, dtype=int))
    Hs, Ws = hidden.shape
    assert Hs == Ws and Hs in (3, 4)

    bg = BG
    F = int(np.sum(hidden != bg))
    B = int(np.sum(hidden == bg))
    assert F >= 2 and B >= 4

    out = np.full((B * Hs, B * Ws), bg, dtype=int)
    for idx in range(min(F, B * B)):
        sr, sc = divmod(idx, B)
        out[sr * Hs : (sr + 1) * Hs, sc * Ws : (sc + 1) * Ws] = hidden
    return out


def _sample_hidden_sprite(n: int) -> np.ndarray:
    total = n * n
    fg = random.randint(2, total - 4)
    bg = total - fg
    if bg < 4:
        fg = total - 4
        bg = 4
    sprite = np.full((n, n), BG, dtype=int)

    fg_color = random.randint(1, 9)
    while fg_color == BG:
        fg_color = random.randint(1, 9)

    positions = list(range(total))
    random.shuffle(positions)
    for pos in positions[:fg]:
        r, c = divmod(pos, n)
        sprite[r, c] = fg_color
    return sprite


def _expand_sprite(sprite: np.ndarray, row_reps: list[int], col_reps: list[int]) -> np.ndarray:
    grid = sprite
    grid = np.repeat(grid, row_reps, axis=0)
    grid = np.repeat(grid, col_reps, axis=1)
    return grid


def generate_input() -> np.ndarray:
    for _ in range(2000):
        n = random.choice([3, 4])
        hidden = _sample_hidden_sprite(n)

        F = int(np.sum(hidden != BG))
        B = int(np.sum(hidden == BG))
        if not (F >= 2 and B >= 4 and B <= 7):
            continue
        Hs, Ws = hidden.shape
        row_reps = [random.randint(1, 4) for _ in range(Hs)]
        col_reps = [random.randint(1, 4) for _ in range(Ws)]
        inp = _expand_sprite(hidden, row_reps, col_reps)

        if inp.shape[0] > 30 or inp.shape[1] > 30:
            continue
        if B * max(Hs, Ws) > 30:
            continue
        try:
            out = main(inp)
            assert out.shape == (B * Hs, B * Ws)
        except Exception:
            continue
        return inp

    raise RuntimeError("failed to generate valid puzzle 3 input")

