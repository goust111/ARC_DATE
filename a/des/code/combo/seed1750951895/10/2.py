import numpy as np


_RNG = np.random.default_rng()
_MAX_RETRIES = 400
_GRID_H_RANGE = (12, 23)
_GRID_W_RANGE = (12, 23)
_TILE_H_RANGE = (2, 5)
_TILE_W_RANGE = (2, 5)
_RECT_COUNT_RANGE = (1, 4)


def _neighbors(r: int, c: int, h: int, w: int):
    if r > 0:
        yield r - 1, c
    if r + 1 < h:
        yield r + 1, c
    if c > 0:
        yield r, c - 1
    if c + 1 < w:
        yield r, c + 1


def _find_rectangles(grid: np.ndarray) -> list[dict]:
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    seen = np.zeros((h, w), dtype=bool)
    rects = []
    for r in range(h):
        for c in range(w):
            if seen[r, c]:
                continue
            color = int(g[r, c])
            stack = [(r, c)]
            seen[r, c] = True
            coords = []
            while stack:
                cr, cc = stack.pop()
                coords.append((cr, cc))
                for nr, nc in _neighbors(cr, cc, h, w):
                    if not seen[nr, nc] and int(g[nr, nc]) == color:
                        seen[nr, nc] = True
                        stack.append((nr, nc))
            arr = np.asarray(coords, dtype=int)
            r0, c0 = arr.min(axis=0)
            r1, c1 = arr.max(axis=0)
            hh = int(r1 - r0 + 1)
            ww = int(c1 - c0 + 1)
            if hh <= 1 or ww <= 1:
                continue
            if len(coords) != hh * ww:
                continue
            rects.append(
                {
                    "color": color,
                    "bbox": (int(r0), int(c0), int(r1), int(c1)),
                    "area": int(hh * ww),
                }
            )
    return rects


def _rect_mask(shape: tuple[int, int], rects: list[dict]) -> np.ndarray:
    mask = np.zeros(shape, dtype=bool)
    for rect in rects:
        r0, c0, r1, c1 = rect["bbox"]
        mask[r0 : r1 + 1, c0 : c1 + 1] = True
    return mask


def _period_consistent_rows(grid: np.ndarray, visible: np.ndarray, period: int) -> bool:
    h, w = grid.shape
    for c in range(w):
        for r in range(h - period):
            if visible[r, c] and visible[r + period, c] and int(grid[r, c]) != int(grid[r + period, c]):
                return False
    return True


def _period_consistent_cols(grid: np.ndarray, visible: np.ndarray, period: int) -> bool:
    h, w = grid.shape
    for r in range(h):
        for c in range(w - period):
            if visible[r, c] and visible[r, c + period] and int(grid[r, c]) != int(grid[r, c + period]):
                return False
    return True


def _infer_periods(grid: np.ndarray, visible: np.ndarray) -> tuple[int, int]:
    h, w = grid.shape
    row_period = next((p for p in range(1, h + 1) if _period_consistent_rows(grid, visible, p)), h)
    col_period = next((p for p in range(1, w + 1) if _period_consistent_cols(grid, visible, p)), w)
    return row_period, col_period


def _tile_from_visible(grid: np.ndarray, visible: np.ndarray, periods: tuple[int, int]) -> np.ndarray:
    pr, pc = periods
    tile = np.full((pr, pc), -1, dtype=int)
    for r, c in zip(*np.where(visible)):
        rr = int(r % pr)
        cc = int(c % pc)
        value = int(grid[r, c])
        if tile[rr, cc] == -1:
            tile[rr, cc] = value
        else:
            assert int(tile[rr, cc]) == value
    assert np.all(tile != -1)
    return tile


def _reconstruct(grid: np.ndarray, rects: list[dict]) -> tuple[np.ndarray, tuple[int, int], np.ndarray]:
    assert rects, "expected at least one solid rectangle"
    target = max(rects, key=lambda rect: (rect["area"], -rect["bbox"][0], -rect["bbox"][1]))
    mask = _rect_mask(grid.shape, rects)
    visible = ~mask
    periods = _infer_periods(grid, visible)
    tile = _tile_from_visible(grid, visible, periods)
    out = np.asarray(grid, dtype=int).copy()
    r0, c0, r1, c1 = target["bbox"]
    pr, pc = periods
    for r in range(r0, r1 + 1):
        for c in range(c0, c1 + 1):
            out[r, c] = int(tile[r % pr, c % pc])
    return out, periods, target["bbox"]


def main(grid: np.ndarray) -> np.ndarray:
    """
    Restore the periodic background underneath the largest solid rectangular occluder.

    Input structure:
    - A full-grid background is generated by tiling a small periodic pattern.
    - One or more filled monochrome rectangles occlude parts of that pattern.
    - The largest such rectangle is the region to repair.

    Rule:
    - Detect 4-connected monochrome objects that are completely filled rectangles
      with both dimensions greater than one.
    - Treat every such rectangle as an occlusion mask when inferring the minimal
      row/column periods from the remaining visible cells.
    - Repaint only the largest rectangle using the inferred periodic tile.
    - Leave smaller rectangles unchanged.
    """
    g = np.asarray(grid, dtype=int)
    assert g.ndim == 2
    rects = _find_rectangles(g)
    out, _, _ = _reconstruct(g, rects)
    return out


def _is_primitive_axis(arr: np.ndarray, axis: int) -> bool:
    size = arr.shape[axis]
    for p in range(1, size):
        if size % p != 0:
            continue
        ok = True
        for i in range(size):
            sl0 = [slice(None)] * arr.ndim
            sl1 = [slice(None)] * arr.ndim
            sl0[axis] = i
            sl1[axis] = i % p
            if not np.array_equal(arr[tuple(sl0)], arr[tuple(sl1)]):
                ok = False
                break
        if ok:
            return False
    return True


def _make_tile(tile_h: int, tile_w: int) -> np.ndarray:
    palette = np.arange(10, dtype=int)
    for _ in range(200):
        color_count = int(_RNG.integers(3, min(7, len(palette)) + 1))
        colors = _RNG.choice(palette, size=color_count, replace=False)
        tile = _RNG.choice(colors, size=(tile_h, tile_w), replace=True)
        if len(set(map(int, tile.ravel()))) < 2:
            continue
        if _is_primitive_axis(tile, 0) and _is_primitive_axis(tile, 1):
            return tile.astype(int)
    raise RuntimeError("failed to create primitive tile")


def _repeat_tile(tile: np.ndarray, h: int, w: int) -> np.ndarray:
    th, tw = tile.shape
    rows = np.arange(h) % th
    cols = np.arange(w) % tw
    return tile[rows[:, None], cols[None, :]]


def _sample_rectangles(h: int, w: int) -> list[tuple[int, int, int, int]]:
    count = int(_RNG.integers(_RECT_COUNT_RANGE[0], _RECT_COUNT_RANGE[1] + 1))
    rects = []
    occupied = np.zeros((h, w), dtype=bool)
    target_area = None
    for idx in range(count):
        for _ in range(200):
            if idx == 0:
                rh = int(_RNG.integers(max(3, h // 4), max(4, h // 2 + 1)))
                rw = int(_RNG.integers(max(3, w // 4), max(4, w // 2 + 1)))
            else:
                max_h = max(3, h // 3 + 1)
                max_w = max(3, w // 3 + 1)
                rh = int(_RNG.integers(2, max_h))
                rw = int(_RNG.integers(2, max_w))
            if rh >= h or rw >= w:
                continue
            r0 = int(_RNG.integers(1, h - rh))
            c0 = int(_RNG.integers(1, w - rw))
            r1 = r0 + rh - 1
            c1 = c0 + rw - 1
            grown = occupied[max(0, r0 - 1) : min(h, r1 + 2), max(0, c0 - 1) : min(w, c1 + 2)]
            if grown.any():
                continue
            area = rh * rw
            if idx == 0:
                target_area = area
            elif area >= target_area:
                continue
            occupied[r0 : r1 + 1, c0 : c1 + 1] = True
            rects.append((r0, c0, r1, c1))
            break
        else:
            return []
    _RNG.shuffle(rects)
    return rects


def _visible_covers_all_residues(mask: np.ndarray, periods: tuple[int, int]) -> bool:
    pr, pc = periods
    seen = np.zeros((pr, pc), dtype=bool)
    for r, c in zip(*np.where(~mask)):
        seen[r % pr, c % pc] = True
    return bool(seen.all())


def _paint_rectangles(base: np.ndarray, rects: list[tuple[int, int, int, int]]) -> np.ndarray:
    grid = base.copy()
    used = set(map(int, base.ravel()))
    palette = [c for c in range(10) if c not in used]
    if len(palette) < len(rects):
        palette = list(range(10))
    colors = _RNG.choice(np.array(palette, dtype=int), size=len(rects), replace=False)
    for color, (r0, c0, r1, c1) in zip(colors, rects):
        grid[r0 : r1 + 1, c0 : c1 + 1] = int(color)
    return grid


def _gen_attempt() -> np.ndarray | None:
    h = int(_RNG.integers(_GRID_H_RANGE[0], _GRID_H_RANGE[1] + 1))
    w = int(_RNG.integers(_GRID_W_RANGE[0], _GRID_W_RANGE[1] + 1))
    tile_h = int(_RNG.integers(_TILE_H_RANGE[0], min(_TILE_H_RANGE[1], h - 2) + 1))
    tile_w = int(_RNG.integers(_TILE_W_RANGE[0], min(_TILE_W_RANGE[1], w - 2) + 1))
    tile = _make_tile(tile_h, tile_w)
    base = _repeat_tile(tile, h, w)

    rects = _sample_rectangles(h, w)
    if not rects:
        return None
    mask = np.zeros((h, w), dtype=bool)
    for r0, c0, r1, c1 in rects:
        mask[r0 : r1 + 1, c0 : c1 + 1] = True
    if not _visible_covers_all_residues(mask, (tile_h, tile_w)):
        return None

    grid = _paint_rectangles(base, rects)
    found = _find_rectangles(grid)
    if len(found) != len(rects):
        return None

    try:
        rebuilt, periods, bbox = _reconstruct(grid, found)
    except AssertionError:
        return None

    target = max(rects, key=lambda rect: (rect[2] - rect[0] + 1) * (rect[3] - rect[1] + 1))
    if periods != (tile_h, tile_w):
        return None
    if tuple(bbox) != tuple(target):
        return None

    expected = grid.copy()
    r0, c0, r1, c1 = target
    expected[r0 : r1 + 1, c0 : c1 + 1] = base[r0 : r1 + 1, c0 : c1 + 1]
    if not np.array_equal(rebuilt, expected):
        return None
    return grid


def generate_input() -> np.ndarray:
    for _ in range(_MAX_RETRIES):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError(f"failed to generate valid input after {_MAX_RETRIES} attempts")
