import random
import numpy as np


def _components(mask):
    h, w = mask.shape
    seen = np.zeros((h, w), bool)
    comps = []
    for r in range(h):
        for c in range(w):
            if not mask[r, c] or seen[r, c]:
                continue
            q = [(r, c)]
            seen[r, c] = True
            pts = []
            while q:
                x, y = q.pop()
                pts.append((x, y))
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < h and 0 <= ny < w and mask[nx, ny] and not seen[nx, ny]:
                        seen[nx, ny] = True
                        q.append((nx, ny))
            comps.append(pts)
    return comps


def main(grid: np.ndarray) -> np.ndarray:
    """Wrap the largest colored cluster in successive outline layers ordered by cluster area.

    Input structure: black background with separated 4-connected colored
    clusters, one cluster per color and all cluster areas distinct.
    Rule: sort clusters by decreasing area, keep only the largest shape as the
    core, erase all others, then use each smaller cluster's color in order to
    paint the current motif's 4-neighbor background frontier as a new outline.
    Key insight: the consumed clusters contribute only their colors and area
    order; the final geometry is generated by iterative outlining.
    """
    comps = []
    for color in [int(x) for x in np.unique(grid) if x != 0]:
        pts = [(int(r), int(c)) for r, c in np.argwhere(grid == color)]
        comps.append((len(pts), color, pts))
    if not comps:
        return grid.copy()
    comps.sort(reverse=True)
    out = np.zeros_like(grid)
    current = np.zeros(grid.shape, bool)
    for r, c in comps[0][2]:
        out[r, c] = comps[0][1]
        current[r, c] = True
    for _, color, _pts in comps[1:]:
        frontier = np.zeros(grid.shape, bool)
        for r, c in np.argwhere(current):
            for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nr, nc = int(r) + dr, int(c) + dc
                if 0 <= nr < grid.shape[0] and 0 <= nc < grid.shape[1] and not current[nr, nc]:
                    frontier[nr, nc] = True
        out[frontier] = color
        current |= frontier
    return out


def generate_input() -> np.ndarray:
    grid = np.zeros((22, 22), dtype=int)
    colors = random.sample([1, 2, 3, 4, 6, 7, 8, 9], random.randint(3, 6))
    areas = random.sample(range(2, 9), len(colors))
    shapes = {
        2: [(0, 0), (0, 1)],
        3: [(0, 0), (1, 0), (1, 1)],
        4: [(0, 0), (0, 1), (1, 0), (1, 1)],
        5: [(0, 1), (1, 0), (1, 1), (1, 2), (2, 1)],
        6: [(0, 0), (0, 1), (1, 1), (2, 1), (2, 2), (2, 3)],
        7: [(0, 1), (1, 0), (1, 1), (1, 2), (2, 1), (3, 1), (3, 2)],
        8: [(0, 1), (0, 2), (1, 0), (1, 1), (1, 2), (2, 1), (3, 1), (3, 2)],
    }
    for color, area in zip(colors, areas):
        shape = shapes[area]
        for _ in range(300):
            r = random.randint(2, 18)
            c = random.randint(2, 18)
            cells = [(r + a, c + b) for a, b in shape]
            if all(0 <= x < 22 and 0 <= y < 22 and grid[x, y] == 0 for x, y in cells):
                if all(grid[max(0, x - 1):min(22, x + 2), max(0, y - 1):min(22, y + 2)].sum() == 0 for x, y in cells):
                    for x, y in cells:
                        grid[x, y] = color
                    break
    return grid
