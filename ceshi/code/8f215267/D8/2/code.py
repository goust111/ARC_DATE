from __future__ import annotations

# Variant of 8f215267
# Dimension: D8 — 输出网格形状 (grid_shape)
# Change: 输出网格与输入网格尺寸完全相同（23列宽，行数不变）... → 仅输出框架内部
#
# Design analysis
# - Concrete change: the input stays the same as the original task: 5x11 hollow frames are
#   stacked on the left, monochrome sprites are scattered on the right. The output no longer
#   keeps the whole 23-column canvas. Instead, for each frame we keep only its 3x9 interior
#   and stack those interiors top-to-bottom in frame order. This follows the same "crop the
#   useful region" spirit as the reference task a251c730, but here the useful regions are
#   multiple frame interiors rather than one rectangle.
# - Behavior trace: originally the solver copied the full grid, erased all sprites, then drew
#   same-color tally dots at absolute positions inside each frame. In this variant the count
#   logic is unchanged, but the final rendering step changes: each frame becomes a fresh 3x9
#   interior patch with dots on its middle row, and the solver concatenates those patches.
# - Complexity calibration: keeping the frame count at 3-4 and the dot count at 0-4 preserves
#   the original reasoning load. The D8 change is visually obvious because outputs are always
#   width 9 instead of width 23, while still showing repeated per-frame structure.
# - Implicit assumptions reviewed:
#   * Frame detection still relies on hollow rectangles occupying a sparse fraction of their
#     bounding box. The generator preserves 5x11 hollow frames, so this remains safe.
#   * The new output order depends on sorting frames by top row. The generator keeps frames in
#     a single vertical stack, so top-to-bottom order is unambiguous.
#   * Dot placement still assumes at most four matches fit the 9-wide interior under the
#     original spacing rule. The generator still caps each frame count at 4.
#   * Cropped interiors use the global background because the original frame interiors are
#     background except for tally dots. The input is generated by removing those dots before
#     adding right-side sprites, so no hidden interior structure is lost.
# - Placement legality: sprites are still placed only in the right-side canvas via
#   random_free_location with padding, so they do not overlap each other or any frame.
# - Visual cleanliness: removing borders from the output reduces clutter instead of adding it.
#   Each frame contributes a clean 3-row band, which makes the "output is only the inside"
#   rule observable from a few examples.
# - New solver assumptions guaranteed by the generator:
#   * there is at least one frame;
#   * all frames keep the same 5x11 geometry, so every cropped interior is exactly 3x9;
#   * frames do not overlap and are strictly vertically ordered.

import numpy as np
from arc_utils import bbox_h, bbox_w, find_components, get_bg
from arc_utils import paste, random_free_location

# --- layout geometry ---
FRAME_H = 5
FRAME_W = 11
INTERIOR_H = FRAME_H - 2
INTERIOR_W = FRAME_W - 2
FRAME_R0 = 1
FRAME_C0 = 1
FRAME_GAP = 2
GRID_W = 23
RIGHT_C0 = 13
RIGHT_W = 9

# --- structural counts ---
N_FRAMES_RANGE = (3, 5)
N_DISTRACTORS_RANGE = (1, 3)
TOTAL_PATTERNS_RANGE = (5, 11)
MAX_DOTS_PER_FRAME = 4
BOTTOM_PAD_RANGE = (0, 7)

# --- sprite shape ---
SPRITE_AREA_RANGE = (2, 9)
SPRITE_MAX_H = 4
SPRITE_MAX_W = 3
SPRITE_PADDING = 1

# --- retry budget ---
MAX_ATTEMPTS = 300


def _is_frame(comp: dict) -> bool:
    b = comp["bbox"]
    h = bbox_h(b)
    w = bbox_w(b)
    area = int(comp["area"])
    return (h >= FRAME_H) and (w >= FRAME_W) and (area < (h * w * 0.7))


def _frame_sort_key(comp: dict) -> tuple[int, int]:
    r0, c0, _, _ = map(int, comp["bbox"])
    return int(r0), int(c0)


def _interior_patch(color: int, bg: int, n_dots: int) -> np.ndarray:
    patch = np.full((INTERIOR_H, INTERIOR_W), bg, dtype=int)
    mid_r = INTERIOR_H // 2
    for i in range(int(n_dots)):
        cc = INTERIOR_W - 2 - 2 * i
        if cc >= 0:
            patch[mid_r, cc] = int(color)
    return patch


def main(grid: np.ndarray) -> np.ndarray:
    """
    Count same-color patterns per frame and represent the tally as cropped interiors only.

    Input structure:
    - bg = most common color.
    - Hollow rectangular frames in various colors.
    - Small monochrome pattern sprites scattered outside frames.

    Rule:
    - Ignore the full-canvas output shape from the original task.
    - For each frame of color C, count how many patterns share color C.
    - Build only that frame's 3x9 interior, with tally dots on the center row spaced by 2
      from the right.
    - Stack those interiors top-to-bottom in the same order as the input frames.
    """
    g = np.array(grid, dtype=int)
    bg = int(get_bg(g))

    regions = find_components(g, bg=bg, connectivity=4, monochromatic=True, return_format="dict")

    frames: list[dict] = []
    patterns: list[dict] = []
    for comp in regions:
        if _is_frame(comp):
            frames.append(comp)
        else:
            patterns.append(comp)

    frames.sort(key=_frame_sort_key)
    assert frames, "expected at least one frame"

    patches: list[np.ndarray] = []
    for f in frames:
        col = int(f["color"])
        num_patterns = sum(1 for p in patterns if int(p["color"]) == col)
        patches.append(_interior_patch(col, bg, num_patterns))

    return np.vstack(patches)


def _frame_patch(color: int, bg: int, n_dots: int) -> np.ndarray:
    patch = np.full((FRAME_H, FRAME_W), bg, dtype=int)
    patch[0, :] = color
    patch[-1, :] = color
    patch[:, 0] = color
    patch[:, -1] = color
    patch[1:-1, 1:-1] = _interior_patch(color, bg, n_dots)
    return patch


def _sample_counts(rng: np.random.Generator, n_frames: int, total_match: int) -> list[int]:
    counts = [0] * n_frames
    order = rng.permutation(n_frames)
    remaining = total_match
    for pos, idx in enumerate(order):
        frames_left = n_frames - pos - 1
        lo = max(0, remaining - MAX_DOTS_PER_FRAME * frames_left)
        hi = min(MAX_DOTS_PER_FRAME, remaining)
        val = int(rng.integers(lo, hi + 1))
        counts[int(idx)] = val
        remaining -= val
    return counts


def _grow_sprite(rng: np.random.Generator, h: int, w: int, area: int) -> list[tuple[int, int]]:
    seed = (int(rng.integers(0, h)), int(rng.integers(0, w)))
    cells = {seed}
    while len(cells) < area:
        frontier = []
        for r, c in cells:
            for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                nb = (r + dr, c + dc)
                if 0 <= nb[0] < h and 0 <= nb[1] < w and nb not in cells:
                    frontier.append(nb)
        cells.add(frontier[int(rng.integers(0, len(frontier)))])
    return list(cells)


def _make_sprite(rng: np.random.Generator, color: int, bg: int) -> np.ndarray:
    area = int(rng.integers(*SPRITE_AREA_RANGE))
    dims = [
        (h, w)
        for h in range(1, SPRITE_MAX_H + 1)
        for w in range(1, SPRITE_MAX_W + 1)
        if h * w >= area
    ]
    h, w = dims[int(rng.integers(0, len(dims)))]
    cells = _grow_sprite(rng, h, w, area)
    rs, cs = zip(*cells)
    r_min, c_min = min(rs), min(cs)
    patch = np.full((max(rs) - r_min + 1, max(cs) - c_min + 1), bg, dtype=int)
    for r, c in cells:
        patch[r - r_min, c - c_min] = color
    return patch


def _build_cropped_output(bg: int, frame_colors: list[int], counts: list[int]) -> np.ndarray:
    return np.vstack([_interior_patch(color, bg, count) for color, count in zip(frame_colors, counts)])


def _gen_attempt() -> np.ndarray | None:
    rng = np.random.default_rng()

    n_frames = int(rng.integers(*N_FRAMES_RANGE))
    n_distractors = int(rng.integers(*N_DISTRACTORS_RANGE))
    total_patterns = int(rng.integers(*TOTAL_PATTERNS_RANGE))
    total_match = total_patterns - n_distractors

    palette = rng.choice(np.arange(10), size=1 + n_frames + n_distractors, replace=False)
    bg = int(palette[0])
    frame_colors = [int(x) for x in palette[1 : 1 + n_frames]]
    distractor_colors = [int(x) for x in palette[1 + n_frames :]]

    counts = _sample_counts(rng, n_frames, total_match)
    bottom_pad = int(rng.integers(*BOTTOM_PAD_RANGE)) if n_frames == 3 else 0
    height = FRAME_R0 + n_frames * FRAME_H + (n_frames - 1) * FRAME_GAP + bottom_pad

    full_out = np.full((height, GRID_W), bg, dtype=int)
    frame_rows: list[int] = []
    for i, (color, count) in enumerate(zip(frame_colors, counts)):
        r0 = FRAME_R0 + i * (FRAME_H + FRAME_GAP)
        frame_rows.append(r0)
        paste(full_out, _frame_patch(color, bg, count), r0, FRAME_C0)

    cropped_out = _build_cropped_output(bg, frame_colors, counts)

    inp = full_out.copy()
    for r0, count in zip(frame_rows, counts):
        mid_r = r0 + FRAME_H // 2
        dot_cols = [FRAME_C0 + FRAME_W - 3 - 2 * i for i in range(count)]
        inp[mid_r, dot_cols] = bg

    right_canvas = np.full((height, RIGHT_W), bg, dtype=int)
    pattern_colors = [c for c, n in zip(frame_colors, counts) for _ in range(n)]
    pattern_colors.extend(distractor_colors)
    rng.shuffle(pattern_colors)

    try:
        for color in pattern_colors:
            sprite = _make_sprite(rng, color, bg)
            r0, c0 = random_free_location(
                right_canvas,
                sprite,
                transparent=bg,
                padding=SPRITE_PADDING,
                padding_connectivity=8,
            )
            paste(right_canvas, sprite, r0, c0, transparent=bg)
    except ValueError:
        return None

    paste(inp, right_canvas, 0, RIGHT_C0, transparent=bg)
    if np.array_equal(main(inp), cropped_out):
        return inp
    return None


def generate_input() -> np.ndarray:
    for _ in range(MAX_ATTEMPTS):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError(f"failed to generate a valid input after {MAX_ATTEMPTS} attempts")
