# Variant of 38007db0
# Dimension: D1 — 匹配条件：行对齐选取唯一项 (match_cond)
# Change: s.pos.row == d.pos.row — 每行中出现一次的奇异单元格被提取到输出对应行... → 列对齐选取唯一项
#
# Design analysis
# - Concrete behavior:
#   The lattice geometry stays the same: square cells separated by 1-pixel lattice lines,
#   with a 1-pixel bg padding and a sprite inside each cell. The old task hides one odd cell
#   in every row and collapses the grid to a single column. This variant instead hides one odd
#   cell in every column and collapses the grid to a single row. The output therefore keeps the
#   original column layout and removes the extra lattice rows.
# - Behavior trace on a small example:
#   Old logic on a 3x4 cell grid: scan row 0, find the one cell different from the other three,
#   copy it into output row 0; repeat for rows 1 and 2, giving a 3x1 output lattice.
#   New logic on the same geometry: scan column 0, find the one cell different from the other
#   two or three cells in that column, copy it into output column 0; repeat for every column,
#   giving a 1x4 output lattice.
# - Complexity calibration:
#   The visual vocabulary remains tight: exactly 3 colors and one shared base sprite, while each
#   output cell is still a small flip-variant of that base. This preserves recognizability and
#   avoids adding new latent rules. To make the column rule visible, the generator forces at least
#   one row to contain zero odd cells, so the data cannot silently behave like the original
#   per-row extraction.
# - Implicit assumptions review:
#   `row_lines` / `col_lines` detection still relies on full-line lattice color and remains valid.
#   The old `for (ra, rb) in r_slices` loop assumed "there exists a unique cell in every row";
#   that is no longer true, so the counting loop must move to `c_slices`.
#   The old output builder assumed output width shrinks to one cell and kept all original lattice
#   rows. In this variant that would be wrong: width must stay unchanged, height must shrink to
#   one cell, and only the top/bottom lattice rows may remain.
# - Placement legality:
#   Cells still occupy disjoint lattice slots generated by `_build_lattice`, so there is no
#   overlap risk. Each input column contains exactly one unique cell and `n_rows >= 3`, ensuring a
#   clear majority base pattern in that column.
# - Visual observability / cleanliness:
#   A human sees repeated base cells down each column with one discrepant cell, and the output is
#   a clean single-row strip of those discrepant cells. Because at least one input row is entirely
#   base, the sample set visibly resists a row-wise interpretation.
# - New solver assumptions checked against generator:
#   `main()` now assumes every column has at least one signature with frequency 1; the generator
#   guarantees this by placing one unique variant in each column and filling all other cells there
#   with the exact same base cell.

from __future__ import annotations

from collections import Counter
import itertools
import math

import numpy as np

from arc_utils import paste


def main(grid: np.ndarray) -> np.ndarray:
    """
    Extract the unique cell from each lattice column into a single-row lattice.
    """
    g = np.array(grid, dtype=int)
    H, W = g.shape

    row_lines = [r for r in range(H) if len(set(map(int, g[r, :]))) == 1]
    col_lines = [c for c in range(W) if len(set(map(int, g[:, c]))) == 1]
    assert row_lines and col_lines

    vals = [int(g[r, 0]) for r in row_lines] + [int(g[0, c]) for c in col_lines]
    L = int(Counter(vals).most_common(1)[0][0])
    row_lines = sorted(r for r in row_lines if int(g[r, 0]) == L)
    col_lines = sorted(c for c in col_lines if int(g[0, c]) == L)

    r_slices = [(row_lines[i] + 1, row_lines[i + 1]) for i in range(len(row_lines) - 1)]
    c_slices = [(col_lines[j] + 1, col_lines[j + 1]) for j in range(len(col_lines) - 1)]
    r_slices = [(a, b) for a, b in r_slices if b > a]
    c_slices = [(a, b) for a, b in c_slices if b > a]
    assert r_slices and c_slices

    cell_h = int(r_slices[0][1] - r_slices[0][0])

    bg_candidates = [int(x) for x in g.flatten() if int(x) != L]
    assert bg_candidates
    bg = int(Counter(bg_candidates).most_common(1)[0][0])

    chosen_cells: list[np.ndarray] = []
    for ca, cb in c_slices:
        cells = [g[int(ra):int(rb), int(ca):int(cb)] for ra, rb in r_slices]
        sigs = [cell.tobytes() for cell in cells]
        cnt = Counter(sigs)
        uniq_idx = next((i for i, s in enumerate(sigs) if int(cnt[s]) == 1), None)
        assert uniq_idx is not None
        chosen_cells.append(cells[int(uniq_idx)])

    out_h = int(cell_h + 2)
    out = np.full((out_h, W), int(bg), dtype=int)
    out[0, :] = int(L)
    out[-1, :] = int(L)
    for c in col_lines:
        out[:, int(c)] = int(L)

    for j, (ca, cb) in enumerate(c_slices):
        out[1:1 + int(cell_h), int(ca):int(cb)] = chosen_cells[int(j)]

    return out


def _make_cell(inner: np.ndarray, bg: int) -> np.ndarray:
    s = inner.shape[0] + 2
    cell = np.full((s, s), int(bg), dtype=int)
    paste(cell, inner, 1, 1)
    return cell


def _build_lattice(cells: list[list[np.ndarray]], lattice: int, bg: int) -> np.ndarray:
    rows = len(cells)
    cols = len(cells[0])
    cell_size = cells[0][0].shape[0]
    grid = np.full((rows * (cell_size + 1) + 1, cols * (cell_size + 1) + 1), int(bg), dtype=int)
    for r in range(rows + 1):
        grid[r * (cell_size + 1), :] = int(lattice)
    for c in range(cols + 1):
        grid[:, c * (cell_size + 1)] = int(lattice)
    for r, row in enumerate(cells):
        for c, cell in enumerate(row):
            paste(grid, cell, 1 + r * (cell_size + 1), 1 + c * (cell_size + 1))
    return grid


def _choose_odd_rows(rng: np.random.Generator, n_rows: int, n_cols: int) -> np.ndarray | None:
    for _ in range(80):
        odd_rows = rng.integers(0, n_rows, size=n_cols)
        counts = np.bincount(odd_rows, minlength=n_rows)
        if int(np.min(counts)) == 0:
            return odd_rows
    return None


def _gen_attempt() -> np.ndarray | None:
    rng = np.random.default_rng()

    lattice, bg, sp = map(int, rng.choice(10, size=3, replace=False))
    cell_size = int(rng.choice([5, 6]))
    n_rows = int(rng.integers(3, 5))
    n_cols = int(rng.integers(3, 5))

    inner_size = cell_size - 2
    inner_area = inner_size * inner_size
    min_fill = math.ceil(0.4 * inner_area)
    max_fill = math.floor(0.9 * inner_area)
    fill = int(rng.integers(min_fill, max_fill + 1))

    base_inner = np.full((inner_size, inner_size), int(bg), dtype=int)
    on_idx = rng.choice(inner_area, size=fill, replace=False)
    base_inner.flat[on_idx] = int(sp)

    unique_cells: list[np.ndarray] = []
    used_flip_sets: set[tuple[int, ...]] = set()
    for _ in range(n_cols):
        flip_count = int(rng.integers(1, 4))
        candidates = list(itertools.combinations(range(inner_area), flip_count))
        available = [fs for fs in candidates if fs not in used_flip_sets]
        if not available:
            return None
        flip_set = available[int(rng.integers(len(available)))]
        used_flip_sets.add(flip_set)
        variant_inner = base_inner.copy()
        for idx in flip_set:
            variant_inner.flat[int(idx)] = sp if int(variant_inner.flat[int(idx)]) == int(bg) else bg
        unique_cells.append(_make_cell(variant_inner, bg))

    odd_rows = _choose_odd_rows(rng, n_rows, n_cols)
    if odd_rows is None:
        return None

    out = _build_lattice([unique_cells], lattice, bg)

    base_cell = _make_cell(base_inner, bg)
    in_cells = [[base_cell.copy() for _ in range(n_cols)] for _ in range(n_rows)]
    for col in range(n_cols):
        in_cells[int(odd_rows[col])][col] = unique_cells[col].copy()
    inp = _build_lattice(in_cells, lattice, bg)

    return inp if np.array_equal(main(inp), out) else None


def generate_input() -> np.ndarray:
    for _ in range(300):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate valid input after 300 attempts")
