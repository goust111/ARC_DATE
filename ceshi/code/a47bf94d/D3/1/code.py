# Dimension: D3 — 传输轨迹可视化 (trajectory)
# Change: 无轨迹涂色——管道网络在输入和输出中保持不变，不因token传输而涂色或改变... → 间歇轨迹涂色

import random

import numpy as np

from arc_utils import components_mask, get_bg, neighbors4

# Design analysis for the D3 variant
# ----------------------------------
# a) Concrete behavior:
#    - The base task logic stays the same: a solid 3x3 token turns into a diamond
#      in place and sends an X to the far endpoint; an X stays and sends a diamond.
#    - New visible effect: while a token is transmitted, the exposed pipe cells on
#      its route are recolored with the token color every 3 visible pipe cells,
#      producing a dashed trail.
#    - "Exposed pipe cells" means only original color-8 wire cells on the traced
#      route. We intentionally do not recolor color-9 rectangles or color-5
#      crossing brackets, so the structural wire cues remain legible.
#    - Small example:
#      original: endpoint -> 8 8 8 8 8 8 -> far endpoint
#      variant : endpoint -> C 8 8 C 8 8 -> far endpoint
#      where C is the transmitted token color.
#
# b) Complexity calibration:
#    - The period is a small global constant (3), inspired by the source task
#      221dfab4 where a short repeating rhythm is the whole visual clue.
#    - We do not make the period color-dependent or per-instance hidden. Each grid
#      has 4-5 channels, so the same spacing repeats multiple times in one example.
#    - This is strong enough to be visible, but still local enough that the task
#      does not become a separate path-measurement puzzle.
#
# c) Hidden assumptions audited against the original solver:
#    - Original _trace_wire only needed the far endpoint; the variant needs the
#      ordered path. Therefore tracing must now preserve visit order.
#    - Blindly recoloring every traced cell would be unsafe because crossover
#      centers are shared by multiple logical routes. The original task could leave
#      them unchanged; the variant would create overwrite-order bugs there.
#    - To avoid that, trajectory painting is restricted to original color-8 cells
#      whose degree inside the track component is <= 2. Shared intersections are
#      thus skipped, keeping route coloring deterministic.
#    - The original jump-through behavior inside color-9 rectangles is still valid.
#      Since those interiors are not recolored, we do not need to materialize the
#      full hidden path inside a rectangle.
#
# d) Placement legality:
#    - Input generation keeps the original token placement and wire construction.
#      Trajectories are output-only, so they cannot invalidate token detection.
#    - Recoloring happens only on cells that were already wire cells, so no new
#      overlap with tokens can occur.
#
# e) Visual observability:
#    - A human can compare input/output and see that the wire network no longer
#      stays uniformly cyan: each transmitted color leaves evenly spaced dots.
#    - Because there are several channels per example, the repeated spacing is
#      visible within a single pair, not only across different examples.
#
# f) Visual cleanliness:
#    - Skipping color-5 and color-9 structure avoids turning junctions into noisy
#      multicolor blobs. The dashed trails sit on the ordinary straight pipe cells.
#
# g) Color inference:
#    - No hidden recoloring map is introduced. The trail uses the same token color
#      as the transmitted object, which is directly observable from the endpoint
#      token that produced it.
#
# New solver assumptions and generator guarantees:
#    - Every active route contains enough exposed color-8 cells that the dashed
#      pattern is visible; the generator rejects low-visibility samples.
#    - Token colors remain from {1,2,3,4,6,7}, disjoint from wire colors {5,8,9}.

_N4 = [(-1, 0), (1, 0), (0, -1), (0, 1)]

_DIAMOND_OFF = [(-1, 0), (1, 0), (0, -1), (0, 1)]
_X_OFF = [(-1, -1), (-1, 1), (0, 0), (1, -1), (1, 1)]

TRAJECTORY_PERIOD = 3


def _find_solid_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for maximal 3x3 solid blocks."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            col = int(sub[0, 0])
            if col == bg or np.any(sub != col):
                continue
            maximal = True
            for rr in range(r0, r0 + 3):
                for cc in range(c0, c0 + 3):
                    for nr, nc in neighbors4(rr, cc):
                        if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                            if int(g[nr, nc]) == col:
                                maximal = False
                                break
                    if not maximal:
                        break
                if not maximal:
                    break
            if not maximal:
                continue
            found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _find_x_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for isolated 3x3 X patterns."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}

    mask = np.zeros((3, 3), dtype=bool)
    for rr, cc in [(0, 0), (0, 2), (1, 1), (2, 0), (2, 2)]:
        mask[rr, cc] = True

    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            col = int(sub[0, 0])
            if col == bg:
                continue
            if np.any(sub[mask] != col) or np.any(sub[~mask] != bg):
                continue
            isolated = True
            for dr0, dc0 in _X_OFF:
                rr, cc = r0 + 1 + dr0, c0 + 1 + dc0
                for nr, nc in neighbors4(rr, cc):
                    if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                        if int(g[nr, nc]) == col:
                            isolated = False
                            break
                if not isolated:
                    break
            if not isolated:
                continue
            found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _components(mask: np.ndarray) -> list[list[tuple[int, int]]]:
    return [[(int(r), int(c)) for r, c in comp] for comp in components_mask(mask, connectivity=4)]


def _find_9rects(g: np.ndarray) -> list[tuple[set[tuple[int, int]], dict[str, list[tuple[int, int]]]]]:
    """Find color-9 rectangular blocks and their wire connections per face."""
    mask9 = g == 9
    if not mask9.any():
        return []
    h, w = g.shape
    rects = []
    for comp9 in components_mask(mask9, connectivity=4):
        cells = set((int(r), int(c)) for r, c in comp9)
        rs = [r for r, _ in cells]
        cs = [c for _, c in cells]
        r0, r1, c0, c1 = min(rs), max(rs), min(cs), max(cs)
        faces: dict[str, list[tuple[int, int]]] = {}
        for r, c in cells:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) not in cells and 0 <= nr < h and 0 <= nc < w and int(g[nr, nc]) in (5, 8):
                    face = "N" if nr < r0 else "S" if nr > r1 else "W" if nc < c0 else "E"
                    faces.setdefault(face, []).append((nr, nc))
        rects.append((cells, faces))
    return rects


_OPP = {"N": "S", "S": "N", "E": "W", "W": "E"}
_DIR2FACE = {(1, 0): "N", (-1, 0): "S", (0, 1): "W", (0, -1): "E"}
_FACE2DIR = {"S": (1, 0), "N": (-1, 0), "E": (0, 1), "W": (0, -1)}


def _trace_wire(
    comp: set[tuple[int, int]],
    start: tuple[int, int],
    dir0: tuple[int, int],
    h: int,
    w: int,
    rects_9: list[tuple[set[tuple[int, int]], dict[str, list[tuple[int, int]]]]],
) -> tuple[tuple[int, int], tuple[int, int], list[tuple[int, int]]]:
    """
    Follow a wire greedily and return (terminal_cell, exit_direction, visited_path).

    The path records the visible traversal order. Inside color-9 rectangles we still
    jump directly to the chosen exit because the variant does not recolor those cells.
    """
    cur, d, prev = start, dir0, None
    path = [start]
    visited: set[tuple[tuple[int, int], tuple[int, int]]] = set()
    for _ in range(h * w * 4):
        if (cur, d) in visited:
            assert False, "wire trace looped — should not happen with 9-rect pass-through"
        visited.add((cur, d))

        jumped = False
        for cells9, faces9 in rects_9:
            if cur in cells9:
                entry_face = _DIR2FACE[d]
                opp = _OPP[entry_face]
                if opp in faces9:
                    exit_face = opp
                else:
                    others = [f for f in faces9 if f != entry_face]
                    assert len(others) == 1
                    exit_face = others[0]
                pts = faces9[exit_face]
                er, ec = cur
                if entry_face in ("N", "S"):
                    exit_cell = min(pts, key=lambda p: abs(p[1] - ec))
                else:
                    exit_cell = min(pts, key=lambda p: abs(p[0] - er))
                cur, d, prev = exit_cell, _FACE2DIR[exit_face], None
                if path[-1] != exit_cell:
                    path.append(exit_cell)
                jumped = True
                break
        if jumped:
            continue

        r, c = cur
        opts = [((nr, nc), nr - r, nc - c) for nr, nc in neighbors4(r, c) if (nr, nc) in comp]
        if not opts:
            return cur, d, path

        rev = (-d[0], -d[1])
        nonrev = [o for o in opts if (o[1], o[2]) != rev]
        opts2 = nonrev if nonrev else opts

        straight = [o for o in opts2 if (o[1], o[2]) == d]
        if straight:
            p, dr, dc = straight[0]
        else:
            perp = [o for o in opts2 if o[1] * d[0] + o[2] * d[1] == 0]
            if perp:
                p, dr, dc = sorted(perp, key=lambda x: (x[1], x[2]))[0]
            else:
                p, dr, dc = opts2[0]

        if p == prev:
            return cur, d, path

        prev = cur
        cur = p
        d = (dr, dc)
        path.append(cur)

    assert False, "wire trace exceeded step limit"


def _degree_map(comp: set[tuple[int, int]]) -> dict[tuple[int, int], int]:
    deg = {p: 0 for p in comp}
    for r, c in comp:
        for nr, nc in neighbors4(r, c):
            if (nr, nc) in comp:
                deg[(r, c)] += 1
    return deg


def _paint_trajectory(
    out: np.ndarray,
    g: np.ndarray,
    path: list[tuple[int, int]],
    deg: dict[tuple[int, int], int],
    col: int,
) -> None:
    """Paint every TRAJECTORY_PERIOD-th eligible path cell with the token color."""
    eligible: list[tuple[int, int]] = []
    seen: set[tuple[int, int]] = set()
    for cell in path:
        if cell in seen:
            continue
        seen.add(cell)
        r, c = cell
        if int(g[r, c]) != 8:
            continue
        if deg.get(cell, 0) > 2:
            continue
        eligible.append(cell)

    for idx, (r, c) in enumerate(eligible):
        if idx % TRAJECTORY_PERIOD == 0:
            out[r, c] = col


def main(grid: np.ndarray) -> np.ndarray:
    """
    Route colored tokens through the wire network and reveal a dashed travel trail.

    Input structure:
    - Background cells surround a connected cyan/grey/maroon wire network plus 3x3
      tokens placed two cells away from wire endpoints.
    - Tokens are either solid 3x3 blocks or X-patterns; some far endpoints may
      already contain a resting diamond.

    Rule:
    - Every solid token turns into a diamond at its original position.
    - Each source token sends its complementary shape to the opposite endpoint:
      solid sends an X, X sends a diamond.
    - Along the transmitted route, every third exposed color-8 wire cell is
      recolored to the token color, creating a dashed trajectory.

    Key insight: The original endpoint-to-endpoint routing is unchanged; the new
    information is a periodic visual trail stamped onto the traversed wire cells.
    """
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    bg = get_bg(g)

    solids = _find_solid_3x3(g, bg)
    xs = _find_x_3x3(g, bg)

    track_mask = g != bg
    for (_, _), (_, (r0, c0)) in solids.items():
        track_mask[r0 : r0 + 3, c0 : c0 + 3] = False
    for cr, cc in xs.keys():
        for dr, dc in _X_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w:
                track_mask[rr, cc2] = False

    comps = _components(track_mask)
    rects_9 = _find_9rects(g)

    out = g.copy()

    for (cr, cc), (col, (r0, c0)) in solids.items():
        out[r0 : r0 + 3, c0 : c0 + 3] = bg
        for dr, dc in _DIAMOND_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w:
                out[rr, cc2] = col

    for pts in comps:
        comp = set(pts)
        if len(comp) < 4:
            continue

        comp_colors = {int(g[r, c]) for r, c in comp}
        deg = _degree_map(comp)
        endpoints = [p for p in comp if deg[p] <= 1]
        if not endpoints:
            continue

        for ep in endpoints:
            er, ec = ep
            for odr, odc in _N4:
                cen = (er + 2 * odr, ec + 2 * odc)
                if not (0 <= cen[0] < h and 0 <= cen[1] < w):
                    continue

                if cen in solids:
                    col, _ = solids[cen]
                    if col in comp_colors:
                        continue
                    dir_in = (-odr, -odc)
                    end, dd, path = _trace_wire(comp, ep, dir_in, h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    for dr, dc in _X_OFF:
                        rr, cc2 = dest[0] + dr, dest[1] + dc
                        if 0 <= rr < h and 0 <= cc2 < w:
                            out[rr, cc2] = col
                    _paint_trajectory(out, g, path, deg, col)

                elif cen in xs:
                    col, _ = xs[cen]
                    if col in comp_colors:
                        continue
                    dir_in = (-odr, -odc)
                    end, dd, path = _trace_wire(comp, ep, dir_in, h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    for dr, dc in _DIAMOND_OFF:
                        rr, cc2 = dest[0] + dr, dest[1] + dc
                        if 0 <= rr < h and 0 <= cc2 < w:
                            out[rr, cc2] = col
                    _paint_trajectory(out, g, path, deg, col)

    return out


