# Design analysis for the D5 variant
# - concretization:
#   input keeps the original channel/wire layout, but every channel now has a
#   solid 3x3 sender on one endpoint and a same-colored diamond receiver on the
#   opposite endpoint. The receiver is already visible in the input; the output
#   does not create a new remote token in empty space.
# - behavior trace:
#   original on one channel: solid at source -> local diamond, remote empty spot
#   gets an X.
#   variant on one channel: solid at source -> local diamond, remote diamond
#   gets the missing corner set overlaid onto it, so the remote 3x3 becomes a
#   full solid block.
#   Example: top solid color 2 routed to bottom diamond color 2.
#   Input top = 3x3 solid, input bottom = diamond. Output top = diamond,
#   output bottom = 3x3 solid.
# - complexity calibration:
#   the wire permutation, crossing markers, and optional 9-rect pass-throughs
#   stay unchanged so the task remains a routing puzzle instead of a trivial
#   local rewrite. Every generated channel participates in the overlay rule, and
#   source sides are mixed between top and bottom to make the rule visible in
#   both directions.
# - hidden-assumption audit against the original main():
#   the old solver only removed solid/X cells from the track mask and wrote the
#   transmitted complement into mostly empty destinations. That is unsafe here:
#   diamonds are real input objects and must be excluded from wire components,
#   and the far-end write must deliberately merge with an existing receiver
#   instead of assuming emptiness.
# - placement legality:
#   centers still sit exactly two cells away from degree-1 wire endpoints, the
#   top centers are distinct channel columns, and the bottom centers are distinct
#   permutation targets, so 3x3 token areas never overlap. Receivers always use
#   the routed color of their own channel, ensuring that each solid has exactly
#   one legal completion target.
# - visual observability:
#   humans can compare input/output and see a consistent swap:
#   one endpoint loses the four corners, the other endpoint gains exactly those
#   corners around an already-present plus-shape. The result is a solid block,
#   which is visually distinct from the original task's remote X.
# - cleanliness:
#   only one overlay happens in any 3x3 token window, so no endpoint contains
#   multiple unrelated colors or layered patterns.
# - new solver assumptions that the generator guarantees:
#   each token color appears once as a solid sender and once as a diamond
#   receiver, both attached to the same wire component; no X input tokens are
#   generated because an X receiver would be indistinguishable from an X sender.

_N4 = [(-1, 0), (1, 0), (0, -1), (0, 1)]

_DIAMOND_OFF = [(-1, 0), (1, 0), (0, -1), (0, 1)]
_X_OFF = [(-1, -1), (-1, 1), (0, 0), (1, -1), (1, 1)]
_SOLID_OFF = [
    (-1, -1),
    (-1, 0),
    (-1, 1),
    (0, -1),
    (0, 0),
    (0, 1),
    (1, -1),
    (1, 0),
    (1, 1),
]


def _find_solid_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for maximal 3x3 solid blocks."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            col = int(sub[0, 0])
            if col == bg or np.any(sub != col):
                continue
            maximal = True
            for rr in range(r0, r0 + 3):
                for cc in range(c0, c0 + 3):
                    for nr, nc in neighbors4(rr, cc):
                        if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                            if int(g[nr, nc]) == col:
                                maximal = False
                                break
                    if not maximal:
                        break
                if not maximal:
                    break
            if not maximal:
                continue
            found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _find_diamond_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for isolated 3x3 diamond patterns."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}

    mask = np.zeros((3, 3), dtype=bool)
    for rr, cc in [(0, 1), (1, 0), (1, 2), (2, 1)]:
        mask[rr, cc] = True

    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0 : r0 + 3, c0 : c0 + 3]
            vals = sub[mask]
            if vals.size == 0:
                continue
            col = int(vals[0])
            if col == bg or np.any(vals != col):
                continue
            if np.any(sub[~mask] != bg):
                continue
            isolated = True
            for dr0, dc0 in _DIAMOND_OFF:
                rr, cc = r0 + 1 + dr0, c0 + 1 + dc0
                for nr, nc in neighbors4(rr, cc):
                    if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                        if int(g[nr, nc]) == col:
                            isolated = False
                            break
                if not isolated:
                    break
            if not isolated:
                continue
            found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _components(mask: np.ndarray) -> list[list[tuple[int, int]]]:
    return [[(int(r), int(c)) for r, c in comp] for comp in components_mask(mask, connectivity=4)]


def _find_9rects(g: np.ndarray) -> list[tuple[set, dict]]:
    """Find color-9 rectangular blocks and their wire connections per face."""
    mask9 = g == 9
    if not mask9.any():
        return []
    h, w = g.shape
    rects = []
    for comp9 in components_mask(mask9, connectivity=4):
        cells = set((int(r), int(c)) for r, c in comp9)
        rs = [r for r, _ in cells]
        cs = [c for _, c in cells]
        r0, r1, c0, c1 = min(rs), max(rs), min(cs), max(cs)
        faces: dict[str, list] = {}
        for r, c in cells:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) not in cells and 0 <= nr < h and 0 <= nc < w and int(g[nr, nc]) in (5, 8):
                    face = "N" if nr < r0 else "S" if nr > r1 else "W" if nc < c0 else "E"
                    faces.setdefault(face, []).append((nr, nc))
        rects.append((cells, faces))
    return rects


_OPP = {"N": "S", "S": "N", "E": "W", "W": "E"}
_DIR2FACE = {(1, 0): "N", (-1, 0): "S", (0, 1): "W", (0, -1): "E"}
_FACE2DIR = {"S": (1, 0), "N": (-1, 0), "E": (0, 1), "W": (0, -1)}


def _trace_wire(
    comp: set[tuple[int, int]],
    start: tuple[int, int],
    dir0: tuple[int, int],
    h: int,
    w: int,
    rects_9: list[tuple[set, dict]],
) -> tuple[tuple[int, int], tuple[int, int]]:
    """
    Greedy wire following with 9-rect pass-through.

    At a color-9 rectangle: exit from opposite face (aligned with entry column/row).
    If no opposite exit, assert exactly one other exit face and use that.
    """
    cur, d, prev = start, dir0, None
    visited: set[tuple[tuple[int, int], tuple[int, int]]] = set()
    for _ in range(h * w * 4):
        if (cur, d) in visited:
            assert False, "wire trace looped — should not happen with 9-rect pass-through"
        visited.add((cur, d))

        jumped = False
        for cells9, faces9 in rects_9:
            if cur in cells9:
                entry_face = _DIR2FACE[d]
                opp = _OPP[entry_face]
                if opp in faces9:
                    exit_face = opp
                else:
                    others = [f for f in faces9 if f != entry_face]
                    assert len(others) == 1
                    exit_face = others[0]
                pts = faces9[exit_face]
                er, ec = cur
                if entry_face in ("N", "S"):
                    exit_cell = min(pts, key=lambda p: abs(p[1] - ec))
                else:
                    exit_cell = min(pts, key=lambda p: abs(p[0] - er))
                cur, d, prev = exit_cell, _FACE2DIR[exit_face], None
                jumped = True
                break
        if jumped:
            continue

        r, c = cur
        opts = [((nr, nc), nr - r, nc - c) for nr, nc in neighbors4(r, c) if (nr, nc) in comp]
        if not opts:
            return cur, d

        rev = (-d[0], -d[1])
        nonrev = [o for o in opts if (o[1], o[2]) != rev]
        opts2 = nonrev if nonrev else opts

        straight = [o for o in opts2 if (o[1], o[2]) == d]
        if straight:
            p, dr, dc = straight[0]
        else:
            perp = [o for o in opts2 if o[1] * d[0] + o[2] * d[1] == 0]
            if perp:
                p, dr, dc = sorted(perp, key=lambda x: (x[1], x[2]))[0]
            else:
                p, dr, dc = opts2[0]

        if p == prev:
            return cur, d

        prev = cur
        cur = p
        d = (dr, dc)

    assert False, "wire trace exceeded step limit"


def _stamp_token(grid: np.ndarray, center_r: int, center_c: int, color: int, offsets: list[tuple[int, int]]) -> None:
    for dr, dc in offsets:
        grid[center_r + dr, center_c + dc] = color


def main(grid: np.ndarray) -> np.ndarray:
    """
    Route the corner-part of each solid token through the wire network and merge it with a remote receiver.

    Input structure:
    - Background cells are empty.
    - Non-background cells form one orthogonal wire network plus paired 3x3 tokens near degree-1 wire endpoints.
    - For each token color, one endpoint has a solid 3x3 sender and the routed endpoint already contains a same-colored diamond receiver.

    Rule:
    - A solid sender loses its four corners and becomes a diamond in place.
    - The missing corner-set travels along the attached wire.
    - At the far endpoint, that transmitted part is overlaid onto the existing diamond receiver, so the receiver becomes a full solid 3x3 block.

    Key insight:
    - The output is not created by dropping a fresh token into empty space; instead, the far endpoint already shows the stationary half of the shape, and the routed half completes it into a solid block.
    """
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    bg = get_bg(g)

    solids = _find_solid_3x3(g, bg)
    diamonds = _find_diamond_3x3(g, bg)

    track_mask = g != bg
    for _, (_, (r0, c0)) in solids.items():
        track_mask[r0 : r0 + 3, c0 : c0 + 3] = False
    for (cr, cc), _ in diamonds.items():
        for dr, dc in _DIAMOND_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w:
                track_mask[rr, cc2] = False

    comps = _components(track_mask)
    rects_9 = _find_9rects(g)

    out = g.copy()

    for (cr, cc), (col, (r0, c0)) in solids.items():
        out[r0 : r0 + 3, c0 : c0 + 3] = bg
        _stamp_token(out, cr, cc, col, _DIAMOND_OFF)

    for pts in comps:
        comp = set(pts)
        if len(comp) < 4:
            continue

        deg = {p: 0 for p in comp}
        for r, c in comp:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) in comp:
                    deg[(r, c)] += 1
        endpoints = [p for p in comp if deg[p] <= 1]
        if not endpoints:
            continue

        for ep in endpoints:
            er, ec = ep
            for odr, odc in _N4:
                cen = (er + 2 * odr, ec + 2 * odc)
                if cen not in solids:
                    continue

                col, _ = solids[cen]
                dir_in = (-odr, -odc)
                end, dd = _trace_wire(comp, ep, dir_in, h, w, rects_9)
                dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])

                if dest in diamonds and diamonds[dest][0] == col:
                    dr0, dc0 = dest[0] - 1, dest[1] - 1
                    out[dr0 : dr0 + 3, dc0 : dc0 + 3] = col
                else:
                    _stamp_token(out, dest[0], dest[1], col, _X_OFF)

    return out


