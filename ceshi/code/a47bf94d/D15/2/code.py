# Design analysis for D15 / frame_separation variant
# --------------------------------------------------
# spec_variant:
#   unchanged_input:
#     - Input stays as the original single-panel wiring puzzle: one wire network,
#       4-5 channels, token centers two cells away from degree-1 endpoints, and
#       optional maroon 9-rect pass-through blocks inside the cyan/grey wire.
#   changed_output:
#     - Output becomes two copies of the same wiring canvas placed side by side,
#       with a full-height solid separator column between them.
#     - Left panel = "source-side result": only the endpoint that originally held
#       the active token is shown, after its local in-place update.
#         solid 3x3 -> diamond at the same center
#         X token -> unchanged X at the same center
#     - Right panel = "destination-side result": only the opposite endpoint that
#       receives the transmitted complement is shown.
#         source solid -> emit X to far endpoint
#         source X -> emit diamond to far endpoint
#         pre-placed far diamonds from the input remain only in this panel
#   concrete_trace:
#     - Original task on one channel:
#         input: top solid(color A), wire routes to bottom endpoint
#         output(single grid): top diamond(A) and bottom X(A) shown together
#     - Variant:
#         left panel shows only the top diamond(A)
#         right panel shows only the bottom X(A)
#         both panels keep the same wire geometry, and a separator column marks
#         that the answer is now a structured two-view display.
#   complexity_calibration:
#     - The token logic, permutation routing, crossings, and 9-rect behavior stay
#       unchanged, so the puzzle is not simplified into a trivial copy task.
#     - We add exactly one new structural degree of freedom: output framing.
#       This is visible in every example because width becomes 2*W+1 and the two
#       panels differ in token placement.
#   implicit_assumption_review:
#     - Original `out = g.copy()` was harmless because one canvas kept both local
#       and remote effects. It is wrong here because source tokens would leak into
#       the destination panel and pre-placed destination diamonds would leak into
#       the source panel. We therefore build a token-free base canvas first.
#     - Original solver never needed to identify diamond tokens explicitly; they
#       could just remain in the copied output. The split-panel rule requires
#       distinguishing them so they can be removed from the left panel and kept
#       only on the right panel.
#     - Track extraction must also remove diamond cells; otherwise they remain as
#       irrelevant tiny components. That was mostly harmless before, but explicit
#       removal keeps the two-panel construction clean and deterministic.
#   placement_legality:
#     - Generator still uses the original spacing and endpoint gaps, so tokens do
#       not overlap wires or each other. The new output only duplicates the same
#       legal canvas horizontally with one separator column, so no new placement
#       collisions are introduced.
#   visual_observability:
#     - The separator is a full-height grey column, which is visually distinct
#       from token colors and from the sparse crossing markers of the wire.
#     - Left and right panels each contain only one role (source vs destination),
#       so the change is inferable from 2-3 examples without relying on hidden
#       metadata such as color ordering.
#   cleanliness:
#     - Each panel keeps the original uncluttered wire drawing. Tokens are not
#       overlaid across roles, which is cleaner than the original single-canvas
#       superposition and makes the D15 change easy to spot.

_N4 = [(-1, 0), (1, 0), (0, -1), (0, 1)]

_DIAMOND_OFF = [(-1, 0), (1, 0), (0, -1), (0, 1)]
_X_OFF = [(-1, -1), (-1, 1), (0, 0), (1, -1), (1, 1)]
_SOLID_OFF = [
    (-1, -1), (-1, 0), (-1, 1),
    (0, -1), (0, 0), (0, 1),
    (1, -1), (1, 0), (1, 1),
]
_DIVIDER_COLOR_PREF = (5, 9, 8)


def _find_solid_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for maximal 3x3 solid blocks."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0:r0 + 3, c0:c0 + 3]
            col = int(sub[0, 0])
            if col == bg or np.any(sub != col):
                continue
            maximal = True
            for rr in range(r0, r0 + 3):
                for cc in range(c0, c0 + 3):
                    for nr, nc in neighbors4(rr, cc):
                        if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                            if int(g[nr, nc]) == col:
                                maximal = False
                                break
                    if not maximal:
                        break
                if not maximal:
                    break
            if maximal:
                found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _find_x_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for isolated 3x3 X patterns."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    mask = np.zeros((3, 3), dtype=bool)
    for rr, cc in [(0, 0), (0, 2), (1, 1), (2, 0), (2, 2)]:
        mask[rr, cc] = True

    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0:r0 + 3, c0:c0 + 3]
            col = int(sub[0, 0])
            if col == bg:
                continue
            if np.any(sub[mask] != col) or np.any(sub[~mask] != bg):
                continue
            isolated = True
            for dr0, dc0 in _X_OFF:
                rr, cc = r0 + 1 + dr0, c0 + 1 + dc0
                for nr, nc in neighbors4(rr, cc):
                    if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                        if int(g[nr, nc]) == col:
                            isolated = False
                            break
                if not isolated:
                    break
            if isolated:
                found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _find_diamond_3x3(g: np.ndarray, bg: int) -> dict[tuple[int, int], tuple[int, tuple[int, int]]]:
    """Return {center: (color, (r0,c0))} for isolated 3x3 diamond patterns."""
    h, w = g.shape
    found: dict[tuple[int, int], tuple[int, tuple[int, int]]] = {}
    mask = np.zeros((3, 3), dtype=bool)
    for rr, cc in [(0, 1), (1, 0), (1, 2), (2, 1)]:
        mask[rr, cc] = True

    for r0 in range(h - 2):
        for c0 in range(w - 2):
            sub = g[r0:r0 + 3, c0:c0 + 3]
            vals = {int(v) for v in sub[mask].ravel()}
            if len(vals) != 1:
                continue
            col = next(iter(vals))
            if col == bg or np.any(sub[~mask] != bg):
                continue
            isolated = True
            for dr0, dc0 in _DIAMOND_OFF:
                rr, cc = r0 + 1 + dr0, c0 + 1 + dc0
                for nr, nc in neighbors4(rr, cc):
                    if 0 <= nr < h and 0 <= nc < w and not (r0 <= nr < r0 + 3 and c0 <= nc < c0 + 3):
                        if int(g[nr, nc]) == col:
                            isolated = False
                            break
                if not isolated:
                    break
            if isolated:
                found[(r0 + 1, c0 + 1)] = (col, (r0, c0))
    return found


def _components(mask: np.ndarray) -> list[list[tuple[int, int]]]:
    return [[(int(r), int(c)) for r, c in comp] for comp in components_mask(mask, connectivity=4)]


def _find_9rects(g: np.ndarray) -> list[tuple[set[tuple[int, int]], dict[str, list[tuple[int, int]]]]]:
    """Find color-9 rectangles and their adjacent wire-touch faces."""
    mask9 = g == 9
    if not mask9.any():
        return []
    h, w = g.shape
    rects = []
    for comp9 in components_mask(mask9, connectivity=4):
        cells = set((int(r), int(c)) for r, c in comp9)
        rs = [r for r, _ in cells]
        cs = [c for _, c in cells]
        r0, r1, c0, c1 = min(rs), max(rs), min(cs), max(cs)
        faces: dict[str, list[tuple[int, int]]] = {}
        for r, c in cells:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) not in cells and 0 <= nr < h and 0 <= nc < w and int(g[nr, nc]) in (5, 8):
                    face = "N" if nr < r0 else "S" if nr > r1 else "W" if nc < c0 else "E"
                    faces.setdefault(face, []).append((nr, nc))
        rects.append((cells, faces))
    return rects


_OPP = {"N": "S", "S": "N", "E": "W", "W": "E"}
_DIR2FACE = {(1, 0): "N", (-1, 0): "S", (0, 1): "W", (0, -1): "E"}
_FACE2DIR = {"S": (1, 0), "N": (-1, 0), "E": (0, 1), "W": (0, -1)}


def _trace_wire(
    comp: set[tuple[int, int]],
    start: tuple[int, int],
    dir0: tuple[int, int],
    h: int,
    w: int,
    rects_9: list[tuple[set[tuple[int, int]], dict[str, list[tuple[int, int]]]]],
) -> tuple[tuple[int, int], tuple[int, int]]:
    """
    Greedy wire following with 9-rect pass-through.

    At a color-9 rectangle: exit from the opposite face if possible, otherwise
    use the only other available face.
    """
    cur, d, prev = start, dir0, None
    visited: set[tuple[tuple[int, int], tuple[int, int]]] = set()
    for _ in range(h * w * 4):
        if (cur, d) in visited:
            raise AssertionError("wire trace looped")
        visited.add((cur, d))

        jumped = False
        for cells9, faces9 in rects_9:
            if cur in cells9:
                entry_face = _DIR2FACE[d]
                opp = _OPP[entry_face]
                if opp in faces9:
                    exit_face = opp
                else:
                    others = [f for f in faces9 if f != entry_face]
                    assert len(others) == 1
                    exit_face = others[0]
                pts = faces9[exit_face]
                er, ec = cur
                if entry_face in ("N", "S"):
                    exit_cell = min(pts, key=lambda p: abs(p[1] - ec))
                else:
                    exit_cell = min(pts, key=lambda p: abs(p[0] - er))
                cur, d, prev = exit_cell, _FACE2DIR[exit_face], None
                jumped = True
                break
        if jumped:
            continue

        r, c = cur
        opts = [((nr, nc), nr - r, nc - c) for nr, nc in neighbors4(r, c) if (nr, nc) in comp]
        if not opts:
            return cur, d

        rev = (-d[0], -d[1])
        nonrev = [o for o in opts if (o[1], o[2]) != rev]
        opts2 = nonrev if nonrev else opts

        straight = [o for o in opts2 if (o[1], o[2]) == d]
        if straight:
            p, dr, dc = straight[0]
        else:
            perp = [o for o in opts2 if o[1] * d[0] + o[2] * d[1] == 0]
            if perp:
                p, dr, dc = sorted(perp, key=lambda x: (x[1], x[2]))[0]
            else:
                p, dr, dc = opts2[0]

        if p == prev:
            return cur, d

        prev = cur
        cur = p
        d = (dr, dc)

    raise AssertionError("wire trace exceeded step limit")


def _stamp_pattern(grid: np.ndarray, center: tuple[int, int], color: int, offsets: list[tuple[int, int]]) -> None:
    cr, cc = center
    h, w = grid.shape
    for dr, dc in offsets:
        rr, cc2 = cr + dr, cc + dc
        if 0 <= rr < h and 0 <= cc2 < w:
            grid[rr, cc2] = color


def _divider_color(bg: int) -> int:
    for col in _DIVIDER_COLOR_PREF:
        if col != bg:
            return col
    return (bg + 1) % 10


def _assemble_two_panels(left: np.ndarray, right: np.ndarray, bg: int) -> np.ndarray:
    h, w = left.shape
    out = np.full((h, w * 2 + 1), bg, dtype=int)
    out[:, :w] = left
    out[:, w] = _divider_color(bg)
    out[:, w + 1:] = right
    return out


def _solve_split_views(grid: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    bg = get_bg(g)

    solids = _find_solid_3x3(g, bg)
    xs = _find_x_3x3(g, bg)
    diamonds = _find_diamond_3x3(g, bg)

    track_mask = g != bg
    for _, (_, (r0, c0)) in solids.items():
        track_mask[r0:r0 + 3, c0:c0 + 3] = False
    for (cr, cc) in xs:
        for dr, dc in _X_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w:
                track_mask[rr, cc2] = False
    for (cr, cc) in diamonds:
        for dr, dc in _DIAMOND_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w:
                track_mask[rr, cc2] = False

    rects_9 = _find_9rects(g)
    comps = _components(track_mask)

    base = g.copy()
    for _, (_, (r0, c0)) in solids.items():
        base[r0:r0 + 3, c0:c0 + 3] = bg
    for (cr, cc), (col, _) in xs.items():
        for dr, dc in _X_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w and base[rr, cc2] == col:
                base[rr, cc2] = bg
    for (cr, cc), (col, _) in diamonds.items():
        for dr, dc in _DIAMOND_OFF:
            rr, cc2 = cr + dr, cc + dc
            if 0 <= rr < h and 0 <= cc2 < w and base[rr, cc2] == col:
                base[rr, cc2] = bg

    source_panel = base.copy()
    dest_panel = base.copy()

    for center, (col, _) in solids.items():
        _stamp_pattern(source_panel, center, col, _DIAMOND_OFF)
    for center, (col, _) in xs.items():
        _stamp_pattern(source_panel, center, col, _X_OFF)
    for center, (col, _) in diamonds.items():
        _stamp_pattern(dest_panel, center, col, _DIAMOND_OFF)

    for pts in comps:
        comp = set(pts)
        if len(comp) < 4:
            continue

        comp_colors = {int(g[r, c]) for r, c in comp}
        deg = {p: 0 for p in comp}
        for r, c in comp:
            for nr, nc in neighbors4(r, c):
                if (nr, nc) in comp:
                    deg[(r, c)] += 1
        endpoints = [p for p in comp if deg[p] <= 1]
        if not endpoints:
            continue

        for ep in endpoints:
            er, ec = ep
            for odr, odc in _N4:
                cen = (er + 2 * odr, ec + 2 * odc)
                if not (0 <= cen[0] < h and 0 <= cen[1] < w):
                    continue

                if cen in solids:
                    col, _ = solids[cen]
                    if col in comp_colors:
                        continue
                    end, dd = _trace_wire(comp, ep, (-odr, -odc), h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    _stamp_pattern(dest_panel, dest, col, _X_OFF)
                elif cen in xs:
                    col, _ = xs[cen]
                    if col in comp_colors:
                        continue
                    end, dd = _trace_wire(comp, ep, (-odr, -odc), h, w, rects_9)
                    dest = (end[0] + 2 * dd[0], end[1] + 2 * dd[1])
                    _stamp_pattern(dest_panel, dest, col, _DIAMOND_OFF)

    return source_panel, dest_panel


def main(grid: np.ndarray) -> np.ndarray:
    """
    Split the routed token result into source-side and destination-side panels.

    Input structure:
    - One wiring canvas on a single grid: background cells, cyan/grey wire cells,
      optional maroon pass-through rectangles, and 3x3 tokens near wire endpoints.

    Rule:
    - Solve the same local/routed token behavior as the original task, but do not
      superimpose both effects onto one canvas.
    - Build two copies of the canvas: the left panel keeps only the source-end
      result (solid -> diamond, X stays X), while the right panel keeps only the
      far-end received result (solid emits X, X emits diamond, existing diamonds
      remain there). Join the panels with a solid separator column.

    Key insight:
    - The wire logic is unchanged; the novelty is output framing. The answer is a
      two-view decomposition of the original single-grid outcome into "where the
      token started" and "where its complement arrived".
    """
    g = np.asarray(grid, dtype=int)
    bg = get_bg(g)
    left, right = _solve_split_views(g)
    return _assemble_two_panels(left, right, bg)


