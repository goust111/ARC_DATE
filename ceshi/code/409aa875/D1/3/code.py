# Variant of 409aa875
# Dimension: D1 — 发射路径类型（对角线 vs 轴对齐） (path)
# Change: L形精灵沿对角线发射，V形精灵沿轴方向发射；方向由形状的缺口/开口方向决定... → 重力流动路径
#
# Design analysis
# ===============
# Reference audit:
# - The prompt asks to inspect the source-task solver for 28a6681f first.
# - In this workspace I could find
#   /home/lixinyu/snap/new/ARC-data/ARC-AGI-2/data/evaluation/28a6681f.json
#   but no local solver source file named 28a6681f.py under the allowed paths.
# - I therefore only borrow the visible "stepwise falling / flowing downward" idea
#   from the data and keep the rest of this variant anchored to 409aa875.
#
# a) Concretization and behavior trace
# - Input objects stay exactly the same as the original task: 16x16 grid, bg=7,
#   4-9 monochrome 3-pixel triangle sprites, each either an axis-aligned L or a
#   diagonal V. Solver still reads orientation from geometry, not color ids.
# - The changed part is only how a projectile reaches its terminal cell.
# - Original: destination = apex + 5 * launch_dir.
# - Variant: first infer the original launch_dir exactly as before, then keep only
#   its horizontal sign. From the apex, the projectile takes 5 visible conceptual
#   gravity steps; on step s it is at (apex_r + s, apex_c + s * horiz), where
#   horiz in {-1, 0, 1}. So the final cell is apex + (5, 5*horiz).
# - Small example:
#   L sprite with apex=(4,6) and old launch_dir=(-1,-1):
#   original terminal cell = ( -1, 1 ) relative offset -> ( -5,-5 ) from apex,
#   so it would land at ( -1? ) actually (4-5, 6-5) = (-1,1), out of bounds.
#   variant gravity path uses horiz=-1:
#   step cells = (5,5),(6,4),(7,3),(8,2),(9,1); terminal cell = (9,1).
#   The sprite geometry is unchanged, but the visible effect moves below it.
#
# b) Complexity calibration
# - The rule is still learnable from 2-4 ARC examples because only one factor
#   changes: every projectile bends downward.
# - It is not too weak visually because terminals now cluster below emitters
#   instead of extending in the shape-indicated straight line.
# - It is not too unconstrained because horiz only has 3 values {-1,0,1}; that
#   keeps repeated evidence across examples.
#
# c) Old implicit assumptions that must change
# - In the original main(), `rr = ar + 5 * dr` and `cc = ac + 5 * dc` assumed the
#   entire path was a straight ray. That assumption no longer holds.
# - The rest of the solver only used the terminal cell, not intermediate cells.
#   To keep the task focused on D1, this variant preserves that downstream logic:
#   gravity changes where the projectile ends, but hit/collision semantics still
#   depend only on the terminal cell.
# - Generator placement tables also assumed a straight-ray destination. They must
#   be rebuilt from the new gravity terminal cell; otherwise hit/collision events
#   would be sampled against the wrong coordinates.
#
# d) Placement legality
# - Every sprite must fit in bounds.
# - Every gravity path must remain in bounds for all 5 steps. Because row and
#   column progress monotonically, checking the full 5-step path is sufficient.
# - Sprites keep Chebyshev separation >= 2 so connected-component parsing remains
#   stable and triangles never merge.
# - Hit events are still generated by choosing a shooter whose gravity terminal
#   cell lies on a target sprite pixel. Collision events are still generated by
#   choosing two shooters with the same empty terminal cell.
#
# e) Visual observability
# - New outputs visibly differ from the original because markers appear below
#   emitters, often diagonally down-left/down-right or straight down.
# - To avoid accidental degeneration back to the old task, generation rejects any
#   grid whose variant output exactly matches the original straight-line output.
#
# f) Visual cleanliness
# - No projectile trails are drawn; only final effects are visible, as in the
#   source task. This keeps the grid readable.
# - Event counts remain small (0-2 hit sprites, 0-2 bg collisions), so output is
#   not cluttered with too many special cells.
#
# g) Color inference
# - Colors keep their original meaning: 9 marks a lone bg landing or a hit sprite,
#   1 marks a shared bg landing, untouched sprites keep their original single
#   color, and bg stays 7. No new color mapping is introduced.
#
# New solver assumptions to mirror in the generator
# - Every non-bg component is still an isolated 3-pixel triangle recognized by
#   `_triangle_apex_and_dir`.
# - Gravity always moves downward by exactly 5 rows total.
# - The terminal cell, not the intermediate path cells, determines whether a shot
#   hits a sprite or paints background. The generator guarantees examples obey
#   this same assumption when it chooses events.

import random
from collections import Counter, defaultdict

import numpy as np

from arc_utils import components_mask, get_bg as _bg_color, get_bg, neighbors4, neighbors8


def _cc8(mask: np.ndarray) -> list[list[tuple[int, int]]]:
    return [[(int(r), int(c)) for r, c in comp] for comp in components_mask(mask, connectivity=8)]


def _triangle_apex_and_dir(comp: list[tuple[int, int]]) -> tuple[tuple[int, int], tuple[int, int]] | None:
    # Returns (apex_rc, launch_dir_rc). launch_dir is the original task's direction.
    if len(comp) != 3:
        return None
    s = set(comp)

    deg4: dict[tuple[int, int], int] = {}
    deg8: dict[tuple[int, int], int] = {}
    for r, c in comp:
        deg4[(r, c)] = sum(1 for n in neighbors4(r, c) if n in s)
        deg8[(r, c)] = sum(1 for n in neighbors8(r, c) if n in s)

    corners = [p for p, d in deg4.items() if d == 2]
    if corners:
        corner = corners[0]
        cr, cc = corner
        arms = []
        for r, c in comp:
            if (r, c) == corner:
                continue
            dr, dc = r - cr, c - cc
            if abs(dr) + abs(dc) == 1:
                arms.append((dr, dc))
        if len(arms) != 2:
            return None
        dr_sum = arms[0][0] + arms[1][0]
        dc_sum = arms[0][1] + arms[1][1]
        dr = 0 if dr_sum == 0 else (-1 if dr_sum > 0 else 1)
        dc = 0 if dc_sum == 0 else (-1 if dc_sum > 0 else 1)
        return corner, (dr, dc)

    apexes = [p for p, d in deg8.items() if d == 2]
    if len(apexes) != 1:
        return None
    apex = apexes[0]
    ar, ac = apex
    others = [p for p in comp if p != apex]
    d1 = (others[0][0] - ar, others[0][1] - ac)
    d2 = (others[1][0] - ar, others[1][1] - ac)
    dr_sum = d1[0] + d2[0]
    dc_sum = d1[1] + d2[1]
    dr = -(dr_sum // 2)
    dc = -(dc_sum // 2)
    if abs(dr) + abs(dc) != 1:
        return None
    return apex, (dr, dc)


def _sign(x: int) -> int:
    return 0 if x == 0 else (1 if x > 0 else -1)


def _gravity_path(apex: tuple[int, int], launch_dir: tuple[int, int], steps: int = 5) -> list[tuple[int, int]]:
    ar, ac = apex
    _dr, dc = launch_dir
    horiz = _sign(dc)
    return [(ar + step, ac + step * horiz) for step in range(1, steps + 1)]


def _gravity_dest(apex: tuple[int, int], launch_dir: tuple[int, int], steps: int = 5) -> tuple[int, int]:
    return _gravity_path(apex, launch_dir, steps)[-1]


def _straight_dest(apex: tuple[int, int], launch_dir: tuple[int, int], steps: int = 5) -> tuple[int, int]:
    ar, ac = apex
    dr, dc = launch_dir
    return ar + steps * dr, ac + steps * dc


def main(grid: np.ndarray) -> np.ndarray:
    """
    Triangle sprites launch projectiles whose final landing point is bent downward by gravity.

    Input structure:
    - The background is the most frequent color.
    - Every non-background object is a monochrome 3-cell triangle sprite, either an L-shape or a diagonal V-shape.

    Rule:
    - First recover each sprite's apex and its original launch direction from the shape geometry.
    - Then replace the old straight-line shot with a 5-step gravity path: on each step the projectile moves down by 1 row and keeps only the horizontal sign of its launch direction.
    - The terminal cell is the last cell of that gravity path. If that cell lies on a sprite, recolor the entire hit sprite to maroon (9).
    - If multiple projectiles finish on the same empty background cell, paint that cell blue (1); otherwise a lone empty-cell landing paints maroon (9).

    Key insight: Shape still determines the horizontal drift, but gravity forces every projectile to finish below its emitter; only the final gravity-landing cell matters for recoloring.
    """
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    bg = _bg_color(g)

    comps: list[list[tuple[int, int]]] = []
    cell_to_comp: dict[tuple[int, int], int] = {}
    for col in sorted(set(int(v) for v in np.unique(g)) - {bg}):
        for comp in _cc8(g == col):
            cid = len(comps)
            comps.append(comp)
            for rc in comp:
                cell_to_comp[rc] = cid

    dest_to_shooters: dict[tuple[int, int], list[int]] = {}
    for cid, comp in enumerate(comps):
        ad = _triangle_apex_and_dir(comp)
        if ad is None:
            continue
        apex, launch_dir = ad
        path = _gravity_path(apex, launch_dir, steps=5)
        if not path:
            continue
        rr, cc = path[-1]
        if 0 <= rr < h and 0 <= cc < w:
            dest_to_shooters.setdefault((rr, cc), []).append(cid)

    hit_components: set[int] = set()
    for dest in dest_to_shooters:
        if dest in cell_to_comp:
            hit_components.add(cell_to_comp[dest])

    out = g.copy()

    for cid in hit_components:
        for r, c in comps[cid]:
            out[r, c] = 9

    for (r, c), shooters in dest_to_shooters.items():
        if (r, c) in cell_to_comp:
            continue
        out[r, c] = 1 if len(shooters) >= 2 else 9

    return out


def _main_original_straight(grid: np.ndarray) -> np.ndarray:
    g = np.asarray(grid, dtype=int)
    h, w = g.shape
    bg = _bg_color(g)

    comps: list[list[tuple[int, int]]] = []
    cell_to_comp: dict[tuple[int, int], int] = {}
    for col in sorted(set(int(v) for v in np.unique(g)) - {bg}):
        for comp in _cc8(g == col):
            cid = len(comps)
            comps.append(comp)
            for rc in comp:
                cell_to_comp[rc] = cid

    dest_to_shooters: dict[tuple[int, int], list[int]] = {}
    for cid, comp in enumerate(comps):
        ad = _triangle_apex_and_dir(comp)
        if ad is None:
            continue
        rr, cc = _straight_dest(*ad, steps=5)
        if 0 <= rr < h and 0 <= cc < w:
            dest_to_shooters.setdefault((rr, cc), []).append(cid)

    hit_components: set[int] = set()
    for dest in dest_to_shooters:
        if dest in cell_to_comp:
            hit_components.add(cell_to_comp[dest])

    out = g.copy()
    for cid in hit_components:
        for r, c in comps[cid]:
            out[r, c] = 9
    for (r, c), shooters in dest_to_shooters.items():
        if (r, c) in cell_to_comp:
            continue
        out[r, c] = 1 if len(shooters) >= 2 else 9
    return out


# ---- canvas / palette ----
H = W = 16
BG = 7
HIT_COLOR = 9
COLLISION_COLOR = 1
SPRITE_COLORS = [0, 1, 2, 3, 4, 5, 6, 8, 9]

# ---- geometry ----
PROJECTILE_STEPS = 5
DIAG_DIRS = [(-1, -1), (-1, 1), (1, -1), (1, 1)]
AXIS_DIRS = [(-1, 0), (1, 0), (0, -1), (0, 1)]
ALL_DIRS = DIAG_DIRS + AXIS_DIRS

# ---- structural counts per grid ----
SPRITE_COUNT_RANGE = (4, 9)
MAX_HIT_EVENTS = 2
MAX_COLL_EVENTS = 2

# ---- generation retries ----
MAX_ATTEMPTS = 400


def _sprite_cells(apex: tuple[int, int], direction: tuple[int, int]) -> tuple[tuple[int, int], ...]:
    """Return the 3 cells of a canonical triangle sprite with the given original launch direction."""
    ar, ac = apex
    dr, dc = direction
    if abs(dr) + abs(dc) == 2:
        return ((ar, ac), (ar - dr, ac), (ar, ac - dc))
    if dr != 0:
        return ((ar, ac), (ar - dr, ac - 1), (ar - dr, ac + 1))
    return ((ar, ac), (ar - 1, ac - dc), (ar + 1, ac - dc))


def _in_bounds_cells(cells: tuple[tuple[int, int], ...] | list[tuple[int, int]]) -> bool:
    return all(0 <= r < H and 0 <= c < W for r, c in cells)


def _halo(cells: tuple[tuple[int, int], ...]) -> frozenset[tuple[int, int]]:
    return frozenset(
        (rr, cc)
        for r, c in cells
        for rr in range(max(0, r - 1), min(H, r + 2))
        for cc in range(max(0, c - 1), min(W, c + 2))
    )


def _build_placements() -> tuple[list[dict], dict[tuple[int, int], list[dict]]]:
    placements: list[dict] = []
    by_dest: dict[tuple[int, int], list[dict]] = defaultdict(list)
    for ar in range(H):
        for ac in range(W):
            for dr, dc in ALL_DIRS:
                apex = (ar, ac)
                cells = _sprite_cells(apex, (dr, dc))
                if not _in_bounds_cells(cells):
                    continue
                path = _gravity_path(apex, (dr, dc), PROJECTILE_STEPS)
                if not _in_bounds_cells(path):
                    continue
                dest = path[-1]
                placement = {
                    "apex": apex,
                    "dir": (dr, dc),
                    "dest": dest,
                    "path": tuple(path),
                    "cells": cells,
                    "cell_set": frozenset(cells),
                    "halo": _halo(cells),
                    "changed": dest != _straight_dest(apex, (dr, dc), PROJECTILE_STEPS),
                }
                placements.append(placement)
                by_dest[dest].append(placement)
    return placements, by_dest


PLACEMENTS, PLACEMENTS_BY_DEST = _build_placements()


def _fits(placement: dict, occupied: set[tuple[int, int]], reserved_bg: set[tuple[int, int]]) -> bool:
    return not (placement["halo"] & occupied) and not (placement["cell_set"] & reserved_bg)


def _paint_sprite(grid: np.ndarray, placement: dict, color: int) -> None:
    for r, c in placement["cells"]:
        grid[r, c] = color


def _choose_collision_pair(
    rng: random.Random,
    occupied: set[tuple[int, int]],
    reserved_bg: set[tuple[int, int]],
) -> tuple[tuple[int, int], list[dict]] | None:
    dests = list(PLACEMENTS_BY_DEST)
    rng.shuffle(dests)
    for dest in dests:
        if dest in reserved_bg or dest in occupied:
            continue
        candidates = [p for p in PLACEMENTS_BY_DEST[dest] if _fits(p, occupied, reserved_bg)]
        rng.shuffle(candidates)
        for i, first in enumerate(candidates):
            occ2 = occupied | set(first["cells"])
            for second in candidates[i + 1 :]:
                if second["cell_set"] & first["cell_set"]:
                    continue
                if second["halo"] & occ2:
                    continue
                return dest, [first, second]
    return None


def _choose_unique(
    rng: random.Random,
    occupied: set[tuple[int, int]],
    reserved_bg: set[tuple[int, int]],
) -> dict | None:
    candidates = PLACEMENTS[:]
    rng.shuffle(candidates)
    for placement in candidates:
        if placement["dest"] in reserved_bg or placement["dest"] in occupied:
            continue
        if _fits(placement, occupied, reserved_bg):
            return placement
    return None


def _choose_hit(
    rng: random.Random,
    target_sprite: dict,
    occupied: set[tuple[int, int]],
    reserved_bg: set[tuple[int, int]],
    used_target_cells: set[tuple[int, int]],
) -> tuple[dict, tuple[int, int]] | None:
    cells = list(target_sprite["placement"]["cells"])
    rng.shuffle(cells)
    for cell in cells:
        if cell in used_target_cells:
            continue
        candidates = [p for p in PLACEMENTS_BY_DEST[cell] if _fits(p, occupied, reserved_bg)]
        if candidates:
            return rng.choice(candidates), cell
    return None


def _validate_input(grid: np.ndarray, n_sprites: int) -> bool:
    if grid.shape != (H, W):
        return False
    if get_bg(grid) != BG:
        return False
    comps = components_mask(grid != BG, connectivity=8)
    if len(comps) != n_sprites:
        return False
    return all(comp.shape == (3, 2) for comp in comps)


def _counts_for_n(rng: random.Random, n_sprites: int) -> tuple[int, int, int] | None:
    options = []
    for e_hit in range(0, min(MAX_HIT_EVENTS, n_sprites - 1) + 1):
        for e_coll in range(0, min(MAX_COLL_EVENTS, n_sprites // 2) + 1):
            unique = n_sprites - e_hit - 2 * e_coll
            if unique < 0:
                continue
            if unique + e_coll < 1:
                continue
            if e_hit + e_coll < 1:
                continue
            options.append((e_hit, e_coll, unique))
    return rng.choice(options) if options else None


def _place_collisions(rng, e_coll, sprites, occupied, reserved_bg) -> bool:
    for _ in range(e_coll):
        choice = _choose_collision_pair(rng, occupied, reserved_bg)
        if choice is None:
            return False
        dest, pair = choice
        reserved_bg.add(dest)
        for placement in pair:
            sprites.append({"placement": placement, "target": dest, "target_kind": "bg"})
            occupied.update(placement["cells"])
    return True


def _place_unique_landings(rng, n, sprites, occupied, reserved_bg) -> bool:
    for _ in range(n):
        placement = _choose_unique(rng, occupied, reserved_bg)
        if placement is None:
            return False
        reserved_bg.add(placement["dest"])
        sprites.append({"placement": placement, "target": placement["dest"], "target_kind": "bg"})
        occupied.update(placement["cells"])
    return True


def _place_hits(rng, e_hit, sprites, occupied, reserved_bg) -> bool:
    used_target_cells: set[tuple[int, int]] = set()
    hit_targets = rng.sample(range(len(sprites)), e_hit)
    for idx in hit_targets:
        choice = _choose_hit(rng, sprites[idx], occupied, reserved_bg, used_target_cells)
        if choice is None:
            return False
        placement, cell = choice
        sprites.append({"placement": placement, "target": cell, "target_kind": "hit", "target_sprite": idx})
        occupied.update(placement["cells"])
        used_target_cells.add(cell)
    return True


def _render_output(inp: np.ndarray, sprites: list[dict]) -> np.ndarray:
    out = inp.copy()
    bg_targets = Counter(s["target"] for s in sprites if s["target_kind"] == "bg")
    hit_sprite_ids = {s["target_sprite"] for s in sprites if s["target_kind"] == "hit"}
    for idx in hit_sprite_ids:
        _paint_sprite(out, sprites[idx]["placement"], HIT_COLOR)
    for dest, count in bg_targets.items():
        out[dest] = COLLISION_COLOR if count >= 2 else HIT_COLOR
    return out


def _variant_metrics(sprites: list[dict]) -> dict[str, int]:
    changed = sum(1 for s in sprites if s["placement"]["changed"])
    straight_down = sum(1 for s in sprites if s["placement"]["dir"][1] == 0)
    diag_drift = sum(1 for s in sprites if s["placement"]["dir"][1] != 0)
    return {
        "changed_shooters": changed,
        "straight_down_shooters": straight_down,
        "diagonal_drift_shooters": diag_drift,
    }


def _gen_attempt() -> np.ndarray | None:
    rng = random.Random()
    sprite_color = rng.choice(SPRITE_COLORS)
    n_sprites = rng.randint(*SPRITE_COUNT_RANGE)
    counts = _counts_for_n(rng, n_sprites)
    if counts is None:
        return None
    e_hit, e_coll, unique_total = counts

    sprites: list[dict] = []
    occupied: set[tuple[int, int]] = set()
    reserved_bg: set[tuple[int, int]] = set()

    if not _place_collisions(rng, e_coll, sprites, occupied, reserved_bg):
        return None

    base_needed = max(0, e_hit - len(sprites))
    if base_needed > unique_total:
        return None
    if not _place_unique_landings(rng, base_needed, sprites, occupied, reserved_bg):
        return None

    if not _place_hits(rng, e_hit, sprites, occupied, reserved_bg):
        return None

    remaining = n_sprites - len(sprites)
    if remaining < 0 or not _place_unique_landings(rng, remaining, sprites, occupied, reserved_bg):
        return None

    metrics = _variant_metrics(sprites)
    if metrics["changed_shooters"] < 1:
        return None

    inp = np.full((H, W), BG, dtype=int)
    for sprite in sprites:
        _paint_sprite(inp, sprite["placement"], sprite_color)

    if not _validate_input(inp, n_sprites):
        return None

    out = _render_output(inp, sprites)

    if np.count_nonzero(out != BG) <= np.count_nonzero(inp != BG):
        return None
    if not np.any(out == HIT_COLOR):
        return None
    if np.array_equal(inp, out):
        return None

    straight = _main_original_straight(inp)
    if np.array_equal(straight, out):
        return None

    try:
        solved = main(inp)
    except Exception:
        return None
    if not np.array_equal(solved, out):
        return None
    return inp


def generate_input() -> np.ndarray:
    for _ in range(MAX_ATTEMPTS):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError(f"Failed to generate valid input after {MAX_ATTEMPTS} attempts")
