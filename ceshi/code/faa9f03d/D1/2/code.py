# Variant of faa9f03d
# Dimension: D1 — 核心变换：间隙填充与射线重定向 (transform)
# Change: 红色标记处恢复线色并填充面对端点间的间隙；黄色标记处擦除旧臂并从端点通过标记延伸到网格边缘... → 反射而非擦除旧臂
#
# Design analysis for this variant
# --------------------------------
# spec_like:
#   core_change:
#     old_yellow: marker replaces the first cell of a missing straight arm; solver deletes the arm on the opposite side of the pivot and extends a new straight ray through the marker to the boundary.
#     new_yellow: marker still sits on the first missing cell, but the existing perpendicular arm is kept and its visible straight length is copied onto the marker side. This is a 90-degree turn reconstruction rather than an erase-and-flip ray.
#   concrete_pixel_behavior:
#     - Red markers still stand in for missing line cells and are repaired before ordinary gap filling.
#     - Yellow markers now live at the first cell of a missing segment that starts at a corner pixel ("pivot").
#     - The pivot remains visible in the input.
#     - One orthogonal arm of the corner remains visible; the other arm is missing for exactly the visible length of that source arm.
#     - Any farther continuation beyond the removed yellow span may remain in place, so the yellow repair reconnects a detached fragment rather than painting to the edge.
#   traced_example:
#     - Output corner: source arm has 3 cells upward from pivot; target arm goes right for 5 cells before turning.
#     - Input: cells 1..3 on the right are removed, cell 1 becomes yellow, cells 4..5 on the right remain.
#     - Original logic would over-extend the right arm all the way to the boundary.
#     - Variant logic copies the 3-cell source length onto the right side, reconnecting exactly the intended fragment.
#   complexity_calibration:
#     - The new rule is visually obvious because the repaired yellow arm length matches a perpendicular visible arm, not the boundary distance.
#     - Yellow cases are restricted to clean corners with a single perpendicular source arm, so the inference has one stable branch rather than many ambiguous subcases.
#     - The detached far fragment beyond the yellow gap makes the difference from the original task observable on the same input.
#   implicit_assumptions_review:
#     - Marker assignment by nearest line-of-sight still holds.
#     - Ordinary gap filling would incorrectly bridge marker-to-fragment gaps, so the solver must explicitly exempt yellow-directed spans from generic filling.
#     - Yellow reconstruction now assumes the pivot is a non-crossing turn and exactly one perpendicular straight arm is visible from it in the input; the generator enforces this.
#     - The reflected span length is taken from the contiguous visible source arm; red and yellow markers are therefore blocked from that source segment during generation.
#   placement_legality:
#     - Yellow candidates are chosen only when the source straight run has length >= 2 and the target straight run is at least that long.
#     - Removed yellow cells avoid crossings, and the boundary distance on the target side must exceed the copied length so the variant does not collapse to the original boundary-ray behavior.
#     - Multiple yellow selections are blocked from overlapping each other's pivots, spans, or source arms.
#   visual_observability:
#     - The task remains sparse and rectilinear, with only one extra local motif: a corner whose missing arm length matches the perpendicular visible arm.
#     - No hidden ranking uses color identity beyond the original crossing tie-break already present in the source task.
#   cleanliness:
#     - Crossings stay at most binary and still involve the dominant color.
#     - Yellow repairs are local spans rather than long edge-filling sweeps, reducing clutter near boundaries.

from __future__ import annotations

import random

import numpy as np

from arc_utils import components_mask, get_bg


DIRS4 = ((-1, 0), (1, 0), (0, -1), (0, 1))


def _pts(mask: np.ndarray) -> set[tuple[int, int]]:
    return {tuple(map(int, rc)) for rc in np.argwhere(mask)}


def _axis_support(mask: set[tuple[int, int]], r: int, c: int, axis: int) -> bool:
    if axis == 0:
        return (r, c - 1) in mask or (r, c + 1) in mask
    return (r - 1, c) in mask or (r + 1, c) in mask


def _perp_support(mask: set[tuple[int, int]], r: int, c: int, axis: int) -> bool:
    if axis == 0:
        return (r - 1, c) in mask or (r + 1, c) in mask
    return (r, c - 1) in mask or (r, c + 1) in mask


def _component_count(shape: tuple[int, int], pts: set[tuple[int, int]]) -> int:
    mask = np.zeros(shape, dtype=bool)
    for r, c in pts:
        mask[r, c] = True
    return len(components_mask(mask, connectivity=4))


def _perp_dirs(direction: tuple[int, int]) -> tuple[tuple[int, int], tuple[int, int]]:
    dr, dc = direction
    if dr != 0:
        return ((0, -1), (0, 1))
    return ((-1, 0), (1, 0))


def _run_length(pts: set[tuple[int, int]], start: tuple[int, int], direction: tuple[int, int]) -> int:
    dr, dc = direction
    r, c = start[0] + dr, start[1] + dc
    length = 0
    while (r, c) in pts:
        length += 1
        r += dr
        c += dc
    return length


def _dirs_in(pts: set[tuple[int, int]], pt: tuple[int, int]) -> list[tuple[int, int]]:
    r, c = pt
    return [(dr, dc) for dr, dc in DIRS4 if (r + dr, c + dc) in pts]


def main(grid: np.ndarray) -> np.ndarray:
    """
    Repair a one-cell-thick colored line network by restoring singleton markers, filling ordinary orthogonal gaps, and rotating yellow-controlled gaps by copying a perpendicular arm length.

    Input structure:
    - A rectangular grid with a dominant background.
    - Non-marker colors form one-cell-thick axis-aligned stroke fragments that may cross.
    - Marker colors are exactly the foreground colors whose 4-connected components are all singleton pixels.
    - Red singleton markers replace missing line cells; yellow singleton markers replace the first cell of a missing arm that starts at a visible corner.

    Rule:
    - Assign every marker to the nearest visible line color in row/column line-of-sight, preferring an endpoint supported along that same axis.
    - For each line color, fill ordinary row/column gaps between consecutive facing endpoints, except for the directed gaps that begin at yellow markers.
    - For a yellow control, find its pivot on the assigned color, keep the visible source arm attached to that pivot, measure that arm's straight length, and paint the same number of cells from the pivot through the marker in the perpendicular direction.
    - At overlaps, yellow-reflected spans win; otherwise an original-vs-filled crossing uses the more fragmented pre-repair line color, while pure filled crossings use the lower color id.

    Key insight: The singleton markers still identify which sparse fragments belong together, but yellow no longer means "delete the opposite arm and shoot to the edge"; it means "use the visible orthogonal arm as a length template and reconstruct a 90-degree copy on the marked side."
    """
    g = np.asarray(grid, dtype=int)
    bg = int(get_bg(g))
    H, W = g.shape

    colors = set(map(int, g.ravel())) - {bg}
    assert colors, "expected foreground line and marker colors"

    marker_colors: set[int] = set()
    for color in colors:
        comps = components_mask(g == color, connectivity=4)
        assert comps, "foreground color must have at least one component"
        if max(len(comp) for comp in comps) == 1:
            marker_colors.add(int(color))

    line_colors = colors - marker_colors
    assert line_colors, "expected at least one non-marker line color"
    assert marker_colors, "expected singleton marker colors"

    original = {color: _pts(g == color) for color in line_colors}
    assignment: dict[tuple[int, int], int] = {}
    assign_dir: dict[tuple[int, int], tuple[int, int]] = {}

    yellow_controls = _pts(g == 4) if 4 in marker_colors else set()
    marker_mask = np.isin(g, list(marker_colors))
    for r0, c0 in _pts(marker_mask):
        candidates: list[tuple[int, int, int, int, int]] = []
        for dr, dc in DIRS4:
            r, c = r0 + dr, c0 + dc
            dist = 1
            while 0 <= r < H and 0 <= c < W:
                value = int(g[r, c])
                if value in line_colors:
                    axis = 0 if dr == 0 else 1
                    supported = _axis_support(original[value], r, c, axis)
                    candidates.append((dist, 0 if supported else 1, value, dr, dc))
                    break
                if value == bg or value in marker_colors:
                    r += dr
                    c += dc
                    dist += 1
                    continue
                break

        assert candidates, f"marker at {(r0, c0)} cannot see a line color"
        candidates.sort()
        _dist, _unsupported, color, dr, dc = candidates[0]
        assignment[(r0, c0)] = int(color)
        assign_dir[(r0, c0)] = (int(dr), int(dc))

    def yellow_blocks_fill(a: tuple[int, int], b: tuple[int, int], axis: int) -> bool:
        for marker, other in ((a, b), (b, a)):
            if marker not in yellow_controls:
                continue
            dr, dc = assign_dir[marker]
            away = (-dr, -dc)
            if axis == 0 and away[0] == 0:
                delta = other[1] - marker[1]
                if delta * away[1] > 0:
                    return True
            if axis == 1 and away[1] == 0:
                delta = other[0] - marker[0]
                if delta * away[0] > 0:
                    return True
        return False

    masks = {color: set(pts) for color, pts in original.items()}
    marker_pts = {color: set() for color in line_colors}
    for pt, color in assignment.items():
        masks[color].add(pt)
        marker_pts[color].add(pt)

    comp_count = {color: _component_count(g.shape, masks[color]) for color in line_colors}

    def has_axis_support(color: int, r: int, c: int, axis: int) -> bool:
        return (r, c) in marker_pts[color] or _axis_support(masks[color], r, c, axis)

    def should_fill(color: int, a: tuple[int, int], b: tuple[int, int], axis: int) -> bool:
        if yellow_blocks_fill(a, b, axis):
            return False

        r1, c1 = a
        r2, c2 = b
        gap = c2 - c1 - 1 if axis == 0 else r2 - r1 - 1
        if gap <= 0:
            return False

        a_axis = has_axis_support(color, r1, c1, axis)
        b_axis = has_axis_support(color, r2, c2, axis)
        if gap == 1:
            if a_axis or b_axis:
                return True
            a_perp = _perp_support(masks[color], r1, c1, axis)
            b_perp = _perp_support(masks[color], r2, c2, axis)
            return not (a_perp and b_perp)

        if (r1, c1) in marker_pts[color] and (r2, c2) in marker_pts[color]:
            return False
        return a_axis and b_axis

    for color in sorted(line_colors):
        additions: set[tuple[int, int]] = set()
        for r in range(H):
            cols = sorted(c for rr, c in masks[color] if rr == r)
            for c1, c2 in zip(cols, cols[1:]):
                if should_fill(color, (r, c1), (r, c2), axis=0):
                    additions.update((r, c) for c in range(c1 + 1, c2))

        for c in range(W):
            rows = sorted(r for r, cc in masks[color] if cc == c)
            for r1, r2 in zip(rows, rows[1:]):
                if should_fill(color, (r1, c), (r2, c), axis=1):
                    additions.update((r, c) for r in range(r1 + 1, r2))

        masks[color].update(additions)

    control_reflect = {color: set() for color in line_colors}
    if 4 in marker_colors:
        for control in yellow_controls:
            color = assignment[control]
            dr, dc = assign_dir[control]

            r, c = control[0] + dr, control[1] + dc
            pivot: tuple[int, int] | None = None
            while 0 <= r < H and 0 <= c < W:
                if (r, c) in masks[color]:
                    pivot = (r, c)
                    break
                r += dr
                c += dc
            assert pivot is not None, f"yellow control at {control} has no assigned pivot"

            target_dir = (-dr, -dc)
            source_dirs = []
            for sdr, sdc in _perp_dirs(target_dir):
                if (pivot[0] + sdr, pivot[1] + sdc) in masks[color]:
                    source_dirs.append((sdr, sdc))
            assert len(source_dirs) == 1, f"yellow control at {control} needs exactly one perpendicular source arm"

            source_dir = source_dirs[0]
            source_len = _run_length(masks[color], pivot, source_dir)
            assert source_len > 0, f"yellow control at {control} found no source arm length"

            r, c = pivot
            for _ in range(source_len + 1):
                masks[color].add((r, c))
                control_reflect[color].add((r, c))
                r += target_dir[0]
                c += target_dir[1]

    claims: dict[tuple[int, int], list[int]] = {}
    for color, pts in masks.items():
        for pt in pts:
            claims.setdefault(pt, []).append(int(color))

    out = np.full_like(g, bg)

    def marker_brackets(color: int, pt: tuple[int, int]) -> bool:
        r, c = pt
        same_row = [mc for mr, mc in marker_pts[color] if mr == r]
        if any(mc < c for mc in same_row) and any(mc > c for mc in same_row):
            return True
        same_col = [mr for mr, mc in marker_pts[color] if mc == c]
        return any(mr < r for mr in same_col) and any(mr > r for mr in same_col)

    for pt, colors_here in claims.items():
        forced = {color for color in colors_here if pt in control_reflect[color]}
        if forced:
            assert len(forced) == 1, f"ambiguous yellow reflections at {pt}: {forced}"
            out[pt] = next(iter(forced))
            continue

        if len(colors_here) == 1:
            out[pt] = colors_here[0]
            continue

        original_crossing = [color for color in colors_here if int(g[pt]) == color]
        if original_crossing:
            out[pt] = min(colors_here, key=lambda color: (-comp_count[color], color))
        else:
            bracketed = [color for color in colors_here if marker_brackets(color, pt)]
            if bracketed:
                out[pt] = min(bracketed, key=lambda color: (-comp_count[color], color))
            else:
                out[pt] = min(colors_here)

    for color in line_colors:
        for comp in components_mask(out == color, connectivity=4):
            pts_set = set(map(tuple, comp))
            for r, c in pts_set:
                nbrs = [(nr, nc) for nr, nc in ((r - 1, c), (r + 1, c), (r, c - 1), (r, c + 1)) if (nr, nc) in pts_set]
                if len(nbrs) != 1:
                    continue
                on_boundary = r == 0 or r == H - 1 or c == 0 or c == W - 1
                if on_boundary:
                    nr, nc = nbrs[0]
                    dr, dc = nr - r, nc - c
                    if not ((r in (0, H - 1)) and (c in (0, W - 1))):
                        perp = (
                            (r == 0 and dr == 1)
                            or (r == H - 1 and dr == -1)
                            or (c == 0 and dc == 1)
                            or (c == W - 1 and dc == -1)
                        )
                        assert perp, f"boundary endpoint ({r},{c}) color {color} not perpendicular"
                    continue
                adj_other = any(
                    0 <= r + dr < H
                    and 0 <= c + dc < W
                    and int(out[r + dr, c + dc]) not in (bg, color)
                    for dr, dc in DIRS4
                )
                assert adj_other, f"dangling endpoint ({r},{c}) color {color}: not on boundary or crossing"

    color_cells = {c: set() for c in line_colors}
    for r in range(H):
        for c in range(W):
            v = int(out[r, c])
            if v in line_colors:
                color_cells[v].add((r, c))
    crossing_colors = set()
    for r in range(H):
        for c in range(W):
            a = int(out[r, c])
            if a not in line_colors:
                continue
            for b in line_colors - {a}:
                if (((r, c - 1) in color_cells[b] and (r, c + 1) in color_cells[b]) or ((r - 1, c) in color_cells[b] and (r + 1, c) in color_cells[b])):
                    crossing_colors.add(a)
                    crossing_colors.add(b)
    for color in line_colors:
        assert color in crossing_colors, f"color {color} has no crossing with any other color"

    return out


