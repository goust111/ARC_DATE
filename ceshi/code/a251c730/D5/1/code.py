# Design analysis for the D5 variant
# ----------------------------------
# variant_spec:
#   unchanged_input:
#     - 30x30 wallpaper with two bordered rectangles.
#     - source rectangle still contains 2-4 multi-cell two-color sprites.
#     - destination rectangle still contains only singleton anchor-color markers.
#   changed_output:
#     - stamping still happens inside the destination interior after clearing it to dst_bg.
#     - unlike the original task, the border and the unused destination background are discarded.
#     - the returned grid is the minimum axis-aligned bbox of all stamped non-dst_bg pixels.
#     - cells inside that bbox that are not covered by sprites remain dst_bg, so gaps are preserved.
#   behavior_trace:
#     - original: build a full dst rectangle, repaint its border, stamp sprites, return whole rectangle.
#     - variant: build only the destination interior canvas, stamp sprites by anchor-color matching,
#       then crop to the bbox of all stamped foreground pixels.
#     - example: if two 3x3 sprites land near the middle of a 13x12 destination frame, the original
#       output stays 13x12 with a border; the variant may become, for example, 5x8 with no border.
#   complexity_calibration:
#     - keep 1-2 sprite types and 2-3 markers so color matching remains the same concept.
#     - do not introduce new sorting rules or color remaps; only the observed output window changes.
#     - generator forces at least a one-cell margin between stamped sprites and the destination interior
#       boundary so the tight-crop effect is visible and does not collapse back to the full rectangle.
#   assumption_audit:
#     - rectangle finder still assumes exactly one source rectangle has a multi-cell component and one
#       destination rectangle has only singleton components; generator preserves that split.
#     - template extraction still assumes the least frequent sprite color is the unique anchor color;
#       generator keeps each sprite binary-colored with a singleton anchor pixel.
#     - tight cropping assumes at least one marker matches a source template; generator gives every type
#       at least one source copy and every destination marker uses one of those anchor colors.
#     - borderless stamping assumes markers are placed with enough clearance for full sprites; generator
#       places them using the full sprite patch with explicit border/padding constraints.
#   legality_and_visuals:
#     - source sprites remain separated inside the source frame.
#     - destination markers are still single pixels, but the hidden stamped sprites are laid out with
#       non-overlap and one-cell padding in the generator's output-first construction.
#     - because crop size now varies with marker positions, multiple samples visibly differ in shape.


def _interior_bg(grid: np.ndarray, rect: tuple[int, int, int, int]) -> int:
    r0, c0, r1, c1 = map(int, rect)
    inner = grid[int(r0) + 1 : int(r1), int(c0) + 1 : int(c1)]
    return int(Counter(map(int, inner.flatten())).most_common(1)[0][0])


def _rect_components(grid: np.ndarray, rect: tuple[int, int, int, int]) -> tuple[int, list[dict]]:
    r0, c0, r1, c1 = map(int, rect)
    inner = grid[int(r0) + 1 : int(r1), int(c0) + 1 : int(c1)]
    ibg = int(Counter(map(int, inner.flatten())).most_common(1)[0][0])
    comps: list[dict] = []

    for coords in components_mask(inner != int(ibg), connectivity=4):
        if coords.size == 0:
            continue
        rr0, cc0, rr1, cc1 = bbox_coords(coords)
        mask = np.zeros((int(rr1 - rr0 + 1), int(cc1 - cc0 + 1)), dtype=bool)
        mask[coords[:, 0] - int(rr0), coords[:, 1] - int(cc0)] = True
        patch = inner[int(rr0) : int(rr1) + 1, int(cc0) : int(cc1) + 1].copy()
        patch[~mask] = 0

        vals = [int(inner[int(r), int(c)]) for r, c in coords]
        comps.append(
            {
                "size": int(coords.shape[0]),
                "colors": dict(Counter(vals)),
                "bbox": (int(rr0), int(cc0), int(rr1), int(cc1)),
                "mask": mask,
                "patch": patch,
            }
        )

    comps.sort(key=lambda d: -int(d["size"]))
    return int(ibg), comps


def _find_task_rectangles(grid: np.ndarray) -> list[tuple[int, tuple[int, int, int, int], int, int]]:
    g = np.array(grid, dtype=int)
    H, W = g.shape
    rects: list[tuple[int, tuple[int, int, int, int], int, int]] = []
    min_h = 6
    min_w = 6
    for r0 in range(int(H)):
        for c0 in range(int(W)):
            bc = int(g[int(r0), int(c0)])
            for r1 in range(int(r0 + min_h - 1), int(H)):
                for c1 in range(int(c0 + min_w - 1), int(W)):
                    if int(g[int(r0), int(c1)]) != int(bc):
                        continue
                    if int(g[int(r1), int(c0)]) != int(bc):
                        continue
                    if int(g[int(r1), int(c1)]) != int(bc):
                        continue
                    if not bool((g[int(r0), int(c0) : int(c1) + 1] == int(bc)).all()):
                        continue
                    if not bool((g[int(r1), int(c0) : int(c1) + 1] == int(bc)).all()):
                        continue
                    if not bool((g[int(r0) : int(r1) + 1, int(c0)] == int(bc)).all()):
                        continue
                    if not bool((g[int(r0) : int(r1) + 1, int(c1)] == int(bc)).all()):
                        continue
                    ibg = _interior_bg(g, (int(r0), int(c0), int(r1), int(c1)))
                    if int(ibg) == int(bc):
                        continue
                    area = int((int(r1) - int(r0) + 1) * (int(c1) - int(c0) + 1))
                    rects.append((int(area), (int(r0), int(c0), int(r1), int(c1)), int(bc), int(ibg)))

    rects.sort(reverse=True, key=lambda x: int(x[0]))
    return rects[:6]


def _tight_crop(canvas: np.ndarray, bg: int) -> np.ndarray:
    nz = np.argwhere(canvas != int(bg))
    assert nz.size > 0
    r0, c0, r1, c1 = bbox_coords(nz)
    return canvas[int(r0) : int(r1) + 1, int(c0) : int(c1) + 1]


def main(grid: np.ndarray) -> np.ndarray:
    """
    Stamp source sprites onto destination markers, then return only the stamped bbox.

    Input structure:
    - Two bordered rectangles sit on striped wallpaper: a source frame with multi-cell sprites and
      a destination frame whose interior contains only singleton anchor-color markers.
    - Within each source sprite, the least frequent color is its unique anchor pixel and template key.

    Rule:
    - Match each destination marker to the source sprite sharing that anchor color.
    - Clear the destination interior to its background color, then stamp each matched sprite so the
      sprite anchor lands exactly on the marker.
    - Discard the destination border and crop the result to the minimum bbox covering all stamped pixels.

    Key insight: The anchor color still identifies both which sprite to use and where to place it, but
    the observable output is now determined by the combined footprint of the stamped sprites, not by the frame.
    """
    g = np.array(grid, dtype=int)

    rects = _find_task_rectangles(g)
    assert rects

    src = None
    dst = None
    for _area, rect, bc, _ibg in rects:
        ibg2, comps = _rect_components(g, rect)
        max_sz = max([int(c["size"]) for c in comps], default=0)
        if max_sz > 1 and src is None:
            src = (rect, bc, ibg2, comps)
        if max_sz == 1 and len(comps) > 0 and dst is None:
            dst = (rect, bc, ibg2, comps)

    assert src is not None and dst is not None, "must find both source and destination rectangles"

    (_sr, _sc, _sr1, _sc1), _src_bc, _src_bg, src_comps = src
    (dr, dc, dr1, dc1), _dst_bc, dst_bg, _dst_comps = dst

    templates: dict[int, tuple[np.ndarray, np.ndarray, tuple[int, int]]] = {}
    for comp in src_comps:
        cols = {k: int(v) for k, v in comp["colors"].items() if int(k) != 0}
        if not cols:
            continue
        anchor_col = int(min(cols.items(), key=lambda kv: (int(kv[1]), int(kv[0])))[0])
        patch = comp["patch"]
        mask = comp["mask"]
        anchors = np.argwhere((patch == int(anchor_col)) & mask)
        if anchors.size == 0:
            continue
        ar, ac = map(int, anchors[0])
        old = templates.get(int(anchor_col))
        if old is None or int(mask.sum()) > int(old[1].sum()):
            templates[int(anchor_col)] = (patch.copy(), mask.copy(), (int(ar), int(ac)))

    inner = g[int(dr) + 1 : int(dr1), int(dc) + 1 : int(dc1)]
    out = np.full(inner.shape, int(dst_bg), dtype=int)
    for rr, cc in np.argwhere(inner != int(dst_bg)):
        mcol = int(inner[int(rr), int(cc)])
        if int(mcol) not in templates:
            continue
        patch, mask, (ar, ac) = templates[int(mcol)]
        top = int(rr - ar)
        left = int(cc - ac)
        paste(out, patch, int(top), int(left), mask=mask, overwrite=True, clip=True)

    return _tight_crop(out, int(dst_bg))


