# Design analysis for the D5 variant
# ==================================
# a) Concrete behavior and trace
#    - The palette is unchanged: a 2xN or Nx2 legend on one grid edge maps border colors
#      to fill colors.
#    - Hollow sprites are unchanged in input: their enclosed holes are background-colored.
#    - The output change is local to the hole-writing step. Instead of painting every hole
#      cell with the mapped fill color, only hole cells whose absolute grid coordinates satisfy
#      (r + c) % 2 == 0 are painted; odd-parity cells stay background.
#    - Example trace: suppose a 2x2 hole is surrounded by border color 4, and the palette says
#      4 -> 6. Original task writes all four cells to 6. This variant writes 6 only to the two
#      even-parity cells and leaves the other two as 0, producing a visible checkerboard.
#
# b) Complexity calibration
#    - Palette detection, adjacency-based border identification, and distractor sprites stay
#      intact, so the task still requires finding the correct object-color mapping.
#    - The checkerboard effect is visually obvious only when holes have area >= 2, so the
#      generator rejects attempts where every fillable hole is a single cell. This prevents
#      the variant from collapsing into near-original behavior.
#
# c) Implicit-assumption audit of the original main()
#    - _bg_boundary and _palette_mapping depend only on the palette sitting on an edge and bg
#      dominating the border; both still hold.
#    - _fill_enclosed_bg_regions previously assumed every cell in a selected hole should be
#      overwritten. That assumption no longer holds. The new code must write conditionally per
#      cell, otherwise it would silently revert to the old rule.
#    - Adjacent-color counting is still safe because it is computed before any writes inside the
#      same hole matter; the border color remains on the sprite boundary, not inside the hole.
#
# d) Placement legality
#    - Sprites and palette still require at least one background cell of padding, so holes stay
#      distinct and the solver can treat each enclosed bg component independently.
#    - Hole cells are still prevented from touching the outer grid boundary, which preserves the
#      "interior only" interpretation used by the solver.
#
# e) Visual observability
#    - Across 2-4 examples, a human can compare input/output and see that filled interiors are
#      not solid blocks anymore: the same mapped color appears on alternating cells only.
#    - The parity rule is based on visible position, not color id or hidden ordering.
#
# f) Visual cleanliness
#    - Only one layer changes inside each hole: mapped color on alternating cells, background on
#      the others. Borders, palette, and spacing rules stay unchanged, so the grid remains easy
#      to parse.
#
# g) Color-change inferability
#    - The palette still provides the exact fill color. The new structural clue is positional:
#      mapped colors occupy alternating cells inside the hole. Because several filled sprites can
#      reuse the same global checkerboard orientation, the pattern is learnable from few samples.


def _bg_boundary(g: np.ndarray) -> int:
    """Most common color along the 1-cell outer border."""
    border = np.concatenate([g[0, :], g[-1, :], g[1:-1, 0], g[1:-1, -1]])
    vals, cnts = np.unique(border, return_counts=True)
    return int(vals[cnts.argmax()])


def _best_palette(g: np.ndarray, bg: int) -> tuple[str, int, int]:
    """
    Find the 2xN or Nx2 palette block on a grid edge.

    Returns (side, start, end) where:
      - side in {"top","bottom","left","right"}
      - for top/bottom: start/end are column indices [start,end)
      - for left/right: start/end are row indices [start,end)
    """
    h, w = g.shape
    best = None

    def isolated(side: str, start: int, end: int) -> bool:
        """
        Palette cells (excluding bg) should not be 4-neigh adjacent to same-colored cells
        outside the palette region; this prevents accidentally absorbing parts of large sprites
        that touch the grid edge.
        """
        h2, w2 = g.shape
        pal = np.zeros((h2, w2), dtype=bool)
        if side == "top":
            pal[0:2, start:end] = True
        elif side == "bottom":
            pal[h2 - 2 : h2, start:end] = True
        elif side == "left":
            pal[start:end, 0:2] = True
        else:
            pal[start:end, w2 - 2 : w2] = True

        for r, c in zip(*np.where(pal), strict=False):
            v = int(g[int(r), int(c)])
            if v == bg:
                continue
            for rr, cc in neighbors4(int(r), int(c)):
                if 0 <= rr < h2 and 0 <= cc < w2 and not pal[rr, cc]:
                    if int(g[rr, cc]) == v:
                        return False
        return True

    def consider_top() -> None:
        nonlocal best
        if h < 2:
            return
        a = g[0, :]
        b = g[1, :]
        for c0 in range(w):
            for c1 in range(c0 + 2, w + 1):
                seg_a = a[c0:c1]
                seg_b = b[c0:c1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0 or len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("top", c0, c1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(c1 - c0), nonbg)
                cand = (score, "top", c0, c1)
                if best is None or cand[0] > best[0]:
                    best = cand

    def consider_bottom() -> None:
        nonlocal best
        if h < 2:
            return
        a = g[h - 1, :]
        b = g[h - 2, :]
        for c0 in range(w):
            for c1 in range(c0 + 2, w + 1):
                seg_a = a[c0:c1]
                seg_b = b[c0:c1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0 or len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("bottom", c0, c1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(c1 - c0), nonbg)
                cand = (score, "bottom", c0, c1)
                if best is None or cand[0] > best[0]:
                    best = cand

    def consider_left() -> None:
        nonlocal best
        if w < 2:
            return
        a = g[:, 0]
        b = g[:, 1]
        for r0 in range(h):
            for r1 in range(r0 + 2, h + 1):
                seg_a = a[r0:r1]
                seg_b = b[r0:r1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0 or len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("left", r0, r1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(r1 - r0), nonbg)
                cand = (score, "left", r0, r1)
                if best is None or cand[0] > best[0]:
                    best = cand

    def consider_right() -> None:
        nonlocal best
        if w < 2:
            return
        a = g[:, w - 1]
        b = g[:, w - 2]
        for r0 in range(h):
            for r1 in range(r0 + 2, h + 1):
                seg_a = a[r0:r1]
                seg_b = b[r0:r1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0 or len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("right", r0, r1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(r1 - r0), nonbg)
                cand = (score, "right", r0, r1)
                if best is None or cand[0] > best[0]:
                    best = cand

    consider_top()
    consider_bottom()
    consider_left()
    consider_right()

    assert best is not None, "_best_palette must find a valid palette region"
    _, side, start, end = best
    return side, int(start), int(end)


def _palette_mapping(g: np.ndarray, bg: int) -> tuple[dict[int, int], np.ndarray]:
    """Return (mapping border->fill, palette_mask)."""
    h, w = g.shape
    side, start, end = _best_palette(g, bg)
    pal_mask = np.zeros((h, w), dtype=bool)
    mapping: dict[int, int] = {}

    if side == "top":
        pal_mask[0:2, start:end] = True
        border_line = g[0, start:end]
        fill_line = g[1, start:end]
    elif side == "bottom":
        pal_mask[h - 2 : h, start:end] = True
        border_line = g[h - 1, start:end]
        fill_line = g[h - 2, start:end]
    elif side == "left":
        pal_mask[start:end, 0:2] = True
        border_line = g[start:end, 0]
        fill_line = g[start:end, 1]
    else:
        pal_mask[start:end, w - 2 : w] = True
        border_line = g[start:end, w - 1]
        fill_line = g[start:end, w - 2]

    for b, f in zip(border_line.tolist(), fill_line.tolist(), strict=False):
        b = int(b)
        if b == bg:
            continue
        mapping[b] = int(f)

    return mapping, pal_mask


def _checkerboard_fill_region(
    out: np.ndarray, pts: np.ndarray, fill: int
) -> tuple[int, int]:
    """Paint even-parity cells in pts with fill and leave odd-parity cells unchanged."""
    painted = 0
    skipped = 0
    for r, c in pts:
        if (int(r) + int(c)) % 2 == 0:
            out[int(r), int(c)] = fill
            painted += 1
        else:
            skipped += 1
    return painted, skipped


def _fill_enclosed_bg_regions(out: np.ndarray, bg: int, mapping: dict[int, int], pal_mask: np.ndarray) -> None:
    """
    Find enclosed bg regions (excluding the palette area) and checker-fill them
    according to the dominant adjacent border color.
    """
    h, w = out.shape
    bg_mask = (out == bg) & (~pal_mask)
    for pts in components_mask(bg_mask, connectivity=4):
        touches_boundary = any(r == 0 or c == 0 or r == h - 1 or c == w - 1 for r, c in pts)
        if touches_boundary:
            continue

        adj_counts: dict[int, int] = {}
        for r, c in pts:
            for rr, cc in neighbors4(int(r), int(c)):
                if 0 <= rr < h and 0 <= cc < w and not pal_mask[rr, cc]:
                    v = int(out[rr, cc])
                    if v == bg:
                        continue
                    adj_counts[v] = adj_counts.get(v, 0) + 1
        if not adj_counts:
            continue

        border = None
        best = -1
        for col, cnt in adj_counts.items():
            if col in mapping and cnt > best:
                best = cnt
                border = col
        if border is None:
            continue

        _checkerboard_fill_region(out, pts, int(mapping[border]))


def main(grid: np.ndarray) -> np.ndarray:
    """
    Apply palette-driven checkerboard fills inside hollow sprites.

    Input structure:
    - Background cells dominate the outer border, with several hollow sprites elsewhere.
    - A 2×N or N×2 legend sits on one grid edge; its outer line gives border colors and its inner line gives the corresponding interior colors.

    Rule:
    - Detect the edge legend and read it as a border-color to fill-color mapping.
    - Find enclosed background regions that lie inside sprites and do not touch the grid boundary.
    - For each such hole, use the most common adjacent border color to choose the mapped fill color, then paint only the hole cells with even (row+col) parity; odd-parity hole cells remain background.

    Key insight:
    - The palette still tells you which color belongs to each sprite border, but the interior is no longer solid; the fill must be placed on alternating grid cells using global coordinate parity.
    """
    g = np.asarray(grid, dtype=int)
    bg = _bg_boundary(g)
    mapping, pal_mask = _palette_mapping(g, bg)
    assert mapping, "main: palette mapping must be non-empty"

    out = g.copy()
    _fill_enclosed_bg_regions(out, bg, mapping, pal_mask)
    return out


