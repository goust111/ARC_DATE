# Variant of dbff022c
# Dimension: D5 — 变换操作——内部区域的填充方式 (transform)
# Change: 使用 flood_fill 将精灵内部所有背景色像素填充为调色板查找到的单一颜色... → 条纹填充——水平或垂直交替条纹

import random

import numpy as np

from arc_utils import components_mask, neighbors4


# Design analysis for the D5 variant
# - Source-task review: no separate source_task was provided, so only the original
#   dbff022c solver/generator and its official examples were used as the baseline.
# - Concrete behavior:
#   The palette mechanism stays unchanged: a 2xN or Nx2 legend on one outer edge
#   maps sprite border colors to interior fill colors. The changed part is what the
#   output hole looks like. Instead of turning every interior background cell into a
#   single solid color, each enclosed hole becomes alternating stripes made from
#   the mapped fill color and the background color.
# - Stripe rule used here:
#   For one enclosed hole, compute its local bounding box. If the hole is wider
#   than tall, or square, use vertical stripes. If the hole is taller than wide,
#   use horizontal stripes. The first stripe inside the local bbox is always the
#   mapped fill color, and the next stripe is background, alternating by one cell.
#   This makes the branch choice visible from geometry rather than from invisible
#   metadata such as color ids or generation order.
# - Behavior trace on one hole:
#   Original task: a 2x4 hole adjacent to border color 6 and palette value 3 would
#   become all 3s.
#   Variant: the same 2x4 hole is wider than tall, so it becomes vertical stripes:
#   columns 0 and 2 use color 3, columns 1 and 3 stay background 0.
#   The solver still detects the hole and the dominant surrounding border color in
#   exactly the same way; only the writeback step changes.
# - Complexity calibration:
#   The variant keeps only two stripe orientations, derived from visible geometry.
#   That is enough variety to avoid degeneration into the original task, while still
#   being learnable from a few examples. The generator deliberately produces filled
#   sprites whose holes support both horizontal and vertical cases across samples.
# - Implicit assumptions from the original main() that needed review:
#   1. The palette-detection code assumes the palette itself is unchanged and still
#      isolated on a grid edge. This remains true.
#   2. The hole-filling routine originally assumed every cell in a hole could be
#      overwritten with the same fill color. That assumption no longer holds, so the
#      per-cell writeback must depend on hole-local row/column parity.
#   3. The original code safely computed all bg components before mutating the grid.
#      This is still required, because striped filling intentionally leaves some bg
#      cells behind; recomputing components after each fill would split regions and
#      corrupt processing.
#   4. The adjacent-border-color vote must still be taken from the pre-filled hole
#      boundary, not from newly written stripe cells. This code keeps that ordering.
# - Placement legality and solver/generator agreement:
#   The generator keeps the original non-overlap and 1-cell separation constraints
#   between palette and sprites. Filled sprites are additionally filtered so at
#   least one enclosed hole has area >= 2 and matches a requested stripe axis; this
#   guarantees the stripe pattern is visible and that output differs from the
#   original solid-fill behavior on those samples.
# - Visual observability and cleanliness:
#   Stripe direction comes from the hole's aspect ratio, which a human can inspect.
#   The palette still explains the color choice, while the alternating bg cells make
#   the new transform visually obvious. Objects remain separated, so no region mixes
#   multiple semantics in the same area.
# - New solver assumptions introduced by this variant:
#   1. The intended filled holes should have at least two cells if the task is meant
#      to visibly demonstrate striping; the generator enforces that for palette-hit
#      sprites.
#   2. Hole-local bbox geometry determines stripe direction, so the generator must
#      avoid relying on invisible tie-breaks; square holes are consistently mapped to
#      vertical stripes.


def _bg_boundary(g: np.ndarray) -> int:
    """Most common color along the 1-cell outer border."""
    border = np.concatenate([g[0, :], g[-1, :], g[1:-1, 0], g[1:-1, -1]])
    vals, cnts = np.unique(border, return_counts=True)
    return int(vals[cnts.argmax()])


def _best_palette(g: np.ndarray, bg: int) -> tuple[str, int, int]:
    """
    Find the 2xN or Nx2 palette block on a grid edge.

    Returns (side, start, end) where:
      - side in {"top","bottom","left","right"}
      - for top/bottom: start/end are column indices [start,end)
      - for left/right: start/end are row indices [start,end)
    """
    h, w = g.shape
    best = None  # (score_tuple, side, start, end)

    def isolated(side: str, start: int, end: int) -> bool:
        """
        Palette cells (excluding bg) should not be 4-neigh adjacent to same-colored cells
        outside the palette region; this prevents accidentally absorbing parts of large sprites
        that touch the grid edge.
        """
        h2, w2 = g.shape
        pal = np.zeros((h2, w2), dtype=bool)
        if side == "top":
            pal[0:2, start:end] = True
        elif side == "bottom":
            pal[h2 - 2 : h2, start:end] = True
        elif side == "left":
            pal[start:end, 0:2] = True
        else:
            pal[start:end, w2 - 2 : w2] = True

        for r, c in zip(*np.where(pal), strict=False):
            r = int(r)
            c = int(c)
            v = int(g[r, c])
            if v == bg:
                continue
            for rr, cc in neighbors4(r, c):
                if 0 <= rr < h2 and 0 <= cc < w2 and not pal[rr, cc]:
                    if int(g[rr, cc]) == v:
                        return False
        return True

    def consider_top():
        nonlocal best
        if h < 2:
            return
        a = g[0, :]
        b = g[1, :]
        for c0 in range(w):
            for c1 in range(c0 + 2, w + 1):
                seg_a = a[c0:c1]
                seg_b = b[c0:c1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0:
                    continue
                if len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("top", c0, c1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(c1 - c0), nonbg)
                cand = (score, "top", c0, c1)
                if best is None or cand[0] > best[0]:
                    best = cand

    def consider_bottom():
        nonlocal best
        if h < 2:
            return
        a = g[h - 1, :]
        b = g[h - 2, :]
        for c0 in range(w):
            for c1 in range(c0 + 2, w + 1):
                seg_a = a[c0:c1]
                seg_b = b[c0:c1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0:
                    continue
                if len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("bottom", c0, c1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(c1 - c0), nonbg)
                cand = (score, "bottom", c0, c1)
                if best is None or cand[0] > best[0]:
                    best = cand

    def consider_left():
        nonlocal best
        if w < 2:
            return
        a = g[:, 0]
        b = g[:, 1]
        for r0 in range(h):
            for r1 in range(r0 + 2, h + 1):
                seg_a = a[r0:r1]
                seg_b = b[r0:r1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0:
                    continue
                if len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("left", r0, r1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(r1 - r0), nonbg)
                cand = (score, "left", r0, r1)
                if best is None or cand[0] > best[0]:
                    best = cand

    def consider_right():
        nonlocal best
        if w < 2:
            return
        a = g[:, w - 1]
        b = g[:, w - 2]
        for r0 in range(h):
            for r1 in range(r0 + 2, h + 1):
                seg_a = a[r0:r1]
                seg_b = b[r0:r1]
                da = set(map(int, np.unique(seg_a)))
                db = set(map(int, np.unique(seg_b)))
                da.discard(bg)
                db.discard(bg)
                if len(da) < 2 or len(db) < 2:
                    continue
                d = da | db
                if len(d) < 3:
                    continue
                border_keys = [int(x) for x in seg_a.tolist() if int(x) != bg]
                if len(border_keys) == 0:
                    continue
                if len(border_keys) != len(set(border_keys)):
                    continue
                if not isolated("right", r0, r1):
                    continue
                nonbg = int(np.sum(seg_a != bg) + np.sum(seg_b != bg))
                score = (len(set(border_keys)), len(d), -(r1 - r0), nonbg)
                cand = (score, "right", r0, r1)
                if best is None or cand[0] > best[0]:
                    best = cand

    consider_top()
    consider_bottom()
    consider_left()
    consider_right()

    assert best is not None, "_best_palette must find a valid palette region"
    _, side, start, end = best
    return side, int(start), int(end)


def _palette_mapping(g: np.ndarray, bg: int) -> tuple[dict[int, int], np.ndarray]:
    """
    Returns (mapping border->fill, palette_mask).
    """
    h, w = g.shape
    side, start, end = _best_palette(g, bg)
    pal_mask = np.zeros((h, w), dtype=bool)
    mapping: dict[int, int] = {}

    if side == "top":
        pal_mask[0:2, start:end] = True
        border_line = g[0, start:end]
        fill_line = g[1, start:end]
    elif side == "bottom":
        pal_mask[h - 2 : h, start:end] = True
        border_line = g[h - 1, start:end]
        fill_line = g[h - 2, start:end]
    elif side == "left":
        pal_mask[start:end, 0:2] = True
        border_line = g[start:end, 0]
        fill_line = g[start:end, 1]
    else:  # right
        pal_mask[start:end, w - 2 : w] = True
        border_line = g[start:end, w - 1]
        fill_line = g[start:end, w - 2]

    for b, f in zip(border_line.tolist(), fill_line.tolist(), strict=False):
        b = int(b)
        f = int(f)
        if b == bg:
            continue
        mapping[b] = f

    return mapping, pal_mask


def _hole_bbox(pts: np.ndarray) -> tuple[int, int, int, int]:
    rows = pts[:, 0]
    cols = pts[:, 1]
    return int(rows.min()), int(cols.min()), int(rows.max()), int(cols.max())


def _stripe_axis_for_hole(pts: np.ndarray) -> str:
    r0, c0, r1, c1 = _hole_bbox(pts)
    hole_h = r1 - r0 + 1
    hole_w = c1 - c0 + 1
    return "vertical" if hole_w >= hole_h else "horizontal"


def _apply_striped_fill(out: np.ndarray, pts: np.ndarray, bg: int, fill: int) -> None:
    r0, c0, _, _ = _hole_bbox(pts)
    axis = _stripe_axis_for_hole(pts)
    for r, c in pts:
        rr = int(r)
        cc = int(c)
        if axis == "horizontal":
            out[rr, cc] = int(fill) if (rr - r0) % 2 == 0 else int(bg)
        else:
            out[rr, cc] = int(fill) if (cc - c0) % 2 == 0 else int(bg)


def _fill_enclosed_bg_regions(out: np.ndarray, bg: int, mapping: dict[int, int], pal_mask: np.ndarray) -> None:
    """
    Find background regions (excluding the palette area) that do NOT touch the grid boundary,
    infer their surrounding border color, and convert them into alternating stripes made from
    the mapped fill color and background.
    """
    h, w = out.shape
    bg_mask = (out == bg) & (~pal_mask)
    comps = components_mask(bg_mask, connectivity=4)
    for pts in comps:
        touches_boundary = any(r == 0 or c == 0 or r == h - 1 or c == w - 1 for r, c in pts)
        if touches_boundary:
            continue

        adj_counts: dict[int, int] = {}
        for r, c in pts:
            for rr, cc in neighbors4(int(r), int(c)):
                if 0 <= rr < h and 0 <= cc < w:
                    if pal_mask[rr, cc]:
                        continue
                    v = int(out[rr, cc])
                    if v == bg:
                        continue
                    adj_counts[v] = adj_counts.get(v, 0) + 1
        if not adj_counts:
            continue

        border = None
        best = -1
        for col, cnt in adj_counts.items():
            if col not in mapping:
                continue
            if cnt > best:
                best = cnt
                border = col
        if border is None:
            continue

        _apply_striped_fill(out, pts, bg, int(mapping[border]))


def main(grid: np.ndarray) -> np.ndarray:
    """
    Fill enclosed sprite interiors with palette-guided alternating stripes.

    Input structure:
    - bg is the dominant border color, and the scene contains several hollow sprites on that background.
    - A compact 2xN or Nx2 palette legend lies on one grid edge; its outer line lists sprite border colors and its inner line lists the corresponding fill colors.

    Rule:
    - Detect the edge palette and read it as a border-color to fill-color mapping.
    - Find each enclosed background region that is inside a sprite and does not touch the outer grid boundary.
    - Determine the dominant adjacent border color around that hole. If it appears in the palette, fill only alternating rows or columns of the hole with the mapped color while leaving the other stripes as background. Wider-or-square holes use vertical stripes; taller holes use horizontal stripes.

    Key insight:
    - The palette still chooses which color belongs inside each sprite, but the actual interior transform is no longer a solid flood fill. The hole's own geometry reveals whether the mapped color should alternate by column or by row.
    """
    g = np.asarray(grid, dtype=int)
    bg = _bg_boundary(g)

    mapping, pal_mask = _palette_mapping(g, bg)
    assert mapping, "main: palette mapping must be non-empty"

    out = g.copy()
    _fill_enclosed_bg_regions(out, bg, mapping, pal_mask)
    return out


