# Variant of a6f40cea
# Dimension: D15 — 内部填充色基底 (meta)
# Change: 输出基底为封闭框架的内部填充色（均匀单色），可能等于背景色... → 内部有干扰像素需擦除
#
# Design analysis
# variant_spec:
#   core_change:
#     original: 输入中的封闭框内部是纯色底，solver 直接把这层纯色复制成输出基底。
#     variant: 输入中的封闭框内部仍以单一主色为底，但会掺入若干小型干扰块；输出需要恢复干净底色，只保留由外部 open-rect 投影出的路径。
#   concrete_behavior:
#     input:
#       - 一个 1px 厚闭合矩形框。
#       - 框外仍是原题那套 L/U 型开放矩形组件，决定输出中的曼哈顿路径。
#       - 框内不再要求全同色；多数单元格是底色 fill，少量单元格被 1-3 色噪声块替换。
#     output:
#       - 大小仍为框内部尺寸。
#       - 非路径位置全部恢复为 fill。
#       - 路径规则、双色交替相位、U-pair 聚合都与原题一致。
#   behavior_trace:
#     example:
#       - 原题里，frame interior = 全 8；solver 找到 frame 后直接创建满 8 输出，再把外部红/黄路径写上去。
#       - 变体里，frame interior 仍以 8 为主，但内部出现几个零散 2/6/7 色块。
#       - 新 solver 先把 interior 的众数识别为 fill=8，而不是要求整个 interior 全部等于 8；之后仍从外部组件重建路径，并忽略 interior 里的 2/6/7。
#       - 差异点在于：旧逻辑会因 `inner == fill` 断言失败，新逻辑改为“多数底色 + 噪声擦除”。
#   complexity_calibration:
#     - 噪声必须稳定可见，所以生成器强制至少放置 1 个内部噪声块，而不是可选 0 个。
#     - 噪声块只占底色空位中的少量单元，避免压过主规则，也避免 frame 主色不再是多数。
#     - 噪声颜色优先避开路径颜色，降低“把噪声误读成部分路径”的偶然性，但在颜色资源不够时允许回退复用。
#   implicit_assumption_review:
#     - 原 `_find_framed_rect_uniform_fill` 依赖 interior 完全纯色；变体下必须改为“只要求边框完整，interior 众数即 fill”。
#     - 原 `out = full(fill)` 的无条件填底仍成立，因为输出规则没有改变，只是输入底色被污染。
#     - 原 `comp_mask = (g != bg) & (g != fill) & (g != bc)` 会把内部噪声也标成组件；这在原题里无事可做，在变体里仍安全，因为后续只读取 ring 上的组件触点，内部噪声不会出现在 ring。
#     - 原双色相位推断依赖 ring 端点颜色，和 interior 是否纯色无关，因此保持不变。
#   placement_legality:
#     - 内部噪声只允许落在 expected 输出中仍为 fill 的位置，不能覆盖应出现的路径位。
#     - 噪声块尽量不贴 interior 边界，保证视觉上是“框内杂点”而不是新的边界线索。
#     - 生成器继续沿用 oracle 检查 `main(input) == expected`，确保新噪声不会触发 solver 隐式崩溃。
#   visual_observability:
#     - 人眼在 2-3 组样例中会看到：外部 open-rect 仍然稳定决定输出路径，而框内零碎小块在输出中消失。
#     - 由于噪声位置与最终路径无对应关系，且多次样例重复出现“框内杂点被清除”，规则可归纳。
#   cleanliness:
#     - 噪声数量和尺寸受限，且只放在路径之外，避免输出与输入在同一区域叠加过多元素。
#     - 保留原题外部少量 distractor，但不把它们搬进框内路径区域。
#   color_inference:
#     - 不使用颜色 id 排序来决定规则；颜色仅作为对象身份。
#     - 噪声颜色不承载语义映射，解题线索来自其“无结构且在输出中被删除”的空间行为。

from __future__ import annotations

from collections import Counter, defaultdict
import random

import numpy as np
from scipy.ndimage import label

from arc_utils import STRUCT4, get_bg, neighbors4


def _find_framed_rect_dominant_fill(
    g: np.ndarray,
    *,
    bg: int | None = None,
    structure=STRUCT4,
) -> tuple[int, int, int, int, int, int] | None:
    """
    Detect the main 1px-thick rectangular frame even when its interior contains noise.

    Returns (r0, c0, r1, c1, border_color, fill_color) for the largest such rectangle, else None.
    """
    if bg is None:
        bg = int(get_bg(g))
    else:
        bg = int(bg)

    best = None  # (area, fill_count, r0, c0, r1, c1, bc, fill)
    for bc in sorted(set(map(int, g.flatten())) - {int(bg)}):
        lab, n = label(g == int(bc), structure=structure)
        for cid in range(1, int(n) + 1):
            pts = np.argwhere(lab == int(cid))
            if int(len(pts)) < 8:
                continue

            r0, c0 = pts.min(axis=0)
            r1, c1 = pts.max(axis=0)
            r0, c0, r1, c1 = map(int, (r0, c0, r1, c1))
            h = int(r1 - r0 + 1)
            w = int(c1 - c0 + 1)
            if h < 3 or w < 3:
                continue

            per = int(2 * (h + w) - 4)
            if int(len(pts)) != per:
                continue
            if not (g[r0, c0 : c1 + 1] == int(bc)).all():
                continue
            if not (g[r1, c0 : c1 + 1] == int(bc)).all():
                continue
            if not (g[r0 : r1 + 1, c0] == int(bc)).all():
                continue
            if not (g[r0 : r1 + 1, c1] == int(bc)).all():
                continue

            inner = g[r0 + 1 : r1, c0 + 1 : c1]
            if inner.size == 0:
                continue
            fill, fill_count = Counter(map(int, inner.flatten())).most_common(1)[0]
            fill = int(fill)
            fill_count = int(fill_count)
            if fill == int(bc):
                continue
            if fill_count * 2 <= int(inner.size):
                continue

            area = int(h * w)
            cand = (area, fill_count, int(r0), int(c0), int(r1), int(c1), int(bc), int(fill))
            if best is None or cand[:2] > best[:2]:
                best = cand

    if best is None:
        return None
    _area, _fill_count, r0, c0, r1, c1, bc, fill = best
    return int(r0), int(c0), int(r1), int(c1), int(bc), int(fill)


def main(grid: np.ndarray) -> np.ndarray:
    """
    Recover the intended interior drawing from exterior traces around a framed rectangle.

    Input structure:
    - A bg field contains one closed 1px rectangular frame plus colored components outside it.
    - The frame interior is mostly one fill color, but may include small noisy blobs unrelated to the true answer.

    Rule:
    - Output the frame interior only, rebuilt on a clean fill-colored base.
    - Project each ring-touching outside component onto interior edge coordinates and draw the corresponding Manhattan stripe or L-path.
    - Ignore interior noise completely; any non-path clutter inside the frame is erased in the output.

    Key insight: The outside open-rect geometry still carries all path information, while the frame interior must now be denoised by taking its dominant base color rather than trusting every pixel.
    """
    g = np.array(grid, dtype=int)
    H, W = g.shape
    bg = int(get_bg(g))

    found = _find_framed_rect_dominant_fill(g, bg=int(bg))
    assert not (found is None)
    r0, c0, r1, c1, bc, fill = found
    outH = int(r1 - r0 - 1)
    outW = int(c1 - c0 - 1)
    out = np.full((outH, outW), int(fill), dtype=int)
    r_int0 = int(r0 + 1)
    c_int0 = int(c0 + 1)

    def map_to_out(rr: int, cc: int) -> tuple[int, int]:
        r = max(0, min(outH - 1, int(rr - r_int0)))
        c = max(0, min(outW - 1, int(cc - c_int0)))
        return int(r), int(c)

    def build_manhattan(p1: tuple[int, int], p2: tuple[int, int], cornerA: bool) -> list[tuple[int, int]]:
        (ra, ca), (rb, cb) = p1, p2
        if ra == rb:
            step = 1 if cb >= ca else -1
            return [(int(ra), int(c)) for c in range(int(ca), int(cb) + step, step)]
        if ca == cb:
            step = 1 if rb >= ra else -1
            return [(int(r), int(ca)) for r in range(int(ra), int(rb) + step, step)]
        if cornerA:
            step = 1 if rb >= ra else -1
            path = [(int(r), int(ca)) for r in range(int(ra), int(rb) + step, step)]
            step = 1 if cb >= ca else -1
            path += [(int(rb), int(c)) for c in range(int(ca) + step, int(cb) + step, step)]
            return path
        step = 1 if cb >= ca else -1
        path = [(int(ra), int(c)) for c in range(int(ca), int(cb) + step, step)]
        step = 1 if rb >= ra else -1
        path += [(int(r), int(cb)) for r in range(int(ra) + step, int(rb) + step, step)]
        return path

    def inside_corner(p1: tuple[int, int], p2: tuple[int, int], cornerA: bool) -> bool:
        (ra, ca), (rb, cb) = p1, p2
        if ra == rb or ca == cb:
            return True
        corner = (rb, ca) if cornerA else (ra, cb)
        rr, cc = corner
        return (0 < rr < outH - 1) and (0 < cc < outW - 1)

    comp_mask = (g != int(bg)) & (g != int(fill)) & (g != int(bc))
    clab, cn = label(comp_mask, structure=STRUCT4)

    ring = set()
    for cc in range(c0, c1 + 1):
        for rr in (r0 - 1, r1 + 1):
            if 0 <= rr < H:
                ring.add((int(rr), int(cc)))
    for rr in range(r0, r1 + 1):
        for cc in (c0 - 1, c1 + 1):
            if 0 <= cc < W:
                ring.add((int(rr), int(cc)))

    comp_pts: dict[int, list[tuple[int, int, int]]] = defaultdict(list)
    for rr, cc in ring:
        cid = int(clab[rr, cc])
        if cid == 0:
            continue
        col = int(g[rr, cc])
        mr, mc = map_to_out(rr, cc)
        comp_pts[cid].append((mr, mc, col))

    comp_cols: dict[int, list[int]] = {}
    for cid in range(1, int(cn) + 1):
        comp_cols[cid] = sorted(set(map(int, g[clab == int(cid)].flatten())))

    deferred: dict[int, set[tuple[int, int]]] = defaultdict(set)

    for cid, pts in comp_pts.items():
        if len(pts) < 2:
            continue
        cols = comp_cols.get(cid, [])
        if not cols:
            continue

        hist: dict[tuple[int, int], Counter] = defaultdict(Counter)
        for r, c, col in pts:
            hist[(int(r), int(c))][int(col)] += 1

        coords = list(hist.keys())

        if len(cols) == 1:
            colv = int(cols[0])
            uniq = coords
            rows = {r for r, _c in uniq}
            cols2 = {c for _r, c in uniq}
            if len(rows) == 1 or len(cols2) == 1:
                for p in uniq:
                    deferred[colv].add((int(p[0]), int(p[1])))
                continue

            best = None
            for i in range(len(uniq)):
                for j in range(i + 1, len(uniq)):
                    d = abs(uniq[i][0] - uniq[j][0]) + abs(uniq[i][1] - uniq[j][1])
                    if best is None or d > best[0]:
                        best = (d, uniq[i], uniq[j])
            if best is None:
                continue
            _d, p1, p2 = best
            pathA = build_manhattan(p1, p2, True)
            pathB = build_manhattan(p1, p2, False)
            chosen = pathB if (inside_corner(p1, p2, False) and not inside_corner(p1, p2, True)) else pathA
            for rr, cc in chosen:
                out[int(rr), int(cc)] = int(colv)
            continue

        if len(cols) == 2:
            best = None
            for i in range(len(coords)):
                for j in range(i + 1, len(coords)):
                    d = abs(coords[i][0] - coords[j][0]) + abs(coords[i][1] - coords[j][1])
                    if best is None or d > best[0]:
                        best = (d, coords[i], coords[j])
            if best is None:
                continue
            _d, a, b = best
            ca, cb = map(int, cols)
            ha = int(hist[a].most_common(1)[0][0])
            hb = int(hist[b].most_common(1)[0][0])

            pathA = build_manhattan(a, b, True)
            pathB = build_manhattan(a, b, False)
            path = pathB if (inside_corner(a, b, False) and not inside_corner(a, b, True)) else pathA

            def paint_alt(path_pts: list[tuple[int, int]], start_color: int):
                cur = int(start_color)
                for rr, cc in path_pts:
                    out[int(rr), int(cc)] = int(cur)
                    cur = int(cb) if cur == int(ca) else int(ca)

            chosen = None
            for path_pts in (path, list(reversed(path))):
                for start_color in (ca, cb):
                    end_color = start_color if ((len(path_pts) - 1) % 2 == 0) else (cb if start_color == ca else ca)
                    if int(start_color) != int(ha):
                        continue
                    if int(end_color) != int(hb):
                        continue
                    chosen = (path_pts, int(start_color))
                    break
                if chosen is not None:
                    break

            assert chosen is not None

            path_pts, start_color = chosen
            paint_alt(path_pts, start_color)
            continue

    for col, pts in deferred.items():
        pts = list(pts)
        if not pts:
            continue
        tops = [p for p in pts if p[0] == 0]
        bots = [p for p in pts if p[0] == outH - 1]
        if tops and bots:
            for cc in sorted({c for _r, c in pts}):
                rs = [r for r, c in pts if c == cc]
                for rr in range(min(rs), max(rs) + 1):
                    out[int(rr), int(cc)] = int(col)
            continue
        lefts = [p for p in pts if p[1] == 0]
        rights = [p for p in pts if p[1] == outW - 1]
        if lefts and rights:
            for rr in sorted({r for r, _c in pts}):
                cs = [c for r, c in pts if r == rr]
                for cc in range(min(cs), max(cs) + 1):
                    out[int(rr), int(cc)] = int(col)
            continue
        if len(pts) == 1:
            rr, cc = pts[0]
            out[int(rr), int(cc)] = int(col)
            continue
        best = None
        for i in range(len(pts)):
            for j in range(i + 1, len(pts)):
                d = abs(pts[i][0] - pts[j][0]) + abs(pts[i][1] - pts[j][1])
                if best is None or d > best[0]:
                    best = (d, pts[i], pts[j])
        if best is None:
            continue
        _d, p1, p2 = best
        pathA = build_manhattan(p1, p2, True)
        pathB = build_manhattan(p1, p2, False)
        chosen = pathB if (inside_corner(p1, p2, False) and not inside_corner(p1, p2, True)) else pathA
        for rr, cc in chosen:
            out[int(rr), int(cc)] = int(col)

    return out


