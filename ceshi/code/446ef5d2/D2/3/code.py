# Variant of 446ef5d2
# Dimension: D2 — 源对象的形状与结构 (src)
# Change: 散布在背景上的矩形碎片，每块 2-7 格宽高，包含 rect_col 和 interior_col 像素，至少一条边含非... → 碎片包含干扰项

from __future__ import annotations

from collections import Counter
from functools import lru_cache

import numpy as np

from arc_utils import paste, random_free_location


# Design analysis for the D2 variant
# ----------------------------------
# a) Concrete behavior:
#    The input still shows many scattered rectangles plus the 3-cell L marker.
#    The output is still one assembled rectangle anchored at the marker corner.
#    The change is that 1-2 extra rectangles are also scattered on the grid.
#    They look like normal fragments: same rect_col border/wildcard color, same
#    interior palette, same 2-7 size range, and at least one non-rect_col edge.
#    However, they are "near misses": for one true slot they agree on several
#    sides but disagree on at least one required side, so they cannot belong to
#    any valid full tiling.
#    Small trace:
#    - Original: total area of all non-marker rectangles = target rectangle area.
#      Solver can enumerate factor pairs of that total and must use every piece.
#    - Variant: total area is too large because distractors are included.
#      Solver must search for a subset of rectangles whose area forms a legal
#      anchored rectangle and whose edge constraints tile it exactly.
#    - Difference: the key branching point moves from "use all pieces" to
#      "choose which pieces are genuine before/while assembling".
# b) Complexity calibration:
#    Distractors are limited to 1-2 pieces so the image remains readable.
#    They reuse the same palette and piece geometry, so the visual change is
#    obvious but not chaotic. They are generated by mutating one side of a true
#    piece, which keeps them plausible without exploding the search space.
# c) Old implicit assumptions that break:
#    - `total_area = sum(all rect areas)` no longer equals the final rectangle.
#    - Candidate dimensions can no longer be derived only from the total area.
#    - The backtracking step can no longer require `used all pieces`.
#    - Any logic that treats every non-bg rectangle as genuine now fails.
#    The new solver therefore:
#    - computes subset-reachable areas instead of a single total area;
#    - tries anchored rectangle dimensions for those subset areas;
#    - allows unused pieces to remain.
# d) Placement legality:
#    Generator still scatters every rectangle with >=1 background cell padding,
#    so pieces never touch, never overlap, and rectangle extraction remains
#    valid. Marker placement rules are unchanged. Distractors are also placed
#    with the same spacing and remain ordinary rectangles.
# e) Visual observability:
#    Across 2-4 examples a human can see there are "too many" plausible pieces,
#    and some do not belong in the final rectangle because the output omits
#    them. To make the mismatch visible, the generator uses at least 2 interior
#    colors; otherwise rect_col wildcard + one interior color would make
#    side-mismatches nearly invisible and often impossible to enforce.
# f) Visual cleanliness:
#    No new markers or overlays are added. The only extra structure is a small
#    number of extra rectangles, so the grid remains legible and the original
#    task identity is preserved.
# g) Color inference:
#    No new color mapping rule is introduced. Distractors use only rect_col plus
#    the existing interior palette, so color semantics remain the same.
# 9) New solver assumptions and how the generator guarantees them:
#    - There exists exactly one large-area valid assembly chosen by the solver.
#      Generator validates `main(input) == expected_output` and rejects others.
#    - `rect_col` is still the most common pixel across all scattered pieces.
#      Distractors are few and small, and they use the same rect_col.
#    - At least one valid subset area has 4-12 pieces and fits the marker.
#      This is inherited from the true rectangle construction.
#    - Distractors are genuine rectangles and remain separated from all objects.


def _find_marker(g: np.ndarray, bg: int) -> tuple[int, tuple[int, int], tuple[int, int, int, int]]:
    cnt = Counter(map(int, g.flatten()))
    for col in sorted(c for c, n in cnt.items() if int(c) != int(bg) and int(n) == 3):
        pts = [(int(r), int(c)) for r, c in np.argwhere(g == int(col))]
        rs = [r for r, _ in pts]
        cs = [c for _, c in pts]
        r0, r1 = min(rs), max(rs)
        c0, c1 = min(cs), max(cs)
        if (r1 - r0) != 1 or (c1 - c0) != 1:
            continue
        all4 = {(r0, c0), (r0, c1), (r1, c0), (r1, c1)}
        miss = list(all4 - set(pts))
        if len(miss) == 1:
            return int(col), miss[0], (r0, c0, r1, c1)
    raise AssertionError("marker not found")


def _marker_corner(missing: tuple[int, int], bbox: tuple[int, int, int, int]) -> str:
    r0, c0, r1, c1 = bbox
    if missing == (r0, c0):
        return "BR"
    if missing == (r0, c1):
        return "BL"
    if missing == (r1, c0):
        return "TR"
    return "TL"


def _extract_rectangles(g: np.ndarray, bg: int, mark: int) -> list[tuple[int, int, int, int, np.ndarray]]:
    GH, GW = g.shape
    occ = (g != int(bg)) & (g != int(mark))
    used = np.zeros_like(occ, dtype=bool)
    rects: list[tuple[int, int, int, int, np.ndarray]] = []
    while True:
        idx = np.argwhere(occ & (~used))
        if idx.size == 0:
            break
        rr, cc = map(int, idx[0])
        w = 0
        while cc + w < GW and bool(occ[rr, cc + w]) and (not bool(used[rr, cc + w])):
            w += 1
        h = 0
        while rr + h < GH and bool((occ[rr + h, cc : cc + w] & (~used[rr + h, cc : cc + w])).all()):
            h += 1
        used[rr : rr + h, cc : cc + w] = True
        rects.append((rr, cc, h, w, g[rr : rr + h, cc : cc + w].copy()))
    return rects


def _compat(v1: np.ndarray, v2: np.ndarray, rect_col: int) -> bool:
    a = np.array(v1, dtype=int)
    b = np.array(v2, dtype=int)
    m = (a != int(rect_col)) & (b != int(rect_col))
    return bool((a[m] == b[m]).all())


def _fit_top_left(corner: str, mr: int, mc: int, H: int, W: int) -> tuple[int, int]:
    if corner == "TL":
        return mr, mc
    if corner == "TR":
        return mr, mc - W + 1
    if corner == "BL":
        return mr - H + 1, mc
    return mr - H + 1, mc - W + 1


def main(grid: np.ndarray) -> np.ndarray:
    g = np.array(grid, dtype=int)
    GH, GW = g.shape
    bg = int(Counter(map(int, g.flatten())).most_common(1)[0][0])
    mark, missing, mb = _find_marker(g, bg)
    corner = _marker_corner(missing, mb)
    rects = _extract_rectangles(g, bg, mark)
    assert rects

    allpix: list[int] = []
    for _r, _c, _h, _w, a in rects:
        allpix.extend(map(int, a.flatten()))
    rect_col = int(Counter(allpix).most_common(1)[0][0])

    pieces = [a for _r, _c, _h, _w, a in rects]
    n = len(pieces)
    ph = [int(p.shape[0]) for p in pieces]
    pw = [int(p.shape[1]) for p in pieces]
    areas = [int(ph[i] * pw[i]) for i in range(n)]

    mr, mc = map(int, missing)

    # Variant change: candidate rectangle area is a subset-sum over pieces,
    # because some rectangles are distractors and remain unused.
    area_counts: dict[int, int] = {0: 1}  # sum -> bitmask of reachable piece counts
    for a in areas:
        nxt = dict(area_counts)
        for s, cnt_mask in area_counts.items():
            ns = s + int(a)
            nxt[ns] = nxt.get(ns, 0) | (cnt_mask << 1)
        area_counts = nxt

    dims: list[tuple[int, int]] = []
    seen_dims: set[tuple[int, int]] = set()
    min_real_pieces = 4
    for area, cnt_mask in area_counts.items():
        if area <= 0:
            continue
        if ((cnt_mask >> min_real_pieces) == 0):
            continue
        root = int(area**0.5)
        for hh in range(1, root + 1):
            if area % hh != 0:
                continue
            for H, W in ((hh, area // hh), (area // hh, hh)):
                H = int(H)
                W = int(W)
                if (H, W) in seen_dims:
                    continue
                tr, tc = _fit_top_left(corner, mr, mc, H, W)
                if 0 <= tr and 0 <= tc and (tr + H) <= GH and (tc + W) <= GW:
                    seen_dims.add((H, W))
                    dims.append((H, W))
    dims.sort(key=lambda t: (-t[0] * t[1], -min(t[0], t[1]), -max(t[0], t[1])))

    order = sorted(range(n), key=lambda i: (-areas[i], -ph[i], -pw[i], i))
    full_mask = (1 << n) - 1

    @lru_cache(maxsize=None)
    def _reachable_sums(mask: int) -> int:
        if mask == 0:
            return 1
        lb = mask & -mask
        i = lb.bit_length() - 1
        rest = mask ^ lb
        base = _reachable_sums(rest)
        return base | (base << areas[i])

    def assemble(H: int, W: int) -> np.ndarray | None:
        occ2 = np.full((H, W), -1, dtype=int)

        def boundary_ok(a: np.ndarray, r: int, c: int) -> bool:
            h, w = a.shape
            if r == 0 and not np.all(a[0, :] == int(rect_col)):
                return False
            if (r + h) == H and not np.all(a[-1, :] == int(rect_col)):
                return False
            if c == 0 and not np.all(a[:, 0] == int(rect_col)):
                return False
            if (c + w) == W and not np.all(a[:, -1] == int(rect_col)):
                return False
            return True

        def neighbor_ok(a: np.ndarray, r: int, c: int) -> bool:
            h, w = a.shape
            if c > 0:
                left = occ2[r : r + h, c - 1]
                m = left != -1
                if m.any() and (not _compat(left[m], a[:, 0][m], rect_col)):
                    return False
            if (c + w) < W:
                right = occ2[r : r + h, c + w]
                m = right != -1
                if m.any() and (not _compat(right[m], a[:, -1][m], rect_col)):
                    return False
            if r > 0:
                up = occ2[r - 1, c : c + w]
                m = up != -1
                if m.any() and (not _compat(up[m], a[0, :][m], rect_col)):
                    return False
            if (r + h) < H:
                down = occ2[r + h, c : c + w]
                m = down != -1
                if m.any() and (not _compat(down[m], a[-1, :][m], rect_col)):
                    return False
            return True

        def can_place(i: int, r: int, c: int) -> bool:
            a = pieces[i]
            h, w = a.shape
            if (r + h) > H or (c + w) > W:
                return False
            if (occ2[r : r + h, c : c + w] != -1).any():
                return False
            if not boundary_ok(a, r, c):
                return False
            if not neighbor_ok(a, r, c):
                return False
            return True

        def place(i: int, r: int, c: int) -> None:
            a = pieces[i]
            h, w = a.shape
            occ2[r : r + h, c : c + w] = a

        def unplace(i: int, r: int, c: int) -> None:
            a = pieces[i]
            h, w = a.shape
            occ2[r : r + h, c : c + w] = -1

        def next_empty() -> tuple[int, int] | None:
            flat = np.flatnonzero(occ2.ravel() == -1)
            if flat.size == 0:
                return None
            idx = int(flat[0])
            return idx // W, idx % W

        def bt(unused_mask: int, filled_area: int) -> bool:
            remain = H * W - filled_area
            if remain == 0:
                return True
            if ((_reachable_sums(unused_mask) >> remain) & 1) == 0:
                return False

            nxt = next_empty()
            assert nxt is not None
            r, c = nxt
            for i in order:
                if ((unused_mask >> i) & 1) == 0:
                    continue
                if can_place(i, r, c):
                    place(i, r, c)
                    if bt(unused_mask ^ (1 << i), filled_area + areas[i]):
                        return True
                    unplace(i, r, c)
            return False

        if bt(full_mask, 0):
            return occ2
        return None

    ass = None
    used_dim = None
    for H, W in dims:
        ass = assemble(H, W)
        if ass is not None:
            used_dim = (H, W)
            break

    assert ass is not None and used_dim is not None

    H, W = used_dim
    tr, tc = _fit_top_left(corner, mr, mc, H, W)
    out = np.full((GH, GW), int(bg), dtype=int)
    out[tr : tr + H, tc : tc + W] = ass
    return out


def _rand_splits(total: int, rng, min_s: int = 2, max_s: int = 7) -> list[int] | None:
    eff_max = min(max_s, max(min_s, rng.randint(min_s, max_s)))
    segs: list[int] = []
    rem = int(total)
    while rem > 0:
        if rem <= eff_max:
            if rem < min_s:
                return None
            segs.append(rem)
            rem = 0
        else:
            hi = min(eff_max, rem - min_s)
            if min_s > hi:
                return None
            s = rng.randint(min_s, hi)
            segs.append(s)
            rem -= s
    return segs


def _build_rectangle(RH: int, RW: int, rect_col: int, interior_cols: list[int], rng) -> np.ndarray | None:
    rect = np.full((RH, RW), rect_col, dtype=int)
    iH, iW = RH - 2, RW - 2
    if iH < 1 or iW < 1:
        return None

    interior = np.full((iH, iW), rect_col, dtype=int)
    target_fill = rng.uniform(0.35, 0.85)
    target_pixels = max(1, int(target_fill * iH * iW))
    blob_occupied = np.zeros((iH, iW), dtype=bool)

    for ci, ic in enumerate(interior_cols):
        if ci == len(interior_cols) - 1:
            budget = target_pixels - int(blob_occupied.sum())
        else:
            budget = max(1, target_pixels // len(interior_cols))
        if budget <= 0:
            budget = 1

        attempts = 0
        seed = None
        while attempts < 200:
            sr, sc = rng.randint(0, iH - 1), rng.randint(0, iW - 1)
            if blob_occupied[sr, sc]:
                attempts += 1
                continue
            ok = True
            for dr in (-1, 0, 1):
                for dc in (-1, 0, 1):
                    nr, nc = sr + dr, sc + dc
                    if 0 <= nr < iH and 0 <= nc < iW and blob_occupied[nr, nc]:
                        ok = False
                        break
                if not ok:
                    break
            if ok:
                seed = (sr, sc)
                break
            attempts += 1

        if seed is None:
            continue

        blob = {seed}
        frontier = [seed]
        while len(blob) < budget and frontier:
            rng.shuffle(frontier)
            nf = []
            for fr, fc in frontier:
                for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                    nr, nc = fr + dr, fc + dc
                    if (nr, nc) in blob:
                        continue
                    if nr < 0 or nr >= iH or nc < 0 or nc >= iW:
                        continue
                    if blob_occupied[nr, nc]:
                        continue
                    conflict = False
                    for dr2 in (-1, 0, 1):
                        for dc2 in (-1, 0, 1):
                            if dr2 == 0 and dc2 == 0:
                                continue
                            ar, ac = nr + dr2, nc + dc2
                            if 0 <= ar < iH and 0 <= ac < iW:
                                if blob_occupied[ar, ac] and (ar, ac) not in blob:
                                    conflict = True
                                    break
                        if conflict:
                            break
                    if conflict:
                        continue
                    blob.add((nr, nc))
                    nf.append((nr, nc))
                    if len(blob) >= budget:
                        break
                if len(blob) >= budget:
                    break
            frontier = nf

        for br, bc in blob:
            interior[br, bc] = ic
            blob_occupied[br, bc] = True

    fill_ratio = float(np.mean(interior != rect_col))
    if fill_ratio < 0.30 or fill_ratio > 0.90:
        return None

    rect[1:-1, 1:-1] = interior
    return rect


def _partition_rectangle(rect: np.ndarray, rng) -> list[tuple[int, int, int, int]] | None:
    RH, RW = rect.shape
    row_segs = _rand_splits(RH, rng)
    col_segs = _rand_splits(RW, rng)
    if row_segs is None or col_segs is None:
        return None

    row_starts: list[int] = []
    s = 0
    for rs in row_segs:
        row_starts.append(s)
        s += rs
    col_starts: list[int] = []
    s = 0
    for cs in col_segs:
        col_starts.append(s)
        s += cs

    nr, nc_grid = len(row_segs), len(col_segs)
    cell_id = [[i * nc_grid + j for j in range(nc_grid)] for i in range(nr)]
    n_cells = nr * nc_grid
    if n_cells < 4:
        return None

    def _get_piece_bbox(pid: int) -> tuple[int, int, int, int] | None:
        cells = [(i, j) for i in range(nr) for j in range(nc_grid) if cell_id[i][j] == pid]
        if not cells:
            return None
        ri = [c[0] for c in cells]
        ci = [c[1] for c in cells]
        return min(ri), min(ci), max(ri), max(ci)

    def _pixel_size(r0i: int, c0i: int, r1i: int, c1i: int) -> tuple[int, int]:
        h = sum(row_segs[i] for i in range(r0i, r1i + 1))
        w = sum(col_segs[j] for j in range(c0i, c1i + 1))
        return h, w

    target_pieces = rng.randint(4, min(12, n_cells))
    merges = []
    for i in range(nr):
        for j in range(nc_grid):
            if j + 1 < nc_grid:
                merges.append(("h", i, j))
            if i + 1 < nr:
                merges.append(("v", i, j))
    rng.shuffle(merges)

    def _count_pieces() -> int:
        return len(set(cell_id[i][j] for i in range(nr) for j in range(nc_grid)))

    for direction, mi, mj in merges:
        if _count_pieces() <= target_pieces:
            break
        if direction == "h":
            pid1 = cell_id[mi][mj]
            pid2 = cell_id[mi][mj + 1]
        else:
            pid1 = cell_id[mi][mj]
            pid2 = cell_id[mi + 1][mj]
        if pid1 == pid2:
            continue
        bb1 = _get_piece_bbox(pid1)
        bb2 = _get_piece_bbox(pid2)
        if bb1 is None or bb2 is None:
            continue
        mr0 = min(bb1[0], bb2[0])
        mc0 = min(bb1[1], bb2[1])
        mr1 = max(bb1[2], bb2[2])
        mc1 = max(bb1[3], bb2[3])
        ph, pw = _pixel_size(mr0, mc0, mr1, mc1)
        if ph > 7 or pw > 7:
            continue
        ok = True
        for ii in range(mr0, mr1 + 1):
            for jj in range(mc0, mc1 + 1):
                if cell_id[ii][jj] != pid1 and cell_id[ii][jj] != pid2:
                    ok = False
                    break
            if not ok:
                break
        if not ok:
            continue
        for ii in range(nr):
            for jj in range(nc_grid):
                if cell_id[ii][jj] == pid2:
                    cell_id[ii][jj] = pid1

    pieces: list[tuple[int, int, int, int]] = []
    seen = set()
    for i in range(nr):
        for j in range(nc_grid):
            pid = cell_id[i][j]
            if pid in seen:
                continue
            seen.add(pid)
            bb = _get_piece_bbox(pid)
            assert bb is not None
            r0i, c0i, r1i, c1i = bb
            pr = row_starts[r0i]
            pc = col_starts[c0i]
            ph = sum(row_segs[ii] for ii in range(r0i, r1i + 1))
            pw = sum(col_segs[jj] for jj in range(c0i, c1i + 1))
            pieces.append((pr, pc, ph, pw))

    if len(pieces) < 4 or len(pieces) > 12:
        return None
    return pieces


def _slot_side_checks(
    piece: np.ndarray,
    slot: tuple[int, int, int, int],
    rect: np.ndarray,
    rect_col: int,
) -> list[bool]:
    RH, RW = rect.shape
    pr, pc, ph, pw = slot
    if piece.shape != (ph, pw):
        return [False, False, False, False]
    checks: list[bool] = []
    if pr == 0:
        checks.append(bool(np.all(piece[0, :] == rect_col)))
    else:
        checks.append(_compat(piece[0, :], rect[pr - 1, pc : pc + pw], rect_col))
    if pr + ph == RH:
        checks.append(bool(np.all(piece[-1, :] == rect_col)))
    else:
        checks.append(_compat(piece[-1, :], rect[pr + ph, pc : pc + pw], rect_col))
    if pc == 0:
        checks.append(bool(np.all(piece[:, 0] == rect_col)))
    else:
        checks.append(_compat(piece[:, 0], rect[pr : pr + ph, pc - 1], rect_col))
    if pc + pw == RW:
        checks.append(bool(np.all(piece[:, -1] == rect_col)))
    else:
        checks.append(_compat(piece[:, -1], rect[pr : pr + ph, pc + pw], rect_col))
    return checks


def _make_distractor(
    true_piece: np.ndarray,
    slot: tuple[int, int, int, int],
    rect: np.ndarray,
    rect_col: int,
    interior_cols: list[int],
    slots: list[tuple[int, int, int, int]],
    existing: list[np.ndarray],
    rng,
) -> tuple[np.ndarray, dict[str, int]] | None:
    pr, pc, ph, pw = slot
    RH, RW = rect.shape
    if len(interior_cols) < 2:
        return None

    side_specs = []
    if pr > 0:
        side_specs.append(("top", rect[pr - 1, pc : pc + pw], 0))
    if pr + ph < RH:
        side_specs.append(("bottom", rect[pr + ph, pc : pc + pw], ph - 1))
    if pc > 0:
        side_specs.append(("left", rect[pr : pr + ph, pc - 1], 0))
    if pc + pw < RW:
        side_specs.append(("right", rect[pr : pr + ph, pc + pw], pw - 1))
    rng.shuffle(side_specs)

    for side, neigh, fixed in side_specs:
        indices = [i for i, val in enumerate(neigh) if int(val) != int(rect_col)]
        rng.shuffle(indices)
        for pos in indices:
            neigh_val = int(neigh[pos])
            options = [c for c in interior_cols if int(c) != neigh_val]
            if not options:
                continue
            cand = true_piece.copy()
            new_col = int(rng.choice(options))
            if side == "top":
                cand[fixed, pos] = new_col
            elif side == "bottom":
                cand[fixed, pos] = new_col
            elif side == "left":
                cand[pos, fixed] = new_col
            else:
                cand[pos, fixed] = new_col

            fill = float(np.mean(cand != rect_col))
            if fill < 0.10 or fill > 0.60:
                continue
            if not any(np.any(edge != rect_col) for edge in (cand[0, :], cand[-1, :], cand[:, 0], cand[:, -1])):
                continue
            if any(np.array_equal(cand, other) for other in existing):
                continue

            side_checks = _slot_side_checks(cand, slot, rect, rect_col)
            if sum(side_checks) < 2 or all(side_checks):
                continue
            if any(all(_slot_side_checks(cand, s, rect, rect_col)) for s in slots):
                continue

            meta = {
                "base_h": int(ph),
                "base_w": int(pw),
                "partial_sides": int(sum(side_checks)),
            }
            return cand, meta
    return None


def _gen_attempt(return_meta: bool = False):
    import random as _r

    GH = _r.randint(10, 26)
    GW = _r.randint(10, 26)

    palette = list(range(10))
    _r.shuffle(palette)
    bg = palette[0]
    rect_col = palette[1]
    marker_col = palette[2]
    n_interior = _r.randint(2, 3)
    interior_cols = palette[3 : 3 + n_interior]

    corner = _r.choice(["TL", "TR", "BL", "BR"])

    min_side, max_side = 5, min(22, min(GH, GW) - 3)
    if max_side < min_side:
        return None
    RH = _r.randint(min_side, max_side)
    RW = _r.randint(min_side, max_side)
    if _r.random() < 0.5 and max_side >= 8:
        RH = _r.randint(max(6, min_side), max_side)
        RW = _r.randint(max(6, min_side), max_side)

    if corner == "TL":
        mr_min, mr_max = 2, GH - RH
        mc_min, mc_max = 2, GW - RW
    elif corner == "TR":
        mr_min, mr_max = 2, GH - RH
        mc_min, mc_max = RW - 1, GW - 3
    elif corner == "BL":
        mr_min, mr_max = RH - 1, GH - 3
        mc_min, mc_max = 2, GW - RW
    else:
        mr_min, mr_max = RH - 1, GH - 3
        mc_min, mc_max = RW - 1, GW - 3
    if mr_min > mr_max or mc_min > mc_max:
        return None
    mr = _r.randint(mr_min, mr_max)
    mc = _r.randint(mc_min, mc_max)

    rect = _build_rectangle(RH, RW, rect_col, interior_cols, _r)
    if rect is None:
        return None

    pieces = _partition_rectangle(rect, _r)
    if pieces is None:
        return None

    for pr, pc, ph, pw in pieces:
        piece = rect[pr : pr + ph, pc : pc + pw]
        if ph < 2 or pw < 2 or ph > 7 or pw > 7:
            return None
        fill = float(np.mean(piece != rect_col))
        if fill < 0.10 or fill > 0.60:
            return None
        if not any(np.any(edge != rect_col) for edge in (piece[0, :], piece[-1, :], piece[:, 0], piece[:, -1])):
            return None
        if pr == 0 and not np.all(piece[0, :] == rect_col):
            return None
        if pr + ph == RH and not np.all(piece[-1, :] == rect_col):
            return None
        if pc == 0 and not np.all(piece[:, 0] == rect_col):
            return None
        if pc + pw == RW and not np.all(piece[:, -1] == rect_col):
            return None

    if corner == "TL":
        anchor_r, anchor_c = 0, 0
    elif corner == "TR":
        anchor_r, anchor_c = 0, RW - 1
    elif corner == "BL":
        anchor_r, anchor_c = RH - 1, 0
    else:
        anchor_r, anchor_c = RH - 1, RW - 1
    anchor_idx = None
    for i, (pr, pc, ph, pw) in enumerate(pieces):
        if pr <= anchor_r < pr + ph and pc <= anchor_c < pc + pw:
            anchor_idx = i
            break
    if anchor_idx is None:
        return None
    apr, apc, aph, apw = pieces[anchor_idx]
    if corner == "TL" and not (apr == 0 and apc == 0):
        return None
    if corner == "TR" and not (apr == 0 and apc + apw == RW):
        return None
    if corner == "BL" and not (apr + aph == RH and apc == 0):
        return None
    if corner == "BR" and not (apr + aph == RH and apc + apw == RW):
        return None

    if corner == "TL":
        marker_cells = [(mr - 1, mc - 1), (mr - 1, mc), (mr, mc - 1)]
    elif corner == "TR":
        marker_cells = [(mr - 1, mc), (mr - 1, mc + 1), (mr, mc + 1)]
    elif corner == "BL":
        marker_cells = [(mr, mc - 1), (mr + 1, mc - 1), (mr + 1, mc)]
    else:
        marker_cells = [(mr, mc + 1), (mr + 1, mc), (mr + 1, mc + 1)]
    for cr, cc in marker_cells:
        if cr < 0 or cr >= GH or cc < 0 or cc >= GW:
            return None

    piece_arrays = [rect[pr : pr + ph, pc : pc + pw].copy() for pr, pc, ph, pw in pieces]

    distractor_target = _r.randint(1, 2)
    distractors: list[np.ndarray] = []
    distractor_meta: list[dict[str, int]] = []
    candidate_order = list(range(len(piece_arrays)))
    _r.shuffle(candidate_order)
    for idx in candidate_order:
        made = _make_distractor(
            piece_arrays[idx],
            pieces[idx],
            rect,
            rect_col,
            interior_cols,
            pieces,
            piece_arrays + distractors,
            _r,
        )
        if made is None:
            continue
        arr, meta = made
        distractors.append(arr)
        distractor_meta.append(meta)
        if len(distractors) >= distractor_target:
            break
    if len(distractors) != distractor_target:
        return None

    canvas = np.full((GH, GW), bg, dtype=int)
    for cr, cc in marker_cells:
        canvas[cr, cc] = marker_col

    all_arrays = piece_arrays + distractors
    order = list(range(len(all_arrays)))
    _r.shuffle(order)
    for idx in order:
        pa = all_arrays[idx]
        try:
            r0, c0 = random_free_location(canvas, pa, transparent=bg, padding=1)
            paste(canvas, pa, r0, c0)
        except ValueError:
            return None

    tr, tc = _fit_top_left(corner, mr, mc, RH, RW)
    expected_out = np.full((GH, GW), bg, dtype=int)
    expected_out[tr : tr + RH, tc : tc + RW] = rect

    try:
        actual_out = main(canvas)
    except Exception:
        return None
    if not np.array_equal(actual_out, expected_out):
        return None

    if return_meta:
        meta = {
            "true_piece_count": int(len(piece_arrays)),
            "distractor_count": int(len(distractors)),
            "distractor_area": int(sum(int(a.shape[0] * a.shape[1]) for a in distractors)),
            "partial_sides_min": int(min(m["partial_sides"] for m in distractor_meta)),
            "partial_sides_max": int(max(m["partial_sides"] for m in distractor_meta)),
        }
        return canvas, meta
    return canvas


def generate_input() -> np.ndarray:
    for _ in range(300):
        result = _gen_attempt()
        if result is not None:
            return result
    raise RuntimeError("generate_input: failed after 300 attempts")
