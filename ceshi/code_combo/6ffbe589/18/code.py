# Combo variant of 6ffbe589 (index 18)
# combo_spec: D2/1+D9/1
# Name: 颜色频率编码+4-5层

from __future__ import annotations

import random

import numpy as np

from arc_utils import colors_present, find_components, get_bg, paste


# Design analysis for the fused variant:
# - Original behavior: crop the largest board-like component, look outside the board for
#   same-color cue sprites, and rotate each board color by cue_size mod 4.
# - New behavior: keep the same "crop board + rotate each color independently" backbone,
#   but remove external cues entirely. Rotation is now encoded by each color's rank in the
#   board-internal frequency ordering. The i-th most frequent board color rotates i mod 4
#   quarter-turns clockwise.
# - Concrete small example: if a cropped 5-layer board has color counts [46, 40, 33, 26, 14],
#   then their ranks are [0, 1, 2, 3, 4] so the layers rotate by [0, 1, 2, 3, 0] quarter-turns
#   clockwise. The input is generated by rotating those output layers backward, so the solver
#   must recover the ranking from the pixel counts rather than from any outside markers.
# - Complexity calibration: the board has 4 or 5 concentric layers only. This is enough to show
#   multiple different rotations, including the wrap-around case rank 4 -> 0, without creating
#   too many categories for a human to track across 2-4 examples.
# - Hidden assumptions that changed:
#   1) `main()` can no longer assume outside components exist or that colors match one cue each.
#   2) Frequency ranks must be unique; otherwise the encoding is ambiguous. The generator enforces
#      strictly descending layer populations.
#   3) Independent layer rotations must not create overlaps. The generator keeps every color inside
#      its own annulus, and annuli are rotation-invariant.
#   4) The largest component crop still needs to recover the whole board. The generator uses
#      rotation-stable connector scaffolds so the independently inverse-rotated input remains a
#      single connected component.
# - Placement legality and visual cleanliness: only one object is placed on the 20x20 canvas, so
#   there are no cue collisions, no overlap ambiguities, and the cropped output stays visually neat.
# - Observability: the rule depends only on visible quantities (pixel frequencies and nesting depth).
#   No tie-break uses hidden palette ids. The examples visibly show 4-5 nested layers and no external
#   sprites, so this cannot be confused with the original cue-based task.


def crop_largest_component(grid: np.ndarray, *, bg: int | None = None) -> tuple[np.ndarray, tuple[int, int, int, int], int]:
    """Crop the unique largest non-bg component tightly."""
    if bg is None:
        bg = get_bg(grid)
    bg = int(bg)
    comps = find_components(grid, bg=bg, connectivity=8, monochromatic=False, return_format="dict")
    assert comps, "expected at least one foreground component"
    areas = [int(comp["area"]) for comp in comps]
    largest_area = max(areas)
    largest = [comp for comp in comps if int(comp["area"]) == largest_area]
    assert len(largest) == 1, "expected a unique largest foreground component"
    r0, c0, r1, c1 = map(int, largest[0]["bbox"])
    crop = np.array(grid[r0 : r1 + 1, c0 : c1 + 1], dtype=int)
    return crop, (r0, c0, r1, c1), bg


def rotate_color_layer(grid: np.ndarray, color: int, cw_k: int, *, bg: int | None = None) -> np.ndarray:
    """Rotate one color mask inside the fixed square crop by `cw_k` clockwise quarter-turns."""
    if bg is None:
        bg = get_bg(grid)
    bg = int(bg)
    k = int(cw_k) % 4
    if k == 0:
        return grid

    col = int(color)
    mask = (grid == col).astype(int)
    rmask = np.rot90(mask, (-k) % 4)
    assert rmask.shape == mask.shape, "expected a square crop for layer rotation"

    out = grid.copy()
    out[out == col] = bg
    out[rmask == 1] = col
    return out


def _color_stats(grid: np.ndarray, bg: int) -> list[dict[str, int]]:
    """Collect visible per-color stats used for frequency ranking."""
    stats: list[dict[str, int]] = []
    for col in colors_present(grid, exclude={bg}):
        coords = np.argwhere(grid == int(col))
        assert coords.size > 0
        r0, c0 = coords.min(axis=0)
        r1, c1 = coords.max(axis=0)
        inset = min(int(r0), int(c0), int(grid.shape[0] - 1 - r1), int(grid.shape[1] - 1 - c1))
        stats.append(
            {
                "color": int(col),
                "count": int(coords.shape[0]),
                "inset": int(inset),
            }
        )
    return stats


def main(grid: np.ndarray) -> np.ndarray:
    """
    Crop a concentric board and rotate each color layer from an internal frequency code.

    Input structure:
    - bg = most common color.
    - A single large multi-color board cluster, placed alone on the canvas.
    - The board contains 4 or 5 nested color layers sharing one center; there are no outside cue sprites.

    Rule:
    - Tight-crop the largest foreground component.
    - Count the pixels of each non-bg color inside that crop and sort colors by decreasing frequency.
    - Rotate the rank-i color layer by (i mod 4) quarter-turns clockwise inside the crop.

    Key insight: Rotation is encoded purely by within-board color frequency rank, so the solver must
    infer "which layer is 1st/2nd/3rd/..." from visible population sizes instead of matching cues.
    """
    g = np.array(grid, dtype=int)
    crop, _bbox, bg = crop_largest_component(g, bg=int(get_bg(g)))
    h, w = crop.shape
    assert h == w, "expected the cropped board to be square"

    stats = _color_stats(crop, int(bg))
    assert 4 <= len(stats) <= 5, "expected 4-5 color layers"
    counts = [item["count"] for item in stats]
    assert len(set(counts)) == len(counts), "expected unique color frequencies"

    ordered = sorted(stats, key=lambda item: (-item["count"], item["inset"]))
    out = crop.copy()
    for rank, item in enumerate(ordered):
        rot_k = rank % 4
        if rot_k:
            out = rotate_color_layer(out, int(item["color"]), rot_k, bg=int(bg))
    return out


# ---------------- generator ----------------

CANVAS_SIZE = 20
CENTER_SIDE = 5
LAYER_TO_BOARD_SIDE = {4: 11, 5: 13}
GEN_RETRIES = 400

RING_COUNT_RANGES = {
    4: [(31, 35), (25, 28), (19, 21)],
    5: [(39, 43), (32, 35), (25, 28), (19, 21)],
}
CENTER_COUNT_RANGE = {4: (12, 16), 5: (12, 16)}


def _is_rot_asym(mask: np.ndarray) -> bool:
    return all(not np.array_equal(mask, np.rot90(mask, k)) for k in (1, 2, 3))


def _is_connected(mask: np.ndarray) -> bool:
    if not np.any(mask):
        return False
    comps = find_components(mask.astype(int), bg=0, connectivity=8, monochromatic=False, return_format="dict")
    return len(comps) == 1


def _ring_coords(n: int, inset: int) -> list[tuple[int, int]]:
    side = n - 2 * inset
    r0, c0 = inset, inset
    r1, c1 = inset + side - 1, inset + side - 1
    coords: list[tuple[int, int]] = []
    for c in range(c0, c1 + 1):
        coords.append((r0, c))
    for r in range(r0 + 1, r1):
        coords.append((r, c1))
    for c in range(c1, c0 - 1, -1):
        coords.append((r1, c))
    for r in range(r1 - 1, r0, -1):
        coords.append((r, c0))
    return coords


def _ring_mandatory(n: int, inset: int) -> set[tuple[int, int]]:
    side = n - 2 * inset
    r0, c0 = inset, inset
    r1, c1 = inset + side - 1, inset + side - 1
    return {
        (r0, c0),
        (r0, c1),
        (r1, c0),
        (r1, c1),
    }


def _make_ring_mask(n: int, inset: int, target_count: int) -> np.ndarray | None:
    coords = _ring_coords(n, inset)
    area = len(coords)
    mandatory = _ring_mandatory(n, inset)
    gap = area - int(target_count)
    if gap < 1 or area - gap < len(mandatory):
        return None

    for _ in range(80):
        start = random.randrange(area)
        removed = {coords[(start + k) % area] for k in range(gap)}
        if removed & mandatory:
            continue
        keep = [p for p in coords if p not in removed]
        mask = np.zeros((n, n), dtype=bool)
        for r, c in keep:
            mask[r, c] = True
        if not _is_rot_asym(mask):
            continue
        if not _is_connected(mask):
            continue
        return mask
    return None


def _center_scaffold() -> np.ndarray:
    local = np.zeros((CENTER_SIDE, CENTER_SIDE), dtype=bool)
    pts = [
        (0, 0),
        (1, 1),
        (2, 2),
        (3, 3),
        (4, 4),
        (0, 4),
        (1, 3),
        (3, 1),
        (4, 0),
    ]
    for r, c in pts:
        local[r, c] = True
    return local


def _make_center_mask(n: int, layer_count: int) -> np.ndarray | None:
    lo, hi = CENTER_COUNT_RANGE[int(layer_count)]
    top = (n - CENTER_SIDE) // 2
    base = _center_scaffold()
    candidates = [(r, c) for r in range(CENTER_SIDE) for c in range(CENTER_SIDE) if not base[r, c]]
    for _ in range(120):
        target = random.randint(lo, hi)
        local = base.copy()
        random.shuffle(candidates)
        for r, c in candidates[: target - int(local.sum())]:
            local[r, c] = True
        if not _is_rot_asym(local):
            continue
        if not _is_connected(local):
            continue
        mask = np.zeros((n, n), dtype=bool)
        mask[top : top + CENTER_SIDE, top : top + CENTER_SIDE] = local
        return mask
    return None


def _build_output_masks(layer_count: int) -> list[np.ndarray] | None:
    n = LAYER_TO_BOARD_SIDE[int(layer_count)]
    masks: list[np.ndarray] = []
    for inset, (lo, hi) in enumerate(RING_COUNT_RANGES[int(layer_count)]):
        ring_mask = _make_ring_mask(n, inset, random.randint(lo, hi))
        if ring_mask is None:
            return None
        masks.append(ring_mask)

    center_mask = _make_center_mask(n, int(layer_count))
    if center_mask is None:
        return None
    masks.append(center_mask)

    counts = [int(mask.sum()) for mask in masks]
    if any(counts[i] <= counts[i + 1] for i in range(len(counts) - 1)):
        return None
    if len(set(counts)) != len(counts):
        return None
    if any(np.any(masks[i] & masks[j]) for i in range(len(masks)) for j in range(i + 1, len(masks))):
        return None
    board = np.zeros((n, n), dtype=bool)
    for mask in masks:
        board |= mask
    if not _is_connected(board):
        return None
    return masks


def _board_anchor(n: int) -> tuple[int, int]:
    spare = CANVAS_SIZE - n
    side = random.randrange(4)
    if side == 0:
        return spare, random.randint(0, spare)
    if side == 1:
        return 0, random.randint(0, spare)
    if side == 2:
        return random.randint(0, spare), spare
    return random.randint(0, spare), 0


def _compose_board(masks: list[np.ndarray], colors: list[int]) -> np.ndarray:
    n = masks[0].shape[0]
    board = np.zeros((n, n), dtype=int)
    for mask, col in zip(masks, colors):
        assert not np.any((board != 0) & mask)
        board[mask] = int(col)
    return board


def _invert_rank_rotations(out_masks: list[np.ndarray]) -> list[np.ndarray]:
    in_masks: list[np.ndarray] = []
    for rank, mask in enumerate(out_masks):
        in_masks.append(np.rot90(mask.astype(int), rank % 4).astype(bool))
    return in_masks


def _largest_component_bbox(grid: np.ndarray) -> tuple[int, int, int, int]:
    comps = find_components(grid, bg=0, connectivity=8, monochromatic=False, return_format="dict")
    assert comps
    areas = [int(comp["area"]) for comp in comps]
    largest = comps[areas.index(max(areas))]
    return tuple(map(int, largest["bbox"]))


def _gen_attempt() -> np.ndarray | None:
    layer_count = random.choice([4, 5])
    n = LAYER_TO_BOARD_SIDE[int(layer_count)]
    out_masks = _build_output_masks(int(layer_count))
    if out_masks is None:
        return None

    colors = random.sample(range(1, 10), int(layer_count))
    out_board = _compose_board(out_masks, colors)

    in_masks = _invert_rank_rotations(out_masks)
    in_board = _compose_board(in_masks, colors)
    if not _is_connected(in_board != 0):
        return None

    canvas = np.zeros((CANVAS_SIZE, CANVAS_SIZE), dtype=int)
    r0, c0 = _board_anchor(n)
    paste(canvas, in_board, r0, c0, transparent=0)
    board_bbox = (r0, c0, r0 + n - 1, c0 + n - 1)

    comps = find_components(canvas, bg=0, connectivity=8, monochromatic=False, return_format="dict")
    if len(comps) != 1:
        return None
    if _largest_component_bbox(canvas) != board_bbox:
        return None

    solved = main(canvas)
    if not np.array_equal(solved, out_board):
        return None
    return canvas


def generate_input() -> np.ndarray:
    for _ in range(GEN_RETRIES):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate a valid fused 6ffbe589 input")
