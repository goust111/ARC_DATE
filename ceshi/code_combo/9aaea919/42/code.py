# Combo variant of 9aaea919 (index 42)
# combo_spec: D1/2+D9/0
# Name: 位置决定角色+可变车道数

import numpy as np

from arc_utils import get_bg, paste


# Design analysis for the fused positional-role + variable-lane-count variant
# ---------------------------------------------------------------------------
# concrete_behavior:
#   - The canvas stays 30x30 and every lane still contains copies of the same 3x5
#     plus/diamond sprite on a period-4 vertical lattice.
#   - Two visible changes are fused together:
#     1. row 29 no longer contains any red/green marker bars;
#     2. the number of lanes is no longer fixed at 4, but varies from 3 to 6.
#   - Role now comes from horizontal order over the occupied lanes that are actually
#     present: the leftmost lane is always the source, the rightmost lane is always
#     the destination, and any middle lanes are spectators.
# trace_example:
#   - Original task: four fixed lanes; explicit red/green bars tell the solver which
#     lane loses sprites and which lane gains them.
#   - Fused variant: imagine a 5-lane input whose starts are [1, 7, 13, 19, 25].
#     The leftmost lane at col 1 contains 2 sprites, the rightmost lane at col 25
#     contains 3 sprites, and the middle 3 lanes each keep their own colors.
#     The output greys the 2 leftmost sprites in place and adds 2 new copies above
#     the rightmost stack, producing 5 total sprites there.
#   - The key difference is that solver logic must first recover "how many lanes are
#     present and where are their left edges" before the transfer rule can run.
# complexity_calibration:
#   - The fusion changes exactly two axes and keeps everything else stable: sprite
#     geometry, lattice period, recolor-to-grey behavior, and bottom-up filling are
#     unchanged from the seed task.
#   - Variable lane count is visually obvious because the horizontal density changes
#     across examples; positional role is visually obvious because the outer-left lane
#     always turns grey while the outer-right lane always grows.
#   - The generator often uses colors 2 and 3 as ordinary sprite colors so a solver
#     cannot fall back to the original "red means source, green means target" cue.
# implicit_assumption_audit:
#   - Original marker detection is invalid because there are no marker bars at all.
#   - Original fixed-column assumptions are invalid because lane starts depend on the
#     sampled lane count.
#   - A more subtle conflict appears when 6 lanes touch edge-to-edge: component-based
#     extraction on `g != bg` can merge adjacent lanes into one multicolor component.
#     The fused solver therefore does not use connected components for lane recovery;
#     it scans for exact 3x5 sprite windows and groups them by shared left column.
#   - New-sprite placement still assumes the destination lane already contains at least
#     one input sprite so its color and lattice are observable. The generator preserves
#     the original 1-3 sprites-per-lane rule, so that assumption always holds.
# placement_legality:
#   - Every lane window is exactly 5 columns wide, with starts generated by a layout
#     function that distributes the remaining columns across internal gaps and margins.
#   - Lanes may touch but never overlap. Sprites stay inside rows 1..27 because the
#     bottom sprite starts at row 25 and the maximum destination total is 6.
#   - Generation is output-first: build the final grid, erase the transferred sprites
#     from the destination, restore the source color, then oracle-check with `main`.
# visual_observability_and_cleanliness:
#   - Inputs are visually clean because each lane is monochrome and each lane color is
#     distinct, so touching lanes remain separable by color even when gaps shrink.
#   - There are no extra bars or overlays competing with the sprite stacks, which keeps
#     the positional rule legible despite the additional freedom in lane count.
# color_change_inference:
#   - The only recoloring is structurally anchored: the entire leftmost lane turns grey
#     and the new rightmost sprites inherit the pre-existing rightmost lane color.
#   - No hidden ordering by numeric color id is used anywhere; all role inference is
#     based on visible x-position alone.
# new_solver_assumptions_audited:
#   - every lane contains one or more exact 3x5 monochrome plus sprites;
#   - all occupied lanes are recoverable from sprite top-left columns;
#   - the outermost occupied lanes are the unique source and destination;
#   - the destination has enough empty period-4 slots above its current stack.
#   The generator explicitly constructs only inputs that satisfy these assumptions.


# --------------- shared constants ---------------

_H, _W = 30, 30
_SPRITE_H, _SPRITE_W = 3, 5
_BOTTOM_TOP = 25
_PERIOD = 4
_GREY = 5

_MIN_LANES = 3
_MAX_LANES = 6
_MIN_SPRITES = 1
_MAX_SPRITES = 3
_MAX_TARGET_TOTAL = 6
_GEN_RETRIES = 300

_BG_CHOICES = [0, 1, 4, 6, 7, 8, 9]
_SPRITE_MASK = np.array(
    [
        [0, 1, 1, 1, 0],
        [1, 1, 1, 1, 1],
        [0, 1, 1, 1, 0],
    ],
    dtype=bool,
)


def _sprite_patch(color: int, bg: int) -> np.ndarray:
    """Return the canonical 3x5 plus/diamond sprite patch."""
    patch = np.full((_SPRITE_H, _SPRITE_W), bg, dtype=int)
    patch[_SPRITE_MASK] = color
    return patch


def _lane_layout(num_lanes: int) -> tuple[list[int], list[int], tuple[int, int]]:
    """
    Return lane starts, interior gaps, and (left_margin, right_margin) for `num_lanes`.

    Extra columns are distributed round-robin across interior gaps first, then the two
    outer margins, so lower lane counts visibly spread out while higher counts compress.
    """
    assert _MIN_LANES <= num_lanes <= _MAX_LANES
    used = num_lanes * _SPRITE_W
    extra = _W - used
    assert extra >= 0

    gaps = [0] * (num_lanes - 1)
    left_margin = 0
    right_margin = 0
    slots: list[tuple[str, int | None]] = [("gap", i) for i in range(num_lanes - 1)] + [
        ("left", None),
        ("right", None),
    ]
    for k in range(extra):
        kind, idx = slots[k % len(slots)]
        if kind == "gap":
            gaps[int(idx)] += 1
        elif kind == "left":
            left_margin += 1
        else:
            right_margin += 1

    starts = [left_margin]
    for gap in gaps:
        starts.append(starts[-1] + _SPRITE_W + gap)
    assert starts[-1] + _SPRITE_W <= _W - right_margin
    return starts, gaps, (left_margin, right_margin)


def _lane_tops(count: int) -> list[int]:
    """Return top-row positions for `count` sprites, ordered top-to-bottom."""
    return [_BOTTOM_TOP - _PERIOD * k for k in range(count - 1, -1, -1)]


def _paint_lane(grid: np.ndarray, lane_start: int, color: int, count: int, bg: int) -> None:
    """Stamp `count` sprites of `color` into the lane whose window begins at `lane_start`."""
    patch = _sprite_patch(color, bg)
    for r0 in _lane_tops(count):
        paste(grid, patch, r0, lane_start, transparent=bg)


def _find_sprites(g: np.ndarray, bg: int) -> list[dict]:
    """
    Detect exact 3x5 monochrome plus sprites by local window matching.

    This avoids component-merging failures when variable-count layouts make two lanes
    touch horizontally.
    """
    h, w = g.shape
    sprites = []
    for r0 in range(h - _SPRITE_H + 1):
        for c0 in range(w - _SPRITE_W + 1):
            patch = g[r0 : r0 + _SPRITE_H, c0 : c0 + _SPRITE_W]
            fg = patch[_SPRITE_MASK]
            color = int(fg[0])
            if color == bg:
                continue
            if np.any(fg != color):
                continue
            if np.any(patch[~_SPRITE_MASK] != bg):
                continue
            pts = [
                (r0 + dr, c0 + dc)
                for dr in range(_SPRITE_H)
                for dc in range(_SPRITE_W)
                if _SPRITE_MASK[dr, dc]
            ]
            sprites.append({"r0": int(r0), "c0": int(c0), "color": color, "pts": pts})
    return sprites


def _lane_groups(g: np.ndarray, bg: int) -> list[dict]:
    """Group detected sprites into lanes by their shared left column."""
    lanes_by_c0: dict[int, list[dict]] = {}
    for sprite in _find_sprites(g, bg):
        lanes_by_c0.setdefault(sprite["c0"], []).append(sprite)

    lanes = []
    for c0 in sorted(lanes_by_c0):
        sprites = sorted(lanes_by_c0[c0], key=lambda sp: sp["r0"])
        colors = {int(sp["color"]) for sp in sprites}
        assert len(colors) == 1, "expected one monochrome color per lane"

        tops = [int(sp["r0"]) for sp in sprites]
        if len(tops) >= 2:
            diffs = [b - a for a, b in zip(tops, tops[1:]) if b - a > 0]
            period = int(np.gcd.reduce(diffs)) if diffs else _PERIOD
        else:
            period = _PERIOD

        lanes.append(
            {
                "c0": int(c0),
                "color": int(sprites[0]["color"]),
                "sprites": [sp["pts"] for sp in sprites],
                "tops": tops,
                "period": int(period),
            }
        )
    return lanes


def _choose_lane_colors(rng: np.random.Generator, bg: int, num_lanes: int) -> list[int]:
    """
    Frequently include colors 2 and 3 as ordinary lane colors to suppress the original
    marker-color heuristic.
    """
    palette = [c for c in range(10) if c not in (bg, _GREY)]
    special = [c for c in (2, 3) if c in palette]

    if len(special) == 2 and num_lanes >= 2 and rng.random() < 0.85:
        rest = [c for c in palette if c not in special]
        chosen = special + rng.choice(rest, size=num_lanes - 2, replace=False).tolist()
    else:
        chosen = rng.choice(palette, size=num_lanes, replace=False).tolist()

    rng.shuffle(chosen)
    return [int(c) for c in chosen]


def main(grid: np.ndarray) -> np.ndarray:
    """
    Move the leftmost lane's sprites into the rightmost lane, even when the lane count changes.

    Input structure:
    - The background is the most common color. There are no marker bars; instead, 3-6 lanes
      are visible only through repeated monochrome 3x5 plus sprites.
    - Each occupied lane uses one color and shares the same period-4 vertical stacking scheme,
      but the horizontal starts depend on how many lanes were packed into the 30-column canvas.

    Rule:
    - Treat the outer-left lane as the source and the outer-right lane as the destination.
    - Recolor every source sprite to grey (5) in place.
    - Recreate the same number of sprites in the destination lane, using the destination color
      and filling empty lattice slots upward above the existing destination stack.

    Key insight:
    - Because both the marker cues and the fixed four-lane layout are gone, the solver must first
      infer the actual lane set from sprite positions and then use spatial order alone to assign roles.
    """
    g = np.asarray(grid, dtype=int)
    h, _w = g.shape
    bg = get_bg(g)

    lanes = _lane_groups(g, bg)
    assert _MIN_LANES <= len(lanes) <= _MAX_LANES, "expected 3-6 occupied sprite lanes"

    src = lanes[0]
    dst = lanes[-1]
    assert src["sprites"] and dst["sprites"], "expected both outer lanes to contain sprites"

    out = g.copy()

    for pts in src["sprites"]:
        for r, c in pts:
            out[r, c] = _GREY

    src_ref_pts = src["sprites"][0]
    src_ref_r0 = min(r for r, _ in src_ref_pts)
    src_offsets = [(r - src_ref_r0, c - src["c0"]) for r, c in src_ref_pts]
    sprite_h = max(dr for dr, _dc in src_offsets) + 1

    occupied = set(dst["tops"])
    bottom0 = max(dst["tops"])
    placed = 0
    k = 1
    while placed < len(src["sprites"]):
        new_top = bottom0 - k * dst["period"]
        k += 1
        if new_top < 0 or new_top + sprite_h > h:
            if new_top < 0:
                break
            continue
        if new_top in occupied:
            continue

        dst_cells = [(new_top + dr, dst["c0"] + dc) for dr, dc in src_offsets]
        if any(int(out[rr, cc]) != bg for rr, cc in dst_cells):
            continue

        for rr, cc in dst_cells:
            out[rr, cc] = dst["color"]
        occupied.add(new_top)
        placed += 1

    return out


def _gen_attempt() -> np.ndarray | None:
    rng = np.random.default_rng()

    num_lanes = int(rng.integers(_MIN_LANES, _MAX_LANES + 1))
    lane_starts, _gaps, _margins = _lane_layout(num_lanes)

    bg = int(rng.choice(_BG_CHOICES))
    lane_colors = _choose_lane_colors(rng, bg, num_lanes)
    input_counts = rng.integers(_MIN_SPRITES, _MAX_SPRITES + 1, size=num_lanes).tolist()

    src_lane = 0
    dst_lane = num_lanes - 1
    gain = int(input_counts[src_lane])

    output_counts = input_counts[:]
    output_counts[dst_lane] += gain
    if output_counts[dst_lane] > _MAX_TARGET_TOTAL:
        return None

    out = np.full((_H, _W), bg, dtype=int)
    for lane_idx, lane_start in enumerate(lane_starts):
        color = _GREY if lane_idx == src_lane else lane_colors[lane_idx]
        _paint_lane(out, lane_start, int(color), int(output_counts[lane_idx]), bg)

    inp = out.copy()
    _paint_lane(inp, lane_starts[src_lane], int(lane_colors[src_lane]), int(input_counts[src_lane]), bg)

    dst_c0 = lane_starts[dst_lane]
    for r0 in _lane_tops(output_counts[dst_lane])[:gain]:
        inp[r0 : r0 + _SPRITE_H, dst_c0 : dst_c0 + _SPRITE_W] = bg

    if not np.array_equal(main(inp), out):
        return None
    return inp


def generate_input() -> np.ndarray:
    for _ in range(_GEN_RETRIES):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError(f"failed to generate a valid input after {_GEN_RETRIES} attempts")
