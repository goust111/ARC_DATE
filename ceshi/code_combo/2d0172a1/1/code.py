import numpy as np

from arc_utils import find_components, get_bg, label_mask, paste

_CROSS_MASK = np.array(
    [
        [False, True, False],
        [True, True, True],
        [False, True, False],
    ],
    dtype=bool,
)


# Design analysis for the combo variant
# =====================================
# spec grounding:
#   - 输入族不变：16-25 的双颜色网格；前景对象仍是“有且仅有一个洞的手绘 frame”或“小实心 blob”。
#   - tree / sibling-order / outside-side 仍由原题定义，生成器也继续使用 output-first 自校验。
#   - 融合只改 dst 表示：frame 从完整矩形边框变成四角标记；blob 从单点变成 3x3 十字。
# concrete trace:
#   - 设某个 frame 的两个 blob 子节点在原 canonical child group 中占位为上下排列。
#   - 原题：blob 是 1x1，frame 会把 child group 包进 `(h+4,w+4)` 的完整矩形边框，child group 放到
#     `[2:2+h, 2:2+w]`，outside blob 也只占一个点。
#   - D5 部分生效后：每个 blob 变成 anchor=(1,1) 的 3x3 十字，所以同样的兄弟 band 顺序需要更大的
#     中心距，才能继续保留恰好 1 格背景间隔。
#   - D4 部分再叠加后：frame 的外接矩形尺寸和对子节点的 2 格内缩完全保留，但只点亮四个角。于是一个
#     “outer frame containing two crosses” 的输出，不再是完整框包十字，而是四角定框包十字。
# complexity calibration:
#   - 两个变化都强可见：frame 边消失只剩四角，blob 从单点扩大为十字；任何样例里至少有一个 frame 和
#     一个 blob，因此不会退化成肉眼难察觉的小改动。
#   - 没有引入颜色映射、分支形状表或额外 case；blob 永远是同一个十字，frame 永远是同一种四角矩形。
# hidden assumption audit:
#   - `_build_layout()` 原先对 blob 默认 1x1、对 frame 默认连续边框；融合后这两个假设都失效，必须同时
#     改成 cross mask 与 four-corner mask。
#   - `_axis_coordinates()` 只依赖 bbox band、mask.shape、anchor；它不要求 frame 连通，也不要求 blob 是
#     单点，所以在新 anchor/shape 下仍成立。
#   - `_map_frame_axis()` 只读取 canonical child center 在 frame 内的对齐位置；frame 是否画边无关。
#   - `_layout_root()` 原本为 outside dot 预留 3x3 槽位的常数写法只适用于单点。融合后 outside blob 是
#     3x3 十字，所以 root special case 必须像 D5 一样按 blob.anchor 和 mask.shape 计算 extents；同时
#     D4 不影响外接矩形尺寸，因此 four-corner frame 仍可沿用同一留槽逻辑。
# placement legality:
#   - frame 内部仍保留 2 格内缩。对 3x3 十字来说，其最近的十字臂会距离隐含 frame 边界恰好 1 格背景，
#     不会与四角标记或其他兄弟对象接触。
#   - outside blob 在 root 旁边按“中心比 frame 外缘再远 2 格”的方式放置，因此十字最近臂与 frame 隐含
#     边界之间仍有 1 格背景，不会裁切。
#   - 生成器输入端保持原题合法性：rough frame 仍单环单洞，blob 仍小连通块，层级深度仍 1-2。
# observability and cleanliness:
#   - 解题者从 2-4 个样例即可同时看到“粗框→四角矩形”和“粗 blob→十字”两种归一化，且二者都由
#     containment / sibling-order 共同驱动，不依赖颜色值等不可视信息。
#   - 四角标记与十字共享同色，但视觉角色清楚：角永远落在隐含矩形四端，十字永远是 3x3 居中的 plus。
# new solver assumptions checked against generator:
#   - main 仍假设每个 frame 至少有一个 child；`_make_tree()` 保证这一点。
#   - main 假设 outside blob 至多一个，且只和唯一根 frame 同层共存；生成器沿用原题约束保证这一点。
#   - main 假设 blob / frame 在输入里都能通过“是否有 hole”区分；原生成器继续保证 blob 无洞、frame 单洞。


class _Node:
    def __init__(self, coords: np.ndarray, bbox: tuple[int, int, int, int], center: np.ndarray):
        self.coords = coords
        self.bbox = bbox
        self.center = center
        self.is_frame = False
        self.parent: _Node | None = None
        self.children: list[_Node] = []
        self.mask: np.ndarray | None = None
        self.anchor: tuple[int, int] | None = None
        self.axis_map: dict[str, list[tuple[float, int]]] = {"row": [], "col": []}


def _component_holes(shape: tuple[int, int], coords: np.ndarray) -> list[np.ndarray]:
    mask = np.zeros(shape, dtype=bool)
    mask[tuple(coords.T)] = True
    lab, n = label_mask(~mask, connectivity=4)
    boundary = set(lab[0, :]) | set(lab[-1, :]) | set(lab[:, 0]) | set(lab[:, -1])
    return [(lab == k) for k in range(1, n + 1) if k not in boundary]


def _intervals_overlap(a: tuple[int, int], b: tuple[int, int]) -> bool:
    return max(a[0], b[0]) <= min(a[1], b[1])


def _build_layout(node: _Node) -> None:
    if node.mask is not None:
        return

    if not node.is_frame:
        node.mask = _CROSS_MASK.copy()
        node.anchor = (1, 1)
        node.axis_map = {
            "row": [(float(node.center[0]), 1)],
            "col": [(float(node.center[1]), 1)],
        }
        return

    assert node.children
    child_mask, _placements, axis_map = _layout_group(node.children)
    h, w = child_mask.shape
    out = np.zeros((h + 4, w + 4), dtype=bool)
    out[0, 0] = True
    out[0, -1] = True
    out[-1, 0] = True
    out[-1, -1] = True
    out[2 : 2 + h, 2 : 2 + w] |= child_mask

    node.mask = out
    node.anchor = (out.shape[0] // 2, out.shape[1] // 2)
    node.axis_map = {
        "row": [(orig, pos + 2) for orig, pos in axis_map["row"]],
        "col": [(orig, pos + 2) for orig, pos in axis_map["col"]],
    }


def _axis_coordinates(nodes: list[_Node], axis: int) -> dict[_Node, int]:
    items = []
    for node in nodes:
        assert node.mask is not None and node.anchor is not None
        r0, c0, r1, c1 = node.bbox
        interval = (r0, r1) if axis == 0 else (c0, c1)
        mid = (interval[0] + interval[1]) / 2
        items.append((node, interval, mid, node.anchor[axis], node.mask.shape[axis]))

    bands: list[dict] = []
    for item in sorted(items, key=lambda x: x[2]):
        interval = item[1]
        for band in bands:
            if any(_intervals_overlap(interval, other[1]) for other in band["items"]):
                band["items"].append(item)
                band["interval"] = (
                    min(band["interval"][0], interval[0]),
                    max(band["interval"][1], interval[1]),
                )
                break
        else:
            bands.append({"items": [item], "interval": interval})

    coord_by_node: dict[_Node, int] = {}
    coord = 0
    for i, band in enumerate(bands):
        if i:
            prev = bands[i - 1]
            prev_down = max(item[4] - 1 - item[3] for item in prev["items"])
            curr_up = max(item[3] for item in band["items"])
            coord += prev_down + 2 + curr_up
        for item in band["items"]:
            coord_by_node[item[0]] = int(coord)

    return coord_by_node


def _layout_group(nodes: list[_Node]) -> tuple[np.ndarray, dict[_Node, tuple[int, int]], dict[str, list[tuple[float, int]]]]:
    assert nodes
    for node in nodes:
        _build_layout(node)

    row_coord = _axis_coordinates(nodes, axis=0)
    col_coord = _axis_coordinates(nodes, axis=1)

    min_r = min(row_coord[n] - n.anchor[0] for n in nodes if n.anchor is not None)
    min_c = min(col_coord[n] - n.anchor[1] for n in nodes if n.anchor is not None)
    max_r = max(
        row_coord[n] - n.anchor[0] - min_r + n.mask.shape[0]
        for n in nodes
        if n.anchor is not None and n.mask is not None
    )
    max_c = max(
        col_coord[n] - n.anchor[1] - min_c + n.mask.shape[1]
        for n in nodes
        if n.anchor is not None and n.mask is not None
    )

    out = np.zeros((max_r, max_c), dtype=bool)
    placements: dict[_Node, tuple[int, int]] = {}
    axis_map = {"row": [], "col": []}
    for node in nodes:
        assert node.mask is not None and node.anchor is not None
        r = row_coord[node] - node.anchor[0] - min_r
        c = col_coord[node] - node.anchor[1] - min_c
        placements[node] = (int(r), int(c))
        out[r : r + node.mask.shape[0], c : c + node.mask.shape[1]] |= node.mask
        axis_map["row"].append((float(node.center[0]), int(r + node.anchor[0])))
        axis_map["col"].append((float(node.center[1]), int(c + node.anchor[1])))

    return out, placements, axis_map


def _outside_side(blob: _Node, frame: _Node) -> str:
    r0, c0, r1, c1 = blob.bbox
    fr0, fc0, fr1, fc1 = frame.bbox
    if c0 > fc1:
        return "right"
    if c1 < fc0:
        return "left"
    if r0 > fr1:
        return "bottom"
    if r1 < fr0:
        return "top"

    dr = float(blob.center[0] - (fr0 + fr1) / 2)
    dc = float(blob.center[1] - (fc0 + fc1) / 2)
    if abs(dc) >= abs(dr):
        return "right" if dc > 0 else "left"
    return "bottom" if dr > 0 else "top"


def _map_frame_axis(frame: _Node, axis: int, value: float) -> int:
    assert frame.anchor is not None
    key = "row" if axis == 0 else "col"
    candidates = frame.axis_map[key]
    if not candidates:
        return int(frame.anchor[axis])
    return int(min(candidates, key=lambda item: abs(item[0] - value))[1])


def _layout_root(nodes: list[_Node]) -> np.ndarray:
    assert nodes
    for node in nodes:
        _build_layout(node)

    frames = [node for node in nodes if node.is_frame]
    blobs = [node for node in nodes if not node.is_frame]
    if len(frames) == 1 and blobs:
        frame = frames[0]
        assert frame.mask is not None
        placements: dict[_Node, tuple[int, int]] = {frame: (0, 0)}
        extents = [(0, 0, frame.mask.shape[0], frame.mask.shape[1])]

        for blob in blobs:
            assert blob.mask is not None and blob.anchor is not None
            side = _outside_side(blob, frame)
            if side in {"right", "left"}:
                center_r = _map_frame_axis(frame, 0, float(blob.center[0]))
                center_c = frame.mask.shape[1] + 2 if side == "right" else -3
            else:
                center_r = frame.mask.shape[0] + 2 if side == "bottom" else -3
                center_c = _map_frame_axis(frame, 1, float(blob.center[1]))
            r = int(center_r - blob.anchor[0])
            c = int(center_c - blob.anchor[1])
            placements[blob] = (r, c)
            extents.append((r, c, r + blob.mask.shape[0], c + blob.mask.shape[1]))

        min_r = min(e[0] for e in extents)
        min_c = min(e[1] for e in extents)
        max_r = max(e[2] for e in extents)
        max_c = max(e[3] for e in extents)
        out = np.zeros((max_r - min_r, max_c - min_c), dtype=bool)
        for node, (r, c) in placements.items():
            rr = r - min_r
            cc = c - min_c
            assert node.mask is not None
            out[rr : rr + node.mask.shape[0], cc : cc + node.mask.shape[1]] |= node.mask
        return out

    mask, _placements, _axis_map = _layout_group(nodes)
    return mask


def main(grid: np.ndarray) -> np.ndarray:
    """
    Convert a rough nested frame-and-blob sketch into a canonical corner-frame and cross-blob diagram.

    Input structure:
    - The grid uses one background color and one foreground color.
    - Foreground 4-connected objects are either wobbly closed frames with one hole or compact filled blobs.
    - Frames may contain other frames/blobs, and at most one blob may sit outside the outermost frame.

    Rule:
    - Reconstruct the containment tree by checking which components lie inside the hole of each frame.
    - Normalize every blob to the same 3x3 cross centered at its canonical location.
    - Normalize every frame to the implied rectangle around its children, but draw only the four corners of that rectangle while keeping the children inset by two cells from the implied boundary.
    - Preserve sibling row/column ordering from the input, and place any outside blob beside the root frame on the same side as before with one cell of background clearance.

    Key insight:
    - Ignore the exact hand-drawn strokes. The output is determined only by containment, sibling ordering, and two fixed abstractions: frames become corner markers and blobs become crosses.
    """
    g = np.asarray(grid, dtype=int)
    bg = int(get_bg(g))
    fg_colors = sorted(set(map(int, g.flatten())) - {bg})
    assert len(fg_colors) == 1
    fg = int(fg_colors[0])

    comps = find_components(g, bg=bg, connectivity=4, monochromatic=True, colors=[fg], return_format="dict")
    assert comps

    nodes: list[_Node] = []
    holes: list[list[np.ndarray]] = []
    for comp in comps:
        coords = np.asarray(comp["coords"], dtype=int)
        node = _Node(
            coords=coords,
            bbox=tuple(map(int, comp["bbox"])),
            center=coords.mean(axis=0),
        )
        node_holes = _component_holes(g.shape, coords)
        node.is_frame = bool(node_holes)
        nodes.append(node)
        holes.append(node_holes)

    assert any(node.is_frame for node in nodes)
    for node_i, node in enumerate(nodes):
        containers = []
        for frame_i, frame in enumerate(nodes):
            if node_i == frame_i or not frame.is_frame:
                continue
            if any(np.all(hole[tuple(node.coords.T)]) for hole in holes[frame_i]):
                containers.append(frame)
        if containers:
            node.parent = min(containers, key=lambda item: int(item.coords.shape[0]))
            node.parent.children.append(node)

    roots = [node for node in nodes if node.parent is None]
    mask = _layout_root(roots)
    out = np.full(mask.shape, bg, dtype=int)
    out[mask] = fg
    return out


