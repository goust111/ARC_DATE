# Design analysis for combo D5/1 + D11/2 + D12/2
# a) Concretization + trace:
#    - The finished latent object is still the same 9x9 motif: a 3x3 grid of 3x3
#      blocks with D4 block-level symmetry, then expanded to a 15x15 5x5 layout.
#    - The key fusion change is where the damage lives and how it is interpreted.
#      The center block is already present and is built with the D5 symmetry rule
#      rather than the source task's inward-facing boundary rule. One corner block is
#      not blank: it contains a partially correct preview of its true content.
#    - Small trace:
#      original task:
#        1. detect a blank center hole,
#        2. rebuild that center from local inward-facing pixels,
#        3. copy the eight visible blocks outward.
#      combo task:
#        1. detect which corner block is damaged,
#        2. note that opposite-corner 180-degree symmetry yields two suspect corners
#           (the damaged one and its intact diagonal partner),
#        3. use the already-correct D5 center as a tie-breaker: each corner has one
#           anchor pixel that must agree with one center pixel under LR+UD symmetry,
#        4. rebuild the damaged corner from the diagonal corner by rot180,
#        5. expand the repaired motif outward.
#      Example: if the top-left corner is corrupted, both top-left and bottom-right
#      fail the raw "equals rot180(opposite)" test. But only the damaged top-left
#      fails the extra D5 anchor check corner[0,0] == center[2,2], so the solver can
#      identify which member of the pair must be repaired.
# b) Complexity calibration:
#    - The damaged location varies across the four corners, so the task is not a
#      fixed-position patch job.
#    - The corruption masks come from a small recurring library. This keeps the
#      "partial correctness" idea visually stable across samples without exploding
#      into too many unrelated subcases.
#    - The generator forces the damaged corner's D5 anchor pixel to be wrong and
#      also forces the D5 center rule to differ from the legacy center rule, so the
#      fusion signal is active rather than collapsing back into D11 alone.
# c) Hidden-assumption audit of main():
#    - bbox/get_bg still assume one isolated motif on a plain background; generation
#      keeps that unchanged.
#    - The original center-filling helper is invalid here because the center is
#      already occupied and must stay untouched.
#    - A raw opposite-corner comparison is no longer enough to locate the damaged
#      block: it always marks a diagonal pair. The new solver therefore assumes the
#      center follows the D5 symmetry construction and uses that to break the tie.
#    - The repair step assumes exactly one corner block is corrupted and the other
#      seven non-center blocks are intact. The generator enforces this.
#    - The solver assumes block==3 so that each corner has a single fixed anchor cell
#      and the center has a single corresponding D5 anchor target.
# d) Placement legality:
#    - The motif is still placed with a one-block margin on each side, so the 15x15
#      expanded output always fits inside the 16..19 canvas.
#    - Corruption is confined to one existing corner block; no new objects are added,
#      and the repaired motif occupies exactly the original 9x9 footprint.
# e) Visual observability:
#    - Across examples, humans see a filled center plus one "damaged but not empty"
#      corner block. The diagonal corner still looks plausible, so the puzzle reads
#      as a symmetry repair rather than a blank-fill task.
#    - Because the center is generated by the D5 rule and the damaged corner's anchor
#      pixel is forced wrong, the center visibly participates in identifying which
#      corner is broken.
# f) Visual cleanliness:
#    - There is still exactly one compact motif on a clean teal background and one
#      expanded output region. No markers, overlays, or extra objects are introduced.
#    - Damage is limited to a few cells inside a single 3x3 corner block, so the
#      image stays legible rather than cluttered.
# g) Color inference:
#    - No rule depends on numeric color ids. Wrong cells are chosen from the motif's
#      existing foreground palette, so the corruption looks like a damaged version of
#      the same object rather than a hidden code.
# 9) New solver assumptions guaranteed by generate_input():
#    - Exactly one corner block differs from its true symmetric form.
#    - The damaged corner and its diagonal partner are the only corners that fail the
#      opposite-corner rot180 test.
#    - Among those two suspects, exactly one violates the D5 center-anchor relation.
#    - The damaged corner keeps some correct pixels and some wrong pixels, so D12 is
#      visible and the block is not merely blank or fully replaced.


GRID_SIZE_MIN, GRID_SIZE_MAX = 16, 19
BLOCK = 3
MOTIF_SIZE = BLOCK * 3
EXPANDED_SIZE = BLOCK * 5
MOTIF_PAD = 3

BG = 8
FOREGROUND_COLORS = [1, 2, 3, 4, 5, 6, 7, 9]
COLOR_COUNT_MIN, COLOR_COUNT_MAX = 2, 4

MAJORITY_TOTAL_MIN, MAJORITY_TOTAL_MAX = 10, 16
CORNER_MAJOR_MIN, CORNER_MAJOR_MAX = 5, 8
EDGE_MAJOR_MIN, EDGE_MAJOR_MAX = 5, 8

MAX_RETRIES = 300
MIN_CENTER_RULE_DIFF = 8

CORNER_POSITIONS = ((0, 0), (0, 2), (2, 0), (2, 2))

DIAG_ORBITS = (
    ((0, 0),),
    ((1, 1),),
    ((2, 2),),
    ((0, 1), (1, 0)),
    ((0, 2), (2, 0)),
    ((1, 2), (2, 1)),
)
LR_ORBITS = (
    ((0, 0), (0, 2)),
    ((1, 0), (1, 2)),
    ((2, 0), (2, 2)),
    ((0, 1),),
    ((1, 1),),
    ((2, 1),),
)

_CENTER_OFFSETS = np.array([-1, 1, 3], dtype=int)

# For each corner slot, one local anchor pixel must match one center pixel if the
# motif is valid under the D5 symmetry-based center construction.
_CORNER_ANCHOR_TO_CENTER = {
    (0, 0): ((0, 0), (2, 2)),
    (0, 2): ((0, 2), (2, 0)),
    (2, 0): ((2, 0), (0, 2)),
    (2, 2): ((2, 2), (0, 0)),
}

# Canonical "keep-mask" for a damaged top-left corner block. These are later rotated
# so that the false anchor cell lands on the actual damaged corner slot.
_CANONICAL_KEEP_MASKS = {
    "l_shape": np.array(
        [[0, 0, 1], [0, 1, 1], [1, 1, 1]],
        dtype=bool,
    ),
    "diag_gap": np.array(
        [[0, 1, 1], [1, 0, 1], [1, 1, 1]],
        dtype=bool,
    ),
    "stair": np.array(
        [[0, 1, 1], [0, 1, 1], [1, 0, 1]],
        dtype=bool,
    ),
    "split": np.array(
        [[0, 1, 0], [1, 1, 1], [0, 1, 1]],
        dtype=bool,
    ),
}


def _extract_block(g: np.ndarray, r0: int, c0: int, block: int, br: int, bc: int) -> np.ndarray:
    return crop_bbox(
        g,
        (
            int(r0) + br * block,
            int(c0) + bc * block,
            int(r0) + (br + 1) * block - 1,
            int(c0) + (bc + 1) * block - 1,
        ),
    )


def _orbit_indices_containing(orbits, coords):
    coord_set = set(coords)
    return {
        idx
        for idx, orbit in enumerate(orbits)
        if any(coord in coord_set for coord in orbit)
    }


def _major_orbits(orbits, forced_major, forced_minor, target_count):
    forced_major_idxs = _orbit_indices_containing(orbits, forced_major)
    forced_minor_idxs = _orbit_indices_containing(orbits, forced_minor)
    assert not (forced_major_idxs & forced_minor_idxs), "orbit cannot be both major and minor"

    base_count = sum(len(orbits[idx]) for idx in forced_major_idxs)
    usable = [
        idx
        for idx in range(len(orbits))
        if idx not in forced_major_idxs and idx not in forced_minor_idxs
    ]
    choices = []
    for mask in range(1 << len(usable)):
        selected = set(forced_major_idxs)
        total = base_count
        for bit, idx in enumerate(usable):
            if mask & (1 << bit):
                selected.add(idx)
                total += len(orbits[idx])
        if total == target_count:
            choices.append(selected)
    assert choices, "unreachable symmetric majority count"
    return random.choice(choices)


def _seed_block(orbits, forced_major, forced_minor, majority, target_count):
    block = np.full((BLOCK, BLOCK), -1, dtype=int)
    major_idxs = _major_orbits(orbits, forced_major, forced_minor, target_count)
    minor_orbits = []
    for idx, orbit in enumerate(orbits):
        if idx in major_idxs:
            for r, c in orbit:
                block[r, c] = majority
        else:
            minor_orbits.append((block, orbit))
    return block, minor_orbits


def _assign_minor_colors(minor_orbits, colors):
    random.shuffle(minor_orbits)
    guaranteed = list(colors)
    random.shuffle(guaranteed)
    assignments = guaranteed + [
        random.choice(colors) for _ in range(len(minor_orbits) - len(guaranteed))
    ]
    for (block, orbit), color in zip(minor_orbits, assignments):
        for r, c in orbit:
            block[r, c] = color


def _make_blocks(majority, minor_colors, corner_major, edge_major):
    b00, corner_minors = _seed_block(
        DIAG_ORBITS,
        forced_major=[(0, 0)],
        forced_minor=[(2, 2)],
        majority=majority,
        target_count=corner_major,
    )
    b01, edge_minors = _seed_block(
        LR_ORBITS,
        forced_major=[(0, 1)],
        forced_minor=[(2, 1)],
        majority=majority,
        target_count=edge_major,
    )
    minor_orbits = corner_minors + edge_minors
    assert len(minor_orbits) >= len(minor_colors)
    _assign_minor_colors(minor_orbits, minor_colors)
    assert np.all(b00 != -1) and np.all(b01 != -1)
    assert int(b00[0, 0]) == int(majority)
    assert int(b00[2, 2]) != int(majority)
    assert int(b01[0, 1]) == int(majority)
    assert int(b01[2, 1]) != int(majority)
    return b00, b01


def _assemble_motif(b00, b01):
    motif = np.full((MOTIF_SIZE, MOTIF_SIZE), BG, dtype=int)
    blocks = {
        (0, 0): b00,
        (0, 1): b01,
        (0, 2): np.fliplr(b00),
        (1, 0): b01.T,
        (1, 2): np.rot90(b01, -1),
        (2, 0): np.flipud(b00),
        (2, 1): np.flipud(b01),
        (2, 2): np.rot90(b00, 2),
    }
    for (br, bc), blk in blocks.items():
        paste(motif, blk, br * BLOCK, bc * BLOCK)
    return motif


def _legacy_center_patch_from_motif(motif: np.ndarray, majority: int) -> np.ndarray:
    patch = np.full((BLOCK, BLOCK), majority, dtype=int)
    rows = BLOCK + _CENTER_OFFSETS
    cols = BLOCK + _CENTER_OFFSETS
    for r in range(BLOCK):
        for c in range(BLOCK):
            if r == BLOCK // 2 and c == BLOCK // 2:
                continue
            patch[r, c] = int(motif[rows[r], cols[c]])
    return patch


def _symmetry_center_patch_from_motif(motif: np.ndarray, majority: int) -> np.ndarray:
    patch = np.full((BLOCK, BLOCK), majority, dtype=int)
    src_rows = [MOTIF_SIZE - 1, BLOCK + 1, 0]
    src_cols = [MOTIF_SIZE - 1, BLOCK + 1, 0]
    for r in range(BLOCK):
        for c in range(BLOCK):
            if r == BLOCK // 2 and c == BLOCK // 2:
                continue
            patch[r, c] = int(motif[src_rows[r], src_cols[c]])
    return patch


def _variant_diff(motif: np.ndarray, majority: int) -> int:
    new_center = _symmetry_center_patch_from_motif(motif, majority)
    old_center = _legacy_center_patch_from_motif(motif, majority)
    mask = np.ones((BLOCK, BLOCK), dtype=bool)
    mask[BLOCK // 2, BLOCK // 2] = False
    return int(np.count_nonzero(new_center[mask] != old_center[mask]))


def _pick_wrong_foreground(target: int, motif_colors: list[int]) -> int:
    candidates = [color for color in motif_colors if color != int(target)]
    assert candidates, "need an alternate motif color for corruption"
    return int(random.choice(candidates))


def _rotate_keep_mask_for_corner(mask: np.ndarray, hole_corner: tuple[int, int]) -> np.ndarray:
    rotations = {
        (0, 0): 0,
        (0, 2): 3,
        (2, 2): 2,
        (2, 0): 1,
    }
    return np.rot90(mask, rotations[hole_corner])


def _corrupt_corner_block(
    true_block: np.ndarray, hole_corner: tuple[int, int], motif_colors: list[int]
) -> tuple[np.ndarray, str]:
    mask_name = random.choice(sorted(_CANONICAL_KEEP_MASKS))
    keep_mask = _rotate_keep_mask_for_corner(_CANONICAL_KEEP_MASKS[mask_name], hole_corner)
    corrupted = true_block.copy()
    wrong_positions = [tuple(rc) for rc in np.argwhere(~keep_mask)]
    assert wrong_positions, "damage mask must change at least one pixel"

    anchor_local, _ = _CORNER_ANCHOR_TO_CENTER[hole_corner]
    assert anchor_local in wrong_positions, "damage must break the D5 tie-break anchor"

    for r, c in wrong_positions:
        corrupted[r, c] = _pick_wrong_foreground(int(true_block[r, c]), motif_colors)

    assert np.any(corrupted == true_block), "need some already-correct pixels"
    assert np.any(corrupted != true_block), "need some wrong pixels"
    return corrupted, mask_name


def _corner_anchor_matches_center(motif: np.ndarray, br: int, bc: int, block: int) -> bool:
    corner = motif[br * block : (br + 1) * block, bc * block : (bc + 1) * block]
    center = motif[block : 2 * block, block : 2 * block]
    (cr, cc), (zr, zc) = _CORNER_ANCHOR_TO_CENTER[(br, bc)]
    return int(corner[cr, cc]) == int(center[zr, zc])


def _suspect_corners_from_rot180(motif: np.ndarray, block: int) -> list[tuple[int, int]]:
    suspects = []
    for br, bc in CORNER_POSITIONS:
        corner = motif[br * block : (br + 1) * block, bc * block : (bc + 1) * block]
        opposite = motif[
            (2 - br) * block : (3 - br) * block,
            (2 - bc) * block : (3 - bc) * block,
        ]
        if not np.array_equal(corner, np.rot90(opposite, 2)):
            suspects.append((br, bc))
    return suspects


def _find_damaged_corner(motif: np.ndarray, block: int) -> tuple[int, int]:
    suspects = _suspect_corners_from_rot180(motif, block)
    assert len(suspects) == 2, "expected exactly one corrupted corner pair"
    damaged = [
        (br, bc)
        for br, bc in suspects
        if not _corner_anchor_matches_center(motif, br, bc, block)
    ]
    assert len(damaged) == 1, "expected D5 center anchor to disambiguate the damaged corner"
    return damaged[0]


def _restore_corner_from_opposite(motif: np.ndarray, hole_corner: tuple[int, int], block: int) -> np.ndarray:
    br, bc = hole_corner
    src = motif[
        (2 - br) * block : (3 - br) * block,
        (2 - bc) * block : (3 - bc) * block,
    ]
    return np.rot90(src, 2)


def _expanded_output(motif: np.ndarray) -> np.ndarray:
    expanded = np.full((EXPANDED_SIZE, EXPANDED_SIZE), BG, dtype=int)
    paste(expanded, motif, BLOCK, BLOCK)
    for br in range(3):
        for bc in range(3):
            if (br, bc) == (1, 1):
                continue
            src = motif[br * BLOCK : (br + 1) * BLOCK, bc * BLOCK : (bc + 1) * BLOCK]
            paste(expanded, src, (4 - 2 * br) * BLOCK, (4 - 2 * bc) * BLOCK)
    return expanded


def main(grid: np.ndarray) -> np.ndarray:
    """
    Repair one partially corrupted corner of a symmetric 3x3-block motif, then expand the repaired motif into a 5x5 block layout.

    Input structure:
    - A teal canvas contains one 9x9 motif made from nine 3x3 block slots.
    - The center block is already filled, and it follows the motif's global left-right plus up-down symmetry rule.
    - Exactly one corner block is a damaged version of the true corner: some pixels are already correct, while other pixels are wrong.

    Rule:
    - Locate the damaged corner by first finding the diagonal corner pair that breaks 180-degree corner symmetry, then using the center block's symmetry anchor to decide which member of that pair is actually corrupted.
    - Rebuild that corner by rotating the opposite corner block by 180 degrees and replacing the whole damaged 3x3 block with the repaired one.
    - Keep the repaired 9x9 motif in place and copy every non-center block to the point-symmetric outer slot of the implied 5x5 block grid, without rotating the copied block.

    Key insight:
    - The damaged corner cannot be located from "blank space" because the hole already contains plausible pixels. Opposite-corner symmetry narrows the answer to a pair, and the filled D5-style center supplies the extra anchor that reveals which corner needs repair.
    """
    g = np.asarray(grid, dtype=int)
    bg = get_bg(g)
    motif_bbox = bbox(g != bg)
    assert motif_bbox is not None, "expected a foreground motif"
    r0, c0, r1, c1 = motif_bbox
    h = int(r1 - r0 + 1)
    w = int(c1 - c0 + 1)
    assert h == w and h % 3 == 0, "motif must be a square 3x3 block grid"
    block = h // 3
    assert block == 3, "this combo variant uses 3x3 blocks"

    motif = crop_bbox(g, motif_bbox).copy()
    hole_br, hole_bc = _find_damaged_corner(motif, block)
    repaired = _restore_corner_from_opposite(motif, (hole_br, hole_bc), block)
    paste(motif, repaired, hole_br * block, hole_bc * block)

    out = g.copy()
    paste(out, motif, int(r0), int(c0))

    expanded_r0 = int(r0) - block
    expanded_c0 = int(c0) - block
    for br in range(3):
        for bc in range(3):
            if (br, bc) == (1, 1):
                continue
            src = motif[br * block : (br + 1) * block, bc * block : (bc + 1) * block]
            dst_r = expanded_r0 + (4 - 2 * br) * block
            dst_c = expanded_c0 + (4 - 2 * bc) * block
            paste(out, src, dst_r, dst_c)
    return out


def variant_metrics(grid: np.ndarray) -> dict[str, int]:
    g = np.asarray(grid, dtype=int)
    bg = get_bg(g)
    motif_bbox = bbox(g != bg)
    assert motif_bbox is not None
    motif = crop_bbox(g, motif_bbox)
    block = motif.shape[0] // 3

    suspects = _suspect_corners_from_rot180(motif, block)
    damaged = _find_damaged_corner(motif, block)
    repaired = _restore_corner_from_opposite(motif, damaged, block)
    current = motif[
        damaged[0] * block : (damaged[0] + 1) * block,
        damaged[1] * block : (damaged[1] + 1) * block,
    ]
    anchor_local, _ = _CORNER_ANCHOR_TO_CENTER[damaged]
    anchor_wrong = int(current[anchor_local] != repaired[anchor_local])

    return {
        "suspect_count": len(suspects),
        "d5_tiebreak_candidates": sum(
            int(not _corner_anchor_matches_center(motif, br, bc, block)) for br, bc in suspects
        ),
        "damaged_correct_cells": int(np.sum(current == repaired)),
        "damaged_wrong_cells": int(np.sum(current != repaired)),
        "anchor_wrong": anchor_wrong,
    }


def _gen_attempt(return_meta: bool = False):
    n = random.randint(GRID_SIZE_MIN, GRID_SIZE_MAX)
    color_count = random.randint(COLOR_COUNT_MIN, COLOR_COUNT_MAX)
    colors = random.sample(FOREGROUND_COLORS, color_count)
    majority = colors[0]
    minor_colors = colors[1:]

    possible_totals = [
        total
        for total in range(MAJORITY_TOTAL_MIN, MAJORITY_TOTAL_MAX + 1)
        if 18 - total >= len(minor_colors)
    ]
    majority_total = random.choice(possible_totals)
    pairs = [
        (corner, majority_total - corner)
        for corner in range(CORNER_MAJOR_MIN, CORNER_MAJOR_MAX + 1)
        if EDGE_MAJOR_MIN <= majority_total - corner <= EDGE_MAJOR_MAX
    ]
    corner_major, edge_major = random.choice(pairs)

    b00, b01 = _make_blocks(majority, minor_colors, corner_major, edge_major)
    motif = _assemble_motif(b00, b01)
    center = _symmetry_center_patch_from_motif(motif, majority)
    if _variant_diff(motif, majority) < MIN_CENTER_RULE_DIFF:
        return (None, None) if return_meta else None

    full_motif = motif.copy()
    paste(full_motif, center, BLOCK, BLOCK)

    hole_corner = random.choice(CORNER_POSITIONS)
    true_corner = full_motif[
        hole_corner[0] * BLOCK : (hole_corner[0] + 1) * BLOCK,
        hole_corner[1] * BLOCK : (hole_corner[1] + 1) * BLOCK,
    ]
    corrupted_corner, mask_name = _corrupt_corner_block(true_corner, hole_corner, colors)

    input_motif = full_motif.copy()
    paste(input_motif, corrupted_corner, hole_corner[0] * BLOCK, hole_corner[1] * BLOCK)
    expanded = _expanded_output(full_motif)

    r0 = random.randint(MOTIF_PAD, n - MOTIF_SIZE - MOTIF_PAD)
    c0 = random.randint(MOTIF_PAD, n - MOTIF_SIZE - MOTIF_PAD)
    inp = np.full((n, n), BG, dtype=int)
    out = np.full((n, n), BG, dtype=int)
    paste(inp, input_motif, r0, c0)
    paste(out, expanded, r0 - BLOCK, c0 - BLOCK)

    if not np.array_equal(main(inp), out):
        return (None, None) if return_meta else None

    if return_meta:
        meta = variant_metrics(inp)
        meta["mask_name"] = mask_name
        meta["hole_br"] = hole_corner[0]
        meta["hole_bc"] = hole_corner[1]
        meta["center_rule_diff"] = _variant_diff(motif, majority)
        return inp, meta
    return inp


def generate_input() -> np.ndarray:
    for _ in range(MAX_RETRIES):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise AssertionError("failed to generate a valid db0c5428 combo variant input")
