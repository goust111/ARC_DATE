# Combo variant of e87109e9 (index 19)
# combo_spec: D4/3+D10/2
# Name: 仅转弯点涂色加轨迹提取

from __future__ import annotations

import random

import numpy as np

from arc_utils import bbox_coords, components_mask

# Design analysis for the fused D4/3 + D10/2 variant
# a) Concrete behavior and trace:
#    - Keep the original input grammar unchanged: a 6-row legend on top encodes
#      left-turn/right-turn by bar position, and the main area below contains one
#      solid teal square plus 3-4 colored edge obstacles.
#    - The hidden ray geometry also stays unchanged: from the teal square, launch
#      four sz-by-sz sliding beams; when the next footprint would overlap an
#      obstacle color C, consult the legend and rotate 90 degrees without
#      entering the obstacle.
#    - The output rule changes in two coupled ways:
#      1. D10/2 removes every input object from the rendered output. The solver
#         no longer returns the cropped base with beams overlaid; it returns an
#         all-black canvas of the cropped main-grid size.
#      2. D4/3 then renders only local turn skeletons on that black canvas. For
#         each turn event, paint the beam footprint at the turn anchor itself,
#         plus the immediately previous anchor and the first anchor after the
#         turn. Straight segments stay invisible.
#    - Example trace for sz=2:
#      if the north-going beam advances several hidden steps, stops at anchor
#      (r,c) because (r-1,c) would hit color 4, and color 4 means clockwise,
#      then the original task painted the full north segment and then the full
#      east segment. The fused output paints only three 2x2 footprints centered
#      on anchors (r+1,c), (r,c), and (r,c+1), while the obstacle, source, and
#      all untouched background are forced to black.
# b) Complexity calibration:
#    - The only visible color in the output is still teal. No extra legend code
#      or bounce-count palette is introduced, so the added reasoning burden comes
#      purely from hidden-path reconstruction.
#    - We keep the original 4-5 total turns so every sample contains several
#      repeated L-shaped local marks. That prevents the fusion from collapsing
#      into a single accidental corner.
#    - Generator rejects samples where a turn is too close to the source or edge:
#      each turn must contribute a full `prev + turn + next` local footprint set,
#      otherwise the new behavior would be visually weak.
# c) Hidden-assumption audit:
#    - Original `main()` painted into `out` and then reused `out` to detect later
#      obstacle hits. That was safe only because visible teal trail should behave
#      like traversable space. After D10/2, output no longer stores obstacles at
#      all, so obstacle queries must read from the immutable cropped input base.
#    - Original rendering assumed keeping the source and obstacles was harmless.
#      Broken here: the final image must black out source, obstacles, and input
#      background, so simulation and rendering must be separated.
#    - Original code could tolerate turns immediately next to the source because a
#      continuous trail naturally merged with the source square. Broken here:
#      such turns would cause the "one step before the turn" footprint to overlap
#      the source, contradicting the fused rule that the source disappears. The
#      generator therefore rejects these cases.
# d) Placement legality:
#    - Obstacle rectangles are still generated by the original path-first edge
#      scheme: no overlaps, no contact with the teal square, and all intended hit
#      colors are reachable by the hidden beams.
#    - Additional fused legality checks ensure every turn has a valid previous
#      footprint and a valid first post-turn footprint, and that different turn
#      markers do not overlap each other.
# e) Visual observability:
#    - Across a few examples, humans will repeatedly see a black output with only
#      several short teal corner-like stamps. Since the input still shows the
#      source square and obstacles, the intended inference is "the rays still
#      exist, but only their turning neighborhoods survive."
#    - The legend remains necessary because the hidden continuation direction can
#      only be recovered from obstacle color to left/right-turn mapping.
# f) Visual cleanliness:
#    - Obstacles vanish from the output entirely, so the image contains just one
#      layer of teal marks on black. The generator forbids overlapping turn marks
#      to avoid noisy merged clusters.
#    - Only 3-4 obstacles and 4-5 turns are used, keeping the skeleton sparse and
#      visually distinct from a dense continuous flood-fill.
# g) Change inferability:
#    - No new color mapping is introduced. All samples use the same output palette
#      structure: black background plus teal turn marks.
#    - The rule difference is structural and repeated: long hidden straight runs
#      from the input are systematically absent in the output, while every actual
#      turn leaves a short 3-footprint L-pattern. That is inferable from 2-4
#      examples without relying on color-id arithmetic.
# 9) New solver assumptions guaranteed by the generator:
#    - Each turn yields a full local mark with non-source cells at the previous,
#      current, and first post-turn anchors.
#    - Turn markers from different hits are pairwise disjoint, so the solver does
#      not need to disambiguate merged skeleton pieces.
#    - The D4/3 effect is active on every sample: the full extracted trajectory
#      contains strictly more teal cells than the fused skeleton output.

_DIRS = [(-1, 0), (0, 1), (1, 0), (0, -1)]
_N, _E, _S, _W = range(4)


def _parse_legend(grid: np.ndarray, legend_h: int) -> dict[int, str]:
    """
    Legend is a top region with a background color and 4 vertical bars.
    Each bar's side inside its cell encodes turn direction:
      - left bar  -> 'L' (counterclockwise turn)
      - right bar -> 'R' (clockwise turn)
    """
    legend = grid[:legend_h, :]
    assert legend.size, "legend must be non-empty"
    vals, counts = np.unique(legend, return_counts=True)
    bg = int(vals[counts.argmax()])

    sep_cols = [c for c in range(legend.shape[1]) if np.all(legend[:, c] == bg)]
    assert len(sep_cols) >= 2, "legend separator columns must exist"

    turn: dict[int, str] = {}
    for a, b in zip(sep_cols, sep_cols[1:], strict=False):
        if b - a <= 2:
            continue
        interior = legend[1 : legend_h - 1, a + 1 : b]
        colors = set(map(int, np.unique(interior)))
        colors.discard(bg)
        colors.discard(0)
        assert len(colors) == 1, "each legend cell must encode exactly one color"
        color = int(next(iter(colors)))
        xs = np.where(interior == color)[1]
        x = int(xs[0])
        turn[color] = "L" if x <= (interior.shape[1] - 1) // 2 else "R"
    assert len(turn) == 4, "legend must encode four turn colors"
    return turn


def _find_teal_square(g: np.ndarray, teal: int = 8) -> tuple[int, int, int]:
    """Return (r0, c0, size) for the unique solid teal square."""
    candidates: list[tuple[int, int, int]] = []
    for cells in components_mask(g == teal, connectivity=4):
        r0, c0, r1, c1 = bbox_coords(cells)
        hh = r1 - r0 + 1
        ww = c1 - c0 + 1
        if hh != ww:
            continue
        size = hh
        if int(np.sum(g[r0 : r1 + 1, c0 : c1 + 1] == teal)) != size * size:
            continue
        candidates.append((int(r0), int(c0), int(size)))
    assert len(candidates) == 1, "main grid must contain exactly one solid teal square"
    return candidates[0]


def _rot(d: int, turn: str) -> int:
    return (d - 1) % 4 if turn == "L" else (d + 1) % 4


def _source_mask(shape: tuple[int, int], src: tuple[int, int, int]) -> np.ndarray:
    sr, sc, sz = src
    mask = np.zeros(shape, dtype=bool)
    mask[sr : sr + sz, sc : sc + sz] = True
    return mask


def _anchor_in_bounds(r: int, c: int, sz: int, shape: tuple[int, int]) -> bool:
    h, w = shape
    return 0 <= r and 0 <= c and r + sz - 1 < h and c + sz - 1 < w


def _cells_for_anchor(
    anchor: tuple[int, int] | None,
    shape: tuple[int, int],
    sz: int,
    src_mask: np.ndarray | None = None,
) -> set[tuple[int, int]]:
    if anchor is None:
        return set()
    r, c = anchor
    if not _anchor_in_bounds(r, c, sz, shape):
        return set()
    cells: set[tuple[int, int]] = set()
    for rr in range(r, r + sz):
        for cc in range(c, c + sz):
            if src_mask is not None and bool(src_mask[rr, cc]):
                continue
            cells.add((rr, cc))
    return cells


def _paint_anchor(
    out: np.ndarray,
    anchor: tuple[int, int] | None,
    sz: int,
    src_mask: np.ndarray,
    color: int,
) -> None:
    for rr, cc in _cells_for_anchor(anchor, out.shape, sz, src_mask):
        out[rr, cc] = color


def _event_cells(
    shape: tuple[int, int],
    hit: tuple[tuple[int, int], tuple[int, int], tuple[int, int] | None, int, int, int],
    sz: int,
    src_mask: np.ndarray,
) -> set[tuple[int, int]]:
    prev_anchor, turn_anchor, next_anchor, _d_in, _d_out, _obs = hit
    cells: set[tuple[int, int]] = set()
    for anchor in (prev_anchor, turn_anchor, next_anchor):
        cells |= _cells_for_anchor(anchor, shape, sz, src_mask)
    return cells


def _simulate_beams(
    base: np.ndarray, turns: dict[int, str], bg: int
) -> tuple[
    tuple[int, int, int],
    list[list[tuple[int, int]]],
    list[list[tuple[tuple[int, int], tuple[int, int], tuple[int, int] | None, int, int, int]]],
]:
    """
    Simulate the hidden beam geometry on the cropped base grid.

    Returns:
      src: (sr, sc, sz)
      steps_by_beam: anchors reached on straight motion, excluding the source anchor
      hits_by_beam: for each turn, (prev_anchor, turn_anchor, next_anchor, d_in, d_out, obs_color)
    """
    teal = 8
    src = _find_teal_square(base, teal=teal)
    sr, sc, sz = src
    h, w = base.shape

    def obstacle_at(anchor: tuple[int, int]) -> int | None:
        r, c = anchor
        blk = base[r : r + sz, c : c + sz]
        colors = set(map(int, np.unique(blk)))
        colors.discard(bg)
        colors.discard(teal)
        if not colors:
            return None
        assert len(colors) == 1, "beam footprint must not hit mixed obstacle colors"
        return int(next(iter(colors)))

    steps_by_beam: list[list[tuple[int, int]]] = []
    hits_by_beam: list[
        list[tuple[tuple[int, int], tuple[int, int], tuple[int, int] | None, int, int, int]]
    ] = []

    for d0 in range(4):
        r, c, d = sr, sc, d0
        seen: set[tuple[int, int, int]] = set()
        beam_steps: list[tuple[int, int]] = []
        beam_hits: list[
            tuple[tuple[int, int], tuple[int, int], tuple[int, int] | None, int, int, int]
        ] = []
        while True:
            state = (r, c, d)
            assert state not in seen, "beam path must not cycle"
            seen.add(state)

            dr, dc = _DIRS[d]
            nr, nc = r + dr, c + dc
            if not _anchor_in_bounds(nr, nc, sz, (h, w)):
                break

            obs = obstacle_at((nr, nc))
            if obs is None:
                r, c = nr, nc
                beam_steps.append((r, c))
                continue

            assert obs in turns, "obstacle color must be encoded by the legend"
            d_out = _rot(d, turns[obs])
            prev_anchor = (r - dr, c - dc)
            dr2, dc2 = _DIRS[d_out]
            next_anchor = (r + dr2, c + dc2)
            if not _anchor_in_bounds(next_anchor[0], next_anchor[1], sz, (h, w)):
                next_anchor = None
            elif obstacle_at(next_anchor) is not None:
                next_anchor = None
            beam_hits.append((prev_anchor, (r, c), next_anchor, d, d_out, obs))
            assert len(beam_hits) <= 2, "generator family expects at most two turns per beam"
            d = d_out

        steps_by_beam.append(beam_steps)
        hits_by_beam.append(beam_hits)

    return src, steps_by_beam, hits_by_beam


def _render_full_trajectory(
    shape: tuple[int, int],
    steps_by_beam: list[list[tuple[int, int]]],
    src: tuple[int, int, int],
    teal: int = 8,
) -> np.ndarray:
    """D10/2-only baseline: extract the full hidden trajectory on a black canvas."""
    out = np.zeros(shape, dtype=int)
    src_mask = _source_mask(shape, src)
    sz = src[2]
    for beam_steps in steps_by_beam:
        for anchor in beam_steps:
            _paint_anchor(out, anchor, sz, src_mask, teal)
    return out


def _render_turn_skeleton(
    shape: tuple[int, int],
    hits_by_beam: list[list[tuple[tuple[int, int], tuple[int, int], tuple[int, int] | None, int, int, int]]],
    src: tuple[int, int, int],
    teal: int = 8,
) -> np.ndarray:
    """Fused D4/3 + D10/2 rendering: only turn-local footprints survive."""
    out = np.zeros(shape, dtype=int)
    src_mask = _source_mask(shape, src)
    sz = src[2]
    for beam_hits in hits_by_beam:
        for hit in beam_hits:
            prev_anchor, turn_anchor, next_anchor, _d_in, _d_out, _obs = hit
            for anchor in (prev_anchor, turn_anchor, next_anchor):
                _paint_anchor(out, anchor, sz, src_mask, teal)
    return out


def _fusion_metrics(
    shape: tuple[int, int],
    src: tuple[int, int, int],
    steps_by_beam: list[list[tuple[int, int]]],
    hits_by_beam: list[list[tuple[tuple[int, int], tuple[int, int], tuple[int, int] | None, int, int, int]]],
) -> dict[str, int]:
    full = _render_full_trajectory(shape, steps_by_beam, src)
    fused = _render_turn_skeleton(shape, hits_by_beam, src)
    turn_count = sum(len(beam_hits) for beam_hits in hits_by_beam)
    return {
        "turn_count": turn_count,
        "full_cells": int(np.count_nonzero(full == 8)),
        "fused_cells": int(np.count_nonzero(fused == 8)),
        "hidden_cells": int(np.count_nonzero((full == 8) & (fused == 0))),
        "diff_cells": int(np.count_nonzero(full != fused)),
    }


def main(grid: np.ndarray) -> np.ndarray:
    """
    Emit four hidden teal beams, but reveal only local skeleton marks at turns.

    Input structure:
    - Top band: a grey legend whose four colored vertical bars encode left-turn vs right-turn by side placement.
    - Below: one main grid containing a solid teal square, a single dominant background color, and 3-4 colored obstacle rectangles.

    Rule:
    - Remove the legend from consideration and simulate the same four cardinal beams as in the base task.
    - A beam advances as a sliding copy of the teal square through background cells; if the next footprint would hit obstacle color C, use the legend to rotate 90 degrees and continue.
    - The output is not the painted scene. Start from an all-black canvas of the cropped main-grid size, and for each turn keep only the footprint at the turn anchor plus the footprint one step before and one step after that turn. Leave straight runs, obstacles, background, and the source square black.

    Key insight:
    - The ray paths are still determined entirely by the obstacle colors and the legend's left/right encoding, but most of each path is invisible. The teal output pixels are only turn-local evidence of a larger hidden trajectory.
    """
    g = np.asarray(grid, dtype=int)

    legend_bg = 5
    rows_with_legend = np.where(np.any(g == legend_bg, axis=1))[0]
    assert rows_with_legend.size, "legend rows must be present"
    legend_h = int(rows_with_legend.max() + 1)
    assert np.array_equal(rows_with_legend, np.arange(legend_h)), "legend must occupy the top band"

    turns = _parse_legend(g, legend_h)
    base = g[legend_h:, :].copy()
    assert base.size, "main grid must remain after legend crop"

    vals, counts = np.unique(base, return_counts=True)
    bg = int(vals[counts.argmax()])
    src, _steps_by_beam, hits_by_beam = _simulate_beams(base, turns, bg)
    return _render_turn_skeleton(base.shape, hits_by_beam, src)


# --------------- generator ---------------

LEGEND_COLOR_POOL = [1, 2, 3, 4, 6]
BG_COLOR_POOL = [1, 2, 3, 4, 6, 7, 9]
LEGEND_BG = 5
TEAL = 8

GRID_H_RANGE = (19, 24)
GRID_W = 24
LEGEND_H = 6
LEGEND_CELL_STARTS = [1, 7, 13, 19]

TEAL_SZ2_PROB = 0.75
SQUARE_EDGE_GAP = 5

OBS_COUNT_4_PROB = 0.65
OBS_THICKNESS_RANGE = (2, 4)
OBS_SINGLE_MARGIN = 6
OBS_BOTH_GAP = 2

SPAN_MIN_MULT = 3
SPAN_MAX_MULT = 14
SPAN_COMPACT_PROB = 0.4

MAX_RETRIES = 400


def _choose_span(
    axis_len: int,
    required: list[tuple[int, int]],
    excluded: list[tuple[int, int]],
    min_len: int,
    max_len: int,
) -> tuple[int, int] | None:
    """Pick a span covering all required intervals while avoiding all excluded ones."""
    req0 = min(a for a, _ in required)
    req1 = max(b for _, b in required)
    lo = max(min_len, req1 - req0 + 1)
    hi = min(max_len, axis_len)
    choices: list[tuple[int, int, int]] = []
    for length in range(lo, hi + 1):
        start0 = max(0, req1 - length + 1)
        start1 = min(req0, axis_len - length)
        for start in range(start0, start1 + 1):
            end = start + length - 1
            if all(end < a or start > b for a, b in excluded):
                choices.append((length, start, end))
    if not choices:
        return None

    lengths = sorted({length for length, _, _ in choices})
    if random.random() < SPAN_COMPACT_PROB:
        cutoff = lengths[min(len(lengths) - 1, max(0, len(lengths) // 2))]
        pool = [(start, end) for length, start, end in choices if length <= cutoff]
    else:
        pool = [(start, end) for _, start, end in choices]
    return random.choice(pool)


def _make_legend(legend_colors: list[int], turns: dict[int, str]) -> np.ndarray:
    legend = np.full((LEGEND_H, GRID_W), LEGEND_BG, dtype=int)
    for start, color in zip(LEGEND_CELL_STARTS, legend_colors):
        legend[1:5, start : start + 4] = 0
        bar_col = start if turns[color] == "L" else start + 3
        legend[1:5, bar_col] = color
    return legend


def _rand_thickness(lo: int, hi: int) -> int | None:
    return random.randint(lo, hi) if hi >= lo else None


def _thickness_pair(
    axis: int, sz: int, a_present: bool, b_present: bool
) -> tuple[int | None, int | None] | None:
    lo, hi_cap = OBS_THICKNESS_RANGE
    if a_present and b_present:
        room = axis - sz - OBS_BOTH_GAP
        if room < 2 * lo:
            return None
        a = random.randint(lo, min(hi_cap, room - lo))
        b = _rand_thickness(lo, min(hi_cap, room - a))
        return (a, b) if b is not None else None
    if a_present:
        t = _rand_thickness(lo, min(hi_cap, axis - sz - OBS_SINGLE_MARGIN))
        return (t, None) if t is not None else None
    if b_present:
        t = _rand_thickness(lo, min(hi_cap, axis - sz - OBS_SINGLE_MARGIN))
        return (None, t) if t is not None else None
    return None, None


def _obstacle_rect(
    side: int, thickness: int, span: tuple[int, int], h: int, w: int
) -> tuple[int, int, int, int]:
    s0, s1 = span
    if side == _N:
        return 0, thickness - 1, s0, s1
    if side == _S:
        return h - thickness, h - 1, s0, s1
    if side == _W:
        return s0, s1, 0, thickness - 1
    return s0, s1, w - thickness, w - 1


def _select_chains(present: set[int], second_hits: int) -> dict[int, int] | None:
    candidates = [
        (side, nxt)
        for side in present
        for nxt in ((side - 1) % 4, (side + 1) % 4)
        if nxt in present
    ]
    random.shuffle(candidates)
    selected: list[tuple[int, int]] = []
    used: set[int] = set()
    for side, nxt in candidates:
        if len(selected) == second_hits:
            break
        if side in used or nxt in used:
            continue
        selected.append((side, nxt))
        used.update((side, nxt))
    return dict(selected) if len(selected) == second_hits else None


def _assign_turns(present: set[int], chains: dict[int, int]) -> dict[int, str]:
    side_turn: dict[int, str] = {}
    for side in present:
        if side in chains:
            nxt = chains[side]
            side_turn[side] = "L" if nxt == (side - 1) % 4 else "R"
        else:
            outward = [t for t in ("L", "R") if _rot(side, t) not in present]
            side_turn[side] = random.choice(outward if outward else ["L", "R"])
    return side_turn


def _compute_span_constraints(
    present: set[int],
    side_turn: dict[int, str],
    chains: dict[int, int],
    sr: int,
    sc: int,
    sz: int,
    lane: dict[int, int],
) -> tuple[dict[int, list[tuple[int, int]]], dict[int, list[tuple[int, int]]]]:
    required: dict[int, list[tuple[int, int]]] = {s: [] for s in present}
    excluded: dict[int, list[tuple[int, int]]] = {s: [] for s in present}

    for side in present:
        base_coord = sc if side in (_N, _S) else sr
        required[side].append((base_coord, base_coord + sz - 1))

    def lane_interval(side: int) -> tuple[int, int]:
        return lane[side], lane[side] + sz - 1

    for side in present:
        nxt = _rot(side, side_turn[side])
        if nxt not in present:
            continue
        if chains.get(side) == nxt:
            required[nxt].append(lane_interval(side))
            after = _rot(nxt, side_turn[nxt])
            if after in present:
                excluded[after].append(lane_interval(nxt))
        else:
            excluded[nxt].append(lane_interval(side))

    return required, excluded


def _gen_attempt() -> np.ndarray | None:
    h, w = random.randint(*GRID_H_RANGE), GRID_W
    sz = 2 if random.random() < TEAL_SZ2_PROB else 3
    obstacle_count = 4 if random.random() < OBS_COUNT_4_PROB else 3
    present = set(random.sample([_N, _E, _S, _W], obstacle_count))
    target_hits = random.choice([4, 5])
    second_hits = target_hits - obstacle_count
    if second_hits < 0 or second_hits > 2:
        return None

    ns = _thickness_pair(h, sz, _N in present, _S in present)
    ew = _thickness_pair(w, sz, _W in present, _E in present)
    if ns is None or ew is None:
        return None
    thickness = {s: t for s, t in zip((_N, _S, _W, _E), (*ns, *ew)) if t is not None}

    min_r, max_r = SQUARE_EDGE_GAP, h - sz - SQUARE_EDGE_GAP
    min_c, max_c = SQUARE_EDGE_GAP, w - sz - SQUARE_EDGE_GAP
    if _N in present:
        min_r = max(min_r, thickness[_N] + 1)
    if _S in present:
        max_r = min(max_r, h - thickness[_S] - sz - 1)
    if _W in present:
        min_c = max(min_c, thickness[_W] + 1)
    if _E in present:
        max_c = min(max_c, w - thickness[_E] - sz - 1)
    if min_r > max_r or min_c > max_c:
        return None
    sr, sc = random.randint(min_r, max_r), random.randint(min_c, max_c)

    lane: dict[int, int] = {}
    if _N in present:
        lane[_N] = thickness[_N] + 1
    if _S in present:
        lane[_S] = h - thickness[_S] - sz
    if _W in present:
        lane[_W] = thickness[_W] + 1
    if _E in present:
        lane[_E] = w - thickness[_E] - sz

    chains = _select_chains(present, second_hits)
    if chains is None:
        return None

    side_turn = _assign_turns(present, chains)
    required, excluded = _compute_span_constraints(
        present, side_turn, chains, sr, sc, sz, lane
    )

    spans: dict[int, tuple[int, int]] = {}
    for side in present:
        axis_len = w if side in (_N, _S) else h
        span = _choose_span(
            axis_len,
            required[side],
            excluded[side],
            SPAN_MIN_MULT * sz,
            min(SPAN_MAX_MULT * sz, axis_len),
        )
        if span is None:
            return None
        spans[side] = span

    legend_colors = random.sample(LEGEND_COLOR_POOL, 4)
    obstacle_colors = random.sample(legend_colors, obstacle_count)
    side_color = dict(zip(sorted(present), obstacle_colors))
    bg = random.choice([c for c in BG_COLOR_POOL if c not in legend_colors])

    base = np.full((h, w), bg, dtype=int)
    base[sr : sr + sz, sc : sc + sz] = TEAL
    occupied = np.zeros((h, w), dtype=bool)
    for side in present:
        r0, r1, c0, c1 = _obstacle_rect(side, thickness[side], spans[side], h, w)
        region = occupied[r0 : r1 + 1, c0 : c1 + 1]
        if region.any():
            return None
        if not (r1 < sr - 1 or r0 > sr + sz or c1 < sc - 1 or c0 > sc + sz):
            return None
        occupied[r0 : r1 + 1, c0 : c1 + 1] = True
        base[r0 : r1 + 1, c0 : c1 + 1] = side_color[side]

    vals, counts = np.unique(base, return_counts=True)
    if int(vals[counts.argmax()]) != bg:
        return None

    turns = {side_color[s]: side_turn[s] for s in present}
    for color in legend_colors:
        turns.setdefault(color, random.choice(["L", "R"]))

    try:
        src, steps_by_beam, hits_by_beam = _simulate_beams(base, turns, bg)
    except AssertionError:
        return None

    hit_counts = [len(beam_hits) for beam_hits in hits_by_beam]
    hit_colors = {obs for beam_hits in hits_by_beam for *_rest, obs in beam_hits}
    if sum(hit_counts) != target_hits or any(c > 2 for c in hit_counts):
        return None
    if set(side_color.values()) - hit_colors:
        return None

    src_mask = _source_mask(base.shape, src)
    used_mark_cells: set[tuple[int, int]] = set()
    expected_event_area = sz * sz + 2 * sz
    turn_events = 0
    for beam_hits in hits_by_beam:
        for hit in beam_hits:
            cells = _event_cells(base.shape, hit, sz, src_mask)
            if len(cells) != expected_event_area:
                return None
            if used_mark_cells & cells:
                return None
            used_mark_cells |= cells
            turn_events += 1
    if turn_events != target_hits:
        return None

    metrics = _fusion_metrics(base.shape, src, steps_by_beam, hits_by_beam)
    if metrics["turn_count"] != target_hits:
        return None
    if metrics["hidden_cells"] < 8:
        return None
    if metrics["diff_cells"] < 8:
        return None
    if metrics["fused_cells"] >= metrics["full_cells"]:
        return None

    legend = _make_legend(legend_colors, turns)
    inp = np.vstack([legend, base])
    expected = _render_turn_skeleton(base.shape, hits_by_beam, src)
    try:
        actual = main(inp)
    except AssertionError:
        return None
    if not np.array_equal(actual, expected):
        return None
    return inp


def generate_input() -> np.ndarray:
    for _ in range(MAX_RETRIES):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate e87109e9 combo input")
