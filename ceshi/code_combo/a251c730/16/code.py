# Combo variant of a251c730 (index 16)
# combo_spec: D2/0+D14/1
# Name: 三色精灵+多类型

from __future__ import annotations

from collections import Counter
import random

import numpy as np

from arc_utils import bbox_coords, components_mask, paste, random_free_location

# Design analysis for the combo variant
# a) Concrete behavior:
#    - The global scene is still wallpaper + one source frame + one destination frame.
#    - The source frame now contains 3-4 sprite types, and every visible sprite is tri-color:
#      one anchor cell, two decoration cells, and three or four body cells.
#    - The destination input still shows only singleton anchor markers, but there are now 4-6
#      markers, so several anchor-color matches must be resolved in one grid.
#    - Example trace:
#      original type set: 2 colors, at most 2 types, 2-3 markers
#      combo type set:    3 colors, 3-4 types, 4-6 markers
#      The transformation rule itself stays "align anchor to marker and stamp the whole sprite",
#      but the evidence the solver must read is richer because the source components are no longer
#      reducible to "body + odd pixel", and there are more simultaneous template keys.
# b) Complexity calibration:
#    - We keep the tri-color cue visually strict: color counts per sprite are exactly (1,2,3) or
#      (1,2,4). This makes the anchor the unique rarest color by visible frequency, never by
#      numeric color-id tie-breaking.
#    - We force 3-4 distinct anchor colors and 4-6 markers, so the "many types" change is present
#      in every sample rather than appearing only occasionally.
#    - Body/decor colors are reused across types but some types swap those two roles, giving visibly
#      different tri-color arrangements without exhausting the 10-color ARC palette.
# c) Implicit assumptions broken in the original solver:
#    - "Take the least-frequent color, breaking ties by color id" is unsafe; the combo requires the
#      least-frequent color to be uniquely rare.
#    - "Any non-anchor pixels can be treated as one bucket" is unsafe; decoration cells must remain.
#    - "A couple of templates are enough" is unsafe; we now expect at least 3 templates and a
#      destination rectangle with several singleton markers.
#    - The new solver therefore validates source components as 2x3/3x3 tri-color sprites with
#      counts (1,2,3/4), stores the full patch, and explicitly prefers rectangles matching those
#      structural expectations.
# d) Placement legality:
#    - Source sprites are placed with border/padding=1 so 4-connected components never merge.
#    - Destination markers are generated by first placing the full future sprite footprints on a
#      temporary output canvas; only their anchor cells are kept in the input destination frame.
#      This guarantees non-overlap and in-bounds stamping.
#    - Rectangle sizes are biased upward relative to the original task so 3-4 types and 4-6 markers
#      fit comfortably inside the fixed 30x30 canvas.
# e) Visual observability:
#    - A human can see three changes directly from a few examples: source sprites are tri-color,
#      there are more distinct anchor colors, and the destination contains more markers than before.
#    - No hidden ordering by numeric color id is used; the anchor cue is the unique singleton color
#      inside each source sprite, which is a visible frequency fact.
# f) Visual cleanliness:
#    - Sprites stay tiny (2x3 or 3x3) and disconnected.
#    - The destination input remains sparse because it still contains only singleton markers, even
#      though the eventual output is denser.
#    - The border, backgrounds, anchors, and sprite interior colors are separated enough to avoid
#      one region visually blending into another.
# g) Change inferability:
#    - Marker color equals anchor color exactly; there is no hidden remapping.
#    - The increased type count is supported by repetition: every type appears in the source and in
#      the destination markers at least once.
# h) Post-implementation metric:
#    - We will measure two fusion indicators on generated samples:
#      1. number of distinct valid source templates (must be 3 or 4),
#      2. per-sprite color-count signature (must always be (1,2,3) or (1,2,4)).
#    - Either condition is impossible under the original generator, so this metric catches
#      degeneration back to the base task distribution.
# i) New solver assumptions that the generator must satisfy:
#    - Source components intended as sprites are 4-connected, tri-color, and shape-bounded by 2x3
#      or 3x3.
#    - Every destination marker color is one of the anchor colors seen in the source.
#    - Repeated copies of a type are identical, so any copy can serve as the stored template.

# --------------- solver ---------------


def main(grid: np.ndarray) -> np.ndarray:
    """
    Reconstruct the destination frame by stamping tri-color sprite templates onto matching markers.

    Input structure:
    - A striped wallpaper contains two bordered rectangles: a source frame with several disconnected
      tri-color sprites, and a destination frame whose interior shows only singleton anchor markers.
    - There are 3-4 sprite types. Each type uses body, anchor, and decoration colors, with the
      anchor appearing once, decoration twice, and body three or four times.

    Rule:
    - Find the source sprite templates and identify each anchor as the unique least-frequent color
      inside its tri-color component.
    - Match every destination marker to the source template with the same anchor color.
    - Stamp the entire sprite so that its anchor cell lands on the marker, and return the cropped
      destination rectangle with its border preserved.

    Key insight: The destination still keys on anchor colors, but the source evidence is now a
    multi-template tri-color library: the solver must preserve decoration pixels and rely on the
    visible frequency pattern (1,2,3/4) to distinguish the anchor from the other two colors.
    """
    g = np.array(grid, dtype=int)
    H, W = g.shape

    def interior_bg(rect: tuple[int, int, int, int]) -> int:
        r0, c0, r1, c1 = map(int, rect)
        inner = g[r0 + 1 : r1, c0 + 1 : c1]
        return int(Counter(map(int, inner.flatten())).most_common(1)[0][0])

    def rect_components(rect: tuple[int, int, int, int]) -> tuple[int, list[dict]]:
        r0, c0, r1, c1 = map(int, rect)
        inner = g[r0 + 1 : r1, c0 + 1 : c1]
        ibg = int(Counter(map(int, inner.flatten())).most_common(1)[0][0])
        comps: list[dict] = []

        for coords in components_mask(inner != ibg, connectivity=4):
            if coords.size == 0:
                continue
            rr0, cc0, rr1, cc1 = bbox_coords(coords)
            mask = np.zeros((rr1 - rr0 + 1, cc1 - cc0 + 1), dtype=bool)
            mask[coords[:, 0] - rr0, coords[:, 1] - cc0] = True
            patch = inner[rr0 : rr1 + 1, cc0 : cc1 + 1].copy()
            patch[~mask] = 0
            vals = [int(inner[int(r), int(c)]) for r, c in coords]
            comps.append(
                {
                    "size": int(coords.shape[0]),
                    "bbox": (int(rr0), int(cc0), int(rr1), int(cc1)),
                    "mask": mask,
                    "patch": patch,
                    "colors": dict(Counter(vals)),
                }
            )

        comps.sort(key=lambda d: (-int(d["size"]), tuple(sorted(d["colors"].items()))))
        return int(ibg), comps

    def classify_tricolor_sprite(comp: dict) -> tuple[int, int, int] | None:
        colors = {int(col): int(cnt) for col, cnt in comp["colors"].items()}
        if len(colors) != 3:
            return None
        rr0, cc0, rr1, cc1 = comp["bbox"]
        h = int(rr1 - rr0 + 1)
        w = int(cc1 - cc0 + 1)
        if (h, w) not in {(2, 3), (3, 3)}:
            return None
        ordered = sorted((int(cnt), int(col)) for col, cnt in colors.items())
        counts = tuple(cnt for cnt, _col in ordered)
        if counts not in {(1, 2, 3), (1, 2, 4)}:
            return None
        return int(ordered[0][1]), int(ordered[1][1]), int(ordered[2][1])

    rects: list[tuple[int, tuple[int, int, int, int], int, int]] = []
    min_h = 6
    min_w = 6
    for r0 in range(H):
        for c0 in range(W):
            bc = int(g[r0, c0])
            for r1 in range(r0 + min_h - 1, H):
                for c1 in range(c0 + min_w - 1, W):
                    if int(g[r0, c1]) != bc or int(g[r1, c0]) != bc or int(g[r1, c1]) != bc:
                        continue
                    if not bool((g[r0, c0 : c1 + 1] == bc).all()):
                        continue
                    if not bool((g[r1, c0 : c1 + 1] == bc).all()):
                        continue
                    if not bool((g[r0 : r1 + 1, c0] == bc).all()):
                        continue
                    if not bool((g[r0 : r1 + 1, c1] == bc).all()):
                        continue
                    ibg = interior_bg((r0, c0, r1, c1))
                    if ibg == bc:
                        continue
                    area = int((r1 - r0 + 1) * (c1 - c0 + 1))
                    rects.append((area, (int(r0), int(c0), int(r1), int(c1)), int(bc), int(ibg)))

    assert rects, "no candidate rectangles found"

    src: tuple[tuple[int, int, int, int], int, int, list[dict]] | None = None
    dst: tuple[tuple[int, int, int, int], int, int, list[dict]] | None = None
    src_score = (-1, -1)
    dst_score = (-1, -1)

    for _area, rect, bc, _ibg in sorted(rects, reverse=True, key=lambda x: x[0])[:10]:
        ibg2, comps = rect_components(rect)
        if not comps:
            continue
        valid_sprite_comps = [comp for comp in comps if classify_tricolor_sprite(comp) is not None]
        singleton_count = sum(1 for comp in comps if int(comp["size"]) == 1)
        max_sz = max(int(comp["size"]) for comp in comps)

        if max_sz > 1:
            score = (len(valid_sprite_comps), len(comps))
            if len(valid_sprite_comps) >= 3 and score > src_score:
                src = (rect, bc, ibg2, comps)
                src_score = score
        if max_sz == 1:
            score = (singleton_count, len(comps))
            if singleton_count >= 3 and score > dst_score:
                dst = (rect, bc, ibg2, comps)
                dst_score = score

    assert src is not None and dst is not None, "must find source and destination rectangles"

    (_sr, _sc, _sr1, _sc1), _src_bc, _src_bg, src_comps = src
    (dr, dc, dr1, dc1), dst_bc, dst_bg, _dst_comps = dst

    templates: dict[int, tuple[np.ndarray, np.ndarray, tuple[int, int]]] = {}
    for comp in src_comps:
        roles = classify_tricolor_sprite(comp)
        if roles is None:
            continue
        anchor_col, _decor_col, _body_col = roles
        patch = comp["patch"]
        mask = comp["mask"]
        anchors = np.argwhere((patch == anchor_col) & mask)
        if anchors.shape[0] != 1:
            continue
        ar, ac = map(int, anchors[0])
        if anchor_col not in templates or int(mask.sum()) > int(templates[anchor_col][1].sum()):
            templates[anchor_col] = (patch.copy(), mask.copy(), (int(ar), int(ac)))

    assert len(templates) >= 3, "expected at least three tri-color templates"

    out_h = int(dr1 - dr + 1)
    out_w = int(dc1 - dc + 1)
    out = np.full((out_h, out_w), int(dst_bg), dtype=int)
    out[0, :] = int(dst_bc)
    out[-1, :] = int(dst_bc)
    out[:, 0] = int(dst_bc)
    out[:, -1] = int(dst_bc)

    inner = g[dr + 1 : dr1, dc + 1 : dc1]
    for rr, cc in np.argwhere(inner != int(dst_bg)):
        mr = int(dr + 1 + int(rr))
        mc = int(dc + 1 + int(cc))
        mcol = int(g[mr, mc])
        if mcol not in templates:
            continue
        patch, mask, (ar, ac) = templates[mcol]
        top = int((mr - dr) - ar)
        left = int((mc - dc) - ac)
        paste(out, patch, top, left, mask=mask, overwrite=True, clip=True)

    return out


# --------------- generator ---------------

# === CFG: Canvas & layout ===
GRID_SIZE = 30
LAYOUT_CHOICES = ("side_by_side", "stacked")
GAP_RANGE = (1, 2)

# === CFG: Sprite type and multiplicity ===
SPRITE_TYPE_CHOICES = (3, 4)
MARKER_EXTRA_RANGE = (1, 2)
SOURCE_EXTRA_RANGE = (1, 3)
MARKER_PLACE_RETRIES = 40
SOURCE_SPRITE_PADDING = 1

# === CFG: Generation retries ===
MAX_GEN_ATTEMPTS = 500

SPRITE_SHAPES = [
    ("ABC", "BBC"),
    ("ABB", "CBC"),
    ("ABB", "BCC"),
    ("ABB", "BCC", "..B"),
    (".AB", "BBC", "..C"),
    ("AB.", "BBC", ".C."),
    ("A.B", "BBC", "C.."),
    ("A.B", "BBC", ".BC"),
    ("A..", "BBB", "CC."),
    ("A..", "BBB", "BCC"),
    ("..A", "BBB", ".CC"),
    ("..A", "BBB", "CCB"),
    (".AB", "BCB", "C.."),
    ("AB.", "BCB", "..C"),
    ("AB.", "BCB", ".BC"),
    ("A..", "BCB", ".BC"),
]


def _shape_info(shape_rows: tuple[str, ...]) -> tuple[tuple[int, int], tuple[int, int, int]]:
    counts: Counter = Counter()
    anchor_rc: tuple[int, int] | None = None
    for r, row in enumerate(shape_rows):
        for c, ch in enumerate(row):
            if ch == ".":
                continue
            counts[ch] += 1
            if ch == "A":
                anchor_rc = (int(r), int(c))
    assert anchor_rc is not None
    assert counts["A"] == 1
    assert counts["C"] == 2
    assert counts["B"] in (3, 4)
    return anchor_rc, (int(counts["A"]), int(counts["C"]), int(counts["B"]))


for _shape in SPRITE_SHAPES:
    _anchor_rc, _count_sig = _shape_info(_shape)
    assert len(_shape) in (2, 3)
    assert len(_shape[0]) == 3


def _render_sprite(shape_rows: tuple[str, ...], body: int, anchor: int, decor: int, bg: int) -> np.ndarray:
    char_map = {"A": anchor, "B": body, "C": decor}
    rows = [[char_map.get(ch, bg) for ch in row] for row in shape_rows]
    return np.array(rows, dtype=int)


def _make_wallpaper(direction: str, palette: list[int]) -> np.ndarray:
    period = len(palette)
    stripe = np.array(palette * ((GRID_SIZE + period - 1) // period), dtype=int)[:GRID_SIZE]
    if direction == "vertical":
        return np.tile(stripe, (GRID_SIZE, 1))
    return np.tile(stripe.reshape(-1, 1), (1, GRID_SIZE))


def _build_frame(h: int, w: int, border: int, bg: int) -> np.ndarray:
    rect = np.full((h, w), bg, dtype=int)
    rect[0, :] = rect[-1, :] = border
    rect[:, 0] = rect[:, -1] = border
    return rect


def _choose_counts(n_total: int, n_types: int) -> list[int]:
    counts = [1] * n_types
    for _ in range(n_total - n_types):
        counts[random.randrange(n_types)] += 1
    return counts


def _choose_dimensions(layout: str) -> tuple[int, int, int, int, int]:
    for _ in range(80):
        gap = random.randint(*GAP_RANGE)
        if layout == "side_by_side":
            src_h = random.randint(15, 19)
            src_w = random.randint(14, 16)
            dst_h = random.randint(12, 15)
            dst_w = random.randint(11, 13)
            if src_w + dst_w + gap <= GRID_SIZE:
                return src_h, src_w, dst_h, dst_w, gap
        else:
            src_h = random.randint(14, 16)
            src_w = random.randint(13, 17)
            dst_h = random.randint(11, 13)
            dst_w = random.randint(11, 15)
            if src_h + dst_h + gap <= GRID_SIZE:
                return src_h, src_w, dst_h, dst_w, gap
    raise ValueError("no layout dimensions fit")


def _place_rectangles(
    layout: str, src_h: int, src_w: int, dst_h: int, dst_w: int, gap: int
) -> tuple[tuple[int, int], tuple[int, int]]:
    if layout == "side_by_side":
        slack = GRID_SIZE - src_w - dst_w - gap
        left_margin = random.randint(0, slack)
        src_r = random.randint(0, GRID_SIZE - src_h)
        dst_r = random.randint(0, GRID_SIZE - dst_h)
        if random.random() < 0.5:
            src_c, dst_c = left_margin, left_margin + src_w + gap
        else:
            dst_c, src_c = left_margin, left_margin + dst_w + gap
    else:
        slack = GRID_SIZE - src_h - dst_h - gap
        top_margin = random.randint(0, slack)
        src_c = random.randint(0, GRID_SIZE - src_w)
        dst_c = random.randint(0, GRID_SIZE - dst_w)
        if random.random() < 0.5:
            src_r, dst_r = top_margin, top_margin + src_h + gap
        else:
            dst_r, src_r = top_margin, top_margin + dst_h + gap
    return (int(src_r), int(src_c)), (int(dst_r), int(dst_c))


def _assign_palette(n_types: int) -> tuple[list[int], int, int, int, int, int, int, list[int]] | None:
    wallpaper = random.sample(list(range(10)), 4)
    remaining = [c for c in range(10) if c not in wallpaper]
    random.shuffle(remaining)
    if len(remaining) < n_types + 1:
        return None

    random.shuffle(wallpaper)
    dst_bg = int(wallpaper[0])
    src_bg = int(wallpaper[1])
    body_a = int(wallpaper[2])
    body_b = int(wallpaper[3])
    dst_border = int(src_bg)
    src_border = int(remaining.pop())
    anchors = [int(remaining.pop()) for _ in range(n_types)]
    return wallpaper, src_border, dst_border, src_bg, dst_bg, body_a, body_b, anchors


def _place_markers(
    sprite_types: list[dict], marker_type_ids: list[int], dst_h: int, dst_w: int, dst_bg: int
) -> tuple[np.ndarray, list[tuple[int, int, int]]] | None:
    inner = np.full((dst_h - 2, dst_w - 2), dst_bg, dtype=int)
    marker_points: list[tuple[int, int, int]] = []
    for type_id in marker_type_ids:
        sprite = sprite_types[type_id]
        patch = _render_sprite(sprite["shape_rows"], sprite["body"], sprite["anchor"], sprite["decor"], dst_bg)
        placed = False
        for _ in range(MARKER_PLACE_RETRIES):
            try:
                r0, c0 = random_free_location(inner, patch, transparent=dst_bg)
            except ValueError:
                return None
            mr = int(r0 + sprite["anchor_rc"][0])
            mc = int(c0 + sprite["anchor_rc"][1])
            if any(abs(mr - pr) + abs(mc - pc) <= 1 for pr, pc, _ in marker_points):
                continue
            paste(inner, patch, r0, c0, transparent=dst_bg)
            marker_points.append((int(mr), int(mc), int(type_id)))
            placed = True
            break
        if not placed:
            return None
    return inner, marker_points


def _place_sources(
    sprite_types: list[dict], source_type_ids: list[int], src_h: int, src_w: int, src_bg: int
) -> np.ndarray | None:
    inner = np.full((src_h - 2, src_w - 2), src_bg, dtype=int)
    for type_id in source_type_ids:
        sprite = sprite_types[type_id]
        patch = _render_sprite(sprite["shape_rows"], sprite["body"], sprite["anchor"], sprite["decor"], src_bg)
        try:
            r0, c0 = random_free_location(
                inner,
                patch,
                transparent=src_bg,
                border=SOURCE_SPRITE_PADDING,
                padding=SOURCE_SPRITE_PADDING,
                padding_connectivity=4,
            )
        except ValueError:
            return None
        paste(inner, patch, r0, c0, transparent=src_bg)
    return inner


def _gen_attempt() -> np.ndarray | None:
    n_types = random.choice(list(SPRITE_TYPE_CHOICES))
    palette_result = _assign_palette(n_types)
    if palette_result is None:
        return None
    wallpaper, src_border, dst_border, src_bg, dst_bg, body_a, body_b, anchors = palette_result

    if len(set(anchors)) != n_types:
        return None
    if len({src_border, dst_border, src_bg, dst_bg, body_a, body_b, *anchors}) < 5 + n_types:
        return None

    sprite_specs = random.sample(SPRITE_SHAPES, n_types)
    body_decor_pairs = [(body_a, body_b), (body_b, body_a)]
    pair_assignments = [body_decor_pairs[i % 2] for i in range(n_types)]
    random.shuffle(pair_assignments)

    sprite_types: list[dict] = []
    for shape_rows, anchor, (body, decor) in zip(sprite_specs, anchors, pair_assignments):
        anchor_rc, count_sig = _shape_info(shape_rows)
        sprite_types.append(
            {
                "shape_rows": shape_rows,
                "anchor_rc": anchor_rc,
                "body": int(body),
                "anchor": int(anchor),
                "decor": int(decor),
                "count_sig": count_sig,
            }
        )

    n_markers = random.randint(n_types + MARKER_EXTRA_RANGE[0], n_types + MARKER_EXTRA_RANGE[1])
    n_source = random.randint(n_types + SOURCE_EXTRA_RANGE[0], n_types + SOURCE_EXTRA_RANGE[1])
    marker_type_ids = [i for i, ct in enumerate(_choose_counts(n_markers, n_types)) for _ in range(ct)]
    source_type_ids = [i for i, ct in enumerate(_choose_counts(n_source, n_types)) for _ in range(ct)]
    random.shuffle(marker_type_ids)
    random.shuffle(source_type_ids)

    layout = random.choice(list(LAYOUT_CHOICES))
    try:
        src_h, src_w, dst_h, dst_w, gap = _choose_dimensions(layout)
    except ValueError:
        return None
    if src_h * src_w <= dst_h * dst_w:
        return None

    marker_result = _place_markers(sprite_types, marker_type_ids, dst_h, dst_w, dst_bg)
    if marker_result is None:
        return None
    out_inner, marker_points = marker_result

    output = _build_frame(dst_h, dst_w, dst_border, dst_bg)
    paste(output[1:-1, 1:-1], out_inner, 0, 0)

    source_inner = _place_sources(sprite_types, source_type_ids, src_h, src_w, src_bg)
    if source_inner is None:
        return None

    source_rect = _build_frame(src_h, src_w, src_border, src_bg)
    paste(source_rect[1:-1, 1:-1], source_inner, 0, 0)

    dest_rect = _build_frame(dst_h, dst_w, dst_border, dst_bg)
    for mr, mc, type_id in marker_points:
        dest_rect[1 + mr, 1 + mc] = int(sprite_types[type_id]["anchor"])

    try:
        src_pos, dst_pos = _place_rectangles(layout, src_h, src_w, dst_h, dst_w, gap)
    except ValueError:
        return None

    grid = _make_wallpaper(random.choice(["vertical", "horizontal"]), wallpaper)
    paste(grid, source_rect, src_pos[0], src_pos[1])
    paste(grid, dest_rect, dst_pos[0], dst_pos[1])

    try:
        solved = main(grid)
    except AssertionError:
        return None
    if not np.array_equal(solved, output):
        return None
    return grid


def generate_input() -> np.ndarray:
    for _ in range(MAX_GEN_ATTEMPTS):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError(f"failed to generate a251c730 combo variant after {MAX_GEN_ATTEMPTS} attempts")
