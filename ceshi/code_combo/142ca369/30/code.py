# Design analysis for combo D3/3 + D9/1
# ======================================
# a) Concretization and behavior trace
#    Input stays in the original object language: black background, several
#    3-cell monochrome L-arrows, and single-pixel or 3-pixel axis-aligned
#    walls. Rays still travel diagonally, side-touch walls, flip one axis, and
#    inherit the touched wall color.
#    Original local behavior on one bounce:
#      - a long incoming diagonal segment is painted continuously;
#      - the bounce cell is recolored to the wall color;
#      - the outgoing segment is painted continuously too;
#      - arrows and walls remain in the output.
#    Combo behavior on that same bounce:
#      - all free-flight cells away from the bounce remain background;
#      - only the 2 cells immediately before the bounce are painted in the
#        incoming ray color;
#      - the bounce cell is painted in the wall color;
#      - only the next 2 cells after the turn are painted in the new wall
#        color;
#      - arrows and walls are erased, so the output contains only these short
#        reflection markers on a blank background.
#    Concrete example: if a color-2 arrow reaches a wall of color 7 after
#    8 diagonal steps, the original output shows all 8 traversed cells plus the
#    wall and arrow. The combo output shows only steps 7-8 in color 2, the
#    bounce cell in color 7, and the next 2 reflected cells in color 7; every
#    original object pixel becomes background.
# b) Complexity calibration
#    The variant must not collapse into either the original task or a trivial
#    "erase objects" task. To keep the transformation visually obvious:
#      - every generated arrow is forced to bounce at least once;
#      - each pre-bounce segment has length >= 6, so marker windows do not fuse
#        into an apparently continuous trail;
#      - the final post-bounce segment has length >= 4, so the outgoing marker
#        is visible and followed by blank space.
#    A fixed marker radius of 2 keeps the rule learnable from a few examples.
# c) Hidden-assumption audit against the original solver
#    - `out = g.copy()` is invalid because D9/1 erases arrows and walls. The
#      output base must be an all-background grid.
#    - Eager painting while tracing is invalid because D3/3 hides most of the
#      trajectory. Geometry tracing and output painting must be separated.
#    - Painting decisions can no longer depend on `out[...] == bg`; they must
#      depend on whether the corresponding input cell was background in `g`.
#    - Arrow cells still block rays during tracing even though they disappear in
#      the output, because input semantics did not change.
#    - The marker logic assumes a bounce is generated by at most one planned
#      side-touch wall at a time. The generator enforces that by forbidding any
#      occupied pixel in the alternate side-touch slot.
# d) Placement legality
#    The generator reserves the entire invisible ray path, not just visible
#    marker cells, so arrows, walls, and hidden trajectories never overlap.
#    Walls are placed exactly one cell off the diagonal path on the flipped
#    axis, matching the original physics. All candidate placements are checked
#    for in-bounds validity, non-overlap, and enough future room after the
#    bounce.
# e) Visual observability
#    From 2-4 examples a human can still infer the rule because the input walls
#    visibly explain where the short output marks appear, and the output is much
#    sparser than the original. Forcing 2-6 arrows and 1-4 bounces per arrow
#    gives repeated evidence that "only reflection neighborhoods survive".
# f) Visual neatness
#    The output is cleaner than the original because arrows and walls vanish.
#    The generator still prevents overlap among all reserved path cells, so the
#    remaining short diagonal elbows stay separated and legible.
# g) Color inference
#    The color change remains structurally grounded: incoming marker cells keep
#    the pre-bounce ray color, while the bounce cell and outgoing marker inherit
#    the adjacent wall color. Because the wall is still visible in the input,
#    the source of each color switch is human-inferable.
# h) Post-edit assumption audit
#    `main()` now assumes that any intended visible marker cell was background
#    in the input. The generator guarantees this by never overlapping arrows,
#    walls, and reserved ray cells. It also assumes bounce windows stay
#    distinguishable rather than merging into full trails; the segment-length
#    constraints guarantee at least one blank cell between consecutive windows.

MARK_RADIUS = 2
MIN_BOUNCE_SEG_LEN = 6
MIN_FINAL_SEG_LEN = 4


def _is_arrow_pts(pts: list[tuple[int, int]]) -> bool:
    if len(pts) != 3:
        return False
    rs = [r for r, _c in pts]
    cs = [c for _r, c in pts]
    return (max(rs) - min(rs) == 1) and (max(cs) - min(cs) == 1)


def _arrow_dir_and_start(pts: list[tuple[int, int]]):
    rs = [r for r, _c in pts]
    cs = [c for _r, c in pts]
    r0, r1 = min(rs), max(rs)
    c0, c1 = min(cs), max(cs)
    corners = [(r0, c0), (r0, c1), (r1, c0), (r1, c1)]
    pts_set = set(pts)
    miss = [p for p in corners if p not in pts_set]
    if len(miss) != 1:
        return None
    mr, mc = miss[0]
    dr = 1 if mr == r0 else -1
    dc = 1 if mc == c0 else -1

    deg = {p: 0 for p in pts}
    for r, c in pts:
        for rr, cc in ((r - 1, c), (r + 1, c), (r, c - 1), (r, c + 1)):
            if (rr, cc) in pts_set:
                deg[(r, c)] += 1
    start = max(deg, key=lambda p: deg[p])
    return (int(dr), int(dc)), (int(start[0]), int(start[1]))


def _detect_arrows(g: np.ndarray, bg: int):
    arrow_cells: set[tuple[int, int]] = set()
    arrows: list[tuple[int, list[tuple[int, int]]]] = []
    for col in colors_present(g, exclude={bg}):
        for coords in components_mask(g == int(col), connectivity=4):
            pts = [(int(r), int(c)) for r, c in coords]
            if _is_arrow_pts(pts):
                arrows.append((int(col), pts))
                arrow_cells |= set(pts)
    return arrows, arrow_cells


def _trace_marker_ops(
    g: np.ndarray,
    arrow_cells: set[tuple[int, int]],
    wall_cells: set[tuple[int, int]],
    start_col: int,
    pts: list[tuple[int, int]],
):
    H, W = g.shape
    info = _arrow_dir_and_start(pts)
    if info is None:
        return []

    (dr, dc), cur = info
    cur_col = int(start_col)
    recent: list[tuple[int, int, int]] = []
    ops: list[tuple[int, int, int]] = []
    seen: set[tuple[tuple[int, int], int, int, int]] = set()
    pending_after = 0
    pending_color = int(cur_col)

    def mark_before_and_bounce(bounce_pos: tuple[int, int], wall_color: int) -> None:
        before = recent[-(MARK_RADIUS + 1) : -1]
        for rr, cc, old_col in before:
            ops.append((int(rr), int(cc), int(old_col)))
        ops.append((int(bounce_pos[0]), int(bounce_pos[1]), int(wall_color)))

    while True:
        state = (cur, int(dr), int(dc), int(cur_col))
        if state in seen:
            break
        seen.add(state)

        nr = int(cur[0] + dr)
        nc = int(cur[1] + dc)
        if not (0 <= nr < H and 0 <= nc < W):
            break

        if (nr, nc) in wall_cells:
            wall_color = int(g[nr, nc])
            if recent and recent[-1][:2] == cur:
                mark_before_and_bounce(cur, wall_color)
                recent[-1] = (int(cur[0]), int(cur[1]), int(wall_color))
            cur_col = int(wall_color)
            pending_after = MARK_RADIUS
            pending_color = int(wall_color)
            dr, dc = -int(dr), -int(dc)
            continue

        if (nr, nc) in arrow_cells:
            break

        cur = (int(nr), int(nc))
        recent.append((int(nr), int(nc), int(cur_col)))
        if len(recent) > MARK_RADIUS + 1:
            recent.pop(0)

        if pending_after > 0:
            ops.append((int(nr), int(nc), int(pending_color)))
            pending_after -= 1

        bounce_axis = None
        wall_color = None
        if int(dr) == 1 and (nr + 1, nc) in wall_cells:
            bounce_axis = "dr"
            wall_color = int(g[nr + 1, nc])
        elif int(dr) == -1 and (nr - 1, nc) in wall_cells:
            bounce_axis = "dr"
            wall_color = int(g[nr - 1, nc])
        elif int(dc) == 1 and (nr, nc + 1) in wall_cells:
            bounce_axis = "dc"
            wall_color = int(g[nr, nc + 1])
        elif int(dc) == -1 and (nr, nc - 1) in wall_cells:
            bounce_axis = "dc"
            wall_color = int(g[nr, nc - 1])

        if bounce_axis is None or wall_color is None:
            continue

        mark_before_and_bounce(cur, wall_color)
        cur_col = int(wall_color)
        recent[-1] = (int(cur[0]), int(cur[1]), int(wall_color))
        pending_after = MARK_RADIUS
        pending_color = int(wall_color)
        if bounce_axis == "dr":
            dr = -int(dr)
        else:
            dc = -int(dc)

    return ops


def main(grid: np.ndarray) -> np.ndarray:
    g = np.array(grid, dtype=int)
    bg = int(get_bg(g))
    arrows, arrow_cells = _detect_arrows(g, bg)
    wall_cells: set[tuple[int, int]] = {
        (int(r), int(c))
        for r, c in np.argwhere(g != int(bg))
        if (int(r), int(c)) not in arrow_cells
    }

    out = np.full_like(g, bg)
    for start_col, pts in arrows:
        for r, c, color in _trace_marker_ops(g, arrow_cells, wall_cells, start_col, pts):
            if int(g[r, c]) == int(bg):
                out[r, c] = int(color)
    return out


def _steps_to_edge(r: int, c: int, dr: int, dc: int, H: int, W: int) -> int:
    return min((H - 1 - r) if dr == 1 else r, (W - 1 - c) if dc == 1 else c)


def _wall_options(
    cur_r: int,
    cur_c: int,
    cur_dr: int,
    cur_dc: int,
    H: int,
    W: int,
):
    options: list[tuple[list[tuple[int, int]], str]] = []

    wr, wc = cur_r + cur_dr, cur_c
    if 0 <= wr < H:
        if 0 <= wc - 1 and wc + 1 < W:
            options.append(([(wr, wc - 1), (wr, wc), (wr, wc + 1)], "dr"))
        options.append(([(wr, wc)], "dr"))

    wr2, wc2 = cur_r, cur_c + cur_dc
    if 0 <= wc2 < W:
        if 0 <= wr2 - 1 and wr2 + 1 < H:
            options.append(([(wr2 - 1, wc2), (wr2, wc2), (wr2 + 1, wc2)], "dc"))
        options.append(([(wr2, wc2)], "dc"))
    return options


def _render_plan_output(grid: np.ndarray, plans: list[dict]) -> np.ndarray:
    bg = int(get_bg(grid))
    out = np.full_like(grid, bg)
    for plan in plans:
        path = plan["path"]
        for bounce_idx, wall_color in plan["bounces"]:
            for idx in range(max(0, bounce_idx - MARK_RADIUS), bounce_idx):
                r, c, col = path[idx]
                if int(grid[r, c]) == int(bg):
                    out[r, c] = int(col)
            br, bc, _ = path[bounce_idx]
            if int(grid[br, bc]) == int(bg):
                out[br, bc] = int(wall_color)
            for idx in range(bounce_idx + 1, min(len(path), bounce_idx + 1 + MARK_RADIUS)):
                r, c, _ = path[idx]
                if int(grid[r, c]) == int(bg):
                    out[r, c] = int(wall_color)
    return out


def _gen_attempt() -> np.ndarray | None:
    H, W = _rng.randint(18, 20), _rng.randint(18, 20)
    n_arrows = _rng.randint(2, 6)
    palette = list(range(1, 10))
    _rng.shuffle(palette)
    arrow_colors = palette[:n_arrows]

    grid = np.zeros((H, W), dtype=int)
    occupied: set[tuple[int, int]] = set()
    plans: list[dict] = []

    for ai in range(n_arrows):
        color = int(arrow_colors[ai])
        dr, dc = _rng.choice([-1, 1]), _rng.choice([-1, 1])
        n_bounces = _rng.choices([1, 2, 3, 4], weights=[2, 4, 3, 1])[0]

        placed = False
        for _ in range(90):
            r_lo, r_hi = (1 if dr == -1 else 0), (H - 2 if dr == 1 else H - 1)
            c_lo, c_hi = (1 if dc == -1 else 0), (W - 2 if dc == 1 else W - 1)
            if r_lo > r_hi or c_lo > c_hi:
                continue
            sr, sc = _rng.randint(r_lo, r_hi), _rng.randint(c_lo, c_hi)

            mr, mc = sr - dr, sc - dc
            arrow_pts = [(r, c) for r in (mr, sr) for c in (mc, sc) if (r, c) != (mr, mc)]
            arrow_set = set(arrow_pts)
            if any(not (0 <= r < H and 0 <= c < W) or (r, c) in occupied for r, c in arrow_pts):
                continue

            cur_r, cur_c = sr, sc
            cur_dr, cur_dc = dr, dc
            cur_col = color
            ray_set: set[tuple[int, int]] = set()
            wall_set: set[tuple[int, int]] = set()
            path: list[tuple[int, int, int]] = []
            walls: list[tuple[list[tuple[int, int]], int]] = []
            bounces: list[tuple[int, int]] = []
            ok = True

            for bounce_idx in range(n_bounces):
                max_steps = _steps_to_edge(cur_r, cur_c, cur_dr, cur_dc, H, W)
                if max_steps < MIN_BOUNCE_SEG_LEN:
                    ok = False
                    break

                lengths = list(range(MIN_BOUNCE_SEG_LEN, max_steps + 1))
                _rng.shuffle(lengths)
                candidates = []
                for seg_len in lengths:
                    seg_cells = [(cur_r + cur_dr * step, cur_c + cur_dc * step) for step in range(1, seg_len + 1)]
                    if any(cell in occupied or cell in ray_set or cell in arrow_set or cell in wall_set for cell in seg_cells):
                        continue

                    bounce_r, bounce_c = seg_cells[-1]
                    for wall_cells, flip in _wall_options(bounce_r, bounce_c, cur_dr, cur_dc, H, W):
                        if any(cell in occupied or cell in ray_set or cell in arrow_set or cell in wall_set for cell in wall_cells):
                            continue
                        alt_touch = (bounce_r, bounce_c + cur_dc) if flip == "dr" else (bounce_r + cur_dr, bounce_c)
                        if alt_touch in occupied or alt_touch in ray_set or alt_touch in wall_set or alt_touch in arrow_set:
                            continue

                        new_dr = -cur_dr if flip == "dr" else cur_dr
                        new_dc = -cur_dc if flip == "dc" else cur_dc
                        future_need = MIN_BOUNCE_SEG_LEN if bounce_idx < n_bounces - 1 else MIN_FINAL_SEG_LEN
                        if _steps_to_edge(bounce_r, bounce_c, new_dr, new_dc, H, W) < future_need:
                            continue
                        candidates.append((seg_cells, wall_cells, new_dr, new_dc))

                if not candidates:
                    ok = False
                    break

                seg_cells, wall_cells, next_dr, next_dc = _rng.choice(candidates)
                for r, c in seg_cells:
                    path.append((int(r), int(c), int(cur_col)))
                    ray_set.add((int(r), int(c)))

                wall_color = int(_rng.choice(palette))
                walls.append(([(int(r), int(c)) for r, c in wall_cells], wall_color))
                wall_set.update((int(r), int(c)) for r, c in wall_cells)
                bounces.append((len(path) - 1, wall_color))
                cur_r, cur_c = seg_cells[-1]
                cur_dr, cur_dc = next_dr, next_dc
                cur_col = wall_color

            if not ok:
                continue

            final_steps = _steps_to_edge(cur_r, cur_c, cur_dr, cur_dc, H, W)
            if final_steps < MIN_FINAL_SEG_LEN:
                continue
            final_cells = [(cur_r + cur_dr * step, cur_c + cur_dc * step) for step in range(1, final_steps + 1)]
            if any(cell in occupied or cell in ray_set or cell in arrow_set or cell in wall_set for cell in final_cells):
                continue
            for r, c in final_cells:
                path.append((int(r), int(c), int(cur_col)))
                ray_set.add((int(r), int(c)))

            new_cells = set(arrow_pts) | ray_set | wall_set
            expected_count = len(arrow_pts) + len(ray_set) + len(wall_set)
            if len(new_cells) != expected_count or new_cells & occupied:
                continue

            for r, c in arrow_pts:
                grid[r, c] = color
            for wpxs, wcol in walls:
                for r, c in wpxs:
                    grid[r, c] = wcol

            occupied |= new_cells
            plans.append(
                {
                    "arrow_pts": arrow_pts,
                    "path": path,
                    "bounces": bounces,
                    "walls": walls,
                }
            )
            placed = True
            break

        if not placed:
            return None

    expected = _render_plan_output(grid, plans)
    if np.array_equal(expected, grid):
        return None
    if np.count_nonzero(expected) == 0:
        return None
    if not np.array_equal(main(grid), expected):
        return None
    return grid


def generate_input() -> np.ndarray:
    for _ in range(400):
        result = _gen_attempt()
        if result is not None:
            return result
    raise RuntimeError("Failed to generate valid input after 400 attempts")
