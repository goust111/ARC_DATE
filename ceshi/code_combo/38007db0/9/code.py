def _grid_structure(
    g: np.ndarray,
) -> tuple[int, list[int], list[int], list[tuple[int, int]], list[tuple[int, int]]]:
    row_lines = [r for r in range(g.shape[0]) if len(set(map(int, g[r, :]))) == 1]
    col_lines = [c for c in range(g.shape[1]) if len(set(map(int, g[:, c]))) == 1]
    assert row_lines and col_lines

    vals = [int(g[r, 0]) for r in row_lines] + [int(g[0, c]) for c in col_lines]
    lattice = int(Counter(vals).most_common(1)[0][0])
    row_lines = sorted(r for r in row_lines if int(g[r, 0]) == int(lattice))
    col_lines = sorted(c for c in col_lines if int(g[0, c]) == int(lattice))

    r_slices = [(int(row_lines[i]) + 1, int(row_lines[i + 1])) for i in range(len(row_lines) - 1)]
    c_slices = [(int(col_lines[j]) + 1, int(col_lines[j + 1])) for j in range(len(col_lines) - 1)]
    r_slices = [(a, b) for a, b in r_slices if int(b) > int(a)]
    c_slices = [(a, b) for a, b in c_slices if int(b) > int(a)]
    assert r_slices and c_slices

    return lattice, row_lines, col_lines, r_slices, c_slices


def _infer_bg(g: np.ndarray, r_slices: list[tuple[int, int]], c_slices: list[tuple[int, int]]) -> int:
    samples: list[int] = []
    for ra, rb in r_slices:
        for ca, cb in c_slices:
            samples.extend(
                [
                    int(g[ra, ca]),
                    int(g[ra, cb - 1]),
                    int(g[rb - 1, ca]),
                    int(g[rb - 1, cb - 1]),
                ]
            )
    assert samples
    return int(Counter(samples).most_common(1)[0][0])


def _cell_palette(cell: np.ndarray, bg: int) -> tuple[int, int]:
    palette = sorted({int(v) for v in cell.flatten() if int(v) != int(bg)})
    assert len(palette) == 2
    return int(palette[0]), int(palette[1])


def main(grid: np.ndarray) -> np.ndarray:
    """
    Extract the palette-anomalous cell from each lattice row into a single-column lattice.

    Fused rule:
    - Cells use two sprite colors.
    - Every row has exactly one cell whose two-color palette differs by replacing one
      accent color; shape uniqueness is irrelevant and intentionally misleading.
    """
    g = np.array(grid, dtype=int)
    H, _W = g.shape

    lattice, row_lines, _col_lines, r_slices, c_slices = _grid_structure(g)
    bg = _infer_bg(g, r_slices, c_slices)
    cell_w = int(c_slices[0][1] - c_slices[0][0])

    chosen_cells: list[np.ndarray] = []
    for ra, rb in r_slices:
        cells = [g[int(ra) : int(rb), int(ca) : int(cb)] for ca, cb in c_slices]
        palettes = [_cell_palette(cell, bg) for cell in cells]
        palette_counts = Counter(palettes)
        odd_palette = next((palette for palette, cnt in palette_counts.items() if int(cnt) == 1), None)
        assert odd_palette is not None
        odd_idx = next(i for i, palette in enumerate(palettes) if palette == odd_palette)
        chosen_cells.append(cells[int(odd_idx)].copy())

    out = np.full((H, int(cell_w + 2)), int(bg), dtype=int)
    out[:, 0] = int(lattice)
    out[:, -1] = int(lattice)
    for r in row_lines:
        out[int(r), :] = int(lattice)
    for i, (ra, rb) in enumerate(r_slices):
        out[int(ra) : int(rb), 1 : 1 + int(cell_w)] = chosen_cells[int(i)]
    return out


def _make_cell(inner: np.ndarray, bg: int) -> np.ndarray:
    size = inner.shape[0] + 2
    cell = np.full((size, size), int(bg), dtype=int)
    paste(cell, inner, 1, 1)
    return cell


def _build_lattice(cells: list[list[np.ndarray]], lattice: int, bg: int) -> np.ndarray:
    rows = len(cells)
    cols = len(cells[0])
    cell_size = cells[0][0].shape[0]
    grid = np.full((rows * (cell_size + 1) + 1, cols * (cell_size + 1) + 1), int(bg), dtype=int)
    for r in range(rows + 1):
        grid[r * (cell_size + 1), :] = int(lattice)
    for c in range(cols + 1):
        grid[:, c * (cell_size + 1)] = int(lattice)
    for r, row in enumerate(cells):
        for c, cell in enumerate(row):
            paste(grid, cell, 1 + r * (cell_size + 1), 1 + c * (cell_size + 1))
    return grid


def _gen_row_masks(rng: np.random.Generator, inner_size: int, n_cols: int) -> list[np.ndarray] | None:
    inner_area = inner_size * inner_size
    min_fill = max(4, math.ceil(0.45 * inner_area))
    max_fill = min(inner_area - 1, math.floor(0.8 * inner_area))
    if min_fill > max_fill:
        return None

    base = np.zeros((inner_size, inner_size), dtype=bool)
    on_idx = rng.choice(inner_area, size=int(rng.integers(min_fill, max_fill + 1)), replace=False)
    base.flat[on_idx] = True

    masks = [base.copy()]
    seen = {base.tobytes()}
    attempts = 0
    while len(masks) < n_cols and attempts < 300:
        attempts += 1
        flip_count = int(rng.integers(1, min(4, inner_area) + 1))
        flip_idx = rng.choice(inner_area, size=flip_count, replace=False)
        mask = base.copy()
        flat = mask.reshape(-1)
        flat[flip_idx] = ~flat[flip_idx]
        fill = int(mask.sum())
        if fill < 4 or fill >= inner_area:
            continue
        sig = mask.tobytes()
        if sig in seen:
            continue
        seen.add(sig)
        masks.append(mask)

    return masks if len(masks) == n_cols else None


def _paint_mask(mask: np.ndarray, bg: int, shared: int, accent: int) -> np.ndarray | None:
    support = np.argwhere(mask)
    if len(support) < 2:
        return None

    inner = np.full(mask.shape, int(bg), dtype=int)
    shared_pixels: list[tuple[int, int]] = []
    accent_pixels: list[tuple[int, int]] = []
    for r, c in support:
        if int(r + c) % 2 == 0:
            shared_pixels.append((int(r), int(c)))
        else:
            accent_pixels.append((int(r), int(c)))

    if not shared_pixels:
        r, c = map(int, support[0])
        shared_pixels.append((r, c))
        accent_pixels = [(int(rr), int(cc)) for rr, cc in support[1:]]
    elif not accent_pixels:
        r, c = map(int, support[0])
        accent_pixels.append((r, c))
        shared_pixels = [(int(rr), int(cc)) for rr, cc in support[1:]]

    for r, c in shared_pixels:
        inner[int(r), int(c)] = int(shared)
    for r, c in accent_pixels:
        inner[int(r), int(c)] = int(accent)

    colors = {int(v) for v in inner.flatten() if int(v) != int(bg)}
    return inner if colors == {int(shared), int(accent)} else None


def _row_is_non_degenerate(cells: list[np.ndarray], bg: int, odd_col: int) -> bool:
    sigs = [cell.tobytes() for cell in cells]
    if len(set(sigs)) != len(cells):
        return False
    palettes = [_cell_palette(cell, bg) for cell in cells]
    counts = Counter(palettes)
    minority = [palette for palette, cnt in counts.items() if int(cnt) == 1]
    if len(minority) != 1:
        return False
    return int(odd_col) != 0 and palettes[int(odd_col)] == minority[0]


def _gen_attempt() -> np.ndarray | None:
    rng = np.random.default_rng()

    lattice, bg, shared, majority_accent, odd_accent = map(int, rng.choice(10, size=5, replace=False))
    cell_size = int(rng.choice([5, 6]))
    n_rows = int(rng.integers(3, 5))
    n_cols = int(rng.integers(3, 5))
    inner_size = cell_size - 2

    chosen_cells: list[np.ndarray] = []
    in_cells: list[list[np.ndarray]] = []

    for _ in range(n_rows):
        masks = _gen_row_masks(rng, inner_size, n_cols)
        if masks is None:
            return None

        odd_col = int(rng.integers(1, n_cols))
        row_cells: list[np.ndarray] = []
        for col, mask in enumerate(masks):
            accent = odd_accent if int(col) == int(odd_col) else majority_accent
            inner = _paint_mask(mask, bg, shared, accent)
            if inner is None:
                return None
            row_cells.append(_make_cell(inner, bg))

        if not _row_is_non_degenerate(row_cells, bg, odd_col):
            return None

        chosen_cells.append(row_cells[int(odd_col)].copy())
        in_cells.append(row_cells)

    out = _build_lattice([[cell] for cell in chosen_cells], lattice, bg)
    inp = _build_lattice(in_cells, lattice, bg)
    return inp if np.array_equal(main(inp), out) else None


def generate_input() -> np.ndarray:
    for _ in range(300):
        grid = _gen_attempt()
        if grid is not None:
            return grid
    raise RuntimeError("failed to generate valid input after 300 attempts")
