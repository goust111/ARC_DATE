# Combo variant of 38007db0 (index 9)
# combo_spec: D2/0+D9/0
# Name: 多色精灵颜色异常检测
#
# Design analysis
# ===============
# a) Concrete behavior and trace
# - The lattice geometry stays the same as the base task: 1-pixel gridlines, 3-4 cell
#   rows, 3-4 cell columns, square cells of size 5 or 6, and the output is still a
#   single output column that keeps one selected cell from each input row.
# - The fused change is inside the cells and in the row-selection rule:
#   original task:
#     row cells = [same sprite, same sprite, one shape-mutated sprite]
#     solver selects the only full-cell byte pattern that appears once.
#   fused task:
#     row cells = [shape0 colored with {A,B}, shape1 colored with {A,B},
#                  shape2 colored with {A,C}, shape3 colored with {A,B}]
#     all full cells are byte-unique because the shapes differ, so byte counting is
#     useless. The solver must instead inspect each cell's non-background color set
#     and pick the only cell whose two-color palette is the row minority.
# - Small trace on a 3x3 inner sprite:
#     majority cell support:
#       A B .
#       B A B
#       . A B
#     odd cell support on a different shape:
#       A C .
#       C A C
#       . A .
#   The support/shape varies across cells, but almost every cell in the row uses the
#   palette {A,B}; exactly one uses {A,C}. That palette anomaly is what gets extracted.
#
# b) Complexity calibration
# - If I only recolored one otherwise repeated base cell, the old exact-uniqueness
#   solver would still often succeed accidentally. To prevent that degeneration, every
#   cell in a row gets a different support mask, so every full cell is byte-unique.
# - Color freedom is intentionally limited to five global roles:
#   lattice L, background bg, shared sprite color A, majority accent color B,
#   anomaly accent color C.
# - The anomaly is not "any arbitrary recolor": all majority cells use the same
#   two-color palette {A,B}; the odd cell uses {A,C}. This repeats across rows so a
#   human can infer the rule from a few examples.
#
# c) Implicit-assumption audit against the original main()
# - Gridline detection from fully uniform rows/cols still works.
# - The original `bg = most_common(non-L)` assumption breaks because there are now
#   three non-lattice non-bg sprite colors in play. Here bg is inferred from cell
#   corners, which are guaranteed to stay bg due to the 1-pixel padding border.
# - The original `Counter(cell.tobytes())` assumption breaks completely because the
#   generator now forces every cell in a row to be byte-unique.
# - The new solver assumes every cell contains exactly two non-bg colors and that
#   exactly one palette tuple is a row minority. The generator explicitly constructs
#   rows that satisfy both conditions.
#
# d) Placement legality
# - Cells are still built as square arrays and pasted into fixed lattice slots, so
#   there is no overlap and no out-of-bounds placement.
# - `_make_cell` always wraps the inner sprite in a 1-pixel bg border, keeping the
#   cell corners reliable for background inference.
#
# e) Visual observability
# - A human sees rows of different-looking sprites, but almost all of them share the
#   same two foreground colors; one cell in each row swaps one accent color for a new
#   accent color. That repeated palette anomaly is visually obvious.
# - Because the anomaly column varies per row and is never fixed at column 0, the
#   extracted output cannot be explained by a positional shortcut.
#
# f) Visual cleanliness
# - The lattice remains sparse and regular.
# - Within a row, masks are generated by perturbing a row base mask, so the sprites
#   look like related variants instead of unrelated noise.
# - Only two foreground colors appear per cell, which keeps each cell readable despite
#   the added color dimension.
#
# g) Color-change inferability
# - The recolor structure is simple and repeated: majority cells always use {A,B},
#   odd cells always use {A,C}. There is no hidden numeric ordering of color ids.
# - One color A is shared between majority and anomaly cells, so the anomaly reads as
#   "one accent color replaced" rather than "completely different sprite colors".
#
# h) Non-degeneracy check used by the generator
# - For every row, all full-cell byte signatures are unique, the anomaly palette occurs
#   exactly once, and the anomaly column is forced away from column 0.
# - Therefore the original solver and the D9-only byte-uniqueness solver would pick
#   column 0, while this fused solver picks the palette anomaly.
#
# i) New solver assumptions to re-audit
# - `_cell_palette` assumes exactly two non-bg colors per cell: guaranteed by
#   `_paint_mask`.
# - The row loop assumes one palette count equals 1: guaranteed by the row constructor.
# - The output builder assumes uniform cell width and preserved row lines: guaranteed
#   by `_build_lattice`.

