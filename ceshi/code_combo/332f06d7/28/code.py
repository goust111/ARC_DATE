# Combo variant of 332f06d7 (index 28)
# combo_spec: D1/4+D15/0
# Name: 螺旋路径+固定转折模式

from __future__ import annotations

from collections import Counter, defaultdict, deque
import random

import numpy as np

from arc_utils import bbox_h, bbox_w, find_components


# Design analysis for the combo variant
# =====================================
# a) Concrete form and behavior trace
#    - Input still contains one dominant background, one blue traversable region, one black solid n×n mover,
#      and one red solid n×n destination of the same size.
#    - The blue region is no longer an arbitrary meander. In placement coordinates it is a canonical rectangular
#      spiral generated by a fixed turning cycle: go straight when possible, otherwise turn right, so the path
#      always winds with the same handedness.
#    - The mover and destination occupy two cells of that spiral order. Some instances move outer→inner and
#      others inner→outer, but the local turning pattern remains the same in all examples.
#    - Width variation is represented by small local side bulges attached to spiral cells. These make some
#      parts of the corridor visibly wider without changing the canonical spiral order.
#    - Reachable trace:
#      original task: BFS over all feasible n×n placements; if destination is reachable, move there.
#      combo task: reconstruct the canonical spiral order inside the traversable bounding box and advance only
#      along that ordered sequence until the destination index is reached.
#    - Stuck trace:
#      original task: if a chokepoint blocks progress, BFS stops at the globally farthest reachable placement.
#      combo task: one later spiral step is narrowed below width n, so the next spiral cell becomes infeasible.
#      The mover must stop on the last feasible cell on the spiral sequence, even if a widened side bulge is
#      also reachable and is farther in unrestricted BFS distance.
#    - Small example in placement coordinates:
#      spiral order prefix: A -> B -> C -> D -> E
#      attached bulge:      C -> X
#      gate carved between C and D
#      original BFS would end at X (distance 3), while the combo rule ends at C because D is the next spiral
#      cell and it is blocked. This is the key behavioral difference from the source task.
# b) Complexity calibration
#    - The visible change is strong: the river is a regular spiral, not a random corridor.
#    - The turning rule has only one global mode (fixed handedness), so examples reinforce one predictable
#      geometry instead of mixing multiple incompatible spiral conventions.
#    - Width variation is limited to a few one-cell bulges and one optional narrowing gate. That is enough to
#      make the corridor look non-uniform without creating clutter or secondary objects.
# c) Implicit-assumption audit against the original `main()`
#    - Original assumption: all reachable feasible placements are valid movement candidates. Broken here,
#      because off-spiral bulges are reachable but must be ignored.
#    - Original assumption: when the destination is unreachable, the correct stop is the globally farthest BFS
#      node. Broken here; the stop is the last feasible cell before the next blocked spiral step.
#    - Original assumption: arbitrary winding geometry can be handled without recovering global order. Broken
#      here; the solver must infer the canonical spiral from the traversable bounding box and fixed turn rule.
#    - Still valid: the two important colored objects are same-sized solid squares, so size grouping plus color
#      ordering can still identify mover vs destination reliably.
# d) Placement legality
#    - The generator works in placement space first, using spiral top-left coordinates that are guaranteed to
#      stay within a square grid with a one-cell background frame.
#    - Bulges are only added at in-box cells that touch exactly one spiral cell, so they do not enlarge the
#      spiral bounding box and do not create shortcuts to later spiral rings.
#    - The narrowing gate only erases part of the leading row/column of the next spiral placement, preserving
#      the current cell while invalidating the downstream one.
# e) Visual observability
#    - Across 2-4 examples a human can see the same clockwise rectangular spiral and infer that black travels
#      along that spiral toward red.
#    - Reachable vs stuck examples differ by a visible local narrowing on a later ring or turn. The side bulge
#      makes it clear that “reachable blue area” alone is not the rule; the motion follows the spiral order.
#    - No invisible property such as numeric color ranking is needed to recover the path geometry.
# f) Visual cleanliness
#    - The spiral remains the only large blue structure. Bulges are tiny local widenings of that same river,
#      not detached decorations.
#    - Squares remain solid, high-contrast blocks and never overlap each other in the input.
# g) Change inferability
#    - Color semantics are unchanged from the source task: blue is the river, black is the mover, red is the
#      destination, green is background. The only inferred novelty is geometric: fixed-turn spiral ordering.
# h) New solver assumptions introduced here
#    - The traversable region's placement bbox matches the canonical spiral box used by the generator.
#    - Mover and destination both lie on that canonical spiral sequence.
#    - Any extra feasible placements are side bulges only; they do not alter the canonical spiral bbox.
#    - The generator enforces all three properties explicitly.


_BG, _RIVER, _MOVER, _DEST = 3, 1, 0, 2
_DIR4 = [(1, 0), (-1, 0), (0, 1), (0, -1)]


def _find_squares(g: np.ndarray, bg: int) -> list[dict]:
    squares: list[dict] = []
    for comp in find_components(g, bg=bg, connectivity=4, monochromatic=True, return_format="dict"):
        col = int(comp["color"])
        box = comp["bbox"]
        if bbox_h(box) != bbox_w(box):
            continue
        patch = g[int(box[0]) : int(box[2]) + 1, int(box[1]) : int(box[3]) + 1]
        if not bool((patch == col).all()):
            continue
        squares.append({"col": col, "r0": int(box[0]), "c0": int(box[1]), "n": int(bbox_h(box))})
    return squares


def _select_mover_dest(g: np.ndarray, bg: int) -> tuple[dict, dict]:
    squares = _find_squares(g, bg)
    assert not (len(squares) < 2)

    by_n: dict[int, list[dict]] = defaultdict(list)
    for sq in squares:
        by_n[int(sq["n"])].append(sq)
    nside = max(by_n.items(), key=lambda kv: (len(kv[1]), kv[0]))[0]
    cand = sorted(by_n[int(nside)], key=lambda sq: int(sq["col"]))
    assert not (len(cand) < 2)
    return cand[0], cand[1]


def _river_color(g: np.ndarray, bg: int, mover_col: int, dest_col: int) -> int:
    counts = Counter(map(int, g.flatten()))
    for col, _count in counts.most_common():
        if int(col) in (int(bg), int(mover_col), int(dest_col)):
            continue
        return int(col)
    raise AssertionError("river color not found")


def _feasible_windows(trav: np.ndarray, n: int) -> np.ndarray:
    H, W = trav.shape
    h2, w2 = H - n + 1, W - n + 1
    assert not (h2 <= 0 or w2 <= 0)
    feasible = np.zeros((h2, w2), dtype=bool)
    for r in range(h2):
        for c in range(w2):
            feasible[r, c] = bool(trav[r : r + n, c : c + n].all())
    return feasible


def _spiral_path(rows: int, cols: int, top: int = 0, left: int = 0) -> list[tuple[int, int]]:
    used = np.zeros((rows, cols), dtype=bool)
    dirs = [(0, 1), (1, 0), (0, -1), (-1, 0)]
    d = 0
    r = 0
    c = 0
    path: list[tuple[int, int]] = []
    while True:
        path.append((top + r, left + c))
        used[r, c] = True
        moved = False
        for turn in range(4):
            nd = (d + turn) % 4
            dr, dc = dirs[nd]
            nr, nc = r + dr, c + dc
            if not (0 <= nr < rows and 0 <= nc < cols) or bool(used[nr, nc]):
                continue
            blocked = False
            for adr, adc in dirs:
                ar, ac = nr + adr, nc + adc
                if 0 <= ar < rows and 0 <= ac < cols and bool(used[ar, ac]) and (ar, ac) != (r, c):
                    blocked = True
                    break
            if blocked:
                continue
            d = nd
            r, c = nr, nc
            moved = True
            break
        if not moved:
            break
    return path


def _placement_box_from_traversable(trav: np.ndarray, n: int) -> tuple[int, int, int, int]:
    rs, cs = np.where(trav)
    assert not (len(rs) == 0)
    r0 = int(rs.min())
    c0 = int(cs.min())
    rows = int(rs.max() - rs.min() - n + 2)
    cols = int(cs.max() - cs.min() - n + 2)
    assert not (rows <= 0 or cols <= 0)
    return r0, c0, rows, cols


def _follow_spiral_path(
    feasible: np.ndarray,
    spiral: list[tuple[int, int]],
    mover_pos: tuple[int, int],
    dest_pos: tuple[int, int],
) -> tuple[int, int]:
    index = {pos: i for i, pos in enumerate(spiral)}
    assert not (mover_pos not in index or dest_pos not in index)
    s_idx = int(index[mover_pos])
    d_idx = int(index[dest_pos])
    step = 1 if d_idx >= s_idx else -1
    cur_idx = s_idx
    while cur_idx != d_idx:
        nxt_idx = cur_idx + step
        nr, nc = spiral[nxt_idx]
        if not (0 <= nr < feasible.shape[0] and 0 <= nc < feasible.shape[1] and bool(feasible[nr, nc])):
            break
        cur_idx = nxt_idx
    return spiral[cur_idx]


def main(grid: np.ndarray) -> np.ndarray:
    g = np.array(grid, dtype=int)
    bg = int(Counter([int(g[0, 0]), int(g[0, -1]), int(g[-1, 0]), int(g[-1, -1])]).most_common(1)[0][0])
    mover, dest = _select_mover_dest(g, bg)

    n = int(mover["n"])
    sr, sc = int(mover["r0"]), int(mover["c0"])
    dr, dc = int(dest["r0"]), int(dest["c0"])
    river = _river_color(g, bg, int(mover["col"]), int(dest["col"]))

    trav = (g == river) | (g == int(mover["col"])) | (g == int(dest["col"]))
    feasible = _feasible_windows(trav, n)
    assert not (not bool(feasible[sr, sc]))

    top, left, rows, cols = _placement_box_from_traversable(trav, n)
    spiral = _spiral_path(rows, cols, top=top, left=left)
    tr, tc = _follow_spiral_path(feasible, spiral, (sr, sc), (dr, dc))

    out = g.copy()
    out[sr : sr + n, sc : sc + n] = river
    out[tr : tr + n, tc : tc + n] = int(mover["col"])
    return out


def _paint_window(grid: np.ndarray, r: int, c: int, n: int, color: int = _RIVER) -> None:
    grid[r : r + n, c : c + n] = int(color)


def _carve_gate(grid: np.ndarray, cur: tuple[int, int], nxt: tuple[int, int], n: int) -> None:
    keep = random.randint(1, n - 1)
    start = random.randint(0, n - keep)
    keep_mask = np.zeros(n, dtype=bool)
    keep_mask[start : start + keep] = True
    r1, c1 = cur
    r2, c2 = nxt
    if r2 == r1 and c2 == c1 + 1:
        col = c2 + n - 1
        for rr in range(n):
            if not bool(keep_mask[rr]):
                grid[r2 + rr, col] = _BG
    elif r2 == r1 and c2 == c1 - 1:
        col = c2
        for rr in range(n):
            if not bool(keep_mask[rr]):
                grid[r2 + rr, col] = _BG
    elif c2 == c1 and r2 == r1 + 1:
        row = r2 + n - 1
        for cc in range(n):
            if not bool(keep_mask[cc]):
                grid[row, c2 + cc] = _BG
    elif c2 == c1 and r2 == r1 - 1:
        row = r2
        for cc in range(n):
            if not bool(keep_mask[cc]):
                grid[row, c2 + cc] = _BG
    else:
        raise AssertionError("spiral steps must be 4-neighbor adjacent")


def _bulge_candidate(
    host: tuple[int, int],
    path_set: set[tuple[int, int]],
    top: int,
    left: int,
    rows: int,
    cols: int,
) -> tuple[int, int] | None:
    hr, hc = host
    for dr, dc in _DIR4:
        nr, nc = hr + dr, hc + dc
        if not (top <= nr < top + rows and left <= nc < left + cols):
            continue
        if (nr, nc) in path_set:
            continue
        path_neighbors = 0
        for dr2, dc2 in _DIR4:
            if (nr + dr2, nc + dc2) in path_set:
                path_neighbors += 1
        if path_neighbors == 1:
            return nr, nc
    return None


def _legacy_bfs_target(grid: np.ndarray) -> tuple[int, int]:
    g = np.array(grid, dtype=int)
    bg = int(Counter([int(g[0, 0]), int(g[0, -1]), int(g[-1, 0]), int(g[-1, -1])]).most_common(1)[0][0])
    mover, dest = _select_mover_dest(g, bg)
    n = int(mover["n"])
    sr, sc = int(mover["r0"]), int(mover["c0"])
    dr, dc = int(dest["r0"]), int(dest["c0"])
    river = _river_color(g, bg, int(mover["col"]), int(dest["col"]))
    trav = (g == river) | (g == int(mover["col"])) | (g == int(dest["col"]))
    feasible = _feasible_windows(trav, n)
    h2, w2 = feasible.shape

    dist = -np.ones((h2, w2), dtype=int)
    dist[sr, sc] = 0
    q = deque([(sr, sc)])
    while q:
        r, c = q.popleft()
        for dr2, dc2 in _DIR4:
            rr, cc = r + dr2, c + dc2
            if 0 <= rr < h2 and 0 <= cc < w2 and bool(feasible[rr, cc]) and int(dist[rr, cc]) == -1:
                dist[rr, cc] = int(dist[r, c] + 1)
                q.append((rr, cc))

    if 0 <= dr < h2 and 0 <= dc < w2 and bool(feasible[dr, dc]) and int(dist[dr, dc]) >= 0:
        return dr, dc

    best = -1
    tr, tc = sr, sc
    for r in range(h2):
        for c in range(w2):
            if int(dist[r, c]) > best:
                best = int(dist[r, c])
                tr, tc = r, c
    return tr, tc


def _extract_mover_top_left(grid: np.ndarray) -> tuple[int, int]:
    pts = np.argwhere(grid == _MOVER)
    assert not (len(pts) == 0)
    return int(pts[:, 0].min()), int(pts[:, 1].min())


def _windows_overlap(a: tuple[int, int], b: tuple[int, int], n: int) -> bool:
    ar, ac = a
    br, bc = b
    return ar < br + n and br < ar + n and ac < bc + n and bc < ac + n


def _decorate_width_variation(
    grid: np.ndarray,
    move_seq: list[tuple[int, int]],
    path_set: set[tuple[int, int]],
    n: int,
    top: int,
    left: int,
    box: int,
    avoid: set[int],
) -> int:
    added = 0
    candidates = list(range(2, max(2, len(move_seq) - 2)))
    random.shuffle(candidates)
    for idx in candidates:
        if idx in avoid:
            continue
        pocket = _bulge_candidate(move_seq[idx], path_set, top, left, box, box)
        if pocket is None:
            continue
        _paint_window(grid, pocket[0], pocket[1], n, _RIVER)
        added += 1
        break
    return added


def _gen_attempt(force_reached: bool | None = None) -> np.ndarray | None:
    reached = (random.random() < 0.5) if force_reached is None else bool(force_reached)
    inward = random.random() < 0.5
    n = random.choice([1, 2, 3, 4]) if reached else random.choice([2, 3, 4])
    pad = 1

    min_box = max(5, 10 - n - 2 * pad + 1)
    max_box = 20 - n - 2 * pad + 1
    if min_box > max_box:
        return None
    box = random.randint(min_box, max_box)
    H = W = box + 2 * pad + n - 1

    spiral = _spiral_path(box, box, top=pad, left=pad)
    if len(spiral) < 12:
        return None

    grid = np.full((H, W), _BG, dtype=int)
    for r, c in spiral:
        _paint_window(grid, r, c, n, _RIVER)

    move_seq = spiral if inward else list(reversed(spiral))
    mover_r, mover_c = move_seq[0]
    dest_r, dest_c = move_seq[-1]
    if _windows_overlap((mover_r, mover_c), (dest_r, dest_c), n):
        return None
    path_set = set(spiral)

    gate_idx = None
    if reached:
        if random.random() < 0.6:
            _decorate_width_variation(grid, move_seq, path_set, n, pad, pad, box, avoid={0, len(move_seq) - 1})
    else:
        candidate_pairs: list[tuple[int, tuple[int, int]]] = []
        lo = max(2, len(move_seq) // 4)
        hi = len(move_seq) - 3
        for idx in range(lo, hi + 1):
            pocket = _bulge_candidate(move_seq[idx], path_set, pad, pad, box, box)
            if pocket is not None:
                candidate_pairs.append((idx, pocket))
        if not candidate_pairs:
            return None
        gate_idx, pocket = random.choice(candidate_pairs)
        _paint_window(grid, pocket[0], pocket[1], n, _RIVER)
        if random.random() < 0.5:
            _decorate_width_variation(
                grid,
                move_seq,
                path_set,
                n,
                pad,
                pad,
                box,
                avoid={0, len(move_seq) - 1, gate_idx},
            )
        _carve_gate(grid, move_seq[gate_idx], move_seq[gate_idx + 1], n)

    grid[mover_r : mover_r + n, mover_c : mover_c + n] = _MOVER
    grid[dest_r : dest_r + n, dest_c : dest_c + n] = _DEST

    trav = (grid == _RIVER) | (grid == _MOVER) | (grid == _DEST)
    feasible = _feasible_windows(trav, n)
    if not bool(feasible[mover_r, mover_c]):
        return None

    expected_tr, expected_tc = _follow_spiral_path(feasible, spiral, (mover_r, mover_c), (dest_r, dest_c))
    expected = grid.copy()
    expected[mover_r : mover_r + n, mover_c : mover_c + n] = _RIVER
    expected[expected_tr : expected_tr + n, expected_tc : expected_tc + n] = _MOVER

    try:
        actual = main(grid)
    except Exception:
        return None
    if not np.array_equal(actual, expected):
        return None

    dest_reached = expected_tr == dest_r and expected_tc == dest_c
    if reached != dest_reached:
        return None

    if not reached:
        legacy_tr, legacy_tc = _legacy_bfs_target(grid)
        if (legacy_tr, legacy_tc) == (expected_tr, expected_tc):
            return None

    return grid


def generate_input() -> np.ndarray:
    if not hasattr(generate_input, "_next_reached"):
        generate_input._next_reached = False
    target_reached = bool(generate_input._next_reached)
    generate_input._next_reached = not target_reached

    for force_reached, attempts in [(target_reached, 350), (None, 350)]:
        for _ in range(attempts):
            result = _gen_attempt(force_reached)
            if result is not None:
                return result
    raise RuntimeError("Failed to generate valid fixed-turn spiral variant input after 600 attempts")
